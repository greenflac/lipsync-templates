#!/usr/bin/env python3
"""Цена, лицензия и снятие с обслуживания — с портала, где за модель платят.

ЗАЧЕМ ЭТОТ КАНАЛ

`poll_portal.py` сосчитал разницу: на fal.ai продаётся 61 модель липсинка и
соседних задач, о которых база не знает НИ ОДНОЙ строкой. Опрос производит
очередь; записывать он нарочно не умеет — «набирать строки ради строк» уже
кончалось метаданными вместо знания.

Этот канал записывает ТРИ вещи, и ни одной больше:

    price        сколько площадка берёт, СЛОВАМИ площадки
    availability снята ли модель с обслуживания (`deprecated`, `removed`,
                 `status`) — рекомендовать снятую модель значит послать
                 человека платить за 404

ЛИЦЕНЗИЯ С ПОРТАЛА — ОДНОЙ СТРОКОЙ О ПОРТАЛЕ, А НЕ ШЕСТЬЮДЕСЯТЬЮ О МОДЕЛЯХ

ИЗМЕРЕНО 2026-09-02: `licenseType` равен `commercial` у 66 записей из 66.
Поле с нулевым разбросом ничего не говорит о конкретной модели — оно говорит о
КАТАЛОГЕ, и записать его 66 раз значит набрать строки ради строк.

Хуже того, оно способно соврать в опасную сторону. Условия площадки — это
условия ПЕРЕПРОДАЖИ, а не лицензия весов: LTX-Video лежит на HuggingFace с
оговоркой «research only» (записано в базе), и строка `license = commercial`
у той же модели дала бы ложный зелёный на правиле Ц5, которое требует
прочитать лицензию ДО встраивания. Сегодня пересечение пустое — ни одна из
66 моделей портала не имеет в базе строки о лицензии, — то есть подмена ещё
не наблюдалась и предотвращена заранее.

Пишется одна строка с областью `fal.ai-*`: сколько карточек и с каким
значением. Область — не модель, и ни один вопрос о модели её не вернёт как
свойство модели.

Всё три — `portal`-тир и род `claim`: это то, что говорит ПЛОЩАДКА, а не то,
что кто-то измерил. Применимость от них не растёт, и канал этого не обещает.
Категорию, теги и описание не берём: портал раскладывает по своей таксономии,
и её строки читались бы как знание о модели.

ЧЕГО КАНАЛ НЕ ДЕЛАЕТ

Не пересчитывает цену в число. Значение — слова источника: «Your request will
cost $0.07 for every second of output video» несёт и цену, и за что берут, и
округление, а число `0.07` в отрыве от «per second of OUTPUT video» уже
однажды стоило сравнения минуты с секундой. Разбор в число живёт отдельно
(`studio/pricing.py`) и читает эту же строку.

ТРИ ИСХОДА (Р1)

    годно      портал ответил, находки записаны
    не годно   ответ портала не разобрался (схема поменялась)
    не смогли  портал не ответил или закрыт политикой (Ц3: не обходим)

`hidePricing` и пустой `pricingInfoOverride` — это НЕ «бесплатно» и НЕ ошибка:
цена не показана, строка не пишется, и число «не смогли» растёт.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio.mcp import fetch  # noqa: E402
from studio.selfrag import modelnames  # noqa: E402

ПОРТАЛ = "fal.ai"
КАТАЛОГ = "https://fal.ai/api/models?keywords={слово}&page={страница}"
СТРАНИЦ = 3

#: Те же слова, что у опроса (`scripts/poll_portal.py`), и по той же причине:
#: это студия липсинка, канал заводится ради её предмета, а широкий запрос
#: вернул бы каталог портала вместо знания.
СЛОВА: tuple[str, ...] = ("lipsync", "avatar", "talking")

#: Разметка Markdown в цене портала: `**$0.07**`. Снимается, потому что это
#: оформление чужой страницы, а не слова о цене. Само число и все слова вокруг
#: остаются нетронутыми.
ЖИРНЫЙ = re.compile(r"\*\*")

#: ЗА ЧТО БЕРУТ — ИЗ СЛОВ ЦЕНЫ, И ЭТО РЕШАЕТ ИМЯ АТРИБУТА.
#:
#: Разбор цены в число (`studio/pricing.py`) берёт единицу из ИМЕНИ атрибута,
#: а не из текста: имя — то, о чём договорились при записи, текст источник
#: пишет как хочет. Поэтому цена, записанная просто как `price`, для проверки
#: бюджета НЕПРИГОДНА — `comparable_prices` требует, чтобы «за что» было
#: названо, и молча уводит такую строку в «прочие».
#:
#: ИЗМЕРЕНО 2026-09-02 на 31 ценовой строке каталога: 27 говорят «за секунду»,
#: 1 — «за минуту», 3 не говорят ни того ни другого (Ideogram берёт за
#: генерацию и называет цену по режимам качества). Записать все 31 как `price`
#: значит записать цену и оставить проверку бюджета слепой на всех 31.
#:
#: Список закрытый и упорядоченный: сначала минута, потом секунда — иначе
#: «$3 per minute» подошло бы под «per ... second»? нет, но порядок делает
#: правило читаемым, а не зависящим от жадности регулярок. Не опознали —
#: остаётся `price`, и это ЧЕСТНО: цена записана, единица не классифицирована.
#: Выдумывать «за секунду» по умолчанию нельзя: у Ideogram это дало бы цену за
#: секунду там, где берут за генерацию.
ЕДИНИЦА_ЦЕНЫ: tuple[tuple[str, "re.Pattern[str]"], ...] = (
    (
        "price_per_minute",
        re.compile(r"per\s+minute|per\s+\w+\s+minute", re.I),
    ),
    (
        "price_per_second_usd",
        re.compile(
            r"per\s+(?:generated\s+|output\s+|input\s+|video\s+|audio\s+)*seconds?"
            r"|seconds?\s+of\s+(?:generated\s+|output\s+|input\s+)*(?:draft\s+)?video"
            r"|\$\s*[\d.]+\s*/\s*sec",
            re.I,
        ),
    ),
)


#: Первая сумма в тексте — та, которую разборщик (`studio/pricing.py`) возьмёт
#: как цену. Ищется в обоих написаниях: портал пишет и «$0.06», и «0.06 $».
СУММА = re.compile(r"\$\s*\d+(?:[.,]\d+)?|\d+(?:[.,]\d+)?\s*\$")

#: Насколько близко к сумме обязана стоять единица, чтобы считаться единицей
#: ЭТОЙ суммы. ИЗМЕРЕНО 2026-09-02 на 31 ценовой строке каталога: 60 знаков в
#: каждую сторону оставляют 22 строки «за секунду» и отсекают ровно одну —
#: ту, ради которой правило и появилось.
#:
#: ПОЙМАНО ЧТЕНИЕМ СВОЕЙ ЖЕ ВЫДАЧИ (П3). Без близости latentsync получал
#: `price_per_second_usd`, а его цена звучит так:
#:
#:     «$0.2 for videos up to 40 seconds. For longer videos, you will be
#:      charged $0.005 per second of output video.»
#:
#: Слова «per second» в тексте есть — но относятся ко ВТОРОМУ тарифу, а
#: разборщик берёт ПЕРВОЕ число. Выходило «$0.2 за секунду» вместо «$0.2 за
#: ролик до 40 секунд» — ошибка в сорок раз, и молчаливая: проверка бюджета
#: пропустила бы её как обычное число.
#:
#: Такая строка остаётся `price`: у неё два тарифа, и свести их к одной
#: единице нельзя, не соврав.
БЛИЗОСТЬ = 60


def атрибут_цены(текст: str) -> str:
    """Имя атрибута для этой ценовой строки. `price` — единица не опознана.

    Единица засчитывается только рядом с ПЕРВОЙ суммой: разборщик возьмёт
    именно её, и единица от другого тарифа сделала бы из честной цены неверную.
    """
    сумма = СУММА.search(текст)
    если_рядом = текст[max(0, сумма.start() - БЛИЗОСТЬ) : сумма.end() + БЛИЗОСТЬ] if сумма else ""
    for имя, образец in ЕДИНИЦА_ЦЕНЫ:
        if образец.search(если_рядом):
            return имя
    return "price"


#: Адрес страницы модели — он же источник. `modelUrl` портала указывает на
#: RUNTIME (`fal.run/...`), по которому человек ничего не прочтёт; читаемая
#: страница живёт по `fal.ai/models/<id>`, и именно её обязан открыть тот, кто
#: проверяет строку.
СТРАНИЦА = "https://fal.ai/models/{идентификатор}"

#: Область, а не модель: строка о КАТАЛОГЕ. База различает утверждения о
#: модели и утверждения об области (`*`, `<линейка>-*`) и никогда не отдаёт
#: вторые как свойство первой — иначе условия перепродажи площадкой читались
#: бы как лицензия весов.
ОБЛАСТЬ_ПОРТАЛА = "fal.ai-*"


def цена(запись: dict[str, Any]) -> str:
    """Слова портала о цене. Пусто — цена не показана (третий исход, не ноль)."""
    if запись.get("hidePricing"):
        return ""
    текст = ЖИРНЫЙ.sub("", str(запись.get("pricingInfoOverride") or "")).strip()
    return текст


def снята(запись: dict[str, Any]) -> str:
    """Слова о снятии с обслуживания. Пусто — модель на месте.

    Три поля портала об одном: `deprecated`, `removed`, `status`. Читаются все
    три, потому что означают разное — объявлено устаревшей, убрана из
    каталога, не публичная, — и свести их в один флаг значит потерять, ЧТО
    именно случилось.
    """
    причины = []
    if запись.get("deprecated"):
        причины.append("портал отметил модель deprecated")
    if запись.get("removed"):
        причины.append("портал отметил модель removed")
    статус = str(запись.get("status") or "").strip()
    if статус and статус != "public":
        причины.append(f"статус на портале: {статус}")
    return "; ".join(причины)


def заявки(запись: dict[str, Any]) -> list[tuple[str, str, str, str, str]]:
    """Находки одной записи каталога: модель, атрибут, значение, URL, нота.

    Значение — СЛОВА ИСТОЧНИКА. Своё рассуждение уходит в ноту: правило уже
    оплачено на другом канале, где приписанное к значению «— у Runway»
    развело файл с гейтом атрибуции на четырёх строках.
    """
    идентификатор = str(запись.get("id") or "").strip("/")
    имя = modelnames.from_portal_id(идентификатор)
    if not имя:
        return []
    url = СТРАНИЦА.format(идентификатор=идентификатор)
    из_каталога = f"карточка каталога {ПОРТАЛ} по запросу «{запись.get('_слово', '')}»"
    out: list[tuple[str, str, str, str, str]] = []

    п = цена(запись)
    if п:
        out.append((имя, атрибут_цены(п), п, url, из_каталога))

    # ЧЕМ МОДЕЛЬ ЗАНЯТА — СЛОВАМИ ЕЁ СТРАНИЦЫ. ИЗМЕРЕНО 2026-09-02: новые имена
    # с портала не доезжают до кандидатов планировщика вовсе. Из 15 показанных
    # кандидатов на трёх брифах записанный вход был у ОДНОГО: у свежих моделей
    # в базе лежат цена и схема входа, и ни одного слова о том, ЧТО они делают,
    # — а якорный отбор ищет именно слова задачи.
    #
    # Пишется `positioning` (имя уже есть в базе, шестого написания не заводим)
    # и ровно то, что написал вендор:
    #
    #   «sync-3 image to video turns a single still into a talking character»
    #   «Replace or dub audio on an existing video with fast audio-only lip-sync»
    #
    # Тир `portal`, род `claim`: это то, что ПРОДАВЕЦ говорит о товаре.
    # Применимость от этого не растёт и не обещается — она считается отдельно и
    # печатается рядом. Категорию и теги портала по-прежнему не берём: там его
    # таксономия, а не слова о модели.
    описание = str(запись.get("shortDescription") or "").strip()
    if описание:
        out.append((имя, "positioning", описание[:400], url, f"описание модели на {ПОРТАЛ}"))

    мертва = снята(запись)
    if мертва:
        out.append((имя, "availability", мертва, url, из_каталога))

    return out


def спросить(слово: str, страница: int) -> tuple[str, dict[str, Any] | None]:
    """Одна страница каталога. «Не разобралось» отличимо от «не ответил»."""
    ответ = fetch.fetch(КАТАЛОГ.format(слово=слово, страница=страница))
    if ответ.get("outcome") != PASS:
        return (UNMEASURED, None)
    try:
        разобрано = json.loads(ответ.get("text") or "")
    except ValueError:
        return (FAIL, None)
    if not isinstance(разобрано, dict) or "items" not in разобрано:
        return (FAIL, None)
    return (PASS, разобрано)


def собрать(слова: tuple[str, ...] = СЛОВА) -> dict[str, Any]:
    """Каталог целиком. Р2: рядом с находками едут все три числа."""
    записи: dict[str, dict[str, Any]] = {}
    ответило = не_разобралось = не_ответило = 0
    for слово in слова:
        отвечало = False
        for страница in range(1, СТРАНИЦ + 1):
            исход, тело = спросить(слово, страница)
            if исход == UNMEASURED:
                не_ответило += 1
                break
            if исход == FAIL or тело is None:
                не_разобралось += 1
                break
            отвечало = True
            for запись in тело.get("items") or []:
                ключ = str(запись.get("id") or "")
                if ключ and ключ not in записи:
                    записи[ключ] = {**запись, "_слово": слово}
            if страница >= int(тело.get("pages") or 1):
                break
        ответило += 1 if отвечало else 0

    находки: list[tuple[str, str, str, str, str]] = []
    без_цены: list[str] = []
    лицензии: dict[str, int] = {}
    for запись in записи.values():
        находки.extend(заявки(запись))
        if not цена(запись):
            без_цены.append(modelnames.from_portal_id(str(запись.get("id") or "")))
        лиц = str(запись.get("licenseType") or "").strip()
        if лиц:
            лицензии[лиц] = лицензии.get(лиц, 0) + 1
    if лицензии:
        сводка = ", ".join(f"{з}: {n}" for з, n in sorted(лицензии.items(), key=lambda x: -x[1]))
        находки.append(
            (
                ОБЛАСТЬ_ПОРТАЛА,
                "portal_license",
                f"licenseType в каталоге ({len(записи)} карточек) — {сводка}",
                СТРАНИЦА.format(идентификатор=""),
                "условия ПЕРЕПРОДАЖИ площадкой, НЕ лицензия весов модели",
            )
        )
    return {
        "записей": len(записи),
        "находки": находки,
        "без цены": без_цены,
        "ответило": ответило,
        "спрошено": len(слова),
        "не разобралось": не_разобралось,
        "не ответило": не_ответило,
    }


def записать(находки: list[tuple[str, str, str, str, str]], today: str) -> dict[str, Any]:
    """Провести находки через `advice.record`. Тир решает URL, а не канал."""
    from studio.mcp import advice

    записано = отказано = 0
    причины: dict[str, int] = {}
    for модель, атрибут, значение, url, нота in находки:
        out = advice.record(
            модель, атрибут, значение, url, "portal", today, note=нота, read_directly=True
        )
        if out["outcome"] == PASS:
            записано += 1
        else:
            отказано += 1
            ключ = str(out.get("note"))[:100]
            причины[ключ] = причины.get(ключ, 0) + 1
    return {"записано": записано, "отказано": отказано, "причины": причины}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--record", metavar="ДАТА", help="записать находки датой источника ДАТА")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    итог = собрать()
    print(
        f"портал {ПОРТАЛ}: слов спрошено {итог['спрошено']}, ответило {итог['ответило']}, "
        f"не разобралось {итог['не разобралось']}, не ответило {итог['не ответило']}"
    )
    print(
        f"записей каталога {итог['записей']}, находок {len(итог['находки'])}, "
        f"цена не показана у {len(итог['без цены'])}"
    )
    if args.json:
        print(json.dumps(итог["находки"], ensure_ascii=False, indent=1))
    if args.record:
        записи = записать(итог["находки"], args.record)
        print(f"записано {записи['записано']}, отказано {записи['отказано']}")
        for почему, сколько in sorted(записи["причины"].items(), key=lambda x: -x[1]):
            print(f"  {сколько}  {почему}")
    print(
        f"\nпроверено {итог['записей']}\nнарушений 0\nне смогли "
        f"{итог['не ответило'] + итог['не разобралось']}"
    )
    if not итог["ответило"]:
        return 2
    if итог["не разобралось"]:
        return 1
    return 2 if итог["ответило"] < итог["спрошено"] else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
