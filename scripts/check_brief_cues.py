#!/usr/bin/env python3
"""Как заказчик сказал — и вывелся ли из этого план.

ЗАЧЕМ

Владелец назвал два входа продукта: «бот помогает собирать пайплайн на основе
готового креатива И С НУЛЯ». Первый вход работает: тот, у кого ролик уже снят,
говорит операциями — «переозвучить», «попасть в губы», — и планировщик его
понимает. Второй вход формулирует иначе. Тот, у кого нет ничего, называет
РЕЗУЛЬТАТ: «нужен говорящий аватар», «виртуальный ведущий», «портрет должен
ожить и поздороваться». Операций в такой фразе нет вовсе.

ИЗМЕРЕНО 2026-09-03, П3, чтением выдачи глазами:

    «Говорящий аватар для рекламы, английская речь, вертикаль 1080x1920»
        -> шагов 0, исход «не смогли»
    «Нужно озвучить текст и синхронизировать губы персонажа»
        -> шагов 3, план собран

Обе фразы про одну работу. Отвечает планировщик честно (пустой план — это
«не смогли», а не выдумка), но продукт при этом не делает ничего.

ЧТО ЭТОТ СКРИПТ — И ЧЕГО ОН НЕ ДЕЛАЕТ

Это СЧЁТЧИК, а не починка (П1: счётчик раньше ручки). Он не трогает
планировщик и ничего не расширяет. Он печатает долю брифов, из которых
операции выводятся, отдельно по каждой формулировке, — чтобы у любой правки
подсказок был номер, который она обязана сдвинуть, и чтобы «стало лучше» не
было на слово.

НЕГАТИВНЫЙ КОНТРОЛЬ ВСТРОЕН В НАБОР (И5). Четыре брифа не про нашу работу
(логотип, юнит-экономика, кластер, статья). На них план обязан остаться
ПУСТЫМ. Без них «покрытие 100%» достигается одной строкой «выводить все
операции всегда», и счётчик перестаёт мерить.

ТРИ ИСХОДА (Р1)

    годно      операции выводятся из каждого брифа, и ни одной лишней
    не годно   контроль сломан: из брифа «мимо» вывелась операция
    не смогли  бриф, сформулированный результатом, не дал ни одной операции

Разница между вторым и третьим намеренная. Лишняя операция на чужой задаче —
это ЛОЖЬ продукта, и это `не годно`. Пустой план на нашей задаче — это
честное «не знаю», то есть «не смогли»: плохо, но не враньё. Свернуть их в
один исход значило бы не различать эти две беды.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio import planner  # noqa: E402

НАБОР = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "brief_wordings.jsonl"

#: Как сказано: две наши формулировки и контроль.
ОПЕРАЦИЯМИ = "операциями"
РЕЗУЛЬТАТОМ = "результатом"
МИМО = "мимо"


def фикстуры(путь: Path = НАБОР) -> list[dict[str, Any]]:
    строки: list[dict[str, Any]] = []
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        строки.append(json.loads(строка))
    return строки


def разобрать(бриф: str) -> list[str]:
    """Имена шагов, которые планировщик СОБИРАЕТ по брифу.

    Меряется то, что получает заказчик, а не промежуточная развилка: с
    2026-09-03 к выведенным подсказками операциям добавляется замыкание по
    нехватке артефактов (`planner.замкнуть`). Мерить одну `derive` значило бы
    считать дырой то, что продукт уже закрывает, — цифра мимо продукта, чем
    уже был оплачен один отчёт (см. хэндоф, «НЕ ДЕЛАТЬ»).
    """
    операции, _ = planner.замкнуть(planner.derive(бриф), planner.inputs_of(бриф))
    return [оп.name for оп in операции]


def неизвестные_имена(набор: list[dict[str, Any]]) -> list[str]:
    """Имена операций в фикстурах обязаны существовать в планировщике.

    Опечатка в ожидании тихо раздувает измеренную дыру: `перевод_речи` вместо
    `дубляж` — и счётчик уверенно рапортует о непокрытом брифе, который на
    самом деле покрыт. Поймано на себе при первом же прогоне (2026-09-03).
    """
    живые = {оп.name for оп in planner.OPERATIONS}
    return sorted({и for с in набор for и in с["ждём"] if и not in живые})


def свести(набор: list[dict[str, Any]]) -> dict[str, Any]:
    чужие = неизвестные_имена(набор)
    if чужие:
        return {
            "outcome": UNMEASURED,
            "checked": len(набор),
            "violations": 0,
            "unmeasured": len(чужие),
            "по формулировке": {},
            "лишние": [],
            "пусто": [],
            "недостача": [],
            "неизвестные": чужие,
        }

    по_формулировке: dict[str, dict[str, int]] = {}
    пусто: list[str] = []
    лишние: list[str] = []
    недостача: list[tuple[str, list[str]]] = []

    for случай in набор:
        бриф = str(случай["бриф"])
        ждём = set(случай["ждём"])
        как = str(случай["как_сказано"])
        вывелось = set(разобрать(бриф))

        счёт = по_формулировке.setdefault(как, {"всего": 0, "полностью": 0, "хоть_что_то": 0})
        счёт["всего"] += 1
        if вывелось >= ждём and (ждём or not вывелось):
            счёт["полностью"] += 1
        if вывелось:
            счёт["хоть_что_то"] += 1

        if как == МИМО:
            if вывелось:
                лишние.append(f"{бриф[:52]} -> {sorted(вывелось)}")
            continue
        if not вывелось:
            пусто.append(бриф[:64])
        elif not вывелось >= ждём:
            недостача.append((бриф[:52], sorted(ждём - вывелось)))

    исход = FAIL if лишние else (UNMEASURED if пусто or недостача else PASS)
    return {
        "outcome": исход,
        "неизвестные": [],
        "checked": len(набор),
        "violations": len(лишние),
        "unmeasured": len(пусто) + len(недостача),
        "по формулировке": по_формулировке,
        "лишние": лишние,
        "пусто": пусто,
        "недостача": недостача,
    }


def main(argv: list[str]) -> int:
    из_гейта = "--check" in argv
    итог = свести(фикстуры())

    for как in (ОПЕРАЦИЯМИ, РЕЗУЛЬТАТОМ, МИМО):
        с = итог["по формулировке"].get(как)
        if not с:
            continue
        print(
            f"  сказано {как:12} брифов {с['всего']:2}, "
            f"операции вывелись у {с['хоть_что_то']:2}, все ожидаемые у {с['полностью']:2}"
        )
    for имя in итог["неизвестные"]:
        print(f"  НЕТ ТАКОЙ ОПЕРАЦИИ В ПЛАНИРОВЩИКЕ: {имя} — фикстура сломана, а не продукт")
    for бриф in итог["пусто"]:
        print(f"  ПУСТОЙ ПЛАН: {бриф}")
    for бриф, чего in итог["недостача"]:
        print(f"  не хватило {чего}: {бриф}")
    for строка in итог["лишние"]:
        print(f"  ЛИШНЯЯ ОПЕРАЦИЯ НА ЧУЖОЙ ЗАДАЧЕ: {строка}")

    print(
        f"\nпроверено {итог['checked']}\nнарушений {итог['violations']}\n"
        f"не смогли {итог['unmeasured']}"
    )
    if итог["outcome"] == FAIL:
        return 1
    # Счётчик, а не гейт: «не смогли» здесь — это измеренная дыра продукта, и
    # она уже названа в отчёте. Красить ею сборку значило бы либо выключить
    # проверку, либо закрыть дыру подгонкой подсказок под фикстуры. Гейт
    # краснеет ровно на лжи: операция, выведенная из чужой задачи.
    return 0 if not из_гейта or итог["outcome"] != UNMEASURED else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
