#!/usr/bin/env python3
"""Есть ли в дереве тесты, которых гейт не запускает.

ЗАЧЕМ

ИЗМЕРЕНО 2026-09-02: `scripts/check` называл модули `studio/tests` поимённо, и
семь файлов не назывался никто — `test_app`, `test_jobs`, `test_ledger`,
`test_lifecycle`, `test_store`, `test_style`, `test_vector_cache`, вместе 127
тестов. Они существовали, проходили при ручном запуске и никогда не гонялись
гейтом. Среди них — тесты модуля, написанного в тот же день.

Это Т6 в чистом виде: «не запускалось» выглядело как «прошло». И это Е1:
поимённый список — второй способ узнать, какие тесты в дереве есть, а второй
способ узнать известное разъезжается с первым молча.

Правило «добавил тест — впиши в гейт» словами не держится (Ц7), поэтому оно
здесь проверкой: файл `test_*.py` обязан попадать либо в каталог, который гейт
перебирает `unittest discover`, либо в поимённый список.

ТРИ ИСХОДА (Р1)

    годно      каждый файл тестов достижим гейтом
    не годно   есть файл, которого гейт не запускает
    не смогли  гейт не прочитан, или каталог перебора не импортируется

НЕГАТИВНЫЙ КОНТРОЛЬ (И5): `--самопроверка` заводит во временном дереве файл
тестов вне всяких корней и требует, чтобы проверка его нашла. Без этого
«нарушений 0» может означать «ничего не искали».
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parents[1]
ГЕЙТ = КОРЕНЬ / "scripts" / "check"

#: Где вообще ищутся тесты. Каталоги вне этого списка — не наш код
#: (виртуальные окружения, рабочие копии агентов, кэш).
ОБЛАСТЬ = ("lipsync", "studio", "scripts")

#: Как гейт запускает тесты. Обе формы читаются из самого гейта, а не
#: переписываются сюда (Е1): список, скопированный в проверку, разъедется
#: с гейтом ровно так же, как гейт разъехался с каталогом.
#: ДВЕ ФОРМЫ ПЕРЕБОРА, А НЕ ОДНА. С 2026-09-04 гейт зовёт каталоги через
#: `scripts/run_tests.py`, который держит запрет сети (правило Т4). Прежний
#: `unittest discover -s ...` оставлен в образце намеренно: он законен при
#: ручном прогоне, и проверка не должна объявлять его невидимым.
ПЕРЕБОР = re.compile(r"unittest\s+discover\s+-s\s+(\S+)|run_tests\.py\s+(\S+)")
ПОИМЁННО = re.compile(r"unittest\s+((?:[\w.]+\s*)+)$", re.M)

#: `unittest discover` берёт по умолчанию `test*.py`. Файл, названный иначе,
#: перебором не подхватится, даже лёжа в корне перебора и содержа TestCase.
ОБРАЗЕЦ = "test*.py"

#: Что вообще считается файлом тестов при обходе дерева. Шире, чем ОБРАЗЕЦ, и
#: НАМЕРЕННО: `foo_test.py` в каталоге перебора выглядит тестом для человека и
#: невидим для `unittest discover`. Ищи только по образцу перебора — и такой
#: файл не попадёт ни в найденные, ни в пропущенные, то есть исчезнет.
ИМЕНА_ТЕСТОВ = ("test_*.py", "*_test.py", "tests_*.py")


def строки_гейта(путь: Path = ГЕЙТ) -> list[str]:
    return путь.read_text(encoding="utf-8").splitlines()


def корни_перебора(строки: list[str]) -> list[str]:
    корни: list[str] = []
    for с in строки:
        м = ПЕРЕБОР.search(с)
        if м:
            корни.append((м.group(1) or м.group(2)).rstrip("/"))
    return корни


def названные_модули(строки: list[str]) -> set[str]:
    имена: set[str] = set()
    for с in строки:
        if "discover" in с or "run_tests.py" in с:
            continue
        м = ПОИМЁННО.search(с.strip())
        if not м:
            continue
        for слово in м.group(1).split():
            if "." in слово:
                имена.add(слово)
    return имена


def файлы_тестов(корень: Path = КОРЕНЬ, область: tuple[str, ...] = ОБЛАСТЬ) -> list[Path]:
    найдено: list[Path] = []
    for каталог in область:
        основа = корень / каталог
        if not основа.is_dir():
            continue
        пути = {п for образец in ИМЕНА_ТЕСТОВ for п in основа.rglob(образец)}
        for путь in sorted(пути):
            # Рабочие копии других агентов — не наше дерево (Ц2).
            if any(часть in {".claude", "__pycache__", "node_modules"} for часть in путь.parts):
                continue
            найдено.append(путь)
    return найдено


def модуль(путь: Path, корень: Path = КОРЕНЬ) -> str:
    return str(путь.relative_to(корень).with_suffix("")).replace("/", ".")


def подпакет(каталог: Path, корень_перебора: Path) -> bool:
    """Достаёт ли перебор из `корень_перебора` файлы в `каталог`.

    `unittest discover` спускается в ПОДПАКЕТЫ, то есть в подкаталоги, где
    лежит `__init__.py`, и останавливается на первом, где его нет. Сравнивать
    только сам корень значило бы объявлять «гейт не запускает» файл, который
    гейт прекрасно запускает, — ложная тревога учит выключать проверку.
    """
    try:
        путь_вниз = каталог.relative_to(корень_перебора)
    except ValueError:
        return False
    if not (корень_перебора / "__init__.py").is_file():
        # Каталог перебора без `__init__.py` вообще не импортируется: сам
        # `unittest discover` падает на нём с ImportError. Это «не смогли»,
        # а не «достижим» — и ровно этим был закрыт `studio/tests`.
        return False
    текущий = корень_перебора
    for шаг in путь_вниз.parts:
        текущий = текущий / шаг
        if not (текущий / "__init__.py").is_file():
            return False
    return True


def достижим(путь: Path, корни: list[str], модули: set[str], корень: Path = КОРЕНЬ) -> str | None:
    """Чем именно гейт берёт этот файл, или None — если ничем."""
    if модуль(путь, корень) in модули:
        return "назван поимённо"
    if путь.match(ОБРАЗЕЦ):
        for к in корни:
            if подпакет(путь.parent, корень / к.rstrip("/")):
                return f"перебор {к}"
    return None


def проверить(корень: Path = КОРЕНЬ, гейт: Path = ГЕЙТ) -> dict[str, Any]:
    if not гейт.is_file():
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "note": f"гейт не прочитан: {гейт}",
            "мимо": [],
            "не смогли": [],
        }
    строки = строки_гейта(гейт)
    корни = корни_перебора(строки)
    модули = названные_модули(строки)
    файлы = файлы_тестов(корень)

    мимо: list[str] = []
    не_смогли: list[str] = []
    for путь in файлы:
        чем = достижим(путь, корни, модули, корень)
        if чем:
            continue
        # Различаются ДВЕ причины недостижимости, и они не один исход (Р1).
        # Разорванная цепочка `__init__.py` — «не смогли»: каталог назван в
        # гейте, и что там внутри, отсюда не выясняется. Имя мимо образца при
        # целой цепочке — именно «не годно»: файл на месте, гейт его не берёт.
        разорвана = any(
            ((корень / к.rstrip("/")) == путь.parent or (корень / к.rstrip("/")) in путь.parents)
            and not подпакет(путь.parent, корень / к.rstrip("/"))
            for к in корни
        )
        (не_смогли if разорвана else мимо).append(путь.relative_to(корень).as_posix())

    исход = FAIL if мимо else (UNMEASURED if не_смогли else PASS)
    нота = (
        f"гейт не запускает {len(мимо)} файл(ов) тестов"
        if мимо
        else (
            f"каталог перебора без __init__.py: {len(не_смогли)}"
            if не_смогли
            else f"все {len(файлы)} файлов тестов достижимы: перебором {len(корни)} каталогов "
            f"и {len(модули)} поимённых модулей"
        )
    )
    return {
        "outcome": исход,
        "checked": len(файлы),
        "violations": len(мимо),
        "unmeasured": len(не_смогли),
        "note": нота,
        "мимо": мимо,
        "не смогли": не_смогли,
    }


def самопроверка() -> int:
    """И5: подложить файл тестов мимо всех корней и потребовать, чтобы нашли."""
    with tempfile.TemporaryDirectory() as врем:
        корень = Path(врем)
        (корень / "scripts").mkdir()
        (корень / "studio" / "tests").mkdir(parents=True)
        (корень / "studio" / "tests" / "__init__.py").touch()
        (корень / "studio" / "tests" / "test_видимый.py").touch()
        (корень / "studio" / "test_невидимый.py").touch()
        гейт = корень / "scripts" / "check"
        гейт.write_text("python -m unittest discover -s studio/tests -t .\n", encoding="utf-8")
        итог = проверить(корень, гейт)
        плохо = итог["violations"] != 1 or итог["мимо"] != ["studio/test_невидимый.py"]
        print(
            "негативный контроль: подложенный мимо корней файл "
            + ("НЕ НАЙДЕН — проверка слепа" if плохо else "найден")
        )
        return 1 if плохо else 0


def main(argv: list[str]) -> int:
    # Флагов нет намеренно: у скрипта один режим — проверка. Флаг, который
    # ничего не меняет, читается как выбор и однажды будет «выключен».
    argparse.ArgumentParser(description=__doc__).parse_args(argv)

    if самопроверка():
        print("\nпроверено 0\nнарушений 0\nне смогли 1")
        return 2

    итог = проверить()
    for имя in итог["мимо"][:20]:
        print(f"  ГЕЙТ НЕ ЗАПУСКАЕТ: {имя}")
    for имя in итог["не смогли"][:20]:
        print(f"  не смогли проверить (разорвана цепочка __init__.py): {имя}")
    print(f"\n{итог['note']}")
    print(
        f"\nпроверено {итог['checked']}\nнарушений {итог['violations']}\n"
        f"не смогли {итог['unmeasured']}"
    )
    return 0 if итог["outcome"] == PASS else (1 if итог["outcome"] == FAIL else 2)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
