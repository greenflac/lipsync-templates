#!/usr/bin/env python3
"""Раннер тестов, который ДЕРЖИТ ЗАПРЕТ СЕТИ САМ.

ЗАЧЕМ ОН ЕСТЬ. Правило Т4 требует, чтобы тест не ходил в сеть и чтобы это
обеспечивал РАННЕР, а не договорённость. ИЗМЕРЕНО 2026-09-04: запрет держали
16 файлов из 107 — каждый своей парой `setUpModule`/`tearDownModule`. Значит
новый тест, открывший сокет, не заметил бы никто: он попадал бы в остальные
91 файл, краснел бы от чужой аварии и зеленел бы от кэша, а прочитать это по
выдаче было бы нельзя.

ЧТО ИМЕННО ЗАПРЕЩЕНО. Подменяются `socket.socket` и `socket.create_connection`
— те же две точки, что подменяют файлы вручную (Е1: способ один, место одно).
Этого достаточно: `urllib`, `requests` и `httpx` открывают соединение через
них. Локальный сервер не поднимает ни один тест репозитория (проверено
поиском `bind(`, `HTTPServer`, `127.0.0.1` по всем `test_*.py` — 0 совпадений),
поэтому исключения для петли не нужно, а нужное появится — оно будет здесь и
с именем, а не россыпью по файлам.

НЕГАТИВНЫЙ КОНТРОЛЬ ВНУТРИ ПРИБОРА (И5). Прежде чем звать тесты, раннер сам
пробует открыть сокет и обязан получить отказ. Молча установленный запрет,
который на деле не установился, — это худший исход: он выглядит как защита.
Проверка печатается строкой, а не подразумевается.

ЧУЖИЕ ФАЙЛЫ НЕ ПРАВЛЮ (Ц2). Шестнадцать файлов со своим запретом оставлены
как есть: они написаны другими авторами, их запрет не мешает и продолжает
работать при прямом запуске `python -m unittest`. Дубль знания здесь
осознанный и записан: раннер — обязательный слой, файловый — необязательный.

ТРИ ИСХОДА (Р1):
    годно      тесты прошли и запрет проверен
    не годно   тест упал или запрет НЕ установился
    не смогли  каталога нет — нечего запускать, и это не успех
"""

from __future__ import annotations

import socket
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Что видит тест, полезший в сеть. Текст называет ПРАВИЛО, а не только факт:
#: читать это будет тот, кто такой тест написал.
ОТКАЗ = "правило Т4: тест не ходит в сеть, и это держит раннер (scripts/run_tests.py)"


def _отказать(*_args, **_kwargs):
    raise AssertionError(ОТКАЗ)


_НАСТОЯЩИЙ_СОКЕТ = socket.socket


class _БезСети(_НАСТОЯЩИЙ_СОКЕТ):  # type: ignore[misc,valid-type]
    """Сокет, который создаётся, но никуда не соединяется.

    ЗАПРЕЩАЕТСЯ СОЕДИНЕНИЕ, А НЕ СОЗДАНИЕ ОБЪЕКТА, и это не тонкость.
    Первая редакция подменяла сам класс `socket.socket` функцией — ровно так
    это сделано в шестнадцати файлах вручную, — и прогон рассыпался на 32
    ошибках импорта: `unittest.mock` тянет `asyncio`, а `asyncio` при импорте
    берёт у `socket.socket` атрибуты класса. Файловый запрет этого не замечал
    потому, что ставился ПОСЛЕ импорта модуля; раннер ставит его до, и ошибка
    вылезла сразу. Наследник ведёт себя как настоящий сокет во всём, кроме
    `connect`.
    """

    def connect(self, *_args, **_kwargs):
        raise AssertionError(ОТКАЗ)

    def connect_ex(self, *_args, **_kwargs):
        raise AssertionError(ОТКАЗ)


def запретить_сеть() -> None:
    socket.socket = _БезСети  # type: ignore[misc,assignment]
    socket.create_connection = _отказать  # type: ignore[assignment]


def сеть_закрыта() -> bool:
    """Негативный контроль: прибор обязан УМЕТЬ сказать «нет».

    Проверяется ИМЕННО СОЕДИНЕНИЕ и на настоящем адресе-заглушке: «объект
    создался» ничего не доказывает, а доказывает отказ на попытке дойти.
    """
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.connect(("192.0.2.1", 80))
    except AssertionError:
        return True
    except Exception:  # pragma: no cover - иная ошибка тоже не разрешение
        return False
    return False


def main(argv: list[str]) -> int:
    if not argv:
        print("не смогли: не назван каталог тестов")
        return 2
    каталог = ROOT / argv[0]
    if not каталог.is_dir():
        print(f"не смогли: каталога {argv[0]} нет — запускать нечего")
        return 2

    запретить_сеть()
    if not сеть_закрыта():
        print("не годно: запрет сети НЕ установился — прогон остановлен")
        return 1
    print(f"запрет сети: установлен и проверен (негативный контроль прошёл); {argv[0]}")

    sys.path.insert(0, str(ROOT))
    набор = unittest.defaultTestLoader.discover(str(каталог), top_level_dir=str(ROOT))
    итог = unittest.TextTestRunner(verbosity=1).run(набор)
    return 0 if итог.wasSuccessful() else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
