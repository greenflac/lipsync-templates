#!/usr/bin/env python3
"""Какие модули с КОНСТАНТАМИ-РЕШЕНИЯМИ остались без единого мутанта (R7).

ЗАЧЕМ. Критерий релиза R7 требует «покрыты все модули с константами-решениями»,
и до 2026-09-04 число «двадцать модулей без мутантов» я написал глазами. Глазами
же его и оспорить нельзя: под «константой-решением» каждый читатель понимает
своё. Прибор вместо суждения (Ц7) — и заодно определение, которое можно
оспорить по существу.

ЧТО СЧИТАЕТСЯ КОНСТАНТОЙ-РЕШЕНИЕМ. Имя в ВЕРХНЕМ РЕГИСТРЕ, присвоенное на
уровне модуля И упомянутое в этом же модуле внутри УСЛОВИЯ: в `if`/`while`, в
сравнении, в проверке вхождения, в тернарном выражении. Это механическое
приближение к правилу дома («любое значение, от которого зависит ветвление»), и
оно НАМЕРЕННО у́же наивного «все заглавные»: таблицы данных, перечни фикстур и
словари печати ветвлений не решают, а их в репозитории больше всего — на
2026-09-04 наивный счёт давал 80 модулей против 16 покрытых, и разговор об этом
числе был бы разговором ни о чём.

ЧЕГО ОНО НЕ ЛОВИТ, НАЗВАНО ВСЛУХ (И6): константу, которую читает ДРУГОЙ модуль
(`facts.TIER_PROBE` в `factaxis`), и константу, попавшую в условие через
промежуточную переменную. Оба случая — недооценка, то есть прибор скорее
пропустит модуль, чем припишет лишний.

ТРИ ИСХОДА (Р1):
    годно      каждый модуль с константами-решениями упомянут в таблице мутантов
    не годно   есть непокрытые
    не смогли  таблицы мутантов не прочитались — считать не по чему
"""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Где живут таблицы мутантов. Читаются как ТЕКСТ и по образцу пути: разбирать
#: их как питон значило бы исполнять скрипт, который правит исходники.
ТАБЛИЦЫ = ("scripts/mutate_channels.py", "scripts/mutate_planner.py")
ПУТЬ_В_ТАБЛИЦЕ = re.compile(r'"((?:studio|scripts|lipsync)/[\w/]+\.py)"')

#: Каталоги, которые не считаются продуктом: тесты проверяют, а не решают.
НЕ_ПРОДУКТ = ("/tests/", "/fixtures/", "/.claude/")


def покрытые() -> set[str]:
    пути: set[str] = set()
    for имя in ТАБЛИЦЫ:
        файл = ROOT / имя
        if not файл.exists():
            return set()
        пути |= set(ПУТЬ_В_ТАБЛИЦЕ.findall(файл.read_text(encoding="utf-8")))
    return пути


def решающие_константы(исходник: str) -> set[str]:
    """Имена верхнего регистра, от которых в этом же модуле зависит ветвление."""
    дерево = ast.parse(исходник)
    объявлены: set[str] = set()
    for узел in дерево.body:
        цели: list[ast.expr] = []
        if isinstance(узел, ast.Assign):
            цели = list(узел.targets)
        elif isinstance(узел, ast.AnnAssign):
            цели = [узел.target]
        for ц in цели:
            if isinstance(ц, ast.Name) and ц.id.isupper() and len(ц.id) > 2:
                объявлены.add(ц.id)
    if not объявлены:
        return set()

    решают: set[str] = set()

    def имена(узел: ast.AST) -> set[str]:
        return {у.id for у in ast.walk(узел) if isinstance(у, ast.Name) and у.id in объявлены}

    # ИМЯ ПЕРЕМЕННОЙ ДРУГОЕ, И ЭТО НЕ КОСМЕТИКА: выше `узел` перебирал только
    # верхний уровень (`ast.stmt`), здесь — всё дерево (`ast.AST`), и проверка
    # типов честно сказала, что во второй раз в ту же переменную кладут иное.
    for место in ast.walk(дерево):
        if isinstance(место, (ast.If, ast.While, ast.IfExp)):
            решают |= имена(место.test)
        elif isinstance(место, ast.Compare):
            решают |= имена(место)
    return решают


def _в_репозитории() -> set[str] | None:
    """Файлы, которые ЕСТЬ У ЧИТАТЕЛЯ, а не только у меня. None — git не ответил.

    ЗАЧЕМ. Знаменатель, посчитанный по рабочему дереву, включает файлы, которых
    в репозитории нет, и тогда потолок — число, верное там, где я стою, и
    неверное там, где стоит читатель. Ровно этот класс ошибки за 2026-09-04
    встретился трижды: цена «13 316 промптов» на пустом клоне, наличие корпуса,
    и вот теперь собственный ратчет. Прибор обязан считать по тому же
    множеству, что увидит CI.
    """
    готово = subprocess.run(
        ["git", "ls-files", "studio", "lipsync", "scripts"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if готово.returncode != 0:
        return None
    найдено = {с for с in готово.stdout.split() if с.endswith(".py")}
    # ПУСТОЙ ОТВЕТ — ЭТО НЕ «НИ ОДНОГО ФАЙЛА». Дерево без индекса (свежая
    # распаковка, worktree без checkout) отвечает нулём файлов с кодом 0, и
    # прежний разбор честно фильтровал по нему ВСЁ: «проверено 0, нарушений 0»
    # и зелёный гейт. Ноль нарушений при нуле проверок — не успех (Р2).
    return найдено or None


def модули() -> list[Path]:
    из_гита = _в_репозитории()
    найдены = []
    for каталог in ("studio", "lipsync", "scripts"):
        for путь in (ROOT / каталог).rglob("*.py"):
            имя = str(путь.relative_to(ROOT))
            if any(к.strip("/") in имя.split("/") for к in ("tests", "fixtures")):
                continue
            if из_гита is not None and имя not in из_гита:
                continue
            найдены.append(путь)
    return sorted(найдены)


#: Сколько модулей с константами-решениями сегодня без мутантов. ИЗМЕРЕНО
#: 2026-09-04 этим же скриптом: 106 модулей с такими константами, под мутантами
#: 21, без мутантов 85.
#:
#: ЧИСЛО СТОИТ ЗДЕСЬ ПОТОЛКОМ, А НЕ ЦЕЛЬЮ, И ЭТО РАЗНЫЕ ВЕЩИ. Требовать ноль
#: сегодня значило бы держать гейт красным неделю и на второй день его
#: выключить. Потолок запрещает РОСТ: новый модуль с константой-решением и без
#: мутанта красит гейт немедленно, а старый долг виден числом и уменьшается
#: отдельными шагами. Потолок обязан только падать; поднявший его обязан
#: объяснить это в том же коммите.
#:
#: ПОПРАВКА К БЛЮПРИНТУ, НАЗВАННАЯ ВСЛУХ. В `docs/RELEASE_BLUEPRINT.md` у R7
#: стояло «20 модулей без мутантов» — я написал это глазами и ошибся вчетверо.
#: Настоящее число 85, и разница не в определении: даже по узкому определению
#: этого скрипта (константа обязана участвовать в ветвлении ЭТОГО ЖЕ модуля)
#: непокрытых в четыре раза больше, чем я думал.
#: 2026-09-06: 37 -> 36 -> 35 -> 34 -> 33. Сначала под собственных мутантов встал сам этот
#: прибор (чинились его же нарушения Е2 и Р2), затем `studio/measured.py` —
#: адрес измеренных чисел, где списки происхождений и исходов это правила И4 и
#: Р1, записанные данными; затем `studio/corpus.py` — наборы применимости и
#: свидетельства, из которых можно было молча вынуть самое частое имя.
#: Потолок обязан только падать.
ПОТОЛОК = 33


def свести(потолок: int | None = None) -> dict:
    """Итог. `outcome` считается ОТНОСИТЕЛЬНО ПОТОЛКА, а не по наличию долга.

    Печаталось `fail` при долге ровно по потолку — и возвращался ноль. Флаг и
    свидетельство расходились (Е2), и читающий отчёт видел «fail» там, где гейт
    зелёный, а значит переставал верить обоим.
    """
    таблицы = покрытые()
    if not таблицы:
        return {"outcome": "could not measure", "note": "таблицы мутантов не прочитались"}
    с_константами: list[tuple[str, int]] = []
    # НЕ РАЗОБРАЛОСЬ — ЭТО ТРЕТИЙ ИСХОД, А НЕ ПУСТОЕ МЕСТО. `unmeasured` стоял
    # литеральным нулём, а `SyntaxError` глушился молча: половина дерева могла
    # не разобраться, и прибор напечатал бы «проверено 54, нарушений 16, не
    # смогли 0» — а ратчет по этому числу потребовал бы опустить потолок, то
    # есть принять решение по несостоявшемуся измерению (Р2, Е3). Найдено
    # независимой проверкой 2026-09-06 в том же файле, который накануне чинили
    # ради Р2.
    не_разобрались: list[str] = []
    for путь in модули():
        имя = str(путь.relative_to(ROOT))
        try:
            решают = решающие_константы(путь.read_text(encoding="utf-8"))
        except (SyntaxError, ValueError, UnicodeDecodeError):
            не_разобрались.append(имя)
            continue
        if решают:
            с_константами.append((имя, len(решают)))
    if not с_константами:
        return {
            "outcome": "could not measure",
            "note": "ни одного модуля с константами-решениями не нашлось — считать нечего",
        }
    непокрытые = [(и, н) for и, н in с_константами if и not in таблицы]
    порог = ПОТОЛОК if потолок is None else потолок
    return {
        "outcome": ("pass" if len(непокрытые) == порог else "fail")
        if not не_разобрались
        else "fail",
        "checked": len(с_константами),
        "violations": len(непокрытые),
        "unmeasured": len(не_разобрались),
        "не_разобрались": sorted(не_разобрались),
        "покрыто": len(с_константами) - len(непокрытые),
        "непокрытые": sorted(непокрытые, key=lambda п: -п[1]),
    }


def main(argv: list[str]) -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--check", action="store_true", help="код возврата по исходу")
    разбор.add_argument("--top", type=int, default=12, help="сколько непокрытых печатать")
    дано = разбор.parse_args(argv)
    итог = свести()
    if итог["outcome"] == "could not measure":
        print(f"не смогли: {итог['note']}")
        return 2 if дано.check else 0
    for имя, число in итог["непокрытые"][: дано.top]:
        print(f"  БЕЗ МУТАНТОВ {число:3} констант(ы)-решения: {имя}")
    печать = len(итог["непокрытые"]) - дано.top
    if печать > 0:
        print(f"  … и ещё {печать} модуль(ей)")
    for имя in итог.get("не_разобрались", []):
        print(f"  НЕ РАЗОБРАЛСЯ {имя}: считать по нему нечего, и это не ноль констант")
    print()
    print(f"проверено {итог['checked']}")
    print(f"нарушений {итог['violations']}")
    print(f"не смогли {итог['unmeasured']}")
    print()
    print(
        f"{итог['outcome']}: модулей с константами-решениями {итог['checked']}, "
        f"под мутантами {итог['покрыто']}, без мутантов {итог['violations']}"
    )
    if итог["violations"] > ПОТОЛОК:
        print(
            f"НЕ ГОДНО: без мутантов {итог['violations']} при потолке {ПОТОЛОК} — "
            "долг вырос. Заведите мутанта на новый модуль или объясните рост."
        )
        return 1 if дано.check else 0
    if итог["violations"] < ПОТОЛОК:
        print(
            f"ПОТОЛОК УСТАРЕЛ: без мутантов {итог['violations']} при потолке "
            f"{ПОТОЛОК} — опустите ПОТОЛОК до {итог['violations']}, иначе он "
            "перестанет ловить рост."
        )
        return 1 if дано.check else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
