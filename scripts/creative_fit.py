#!/usr/bin/env python3
"""Готовый креатив против того, что модели ПРИНИМАЮТ.

ЗАЧЕМ

«Бот помогает собирать пайплайн на основе готового креатива» — так владелец
назвал цель. Инструмент креатив меряет (`analyse_creative` отдаёт 1536x2752),
а с пределами моделей не сравнивает: ИЗМЕРЕНО 2026-09-02, в плане по такому
кадру `max_resolution` встречается ровно один раз — как строка доказательства
выбранной модели, а не как проверка. Замеры креатива были украшением.

ЧТО ЭТОТ СКРИПТ ДЕЛАЕТ

Берёт кадр (файл креатива или числа), берёт ВСЕ строки базы про разрешение и
отвечает по каждой модели одним из трёх: влезает, не влезает, не записано.
Разбор строки — `studio/resolution.py`, значения фактов не переписываются.

ПОЧВА ТОНКАЯ, И ЭТО ЧАСТЬ ОТВЕТА (Р2)

Разрешение записано у 41 модели из 505. На 92% кандидатов ответ будет «не
записано» — не поломка, а состояние базы, и печатается оно рядом с числами,
потому что «модель не подходит» и «мы не знаем, подходит ли» — разные новости
и разные следующие шаги.

ТРИ ИСХОДА (Р1)

    годно      кадр измерен, сравнение посчитано
    не годно   кадр не влезает НИ В ОДНУ модель с записанным пределом
    не смогли  кадр не измерен, или пределов в базе нет вовсе
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from studio import resolution as R  # noqa: E402
from studio.selfrag.facts import load_facts  # noqa: E402

#: Атрибуты, в которых лежит предел кадра. Подстрокой `resolution`, а не
#: списком: вендоры заводят новые имена (`native_resolution`,
#: `resolution_tiers`, `resolutions_vertex`), и список отставал бы молча.
#: `training_resolution` исключён поимённо — это разрешение ОБУЧЕНИЯ, а не
#: предел входа, и сравнивать с ним креатив значит отвечать не на тот вопрос.
КРОМЕ: frozenset[str] = frozenset({"training_resolution"})


def кадр_из_файла(путь: str) -> tuple[tuple[int, int] | None, str]:
    """Стороны креатива. Меряет тот же прибор, что и `analyse_creative` (Е1)."""
    from studio.mcp import creative

    итог = creative.analyse(путь)
    м = ((итог.get("parts") or {}).get("look") or {}).get("measurements") or {}
    ш, в = м.get("width"), м.get("height")
    if not ш or not в:
        return (None, f"креатив не измерен: {str(итог.get('note'))[:120]}")
    return ((int(ш), int(в)), f"{ш}x{в}")


def пределы() -> list[tuple[str, str, str]]:
    """Строки базы про разрешение: модель, атрибут, значение."""
    return [
        (ф.model, ф.attribute, str(ф.value))
        for ф in load_facts()
        if "resolution" in ф.attribute and ф.attribute not in КРОМЕ
    ]


def сверить(кадр: tuple[int, int]) -> dict[str, Any]:
    """Кадр против каждой записанной строки. Р2: три числа рядом с исходом."""
    влезло: list[tuple[str, str]] = []
    не_влезло: list[tuple[str, str]] = []
    не_разобрали: list[tuple[str, str]] = []
    модели = set()
    for модель, атрибут, значение in пределы():
        модели.add(модель)
        итог = R.влезает(кадр, R.разобрать(значение))
        строка = (модель, f"{атрибут}: {итог['note']}")
        {"годно": влезло, "не годно": не_влезло, "не смогли": не_разобрали}[итог["outcome"]].append(
            строка
        )
    всего = len({ф.model for ф in load_facts()})
    return {
        "влезло": влезло,
        "не влезло": не_влезло,
        "не разобрали": не_разобрали,
        "моделей с пределом": len(модели),
        "моделей в базе": всего,
    }


#: Сколько строк базы про разрешение разбор обязан понимать. ИЗМЕРЕНО
#: 2026-09-02 на ТОМ ЖЕ наборе, который берёт эта проверка: 44 из 45.
#: Первый раз пол был поставлен по числу 45 из 46 — замеру ДРУГОГО набора, в
#: который входило `training_resolution`, и гейт покраснел сразу. Пол ставится
#: прогоном, а не памятью о соседнем прогоне. Пол, а не равенство: строки
#: добавляются, и требовать точного числа значило бы краснеть от пополнения
#: базы. Молча разучиться разбирать — нельзя: разбор, переставший понимать
#: «720p», отвечал бы «не записано» там, где записано, и это ровно тот класс
#: дефекта, за который сегодня заведён `scripts/check_headline.py`.
ПОЛ_РАЗБОРА = 44


def проверка() -> tuple[int, int, int]:
    """Сколько строк про разрешение разбирается сейчас. Сети нет."""
    строки = пределы()
    разобрано = sum(1 for _, _, з in строки if R.разобрать(з).outcome == "годно")
    return (разобрано, len(строки), ПОЛ_РАЗБОРА)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="без сети: пол разбора")
    parser.add_argument("creative", nargs="?", help="файл креатива")
    parser.add_argument("--size", help="стороны через x, если файла нет: 1536x2752")
    args = parser.parse_args(argv)

    if args.check:
        разобрано, всего, пол = проверка()
        годно = разобрано >= пол
        print(
            ("годно" if годно else "не годно")
            + f": строк про разрешение {всего}, разобрано {разобрано} (пол {пол})"
        )
        print(f"\nпроверено {всего}\nнарушений {0 if годно else 1}\nне смогли {всего - разобрано}")
        return 0 if годно else 1

    if args.size:
        try:
            ш, в = (int(ч) for ч in args.size.lower().split("x"))
        except ValueError:
            print(f"не смогли: --size {args.size!r} не разобран как ШИРИНАxВЫСОТА")
            return 2
        кадр, как = (ш, в), args.size
    elif args.creative:
        кадр, как = кадр_из_файла(args.creative)
        if кадр is None:
            print(f"не смогли: {как}")
            return 2
    else:
        print("не смогли: не назван ни файл креатива, ни --size")
        return 2

    итог = сверить(кадр)
    print(f"креатив {как}: длинная сторона {max(кадр)}, короткая {min(кадр)}\n")
    for имя, строки in (("ВЛЕЗАЕТ", итог["влезло"]), ("НЕ ВЛЕЗАЕТ", итог["не влезло"])):
        for модель, почему in sorted(строки)[:12]:
            print(f"  {имя:11} {модель[:26]:28} {почему[:72]}")
        лишних = len(строки) - 12
        if лишних > 0:
            print(f"  {имя:11} ... и ещё {лишних}")
    print(
        f"\nпределов записано у {итог['моделей с пределом']} моделей из "
        f"{итог['моделей в базе']}: у остальных ответ «не записано», и это НЕ «подходит»"
    )
    print(
        f"\nпроверено {len(итог['влезло']) + len(итог['не влезло'])}\n"
        f"нарушений {len(итог['не влезло'])}\nне смогли {len(итог['не разобрали'])}"
    )
    if not итог["влезло"] and not итог["не влезло"]:
        return 2
    return 1 if not итог["влезло"] else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
