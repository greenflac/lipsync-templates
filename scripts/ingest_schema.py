#!/usr/bin/env python3
"""Схема эндпоинта: ЧТО МОДЕЛЬ ПРИНИМАЕТ НА ВХОД, словами самой площадки.

ЗАЧЕМ

Планировщик научился отсекать кандидата, которому вход запрещён, и кандидата,
чей предел кадр не принимает. Оба вопроса упираются в одно: что модель вообще
берёт. Ответ на это площадка отдаёт МАШИННО — по адресу
`fal.ai/api/openapi/queue/openapi.json?endpoint_id=...` лежит OpenAPI входа.

ИЗМЕРЕНО 2026-09-02 на семи эндпоинтах липсинка: ответили 5, у двух адрес
молчит. В ответивших схемах:

    image_url 18   prompt 16   audio_url 16   video_url 9   end_image_url 4
    resolution enum ['480p','720p']  (infinitalk)
    num_frames maximum 721           (infinitalk)

ЧТО ЗАПИСЫВАЕТСЯ, И ПОЧЕМУ ТОЛЬКО ЭТО

Три вещи, каждая — ПРИСУТСТВИЕ поля или его перечисление, то есть факт, а не
толкование:

    accepts_inputs        какие входы эндпоинт принимает (по именам полей)
    resolution_enum       если схема называет `resolution` перечислением
    duration_enum_seconds если схема называет `duration` перечислением

Остальные поля схемы (`seed`, `acceleration`, `prompt`) в базу не идут:
записать «есть поле seed» значит набрать строку, на которую никто не задаёт
вопроса. Эта ошибка на этом проекте разбиралась дважды и оба раза кончалась
метаданными вместо знания.

ТИР И РОД. `portal` и `schema`: это то, что площадка ОБЪЯВЛЯЕТ принимать.
Способность, а не применимость: схема не обещает, что результат хорош.

ТРИ ИСХОДА (Р1)

    годно      схема прочитана, находки записаны
    не годно   ответ не разобрался как OpenAPI со схемой входа
    не смогли  адрес не ответил (Ц3: закрытое не обходим)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio.mcp import fetch  # noqa: E402
from studio.selfrag import modelnames  # noqa: E402

СХЕМА = "https://fal.ai/api/openapi/queue/openapi.json?endpoint_id={эндпоинт}"
ПАУЗА = 0.3

#: КАКОЙ ВИД ВХОДА ПРИНИМАЕТ ЭНДПОИНТ — ПО ФОРМЕ ИМЕНИ ПОЛЯ, А НЕ ПО СПИСКУ.
#:
#: Первая версия держала закрытый список имён (`image_url`, `video_url`, ...),
#: и он ПРОМАХНУЛСЯ на живом заходе. В базу ушло:
#:
#:     kling-video-o1-image-to-video / accepts_inputs = «текст»
#:
#: у эндпоинта, который берёт `start_image_url` и `end_image_url`. Изображение
#: он принимает — а база сказала, что нет. Ложное отрицание, записанное как
#: факт, хуже отсутствия строки: по нему планировщик отвергнет годного
#: кандидата и не скажет почему.
#:
#: ИЗМЕРЕНО 2026-09-02 на 37 схемах очереди портала: 102 различных имени поля.
#: Правило выведено из них, а не придумано:
#:
#:     медиа — имя КОНЧАЕТСЯ на `_url`/`_urls` и содержит image|video|audio
#:     текст — имя содержит `prompt` или `text` отдельным словом
#:
#: Оба правила проверены на всех 102 именах: взяты 19 настоящих входов
#: (включая `start_image_url`, `driven_audio_url`, `reference_pose_video_url`,
#: `multi_prompt`), НЕ взяты восемь, где слово есть, а входа нет:
#:
#:     generate_audio       переключатель вывода, а не вход
#:     preserve_audio       флаг обработки
#:     use_only_first_audio флаг
#:     image_size, num_images, video_quality, video_write_mode  настройки
#:     negative_prompt      уточнение промпта, а не сам вход
#:
#: Суффикс `_url` и есть тот разделитель, который отличает вход от флага:
#: подстрока «audio» без него ловит `generate_audio`.
#:
#: СПИСОК ИМЁН ТЕКСТА РАСТЁТ ОТ ДАННЫХ, А НЕ ОТ ФАНТАЗИИ. `script` добавлен
#: третьим заходом: `mirage-api/avatar-x/text-to-video` называет текст именно
#: так, и без него у эндпоинта «text-to-video» в базу ушло «принимает: аудио,
#: видео» — снова ложное отрицание. Каждое новое имя сюда попадает после того,
#: как его увидели в живой схеме.
МЕДИА_ПОЛЕ = re.compile(r"_urls?$", re.I)
ВИД_ВХОДА = re.compile(r"(image|video|audio)", re.I)
ТЕКСТ_ПОЛЕ = re.compile(r"(^|_)(prompt|text|script)(_|$)", re.I)
НЕ_ВХОД = re.compile(r"^negative_", re.I)

ПО_РУССКИ = {"image": "изображение", "video": "видео", "audio": "аудио", "text": "текст"}


def вид_входа(поле: str) -> str:
    """Вид входа по имени поля, или пусто. Пусто — законный исход."""
    имя = str(поле or "")
    if НЕ_ВХОД.match(имя):
        return ""
    if МЕДИА_ПОЛЕ.search(имя):
        м = ВИД_ВХОДА.search(имя)
        if м:
            return ПО_РУССКИ[м.group(1).lower()]
    if ТЕКСТ_ПОЛЕ.search(имя):
        return ПО_РУССКИ["text"]
    return ""


#: Поля-перечисления, у которых есть свой вопрос в базе. Имя атрибута берётся
#: то же, что уже стоит в базе (`resolution_enum`, `duration_enum_seconds`), —
#: иначе семья атрибутов получит шестое написание одного и того же.
ПЕРЕЧИСЛЕНИЯ: dict[str, str] = {
    "resolution": "resolution_enum",
    "duration": "duration_enum_seconds",
}


#: ЧТО МОДЕЛЬ ВЫДАЁТ. Схема выхода в OpenAPI лежит рядом со схемой входа и
#: читается так же. ИЗМЕРЕНО 2026-09-02 на четырёх эндпоинтах:
#:
#:     pixverse/lipsync   -> video
#:     elevenlabs/tts     -> audio, timestamps
#:     sync-lipsync       -> video
#:     infinitalk         -> seed, video
#:
#: ЗАЧЕМ. Планировщик проверяет, что модель ПРИНИМАЕТ, и не проверяет, что она
#: ВЫДАЁТ. Поймано на живом прогоне через MCP: шагу «озвучка» (produces: аудио)
#: он выбрал `pixverse-lipsync` — липсинк-модель с перечнем голосов в схеме, —
#: а выдаёт она video. Шаг, которому нужен звук, получил модель, которая звука
#: не отдаёт.
#:
#: Скалярные поля выхода (`seed`, `timestamps`) видом не считаются: это не
#: артефакт, а сопровождающие числа. Отсекаются по типу, а не по имени.
СКАЛЯР = frozenset({"integer", "number", "boolean", "string"})


def вид_выхода(поле: str, тело: dict[str, Any]) -> str:
    """Вид артефакта на выходе по имени поля и его типу. Пусто — не артефакт."""
    if str(тело.get("type") or "") in СКАЛЯР:
        return ""
    м = ВИД_ВХОДА.search(str(поле or ""))
    return ПО_РУССКИ[м.group(1).lower()] if м else ""


def схема_выхода(тело: dict[str, Any]) -> dict[str, Any] | None:
    """Схема ВЫХОДА из OpenAPI. Нет её — значит эндпоинт о выходе молчит."""
    схемы = (тело.get("components") or {}).get("schemas") or {}
    for имя, т in схемы.items():
        if имя.endswith("Output") and isinstance(т, dict):
            return т
    return None


def схема_входа(тело: dict[str, Any]) -> dict[str, Any] | None:
    """Схема ВХОДА из OpenAPI. Нет её — значит ответ не тот, что мы ждали."""
    схемы = (тело.get("components") or {}).get("schemas") or {}
    for имя, т in схемы.items():
        if имя.endswith("Input") and isinstance(т, dict):
            return т
    return None


#: Сколько раз переспросить молчащий адрес. ИЗМЕРЕНО 2026-09-02: из пяти
#: эндпоинтов два не ответили, а на повторе ответили ОБА. То есть молчание
#: было икотой площадки, и записать его третьим исходом значило бы занизить
#: покрытие вдвое. Повтор ровно один: второе молчание подряд — уже не икота, а
#: состояние, и настаивать значило бы долбиться в чужой хост.
ПОВТОРОВ = 1


def спросить(эндпоинт: str) -> tuple[str, dict[str, Any] | None]:
    """Одна схема. «Не разобралось» отличимо от «не ответил»."""
    ответ = fetch.fetch(СХЕМА.format(эндпоинт=эндпоинт))
    for _ in range(ПОВТОРОВ):
        if ответ.get("outcome") == PASS:
            break
        time.sleep(ПАУЗА)
        ответ = fetch.fetch(СХЕМА.format(эндпоинт=эндпоинт))
    if ответ.get("outcome") != PASS:
        return (UNMEASURED, None)
    try:
        разобрано = json.loads(ответ.get("text") or "")
    except ValueError:
        return (FAIL, None)
    вход = схема_входа(разобрано) if isinstance(разобрано, dict) else None
    if вход is None:
        return (FAIL, None)
    # Выход едет вместе со входом: это одна схема одного эндпоинта, и второй
    # запрос за ней был бы вторым походом к чужому хосту за тем же файлом.
    вход = dict(вход)
    вход["_выход"] = схема_выхода(разобрано) or {}
    return (PASS, вход)


def заявки(эндпоинт: str, вход: dict[str, Any]) -> list[tuple[str, str, str, str, str]]:
    """Находки одной схемы: модель, атрибут, значение, URL, нота."""
    имя = modelnames.from_portal_id(эндпоинт)
    поля = вход.get("properties") or {}
    url = СХЕМА.format(эндпоинт=эндпоинт)
    # НЕПОЛНОТА НАЗЫВАЕТСЯ ВСЛУХ. Правило типизирует имя поля, а схемы приносят
    # имена, которых оно не знает: `file_urls` у `heygen/v3/video-agent` —
    # «URLs of files to include as assets (images, ...)», то есть вход, вид
    # которого из имени не следует. Строка «принимает: текст» была бы про такую
    # модель ВЕРНА и НЕПОЛНА, а читается как полный список.
    #
    # Число неразобранных полей-ссылок едет в ноту факта: значение остаётся
    # словами о том, что мы поняли, а рядом стоит, сколько не поняли.
    неразобранных = sum(1 for к in поля if МЕДИА_ПОЛЕ.search(к) and not вид_входа(к))
    нота = f"OpenAPI входа эндпоинта {эндпоинт}, полей {len(поля)}" + (
        f"; полей-ссылок без опознанного вида {неразобранных} — список входов НЕПОЛОН"
        if неразобранных
        else ""
    )
    out: list[tuple[str, str, str, str, str]] = []

    виды = sorted({в for к in поля if (в := вид_входа(к))})
    if виды:
        out.append((имя, "accepts_inputs", ", ".join(виды), url, нота))

    # ЧТО МОДЕЛЬ ТРЕБУЕТ, А НЕ ТОЛЬКО ЧТО ПРИНИМАЕТ. Заведено 2026-09-03, и
    # завела его прочитанная глазами выдача (П3): на шаге «генерация видео» в
    # плане стоял `kling-video-lipsync-text-to-video`, у которого в схеме
    # `required: [video_url, text, voice_id]`. То есть модель ТРЕБУЕТ готовое
    # видео — а шагу, который это видео и должен произвести, взять его
    # неоткуда. По «принимает» она проходила: видео она действительно
    # принимает. Разница между «принимает» и «требует» и есть та, из-за
    # которой план предлагал модель, которая на этом шаге не запустится.
    обязательные = sorted({в for к in (вход.get("required") or []) if (в := вид_входа(str(к)))})
    if обязательные:
        out.append((имя, "requires_inputs", ", ".join(обязательные), url, нота))

    выходные = (вход.get("_выход") or {}).get("properties") or {}
    отдаёт = sorted({в for к, т in выходные.items() if (в := вид_выхода(к, т or {}))})
    if отдаёт:
        out.append((имя, "produces_outputs", ", ".join(отдаёт), url, нота))

    for поле, атрибут in ПЕРЕЧИСЛЕНИЯ.items():
        значения = (поля.get(поле) or {}).get("enum")
        if значения:
            out.append((имя, атрибут, ", ".join(str(з) for з in значения), url, нота))
    return out


def обойти(эндпоинты: list[str]) -> dict[str, Any]:
    """Все схемы. Р2: три числа рядом с находками."""
    находки: list[tuple[str, str, str, str, str]] = []
    ответили = не_разобрались = не_ответили = 0
    for номер, э in enumerate(эндпоинты):
        if номер:
            time.sleep(ПАУЗА)
        исход, вход = спросить(э)
        if исход == UNMEASURED:
            не_ответили += 1
            continue
        if исход == FAIL or вход is None:
            не_разобрались += 1
            continue
        ответили += 1
        находки.extend(заявки(э, вход))
    return {
        "находки": находки,
        "ответили": ответили,
        "не разобрались": не_разобрались,
        "не ответили": не_ответили,
        "спрошено": len(эндпоинты),
    }


def записать(находки: list[tuple[str, str, str, str, str]], today: str) -> dict[str, Any]:
    from studio.mcp import advice

    записано = отказано = 0
    причины: dict[str, int] = {}
    for модель, атрибут, значение, url, нота in находки:
        out = advice.record(
            модель, атрибут, значение, url, "portal", today, note=нота, read_directly=True
        )
        if out["outcome"] == PASS:
            записано += 1
        else:
            отказано += 1
            причины[str(out.get("note"))[:90]] = причины.get(str(out.get("note"))[:90], 0) + 1
    return {"записано": записано, "отказано": отказано, "причины": причины}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("endpoints", nargs="+", help="id вида fal-ai/sync-lipsync/v2")
    parser.add_argument("--record", metavar="ДАТА")
    args = parser.parse_args(argv)

    итог = обойти(args.endpoints)
    print(
        f"схем спрошено {итог['спрошено']}, ответили {итог['ответили']}, "
        f"не разобрались {итог['не разобрались']}, не ответили {итог['не ответили']}"
    )
    for модель, атрибут, значение, _url, _нота in итог["находки"]:
        print(f"  {модель[:30]:32} {атрибут:22} {значение[:44]}")
    if args.record:
        з = записать(итог["находки"], args.record)
        print(f"записано {з['записано']}, отказано {з['отказано']}")
        for почему, сколько in sorted(з["причины"].items(), key=lambda x: -x[1]):
            print(f"  {сколько}  {почему}")
    print(
        f"\nпроверено {итог['спрошено']}\nнарушений {итог['не разобрались']}\n"
        f"не смогли {итог['не ответили']}"
    )
    if not итог["ответили"]:
        return 2
    return 1 if итог["не разобрались"] else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
