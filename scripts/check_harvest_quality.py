#!/usr/bin/env python3
"""Гейт прибора, отделяющего находку от заголовка треда.

    python scripts/check_harvest_quality.py --check

ЧТО ЗДЕСЬ СТОРОЖИТСЯ

1. НЕГАТИВНЫЙ КОНТРОЛЬ ИЗ ТРЁХ ПОЛОВИН (И5). Прибор, который красит всё, и
   прибор, который молчит всегда, проходят проверку из одной половины — поэтому
   половин три, и все три взяты из ЖИВОЙ базы. Группы режутся по МЕТКЕ В `note`,
   которую канал оставил в момент записи (Е2: верь свидетельству, а не имени
   скрипта — скрипт правят, записанное остаётся):

   * ЗАГОЛОВОЧНЫЙ ЗАХОД — `note` вида «тред #N, состояние». Это и есть дефект:
     в значении лежит subject line (ИЗМЕРЕНО 2026-09-01: 183 строки в файле,
     181 в живой базе — два значения владелец уже отозвал). Прибор обязан
     осудить их подавляющее большинство;
   * РУЧНОЙ РАЗБОР того же канала — `note` вида «HARVESTED ...» или
     «Пересказ ...», их 20. Прибор обязан ПРОПУСТИТЬ их все: канал тот же,
     разница в том, читали тело треда или заголовок;
   * ПРОЧИЕ КАНАЛЫ — вся остальная база. Ложное осуждение здесь означает, что
     прибор бракует то, ради чего база существует.

   Рядом печатаются, но НЕ гейтятся, ещё две группы. ЗАХОД ПО ТЕЛУ ТРЕДА
   (`note` вида «тело треда #N») — починка канала, которую владелец делает
   прямо сейчас; порог для неё выбирать не этому скрипту, а её автору, и
   числа печатаются, чтобы выбирать было по чему. ИЗМЕРЕНО 2026-09-01: из 123
   строк прибор осуждает 27 — тело треда тоже бывает вопросом или чужой
   трассировкой. НЕОПОЗНАННЫЙ ЗАХОД — строка из обсуждений с меткой, которой
   этот скрипт не знает; она считается в «не смогли», а не молча приписывается
   к ручному разбору, где её осуждение покрасило бы чужую работу.

2. КАЖДЫЙ ПРИЗНАК ИМЕЕТ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Правило, которое ни разу не
   сработало, — это не правило, а строка кода: снять его можно молча. Поэтому
   рядом с живой базой стоит КОНТРОЛЬНЫЙ НАБОР — по случаю на каждый признак и
   ЗДОРОВЫЕ ЧУЖАКИ, которые обязаны пройти. Отозванная владельцем строка
   «Impressive Speed & Quality Out of the Box» взята в набор дословно: в живой
   базе её больше нет, а правило, которое её ловит, должно остаться.

3. ТРИ ИСХОДА РАЗЛИЧЕНЫ (Р1). Если на живой базе не встретилось всех трёх —
   годно, не годно и не смогли, — прибор меряет меньше, чем обещает, и это
   красит гейт. Третий исход настоящий: короткое осмысленное утверждение на
   языке, которого прибор не разбирает.

Рядом с исходом всегда печатаются `проверено N`, `нарушений M`, `не смогли K`
(правило Р2). Пропущенные строки массового захода выписываются ПОИМЁННО: предел
прибора называется, а не заминается. Сети здесь нет (Т4), гита здесь нет — CI
клонирует с `fetch-depth: 1`, и всё, что нужно, лежит в файле базы.

Коды возврата: 0 — годно, 1 — не годно, 2 — не смогли проверить.
"""

