ЗАГОЛОВОЧНЫЙ = "заголовочный заход"
ПО_ТЕЛУ = "заход по телу треда"
РУЧНОЙ = "ручной разбор"
ПРОЧИЕ = "прочие каналы"
НЕОПОЗНАННЫЙ = "неопознанный заход канала"

#: Группы, у которых есть требование. Остальные печатаются и не гейтятся.
ГЕЙТЯТСЯ = (ЗАГОЛОВОЧНЫЙ, РУЧНОЙ, ПРОЧИЕ)


def заголовочный_заход(факт: Fact) -> bool:
    """Строка заголовочного захода: канал сам пометил её при записи."""
    return bool(МЕТКА_ЗАГОЛОВОЧНОГО_ЗАХОДА.match((факт.note or "").strip()))


def из_обсуждений(факт: Fact) -> bool:
    """Строка канала обсуждений и issue — по странице, с которой она снята."""
    ссылка = факт.source_url.lower()
    return any(кусок in ссылка for кусок in СТРАНИЦА_ОБСУЖДЕНИЯ)


def группа(факт: Fact) -> str:
    """Куда попадает строка. Развилка отдельной функцией, чтобы её можно было
    проверить на одной строке, а не только на всей базе (Т5)."""
    заметка = (факт.note or "").strip()
    if МЕТКА_ЗАГОЛОВОЧНОГО_ЗАХОДА.match(заметка):
        return ЗАГОЛОВОЧНЫЙ
    if МЕТКА_ЗАХОДА_ПО_ТЕЛУ.match(заметка):
        return ПО_ТЕЛУ
    if not из_обсуждений(факт):
        return ПРОЧИЕ
    if заметка.startswith(НАЧАЛА_РУЧНОГО_РАЗБОРА):
        return РУЧНОЙ
    return НЕОПОЗНАННЫЙ


def разложить(факты: list[Fact]) -> dict[str, list[Fact]]:
    """Пять групп, из них требование есть у трёх. Порядок печати — постоянный."""
    группы: dict[str, list[Fact]] = {
        ЗАГОЛОВОЧНЫЙ: [],
        РУЧНОЙ: [],
        ПРОЧИЕ: [],
        ПО_ТЕЛУ: [],
        НЕОПОЗНАННЫЙ: [],
    }
    for f in факты:
        группы[группа(f)].append(f)
    return группы


def проверить_контроль() -> tuple[int, list[str]]:
    """Контрольный набор: что прибор обязан сказать на каждый признак.

    Возвращает число сошедшихся случаев и список расхождений. Признак, ни разу
    не встретившийся в наборе, — тоже расхождение: правило без положительного
    контроля снимается молча.
    """
    беды: list[str] = []
    сошлось = 0
    признаки: set[str] = set()
    for атрибут, значение, ожидаемый_исход, ожидаемый_признак in КОНТРОЛЬНЫЙ_НАБОР:
        в = hq.судить(значение, атрибут)
        признаки.add(ожидаемый_признак)
        if в.исход == ожидаемый_исход and в.признак == ожидаемый_признак:
            сошлось += 1
        else:
            беды.append(
                f"контроль: «{значение[:60]}» ожидалось {fa.OUTCOME_WORDS[ожидаемый_исход]}"
                f"/{ожидаемый_признак or '—'}, получено {в.слово}/{в.признак or '—'}"
            )
    ожидаемые_признаки = {
        "трассировка",
        "вопрос",
        "просьба",
        "лицензионный спор",
        "тема письма",
        "ярлык-жалоба",
        "титульный регистр",
        "отчёт об установке",
        "слишком коротко",
        "перечисление",
        "расхождение знака",
        "пусто",
        "язык не разбирается",
        "",
    }
    непокрытые = sorted(ожидаемые_признаки - признаки)
    if непокрытые:
        беды.append(f"признаки без положительного контроля: {', '.join(непокрытые)}")
    return сошлось, беды


def проверить(путь: Path = DEFAULT_FACTS_PATH) -> dict:
    """Вердикт гейта. Три исхода, и третий — «базы нет», а не «нарушений нет»."""
    факты = load_facts(путь)
    if not факты:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "note": f"базы фактов нет или она пуста: {путь}",
            "группы": {},
            "пропущенные": [],
        }

    группы = разложить(факты)
    пустые = [имя for имя in ГЕЙТЯТСЯ if not группы[имя]]
    if пустые:
        return {
            "outcome": UNMEASURED,
            "checked": len(факты),
            "violations": 0,
            "unmeasured": len(пустые),
            "note": f"группы пусты, сравнивать не с чем: {', '.join(пустые)}",
            "группы": {},
            "пропущенные": [],
        }

    сошлось, беды = проверить_контроль()

    итоги = {имя: hq.учесть(строки) for имя, строки in группы.items() if строки}
    исходы_на_базе = set()
    for имя in ГЕЙТЯТСЯ:
        итог = итоги[имя]
        if итог["годно"]:
            исходы_на_базе.add(PASS)
        if итог["осуждено"]:
            исходы_на_базе.add(FAIL)
        if итог["не смогли"]:
            исходы_на_базе.add(UNMEASURED)

    масс = итоги[ЗАГОЛОВОЧНЫЙ]
    доля_осуждённых = масс["осуждено"] / масс["checked"] if масс["checked"] else 0.0
    if доля_осуждённых < ПОЛ_ОСУЖДЕНИЯ:
        беды.append(
            f"заголовочный заход осуждён на {доля_осуждённых:.3f} при поле {ПОЛ_ОСУЖДЕНИЯ}: "
            f"{масс['осуждено']} из {масс['checked']}"
        )

    ручные = итоги[РУЧНОЙ]
    if ручные["осуждено"] > ПОТОЛОК_ЛОЖНЫХ_РУЧНЫХ:
        беды.append(
            f"ручной разбор забракован на {ручные['осуждено']} строках при потолке "
            f"{ПОТОЛОК_ЛОЖНЫХ_РУЧНЫХ}"
        )

    прочие = итоги[ПРОЧИЕ]
    доля_ложных = прочие["осуждено"] / прочие["checked"] if прочие["checked"] else 0.0
    if доля_ложных > ПОТОЛОК_ЛОЖНЫХ_ПРОЧИХ:
        беды.append(
            f"прочие каналы забракованы на {доля_ложных:.3f} при потолке "
            f"{ПОТОЛОК_ЛОЖНЫХ_ПРОЧИХ}: {прочие['осуждено']} из {прочие['checked']}"
        )

    if len(исходы_на_базе) < 3:
        беды.append(
            "на живой базе различено меньше трёх исходов: "
            f"{sorted(fa.OUTCOME_WORDS[и] for и in исходы_на_базе)}"
        )

    пропущенные = [(f.model, f.attribute, f.value) for f, в in масс["строки"] if в.исход == PASS]
    проверено = sum(и["checked"] for и in итоги.values())
    не_смогли = sum(и["не смогли"] for и in итоги.values()) + len(группы[НЕОПОЗНАННЫЙ])
    return {
        "outcome": FAIL if беды else PASS,
        "checked": проверено,
        "violations": len(беды),
        "unmeasured": не_смогли,
        "note": (
            f"контроль сошёлся на {сошлось} из {len(КОНТРОЛЬНЫЙ_НАБОР)} случаев; "
            f"заголовочный заход осуждён на {доля_осуждённых:.3f}"
        ),
        "беды": беды,
        "группы": итоги,
        "пропущенные": пропущенные,
        "неопознанных": len(группы[НЕОПОЗНАННЫЙ]),
    }


def напечатать(вердикт: dict) -> None:
    """Числа рядом с исходом (Р2) и пропущенные строки поимённо."""
    for имя, итог in вердикт.get("группы", {}).items():
        помета = "" if имя in ГЕЙТЯТСЯ else "  (печатается, требования нет)"
        признаки = ", ".join(f"{k} {v}" for k, v in sorted(итог["признаки"].items()))
        print(
            f"  {имя}: проверено {итог['checked']}, осуждено {итог['осуждено']}, "
            f"пропущено {итог['годно']}, не смогли {итог['не смогли']}, "
            f"вне области {итог['вне области']}{помета}"
        )
        if признаки:
            print(f"      признаки: {признаки}")
    пропущенные = вердикт.get("пропущенные") or []
    if пропущенные:
        print(f"  пропущено прибором из заголовочного захода: {len(пропущенные)}")
