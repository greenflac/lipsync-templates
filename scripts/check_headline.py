#!/usr/bin/env python3
"""Верхняя строка ответа против его же тела.

ЗАЧЕМ

За 2026-09-02 в этом проекте семь раз нашлось одно и то же: ответ ЧЕСТЕН В
ДЕТАЛЯХ и НЕВЕРЕН В ЗАГОЛОВКЕ. Гейты сторожили внутреннюю согласованность
знания — тир по URL, дословность цитат, дописывание журналов, — и ни один не
смотрел на строку, которую человек читает первой.

Самый дорогой пример дня, найденный не гейтом, а чтением выдачи глазами:

    model_advice("sync-lipsync-2", "price") -> "nothing is recorded"
    в базе                                  -> price_per_minute = "$3 per minute"

Ответ был согласован сам с собой: атрибута `price` у модели действительно нет,
пустой `claims`, честный третий исход. И при этом заголовок врал: цена в базе
лежала, просто под другим именем. Такую ложь ловит только сравнение ответа с
БАЗОЙ, а не ответа с самим собой.

ЧТО ЭТОТ ГЕЙТ ПРОВЕРЯЕТ

1. СЕМЬЯ. Если ответ говорит «ничего не записано про X.цена», а база держит у
   X хоть одно имя из ценовой (или скоростной) семьи — это нарушение.
   Правила семьи и её негативный контроль — `studio/selfrag/attrfamily.py`.
2. СЧЁТ. `pass` не бывает при `checked == 0` и при пустых утверждениях: «всё
   хорошо, ничего не проверено» — не ответ.
3. НАРУШЕНИЕ. `violations > 0` не бывает при `pass`.
4. ТРЕТИЙ ИСХОД НАЗВАН. Если `unmeasured > 0`, нота обязана говорить об этом
   словами. Число, которого нет в тексте, читатель не увидит.

ЧТО ОН НЕ ПРОВЕРЯЕТ

Верность самих фактов. Здесь сравниваются ответ и база, а не база и мир.

ИЗМЕРЕНО В ДЕНЬ НАПИСАНИЯ: нарушений 0 на 503 моделях. Гейт заведён не потому,
что что-то красное, а потому что зелёное сегодня чинилось руками и обязано
остаться зелёным завтра (Ц7: правило, которое нельзя нарушить наблюдаемо, —
это не правило, а строка в файле).

ТРИ ИСХОДА (Р1)

    годно      ответы сверены, расхождений нет
    не годно   заголовок говорит не то, что тело или база
    не смогли  сверять было нечего (база пуста)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio.mcp import advice  # noqa: E402
from studio.selfrag import attrfamily  # noqa: E402
from studio.selfrag.facts import load_facts  # noqa: E402

#: Слова, которыми ответ объявляет пустоту. Если рядом с ними база НЕ пуста —
#: это и есть ложный заголовок.
ПУСТОТА = ("nothing is recorded", "ничего не записано")

#: Слова, которыми ответ называет третий исход. Хоть одно обязано стоять в
#: ноте, когда `unmeasured > 0`.
ТРЕТИЙ_ИСХОД = ("could not measure", "не смогли", "weakly", "gap", "unknown", "не измер")


#: Слова, которыми спрашивают. ВЫБРАНО два: цена и скорость — те самые, ради
#: которых заводился мониторинг, и те самые, на которых ответ соврал.
СЛОВА: tuple[str, ...] = ("price", "generation_time")

#: Сколько моделей БЕЗ единой строки семьи взять в негативный контроль.
#: ВЫБРАНО 40: гейт обязан не только ловить, но и молчать, а полный обход всех
#: 503 моделей стоит 37 с при 76 с у всей сборки — половина времени за
#: повторение одного и того же «здесь ничего нет».
КОНТРОЛЬНЫХ = 40


def вопросы(по_модели: dict[str, list[str]]) -> tuple[list[tuple[str, str]], int]:
    """Пары «модель, слово вопроса». Возвращает пары и размер контроля.

    Спрашивается семейным словом, а не именем записанного атрибута: именно так
    спрашивает человек и модель, и именно на этом ответ соврал.

    ПОЛНЫЙ ОБХОД ПО РИСКОВЫМ, ВЫБОРКА ПО ОСТАЛЬНЫМ. Ложный заголовок «ничего не
    записано» возможен ровно там, где у модели ЕСТЬ строка семьи, — эти
    проверяются все до одной. Модели без единой строки семьи — негативный
    контроль: гейт обязан на них молчать, и для этого хватает выборки. Выборка
    берётся по алфавиту, а не случайно: прогон должен повторяться.
    """
    рисковые: list[tuple[str, str]] = []
    прочие: list[str] = []
    for модель in sorted(по_модели):
        свои = [с for с in СЛОВА if attrfamily.expand(с, по_модели[модель])]
        if свои:
            рисковые.extend((модель, слово) for слово in СЛОВА)
        else:
            прочие.append(модель)
    контроль = [(м, слово) for м in прочие[:КОНТРОЛЬНЫХ] for слово in СЛОВА]
    return (рисковые + контроль, len(контроль))


def сверить(модель: str, слово: str, записанные: list[str]) -> list[str]:
    """Расхождения одного ответа. Пустой список — расхождений нет."""
    ответ: dict[str, Any] = advice.advise(модель, attribute=слово)
    нота = str(ответ.get("note") or "")
    утверждения = ответ.get("claims") or {}
    непустые = [к for к, в in утверждения.items() if (в or {}).get("values")]
    беды: list[str] = []

    родня = attrfamily.expand(слово, записанные)
    if any(слова in нота for слова in ПУСТОТА) and родня:
        беды.append(f"{модель}.{слово}: заголовок «ничего не записано», а база держит {родня}")

    if ответ.get("outcome") == PASS:
        if not int(ответ.get("checked") or 0):
            беды.append(f"{модель}.{слово}: исход pass при checked=0")
        if not непустые:
            беды.append(f"{модель}.{слово}: исход pass без единого значения")
        if int(ответ.get("violations") or 0):
            беды.append(f"{модель}.{слово}: исход pass при violations>0")

    if int(ответ.get("unmeasured") or 0) and not any(с in нота for с in ТРЕТИЙ_ИСХОД):
        беды.append(f"{модель}.{слово}: unmeasured>0, а нота об этом молчит")

    return беды


def обойти(предел: int = 0) -> dict[str, Any]:
    """Сверить все пары. Р2: три числа рядом с исходом."""
    по_модели: dict[str, list[str]] = {}
    for факт in load_facts():
        по_модели.setdefault(факт.model, []).append(факт.attribute)

    пары, контроль = вопросы(по_модели)
    if предел:
        пары = пары[:предел]
    беды: list[str] = []
    for модель, слово in пары:
        беды.extend(сверить(модель, слово, по_модели.get(модель, [])))
    return {
        "проверено": len(пары),
        "беды": беды,
        "моделей": len(по_модели),
        "контроль": контроль,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="то же самое; ради единообразия")
    parser.add_argument("--limit", type=int, default=0)
    args = parser.parse_args(argv)

    итог = обойти(args.limit)
    for беда in итог["беды"][:20]:
        print(f"  {беда}")
    лишних = len(итог["беды"]) - 20
    if лишних > 0:
        print(f"  ... и ещё {лишних}")

    исход = FAIL if итог["беды"] else (PASS if итог["проверено"] else UNMEASURED)
    словами = {PASS: "годно", FAIL: "не годно", UNMEASURED: "не смогли"}[исход]
    print(
        f"{словами}: сверено вопросов {итог['проверено']} "
        f"(из них негативного контроля {итог['контроль']}) при {итог['моделей']} моделях в базе, "
        f"расхождений {len(итог['беды'])}"
    )
    print(
        f"\nпроверено {итог['проверено']}\nнарушений {len(итог['беды'])}\n"
        f"не смогли {0 if итог['проверено'] else 1}"
    )
    return 0 if исход == PASS else (1 if исход == FAIL else 2)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
