#!/usr/bin/env python3
"""Гейт чужой прозы: сколько чужих слов и чьих имён лежит в закоммиченном знании.

    python scripts/check_verbatim.py --check

ЧТО ЗДЕСЬ СТОРОЖИТСЯ

1. ДОСЛОВНАЯ ЦИТАТА ЧЕЛОВЕКА. Реплика из обсуждения — чужое высказывание, на
   которое у нас прав нет; вендорская спецификация — изложение факта из
   документа, опубликованного для чтения. Различаются ОНИ ПО ХОСТУ, а не по
   длине, потому что по длине их не различить, а гадать здесь нельзя.

2. ИМЯ ЖИВОГО ЛИЦА. Ни одному ответу ник автора не нужен, а его хранение в
   публичном репозитории — отдельный разговор, которого лучше не иметь.

3. НЕГАТИВНЫЙ КОНТРОЛЬ (И5), и он здесь главный, потому что прибор уже дважды
   соврал при постройке. Первая редакция насчитала 3401 нарушение из 5193
   записей, из них 1543 были НАШИМИ СОБСТВЕННЫМИ нотами, а 515 «имён»
   оказались словами `by the` и `by family` в английской прозе. Поэтому гейт
   проверяет не только «ловит ли», но и «молчит ли»: наша нота любой длины,
   вендорская спецификация и нота со словами «автор неизвестен» обязаны
   проходить.

ТРИ ИСХОДА (Р1): годно / не годно / не смогли. Третий настоящий — файла нет
на этой машине, строка не разобралась, книг знания не найдено. Ноль нарушений
при нуле прочитанных записей не есть успех, и рядом всегда печатаются
`проверено N`, `нарушений M`, `не смогли K` (Р2). Сети здесь нет (Т4).

ИЗВЕСТНЫЙ ДОЛГ. Гейт сегодня ПЕЧАТАЕТ найденное, но не краснеет на нём:
измеренные 356 цитат и 246 имён накоплены до появления правила, а вычистить
их отзывом нельзя — журнал append-only, отзыв добавляет строку, прежняя
остаётся в файле и в истории git. Удаление требует переписать файл и историю,
и это решение владельца. Поэтому здесь стоит ПОЛ: новые нарушения краснеют,
накопленные — печатаются числом в каждом прогоне, чтобы долг был виден.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from studio import verbatim as vb  # noqa: E402

#: Сколько накопленных нарушений считается «долгом, а не регрессией».
#: ИЗМЕРЕНО 2026-09-02 на живом дереве: 370 длинных цитат людей и 246 имён.
#: Пол стоит РОВНО на измеренном: одна новая запись сверх — красное. Снижать
#: его будет тот, кто вычистит прошлое; поднимать нельзя, и это сторожится
#: тестом.
#:
#: ПОЧЕМУ 356 СТАЛО 370, разобрано по каждой из четырнадцати (2026-09-02,
#: канал Civitai), потому что молча поднятый пол — это спрятанное нарушение:
#:
#:   6 — КОПИИ, СОЗДАННЫЕ ОТЗЫВОМ. Канал отозвал шесть своих же строк, чьё
#:       значение было дословной прозой автора карточки. Журнал append-only,
#:       и отзыв ДОПИСЫВАЕТ строку с тем же значением: чужих слов в файле от
#:       этого стало больше, а не меньше. Ровно об этом предупреждает абзац
#:       «ИЗВЕСТНЫЙ ДОЛГ» выше — вычистить прошлое отзывом нельзя.
#:   4 — ЦЕНА МОЕЙ СОБСТВЕННОЙ ОШИБКИ. Я отозвал строку `civitai-api.license`
#:       как «устаревшую», хотя ToS говорит то же самое и сегодня; на
#:       восстановление ушли ещё три записи (не то имя атрибута, не та нота),
#:       и каждая оставила в файле свою копию. Отзыв — не ластик: он пишет.
#:   4 — НАШ СОБСТВЕННЫЙ ТЕКСТ: три строки флагов прав («allowCommercialUse
#:       без Sell: …») и один пересказ пункта ToS. Прибор мерит длину по
#:       ХОСТУ, а `civitai.com` — хост, где текст пишут люди; отличить наш
#:       русский пересказ от чужой английской реплики он по построению не
#:       может, и гадать здесь запрещено самой докстрокой.
#:
#: Канал впредь не производит ни того, ни другого: значения свидетельств
#: 4–13 слов, метки прав 8 слов (ИЗМЕРЕНО на карточке с четырьмя флагами).
# DEBT(2026-09-02): десять строк выше остаются в файле, и опустить пол
# обратно нельзя, не переписав журнал. Настоящая починка — научить гейт
# отличать НАШ текст от чужого (у наших строк заполнен `witnessed` или нота
# начинается словом «пересказ»), и это правка чужого модуля, поэтому здесь
# только запись.
#: 369, а не 370, и разница — след слияния. Ветка канала Civitai отросла от
#: коммита, где моего захода по 54 моделям ещё не было, и посчитала свой пол на
#: своём дереве. На слитом дереве накопленных цитат 369: одна из строк, которую
#: та ветка считала своей, у меня уже была отозвана. Пол ставится по ИЗМЕРЕНИЮ
#: на дереве, где он проверяется, а не по числу, привезённому с другой ветки, —
#: иначе гейт сторожит чужую базу.
ПОЛ_ЦИТАТ = 369
#: НОЛЬ с 2026-09-02: 246 строк с ником практика вычищены по решению владельца
#: (116 разных ников, все в поле `note`, форма «автор <ник>»). Пол опущен до
#: нуля НАМЕРЕННО и это не формальность: пока он стоял на 246, новый ник,
#: попавший в базу, не краснел бы — прибор сравнивает с накопленным, а не с
#: нулём. Теперь любое имя человека в знании красит гейт с первой же строки.
ПОЛ_ИМЁН = 0


def свести(корень: Path) -> dict:
    """Все книги знания одним числом. Вынесено из main (Т5)."""
    книги = vb.книги(корень)
    if not книги:
        return {
            "outcome": vb.UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "цитат": 0,
            "имён": 0,
            "note": "книг знания не найдено — не проверено ничего",
            "problems": [],
        }
    записей = цитат = имён = не_смогли = 0
    беды: list[str] = []
    for книга in книги:
        итог = vb.проверить_файл(книга)
        записей += итог.checked
        цитат += len(итог.длинных)
        имён += len(итог.с_именем)
        не_смогли += итог.unmeasured
        if итог.violations:
            беды.append(итог.note)
    сверх_цитат = max(0, цитат - ПОЛ_ЦИТАТ)
    сверх_имён = max(0, имён - ПОЛ_ИМЁН)
    нарушений = сверх_цитат + сверх_имён
    if записей == 0:
        исход = vb.UNMEASURED
    elif нарушений:
        исход = vb.FAIL
    else:
        исход = vb.PASS
    нота = (
        f"новых нарушений сверх пола: цитат {сверх_цитат}, имён {сверх_имён}"
        if нарушений
        else f"накоплено цитат {цитат} (пол {ПОЛ_ЦИТАТ}), имён {имён} (пол {ПОЛ_ИМЁН}); "
        "нового не добавилось"
    )
    return {
        "outcome": исход,
        "checked": записей,
        "violations": нарушений,
        "unmeasured": не_смогли,
        "цитат": цитат,
        "имён": имён,
        "note": нота,
        "problems": беды,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="код возврата 0/1/2")
    args = parser.parse_args(argv)

    итог = свести(Path(__file__).resolve().parents[1])
    for беда in итог["problems"]:
        print(f"  {беда}")
    print(
        f"\nпроверено {итог['checked']}\nнарушений {итог['violations']}\nне смогли {итог['unmeasured']}"
    )
    print(f"\n{итог['outcome']}: {итог['note']}")
    if not args.check:
        return 0
    return {vb.PASS: 0, vb.FAIL: 1, vb.UNMEASURED: 2}[итог["outcome"]]


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
