#!/usr/bin/env python3
"""`unittest.main()` — последняя конструкция файла, а не середина.

    python scripts/check_main_is_last.py --check

ЗАЧЕМ. НАЙДЕНО десятой приёмкой 2026-09-07: в двух файлах тестов
`if __name__ == "__main__": unittest.main()` стоял В СЕРЕДИНЕ, а классы
дописывались ПОСЛЕ него. Прямой запуск файла давал зелёное «OK», не выполнив
11 и 4 проверки соответственно — и число 11 в точности совпало с числом
проверок, которые предыдущий коммит объявил заведёнными.

Гейт спасает `discover`, а человек, запускающий файл руками, получает зелёное
и ложное. Правило записывалось словами дважды и дважды нарушалось следующей же
правкой — значит, его место здесь, а не в тексте (Ц7).

ТРИ ИСХОДА (Р1): `годно` — во всех файлах хвост чист; `не годно` — есть файл, где
после `main()` объявлено что-то ещё; `не смогли` — файл не читается.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path
from typing import Any

КОРНИ: tuple[str, ...] = ("studio", "lipsync", "scripts")

#: Что считается объявлением, потерянным после `main()`. Импорт или присваивание
#: после него безвредны; классы и функции — это невыполненные проверки.
ТЕРЯЕТСЯ = (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)

#: ИЗМЕРЕННЫЙ ПОТОЛОК, А НЕ НОЛЬ. ИЗМЕРЕНО 2026-09-07 при заведении гейта: та
#: же форма дефекта лежит в 34 файлах по всему репозиторию, и большинство из
#: них — чужая территория (`lipsync/**` заморожен, `studio/selfrag/**` и
#: половина `studio/mcp/tests` за другими писателями, Ц2). Чинить их сейчас
#: значило бы подмести чужую незаконченную работу.
#:
#: Потолок делает вот что: он НЕ ДАЁТ ЧИСЛУ РАСТИ. Каждый следующий файл с
#: `main()` посередине красит гейт, а список печатается целиком — долг виден,
#: а не спрятан. Опустить потолок может тот, кто починит чужие файлы.
ПОТОЛОК = 34


def _строка_main(дерево: ast.Module) -> int:
    """Строка `if __name__ == "__main__":`, или -1."""
    for узел in дерево.body:
        if isinstance(узел, ast.If) and "__main__" in ast.dump(узел.test):
            return узел.lineno
    return -1


def проверить(корни: tuple[str, ...] = КОРНИ, потолок: int | None = None) -> dict[str, Any]:
    """Числа рядом с вердиктом (Р2): сколько файлов, сколько бед, сколько не смогли.

    `потолок` подменяется В ТЕСТЕ, а не только в проде: без параметра развилку
    «долг вырос» нельзя было наблюдать иначе как заведением 35 битых файлов, и
    она стояла непроверенной (Т5).
    """
    порог = ПОТОЛОК if потолок is None else потолок
    файлы = [p for корень in корни for p in Path(корень).rglob("test_*.py")]
    беды: list[str] = []
    не_смогли: list[str] = []
    # СЧИТАЕМ ТО, ЧТО СМОТРЕЛИ, А НЕ ВСЁ ПОДРЯД. НАЙДЕНО одиннадцатой приёмкой
    # 2026-09-08: прибор печатал «у 163 файлов из 197 main стоит последним»,
    # а у 6 файлов `main` нет вовсе — про них утверждалось уверенно то, чего
    # он не смотрел. Верное число — 157 из 191 (Р2: ноль нарушений при нуле
    # отработавших проверок не успех).
    с_main = 0
    for путь in файлы:
        try:
            дерево = ast.parse(путь.read_text(encoding="utf-8"))
        except Exception as е:  # pragma: no cover - разбирается только сломанный файл
            не_смогли.append(f"{путь}: {е}")
            continue
        место = _строка_main(дерево)
        if место < 0:
            continue
        с_main += 1
        потеряно = [у.name for у in дерево.body if isinstance(у, ТЕРЯЕТСЯ) and у.lineno > место]
        if потеряно:
            беды.append(f"{путь}:{место} — после main объявлено: {', '.join(потеряно)}")
    # ИСХОД СЧИТАЕТСЯ ОТ ПОТОЛКА, А НЕ ОТ НУЛЯ (Е2: вердикт обязан совпадать с
    # кодом возврата). До правки прибор печатал «не годно» и возвращал 0 —
    # читатель видел отказ там, где гейт пропускал.
    #
    # ЗЕРКАЛО ТОГО ЖЕ ДЕФЕКТА, найденное одиннадцатой приёмкой 2026-09-08 в
    # этом же файле: условие было `if не_смогли and not беды`, и один
    # нечитаемый файл РЯДОМ с одной бедой под потолком давал печать «годно»
    # при коде возврата 1. Третий исход не сворачивается в первый ни при
    # каких соседях (Р1): нечитаемый файл — это «не смогли», точка.
    if не_смогли:
        исход = "не смогли"
    elif len(беды) > порог:
        исход = "не годно"
    else:
        исход = "годно"
    return {
        "outcome": исход,
        "checked": len(файлы),
        "violations": len(беды),
        "unmeasured": len(не_смогли),
        "с_main": с_main,
        "беды": беды,
        "не_смогли": не_смогли,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.parse_args()
    итог = проверить()
    for строка in итог["беды"] + итог["не_смогли"]:
        print(f"  {строка}")
    print(f"\nпроверено {итог['checked']}")
    print(f"нарушений {итог['violations']}")
    print(f"не смогли {итог['unmeasured']}")
    чисто = итог["с_main"] - итог["violations"]
    долг = f"; записанный долг {итог['violations']} при потолке {ПОТОЛОК}"
    без_main = итог["checked"] - итог["с_main"]
    print(
        f"\n{итог['outcome']}: у {чисто} файлов из {итог['с_main']}, где main есть, он стоит "
        f"последним{долг}; ещё {без_main} файл(ов) main не имеют и не смотрелись"
    )
    # КОД ВОЗВРАТА ВЫВОДИТСЯ ИЗ ИСХОДА, А НЕ СЧИТАЕТСЯ ВТОРЫМ ВЫРАЖЕНИЕМ (Е1).
    # Двумя выражениями они разъезжаются молча — ровно так и разъехались, пока
    # исход считался от «не_смогли and not беды». Мутанта на эту строку НЕТ
    # НАРОЧНО: после починки исхода обе формулы дают одно и то же на
    # единственном пути вызова (`main()` всегда с порогом по умолчанию), и
    # мутант молчал бы не потому, что охрана крепка (И5). Правка сделана ради
    # одного источника истины, а не ради наблюдаемой развилки.
    return 0 if итог["outcome"] == "годно" else 1


if __name__ == "__main__":
    sys.exit(main())
