#!/usr/bin/env python3
"""Гейт журналов: что дописано, то остаётся дописанным.

    python scripts/check_append_only.py --check

ЧТО ЗДЕСЬ СТОРОЖИТСЯ

1. РАБОЧЕЕ ДЕРЕВО против HEAD: несохранённая правка журнала на месте.
2. ИСТОРИЯ после пола: коммит, переписавший журнал. Без второго первый
   бесполезен — переписавший коммит сам становится HEAD, и разница исчезает.
   Ровно так прошли незамеченными все четыре известных нарушения.
3. НЕГАТИВНЫЙ КОНТРОЛЬ (И5), оба конца. Прибор пускается по истории ДО пола,
   где нарушения ИЗМЕРЕНЫ и выписаны поимённо, и обязан найти каждое; и по
   журналу, у которого нарушений нет за всю историю, где обязан промолчать.
   Прибор, красящий всё подряд, и прибор, молчащий всегда, оба проходят
   проверку из одной половины — поэтому половин две.

ТРИ ИСХОДА (Р1): годно / не годно / не смогли. Третий — когда сравнивать не с
чем (журнал только заведён, git недоступен), и он НЕ сворачивается в первый.
Рядом печатаются `проверено N`, `нарушений M`, `не смогли K` (Р2). Сети нет (Т4).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from studio import appendonly as ao  # noqa: E402


def контроль() -> dict:
    """Обе половины негативного контроля, на ФИКСТУРАХ (И5).

    Фикстуры, а не история этого репозитория: CI клонирует с `fetch-depth: 1`,
    истории там нет, и контроль, опиравшийся на неё, был зелёным локально и
    красным в CI. Прибор обязан проверяться тем, что есть в любом окружении.
    """
    беды: list[str] = []
    поймано = промолчал = 0
    for имя, было, стало, строка in ao.ФОРМЫ_НАРУШЕНИЙ:
        разошлось = ao.первое_расхождение(list(было), list(стало))
        if разошлось != строка:
            беды.append(f"{имя}: ожидалась строка {строка}, названа {разошлось}")
        else:
            поймано += 1
    for имя, было, стало in ao.ФОРМЫ_БЕЗ_НАРУШЕНИЙ:
        разошлось = ao.первое_расхождение(list(было), list(стало))
        if разошлось:
            беды.append(f"{имя}: прибор нашёл расхождение на строке {разошлось}, а его нет")
        else:
            промолчал += 1
    return {
        "outcome": ao.FAIL if беды else ao.PASS,
        "checked": поймано + промолчал,
        "violations": len(беды),
        "unmeasured": 0,
        "note": (
            "; ".join(беды)
            if беды
            else f"поймано форм нарушения {поймано}, промолчал на {промолчал} здоровых"
        ),
        "problems": беды,
    }


def известные() -> dict:
    """Четыре нарушения, ИЗМЕРЕННЫЕ в истории этого репозитория (И6).

    Третий исход здесь настоящий и частый: при мелком клоне (`fetch-depth: 1`,
    как в CI) истории нет, и «не нашли» означает «не смогли посмотреть», а не
    «нарушения не было». Свернуть его в `не годно` значило бы красить CI
    вечно, свернуть в `годно` — потерять проверку. Поэтому он свой.
    """
    # Глубина меряется читаемостью РОДИТЕЛЯ известного коммита, а не наличием
    # хоть какого-то коммита: в мелком клоне коммит ровно один, и проверка «есть
    # ли коммиты» отвечает «есть» — я поймал это, воспроизведя клон CI (И2).
    путь, первый = ao.ИЗВЕСТНЫЕ_НАРУШЕНИЯ[0][0], ao.ИЗВЕСТНЫЕ_НАРУШЕНИЯ[0][1]
    if ao.строки_в_ревизии(путь, f"{первый}~1") is None:
        return {
            "outcome": ao.UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": len(ao.ИЗВЕСТНЫЕ_НАРУШЕНИЯ),
            "note": "истории в этом клоне нет (мелкий клон) — известные нарушения не проверить",
            "problems": [],
        }
    беды: list[str] = []
    нашлось = 0
    for path, коммит, строка, что in ao.ИЗВЕСТНЫЕ_НАРУШЕНИЯ:
        свои = [
            ш
            for ш in ao.сверить_историю(path, floor=f"{коммит}~1")
            if ш.outcome == ao.FAIL and коммит in ш.почему
        ]
        if not свои:
            беды.append(f"известное нарушение {path}@{коммит} ({что}) прибор НЕ увидел")
        elif свои[0].первая_разошедшаяся != строка:
            беды.append(
                f"{path}@{коммит}: ожидалась строка {строка}, названа {свои[0].первая_разошедшаяся}"
            )
        else:
            нашлось += 1
    return {
        "outcome": ao.FAIL if беды else ao.PASS,
        "checked": нашлось,
        "violations": len(беды),
        "unmeasured": 0,
        "note": "; ".join(беды) if беды else f"найдены все {нашлось} известных нарушения",
        "problems": беды,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="код возврата 0/1/2")
    args = parser.parse_args(argv)

    к = контроль()
    знак = "ok " if к["outcome"] == ao.PASS else "БЕДА"
    print(f"  {знак} негативный контроль на фикстурах: {к['note']}")

    изв = известные()
    метка_изв = {ao.PASS: "ok ", ao.FAIL: "БЕДА", ao.UNMEASURED: "  ?"}[изв["outcome"]]
    print(f"  {метка_изв} известные нарушения в истории: {изв['note']}")

    дерево = ao.сверить_все()
    for с in дерево:
        метка = {ao.PASS: "ok ", ao.FAIL: "БЕДА", ao.UNMEASURED: "  ?"}[с.outcome]
        print(f"  {метка} {с.path}: {с.почему}")
    в_дереве = ao.вердикт(дерево)

    история = [ш for p in ao.ЖУРНАЛЫ for ш in ao.сверить_историю(p)]
    в_истории = ao.вердикт(история)
    # Ноль шагов после пола — это НЕ «сторож ничего не сторожил»: это значит,
    # что журналов после пола ещё никто не трогал. Разница печатается словами,
    # потому что «нечего проверять» и «проверено и чисто» — разные вещи (Р1).
    сказано = "журналов после пола ещё не трогали" if not история else f"{в_истории['note'][:70]}"
    метка = "ok " if в_истории["outcome"] != ao.FAIL else "БЕДА"
    print(f"  {метка} история после пола {ao.ПОЛ[:7]}: шагов {len(история)}, {сказано}")

    checked = к["checked"] + изв["checked"] + в_дереве["checked"] + в_истории["checked"]
    violations = (
        к["violations"] + изв["violations"] + в_дереве["violations"] + в_истории["violations"]
    )
    unmeasured = (
        к["unmeasured"] + изв["unmeasured"] + в_дереве["unmeasured"] + в_истории["unmeasured"]
    )
    print(f"\nпроверено {checked}\nнарушений {violations}\nне смогли {unmeasured}")

    if violations:
        исход = ao.FAIL
    elif checked == 0:
        исход = ao.UNMEASURED
    else:
        исход = ao.PASS
    беды = к["problems"] + изв["problems"] + в_дереве["problems"] + в_истории["problems"]
    print(f"\n{исход}: {'; '.join(беды) if беды else к['note']}")

    if not args.check:
        return 0
    return {ao.PASS: 0, ao.FAIL: 1, ao.UNMEASURED: 2}[исход]


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
