#!/usr/bin/env python3
"""Одна модель — один ответ, каким бы написанием ни спросили.

    python scripts/check_model_names.py            # что в базе сейчас
    python scripts/check_model_names.py --check    # красный, если карман снова раздвоился

ДЕФЕКТ, ИЗМЕРЕНО 2026-09-02 на живой базе

    стоящих утверждений                        1696
    имён модели                                 466
    групп, где одна модель под >1 написанием      9

    advise("flux.2-klein-9b")   4 атрибута, 6 провалов, исход pass
    advise("flux-2-klein-9b")   2 атрибута, 0 провалов, исход pass   <- та же модель

Ответ был не просто неполон — он не сообщал, что неполон. Ни один
существующий гейт этого увидеть не мог: все они судят ОДНУ выдачу (схему,
тир, ссылку), а расхождение есть свойство ПАРЫ выдач на двух написаниях
одного имени. Поэтому прибор смотрит на пару.

ПОЧЕМУ ЭТО ГЕЙТ, А НЕ СТРОКА В ПРАВИЛАХ (Ц7). Свёртка живёт на чтении, в
`studio/selfrag/modelnames.py`. Любой потребитель, который заведёт СВОЮ
нормализацию имени (их было три до этой сессии) или сравнит имя сырой
строкой, снова разведёт карманы — молча и без единого красного теста.

НЕГАТИВНЫЙ КОНТРОЛЬ, ОБЕ ПОЛОВИНЫ (И5). Прибор, который склеивает всё,
отвечает «одна модель» на любой вход: пары РАЗНЫХ моделей обязаны остаться
разными (иначе красный), а подсадное раздвоение обязано быть замечено (иначе
красный тоже — значит прибор не шевелится).

Сети здесь нет.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from studio.selfrag.facts import (  # noqa: E402
    DEFAULT_FACTS_PATH,
    Fact,
    FactStore,
    load_facts,
)
from studio.mcp.advice import advise  # noqa: E402
from studio.selfrag.modelnames import collapsed, fold  # noqa: E402

#: Пары РАЗНЫХ моделей, взятые из живой базы. Литералы, а не выборка из кода
#: (правило Т2): выборка поедет вместе со свёрткой и промолчит. Склеить любую
#: из них — значит отвечать за одну модель фактами о другой.
РАЗНЫЕ: tuple[tuple[str, str], ...] = (
    ("flux-2-pro", "flux-2-pro-edit"),
    ("kling-3.0", "kling-3.0-pro-i2v"),
    ("eleven_v3", "eleven_v3_conversational"),
    ("cogvideox-2b", "cogvideox-5b"),
    ("flux-2-klein-4b", "flux-2-klein-9b"),
)

#: Подсадное раздвоение: одна модель, записанная двумя написаниями. Прибор,
#: который его не заметит, ничего не измеряет.
ПОДСАДНЫЕ: tuple[str, str] = ("проверка-модель-1.0", "проверка_модель_1_0")


def _контроль_разные() -> list[str]:
    """Половина первая: разное обязано остаться разным."""
    return [f"{a} == {b}" for a, b in РАЗНЫЕ if fold(a) == fold(b)]


def _контроль_подсадные() -> list[str]:
    """Половина вторая: прибор обязан шевельнуться на настоящем дубле."""
    один, другой = ПОДСАДНЫЕ
    склад = FactStore(
        [
            Fact(один, "max_seconds", "5", "https://example.test/a", "vendor", "2026-09-02"),
            Fact(другой, "resolution", "720p", "https://example.test/b", "vendor", "2026-09-02"),
        ]
    )
    беды = []
    if склад.attributes(один) != ["max_seconds", "resolution"]:
        беды.append(f"подсадной дубль не склеился: {склад.attributes(один)}")
    if len(collapsed([один, другой])) != 1:
        беды.append("подсадной дубль не опознан как группа")
    return беды


def проверить(path: Path | None = None) -> tuple[int, int, int, list[str]]:
    """(проверено, нарушений, не смогли, что именно). Р2: числа рядом."""
    беды = _контроль_разные() + _контроль_подсадные()
    нарушений = len(беды)
    проверено = len(РАЗНЫЕ) + 2
    не_смогли = 0

    источник = path or DEFAULT_FACTS_PATH
    rows = load_facts(источник)
    if not rows:
        # Р1: третий исход. Пустая база — это «не смогли проверить», а не
        # «нарушений ноль»: ноль нарушений при нуле проверок не успех.
        print(f"базы фактов нет или она пуста: {источник}")
        return проверено, нарушений, не_смогли + 1, беды

    склад = FactStore(rows)
    имена = склад.models()
    группы = collapsed(имена)
    свёрнуто = len(имена) - sum(len(g) - 1 for g in группы)
    print(f"утверждений {len(rows)}, имён {len(имена)}, имён после свёртки {свёрнуто}")
    print(f"групп из >1 написания: {len(группы)}")
    for группа in группы:
        проверено += 1
        # Мерится ТА ВЫДАЧА, которую читает спрашивающий, а не внутренний
        # индекс: дефект был виден именно в ответе `advise` и остался бы
        # невидимым для прибора, который сверяет только ключи хранилища.
        # ЗНАЧЕНИЯ утверждений сверяются тоже — совпадение одних лишь имён
        # атрибутов пропустило бы карман, отвечающий другим числом.
        наборы = {}
        for имя in группа:
            ответ = advise(имя, path=источник)
            наборы[имя] = (
                ответ["outcome"],
                tuple(sorted((a, tuple(v["values"])) for a, v in ответ["claims"].items())),
                len(ответ["failure_modes"]),
            )
        печать = ", ".join(
            f"{имя}({исход}, {len(атрибуты)}а/{провалы}п)"
            for имя, (исход, атрибуты, провалы) in наборы.items()
        )
        if len(set(наборы.values())) > 1:
            нарушений += 1
            беды.append(f"написания одной модели отвечают по-разному: {печать}")
        print(f"  {печать}")
    return проверено, нарушений, не_смогли, беды


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--path", type=Path, default=None)
    args = parser.parse_args(argv)

    проверено, нарушений, не_смогли, беды = проверить(args.path)
    for беда in беды:
        print(f"  НАРУШЕНИЕ: {беда}")
    print(f"\nпроверено {проверено}, нарушений {нарушений}, не смогли {не_смогли}")
    if not args.check:
        return 0
    if нарушений:
        return 1
    return 2 if не_смогли else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
