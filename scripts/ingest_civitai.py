"""Канал Civitai: опыт практиков по одной модели за раз, с записью через advice.record.

ЗАЧЕМ СКРИПТ, А НЕ РУКИ

Разбор одной модели руками — это чтение простыни HTML, отделение прозы автора
от благодарностей и ручной перенос настроек из галереи. Второй раз это ещё
делают, тридцатый — никогда. Логика разбора живёт в `studio/civitai.py`; здесь
точка входа, печать числами и запись.

ЧТО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ

Он не пишет в `model_facts.jsonl` сам. Заявки уходят в `advice.record`,
который сверяет предложенный тир с URL и умеет отказать; отказ — работа гейта,
а не ошибка канала, поэтому заявка повторяется следующей ступенью и только
отказ всеми считается неудачей.

Он не выбирает тир и не решает, что модель годится: права печатаются рядом с
находками, и НЕКОММЕРЧЕСКАЯ метка стоит ДО того, как модель попадёт в
рекомендации (Ц5).

`--check` СЕТИ НЕ ТРОГАЕТ

Гейт гоняет прибор по фикстурам `studio/knowledge/civitai_fixtures.json`,
снятым с живого API 2026-09-01, и требует негативного контроля в обе стороны
(И5): на богатом описании прибор обязан шевельнуться, на пустом — промолчать,
и то же самое по правам. Ноль нарушений при нуле отработавших проверок —
не успех, поэтому рядом с исходом печатаются три числа (Р2).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from studio import civitai  # noqa: E402

ФИКСТУРЫ = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "civitai_fixtures.json"

#: Фикстура, на которой прибор ОБЯЗАН шевельнуться, и та, на которой он обязан
#: сказать «нет». Взяты с обоих краёв живой выдачи (Т3): 1651125 — описание на
#: 11 086 символов с разбором настроек, 2129484 — описание на 3 277 символов из
#: ссылок и благодарностей, где наблюдений нет ни одного.
#: ИЗМЕРЕНО 2026-09-01 на этих самых файлах.
ШЕВЕЛИТСЯ = "1651125"
МОЛЧИТ = "2129484"

#: Модель с ПУСТЫМ списком коммерческих прав и модель с полным. Без второй
#: «все некоммерческие» читалось бы как работа детектора, хотя это была бы его
#: поломка.
БЕЗ_ПРАВ = "2448150"
С_ПРАВАМИ = "2129484"

#: Сколько наблюдений прибор обязан находить на каждой фикстуре. ИЗМЕРЕНО
#: 2026-09-01 на этих файлах и выписано числами, а не «больше нуля»: канал,
#: у которого выход просел с трёх до одного, останется зелёным у любой
#: проверки вида «хоть что-то нашли», и просадку заметит некому. Эти же числа
#: — измеренный выход канала: 4 наблюдения на 4 модели.
ОЖИДАЕМЫХ_НАБЛЮДЕНИЙ: dict[str, int] = {
    "1651125": 3,
    "2354193": 1,
    "2129484": 0,
    "2448150": 0,
}


def _фикстуры(path: Path = ФИКСТУРЫ) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def проверка(path: Path = ФИКСТУРЫ) -> dict[str, Any]:
    """Прибор по фикстурам: шевелится ли он и молчит ли там, где обязан.

    Три исхода (Р1): `годно`, `не годно` (нарушение названо) и `не смогли`
    (фикстур нет или они пусты — проверять было нечего, и это не успех).
    """
    if not path.is_file():
        return {
            "outcome": "не смогли",
            "проверено": 0,
            "нарушений": 0,
            "не смогли": 1,
            "почему": [f"нет файла фикстур {path}"],
        }
    данные = _фикстуры(path)
    модели = данные.get("модели") or {}
    if not модели:
        return {
            "outcome": "не смогли",
            "проверено": 0,
            "нарушений": 0,
            "не смогли": 1,
            "почему": ["в файле фикстур нет ни одной модели"],
        }

    проверено = 0
    беды: list[str] = []
    неизмеримо = 0

    for ключ, модель in модели.items():
        версии = (модель.get("modelVersions") or [])[: civitai.ВЕРСИЙ_ЧИТАЕМ]
        найдено = civitai.наблюдения(
            [модель.get("description")] + [v.get("description") for v in версии]
        )
        проверено += 1
        if найдено["предложений"] == 0:
            неизмеримо += 1
            continue
        безымянных = (
            найдено["предложений"] - len(найдено["наблюдения"]) - sum(найдено["отсев"].values())
        )
        if безымянных:
            беды.append(f"{ключ}: {безымянных} фраз отсеяно без названной причины")
        ждём = ОЖИДАЕМЫХ_НАБЛЮДЕНИЙ.get(ключ)
        if ждём is None:
            неизмеримо += 1
        else:
            проверено += 1
            if len(найдено["наблюдения"]) != ждём:
                беды.append(
                    f"{ключ}: наблюдений {len(найдено['наблюдения'])}, а измерено было {ждём}"
                )

    богатая = модели.get(ШЕВЕЛИТСЯ)
    if богатая is None:
        неизмеримо += 1
    else:
        проверено += 1
        сколько = len(
            civitai.наблюдения(
                [богатая.get("description")]
                + [v.get("description") for v in (богатая.get("modelVersions") or [])]
            )["наблюдения"]
        )
        if сколько == 0:
            беды.append(f"негативный контроль: на {ШЕВЕЛИТСЯ} прибор не нашёл НИ ОДНОГО наблюдения")

    пустая = модели.get(МОЛЧИТ)
    if пустая is None:
        неизмеримо += 1
    else:
        проверено += 1
        сколько = len(
            civitai.наблюдения(
                [пустая.get("description")]
                + [v.get("description") for v in (пустая.get("modelVersions") or [])]
            )["наблюдения"]
        )
        if сколько:
            беды.append(f"негативный контроль: на {МОЛЧИТ} прибор нашёл {сколько} — обязан молчать")

    без = модели.get(БЕЗ_ПРАВ)
    если_есть = модели.get(С_ПРАВАМИ)
    if без is None or если_есть is None:
        неизмеримо += 1
    else:
        проверено += 2
        метки_без = civitai.права(без)
        метки_с = civitai.права(если_есть)
        if not any(m.startswith("НЕКОММЕРЧЕСКАЯ") for m in метки_без):
            беды.append(f"права: {БЕЗ_ПРАВ} с пустым allowCommercialUse не помечена некоммерческой")
        if any(m.startswith("НЕКОММЕРЧЕСКАЯ") for m in метки_с):
            беды.append(f"права: {С_ПРАВАМИ} с полным набором прав помечена некоммерческой")

    версии = данные.get("версии") or {}
    if not версии:
        неизмеримо += 1
    else:
        for ключ, версия in версии.items():
            проверено += 1
            прогон = civitai.прогонные(версия)
            if прогон["outcome"] == "годно" and not прогон.get("сводка"):
                беды.append(f"версия {ключ}: исход «годно» при пустой сводке настроек")

    исход = "не годно" if беды else ("не смогли" if неизмеримо and проверено == 0 else "годно")
    return {
        "outcome": исход,
        "проверено": проверено,
        "нарушений": len(беды),
        "не смогли": неизмеримо,
        "почему": беды,
    }


def записать(строки: list[dict[str, Any]], today: str) -> dict[str, Any]:
    """Провести находки через `advice.record`. Тир предлагается, решает URL.

    Отказ по несовпадению тира — работа гейта, поэтому заявка повторяется
    следующей ступенью, и только отказ всеми ступенями считается неудачей.
    """
    from studio.mcp import advice  # локально: без записи модуль не нужен

    записано = отказано = 0
    причины: dict[str, int] = {}
    out: dict[str, Any] = {}
    for строка in строки:
        if строка.get("outcome") != "годно":
            continue
        # Дата источника — из карточки; `today` только там, где площадка её
        # не сообщила, и нота говорит, какая из двух это была (Е2).
        дата = строка.get("дата") or today
        откуда = "publishedAt версии" if строка.get("дата") else "даты у источника нет, дата чтения"
        for модель, атрибут, значение, url, нота in civitai.заявки(строка):
            нота = f"{нота}; дата: {откуда}"
            for тир in civitai.ТИРЫ_ПО_ОЧЕРЕДИ:
                out = advice.record(
                    модель, атрибут, значение, url, тир, дата, note=нота, read_directly=True
                )
                if out.get("outcome") == "pass":
                    записано += 1
                    break
            else:
                отказано += 1
                почему = str(out.get("note"))[:110]
                причины[почему] = причины.get(почему, 0) + 1
    return {"записано": записано, "отказано": отказано, "причины": причины}


def отчёт(строки: list[dict[str, Any]]) -> int:
    """Печать числами и три исхода (Р1, Р2, Е3)."""
    разобрано = [s for s in строки if s.get("outcome") == "годно"]
    наблюдений = 0
    for строка in строки:
        if строка.get("outcome") != "годно":
            print(f"  НЕ СМОГЛИ  {строка['model_id']}: {строка.get('note', '')}")
            continue
        print(f"\n=== {строка['model_id']} {строка['имя']} ({строка['тип']}, {строка['базовая']})")
        print(f"    автор: {строка['автор'] or '—'}, скачиваний {строка['скачиваний']}")
        if строка["права"]:
            for метка in строка["права"]:
                print(f"    ПРАВА: {метка}")
        else:
            print("    права: ограничений во флагах не нашли")
        наблюдений += len(строка["наблюдения"])
        print(
            f"    описание: предложений {строка['предложений']},"
            f" наблюдений {len(строка['наблюдения'])}"
        )
        for фраза in строка["наблюдения"]:
            print(f"       + {фраза[:160]}")
        for почему, сколько in sorted(строка["отсев"].items(), key=lambda x: -x[1]):
            print(f"       – {сколько}: {почему}")
        for прогон in строка["прогоны"]:
            if прогон.get("outcome") == "годно":
                print(
                    f"    прогоны версии {прогон['версия']}:"
                    f" {прогон['с настройками']} из {прогон['картинок']} картинок"
                    f" — {civitai.словами(прогон['сводка'])}"
                )
            else:
                print(
                    f"    прогоны версии {прогон.get('версия')}: НЕ СМОГЛИ — {прогон.get('почему')}"
                )
    не_смогли = len(строки) - len(разобрано)
    print(
        f"\nпроверено {len(строки)}, разобрано {len(разобрано)}, не смогли {не_смогли};"
        f" наблюдений {наблюдений}"
        + (f", на модель {наблюдений / len(разобрано):.2f}" if разобрано else "")
    )
    if not строки:
        print("исход: не смогли — не назвали ни одной модели")
        return 2
    if not разобрано:
        print("исход: не смогли — ни одна карточка не открылась")
        return 2
    if не_смогли:
        print(f"исход: не смогли полностью — {len(разобрано)} из {len(строки)}")
        return 2
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("models", nargs="*", help="числовые id моделей Civitai, вида 1651125")
    parser.add_argument("--json", action="store_true")
    parser.add_argument(
        "--check",
        action="store_true",
        help="прогнать прибор по фикстурам, без сети: негативный контроль в обе стороны",
    )
    parser.add_argument(
        "--record",
        metavar="ДАТА",
        help="записать находки через advice.record, датой источника ДАТА",
    )
    args = parser.parse_args(argv)

    if args.check:
        итог = проверка()
        for почему in итог["почему"]:
            print(f"  НАРУШЕНИЕ: {почему}")
        print(
            f"civitai: проверено {итог['проверено']},"
            f" нарушений {итог['нарушений']}, не смогли {итог['не смогли']}"
        )
        print(f"исход: {итог['outcome']}")
        return {"годно": 0, "не годно": 1}.get(итог["outcome"], 2)

    if not args.models:
        print("исход: не смогли — не назвали ни одной модели")
        return 2
    строки = [civitai.survey(m) for m in args.models]
    if args.record:
        итог = записать(строки, args.record)
        print(
            f"записано {итог['записано']}, отказано {итог['отказано']},"
            f" моделей {len([s for s in строки if s.get('outcome') == 'годно'])}"
        )
        for почему, сколько in sorted(итог["причины"].items(), key=lambda x: -x[1]):
            print(f"  {сколько}  {почему}")
    if args.json:
        print(json.dumps(строки, ensure_ascii=False, indent=2))
        return 0 if all(s.get("outcome") == "годно" for s in строки) else 2
    return отчёт(строки)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
