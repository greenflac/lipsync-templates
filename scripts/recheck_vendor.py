#!/usr/bin/env python3
"""Вендорские страницы: изменились ли те, на которых стоит база.

ЗАЧЕМ

Владелец назвал предметом мониторинга вендорские сайты. Самое дешёвое и самое
честное, что можно с них взять, — не «что нового написали», а «изменилось ли
то, на что мы уже сослались». Утверждение вендорского тира — это прочитанная
страница; страница поменялась — утверждение обязано быть перечитано, иначе оно
тихо стареет, оставаясь на вид свежим.

ИЗМЕРЕНО 2026-09-03 на живой базе:

    вендорских утверждений               624
    различных вендорских URL             214  (все они и есть цели обхода)
    за ними хостов, закрытых политикой     0  (Ц3: закрытое не обходим)

ПЕРЕСЧЁТ ОТ 2026-09-03, И ОН ВАЖНЕЕ САМИХ ЧИСЕЛ. Днём раньше здесь стояло
«целей 71, за ними 276 утверждений; остальные 141 — хост не записан или
закрыт». Это была ОШИБКА КАНАЛА, а не свойство базы: карта достижимости
строится из ОТКАЗОВ и проб, поэтому хост, который ни разу не отказал, в неё
просто не попадает. Условие «идём, если state == open» пропускало ровно те
хосты, что всегда работали:

    huggingface.co            275 утверждений
    raw.githubusercontent.com  31
    cloud.google.com           29
    cookbook.openai.com        12
    github.com                  1

348 из 624, то есть 56% вендорского тира, не наблюдались вовсе — и «не
смотрели» выглядело как «нечего смотреть». Положений у хоста теперь три
(`ОТКРЫТ`, `ЗАКРЫТ`, `НЕ_ЗАПИСАН`), и третье не сливается со вторым.

ЧТО ЭТОТ КАНАЛ СЧИТАЕТ ИЗМЕНЕНИЕМ

Отпечаток текста страницы. Не слова утверждения: 234 из 276 значений — это
пересказ в 4 и более слов, наш, а не источника, и искать их подстрокой значило
бы получить «не подтверждено» на двух сотнях честных строк. Канал, который
кричит двести раз, учит себя не читать.

ПЕРВЫЙ ПРОГОН НИЧЕГО НЕ ИЗМЕРЯЕТ, И ЭТО НАПИСАНО ЗДЕСЬ, А НЕ ОБНАРУЖИТСЯ ПОТОМ

Отпечатков со времени записи фактов у нас нет — их никто не снимал. Поэтому
первый прогон только заводит основание, и вопрос «изменилось ли» на нём имеет
ровно один честный ответ: не смогли. Со второго прогона ответ появляется.

ТРИ ИСХОДА (Р1)

    годно      страницы прочитаны, изменения посчитаны
    не годно   страница изменилась — утверждения за ней надо перечитать
    не смогли  основания ещё нет, или страница не ответила, или закрыта
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio.mcp import fetch  # noqa: E402
from studio.selfrag.facts import load_facts  # noqa: E402

ОСНОВАНИЕ = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "vendor_pages.jsonl"
КАРТА_ХОСТОВ = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "denied_hosts.jsonl"

#: Пауза между запросами к чужим хостам. ВЫБРАНО 0.5 с: канал ходит по 71
#: адресу на 32 хостах, то есть по паре страниц на хост, и торопиться некуда.
ПАУЗА = 0.5

#: Второй потолок чтения, на который канал переспрашивает ОБРЕЗАННУЮ страницу.
#: ВЫБРАНО 1.6 МБ = вчетверо от потолка `fetch`, и число не с потолка:
#: ИЗМЕРЕНО 2026-09-03 на `kling.ai/quickstart/text-to-video-prompt-guide` —
#: при 400 000 байт приходит ровно потолок и в нём один сплошной CSS (ни
#: одного слова гида), при 1 600 000 страница приходит ЦЕЛИКОМ (839 711 байт)
#: и все пять слов записанного скелета промпта на месте.
#:
#: Переспрашивается РОВНО ОДИН раз. Лестница из потолков означала бы, что
#: канал сам решает, сколько чужого трафика ему занять; страница, не влезшая
#: и во второй, честно уходит в третий исход.
ПОТОЛОК_ПОВТОРА = 1_600_000

#: Разметка и пробелы — оформление, а не текст. Без нормализации страница
#: «менялась» бы от перевёрстки, и канал сообщал бы об изменении там, где
#: вендор не поменял ни слова.
ПРОБЕЛЫ = re.compile(r"\s+")
ТЕГИ = re.compile(r"<[^>]+>")

#: СОДЕРЖИМОЕ `<script>` И `<style>` — НЕ ТЕКСТ СТРАНИЦЫ, И ЭТО ИЗМЕРЕНО.
#:
#: Первая версия снимала только разметку тегов, а тело скриптов оставляла. На
#: втором прогоне по 68 вендорским страницам канал объявил изменившимися 12 —
#: за десять минут, то есть заведомо ложно. Диагноз снят сравнением одной
#: страницы с самой собой (`ai.google.dev/gemini-api/docs/embeddings`, два
#: запроса подряд):
#:
#:     "profiles__enable_profile_collections","concierge__enable_actions_menu"
#:  -> "profiles__enable_completequiz_endpoint","profiles__enable_complete_pl"
#:
#: Это список флагов эксперимента, который CDN тасует на каждый запрос. Текст
#: страницы при этом не менялся ни на слово.
СКРИПТЫ = re.compile(r"<(script|style)\b[^>]*>.*?</\1\s*>", re.I | re.S)

#: Как посчитан отпечаток. Едет в журнал вместе с ним: правило нормализации
#: меняется (и уже поменялось один раз), а отпечатки, снятые разными
#: правилами, сравнивать нельзя — иначе смена правила прочитается как смена
#: ВСЕХ страниц разом. Отпечаток чужого способа — это «не смогли», а не
#: «изменилось».
# 2026-09-03: правило нормализации изменилось — добавлен образец против
# случайного имени класса HuggingFace, — и ЭТО ОБЯЗАНО МЕНЯТЬ ИМЯ СПОСОБА.
# Я на этом и попался: сменил образец, имя оставил, и канал объявил
# изменившимися 72 страницы из 214. Ровно то, о чём предупреждает абзац
# выше; предупреждение написал я же накануне.
СПОСОБ = "text-2026-09-03-без-скриптов-без-hf-класса"

#: Числа, даты и идентификаторы сессии, которые страницы печатают сами по себе
#: и которые меняются при каждом запросе. Не вычистив их, канал сообщал бы об
#: изменении на КАЖДОМ прогоне — то есть не сообщал бы ни о чём.
ШУМ = (
    re.compile(r"\b\d{4}-\d{2}-\d{2}T[\d:.]+Z?\b"),
    # Кавычка после `=` — часть оформления, а не значения, и класс из одного
    # знака её съедал вместо разделителя: `nonce='a1b2'` чистилось до
    # `'a1b2'`, то есть не чистилось. Поймано собственным тестом.
    re.compile(r"\bnonce\s*[=:]\s*[\"']?[\w-]+[\"']?", re.I),
    re.compile(r"\bcsrf[\w-]*\s*[=:]\s*[\"']?[\w-]+[\"']?", re.I),
    re.compile(r"\b[0-9a-f]{32,}\b", re.I),
    # HuggingFace подставляет СВОЁ имя класса на каждый запрос:
    # `hf-sanitized-1uctzfwuvqirhkdmmcnlx` против
    # `hf-sanitized-l7v71eqxhylxdbqrekv9t` на двух запросах подряд к одной
    # странице (ИЗМЕРЕНО 2026-09-03 на `black-forest-labs/FLUX.1-dev`). Без
    # этого канал объявил бы изменившимися все страницы HuggingFace разом —
    # 74 из 214 на живом прогоне, и почти все ложно.
    re.compile(r"hf-sanitized-[a-z0-9]{8,}", re.I),
)


def отпечаток(текст: str) -> str:
    """Отпечаток СОДЕРЖАНИЯ страницы: без тегов, без пробелов, без шума."""
    очищено = СКРИПТЫ.sub(" ", текст or "")
    очищено = ТЕГИ.sub(" ", очищено)
    for образец in ШУМ:
        очищено = образец.sub(" ", очищено)
    очищено = ПРОБЕЛЫ.sub(" ", очищено).strip().casefold()
    return hashlib.sha256(очищено.encode("utf-8")).hexdigest()


#: Три положения хоста, и третье НЕ равно второму. Заведено 2026-09-03 по
#: измерению: карта хостов строилась из ОТКАЗОВ и проб, поэтому хост, который
#: ни разу не отказал, в неё просто не попадал. Канал брал условие
#: «state == open» — и молча пропускал ровно те хосты, что всегда работали.
#:
#: ИЗМЕРЕНО на живой базе: вендорских утверждений 624, из них
#:     на хостах, записанных `open`   276
#:     на хостах, которых В КАРТЕ НЕТ 348  (huggingface.co 275,
#:         raw.githubusercontent.com 31, cloud.google.com 29,
#:         cookbook.openai.com 12, github.com 1)
#: То есть 56% утверждений вендорского тира не наблюдались вовсе, и «не
#: смотрели» выглядело как «нечего смотреть».
ОТКРЫТ = "открыт"
ЗАКРЫТ = "закрыт"
НЕ_ЗАПИСАН = "не записан"


def состояние_хостов(путь: Path = КАРТА_ХОСТОВ) -> dict[str, str]:
    """Что карта говорит про каждый хост. Журнал: побеждает последняя строка."""
    состояние: dict[str, str] = {}
    if not путь.is_file():
        return состояние
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        хост = str(запись.get("host") or "")
        if хост:
            состояние[хост] = ОТКРЫТ if str(запись.get("state") or "") == "open" else ЗАКРЫТ
    return состояние


def положение(хост: str, карта: dict[str, str]) -> str:
    """ОТКРЫТ / ЗАКРЫТ / НЕ_ЗАПИСАН — ровно три, и они не сливаются (Р1)."""
    return карта.get(хост, НЕ_ЗАПИСАН)


def открытые_хосты(путь: Path = КАРТА_ХОСТОВ) -> set[str]:
    """Хосты, про которые карта говорит `open`. Оставлено: на него смотрят тесты
    и он же отвечает на вопрос «что карта УЖЕ знает», отдельно от «куда идти»."""
    return {х for х, с in состояние_хостов(путь).items() if с == ОТКРЫТ}


def адреса(
    *,
    tier: str = "vendor",
    факты: Any = None,
    карта: dict[str, str] | None = None,
) -> tuple[dict[str, int], dict[str, dict[str, int]]]:
    """Куда канал идёт — и что он НЕ смотрит, с числами (Р2).

    Возвращает пару:
      * `url -> сколько утверждений на нём стоит` — цели обхода. Число едет
        вместе с адресом: изменение страницы с двадцатью утверждениями и с
        одним — разной величины работа, и сортировать очередь без него нечем;
      * `положение -> {хост: утверждений}` — что осталось за бортом и почему.

    ХОСТ, КОТОРОГО В КАРТЕ НЕТ, — ЦЕЛЬ, А НЕ ПРОПУСК. Он ни разу не отказывал;
    карта строилась из отказов, поэтому в неё не попал. Первый же запрос
    `fetch.fetch` запишет его положение сам — так карта и заполняется. Это не
    обход Ц3: закрытый политикой хост (`ЗАКРЫТ`) не трогается ни здесь, ни
    зеркалом, ни прокси, и остаётся в отчёте отдельной строкой.
    """
    # Факты и карта принимаются параметрами (Т5): развилка «идём или не идём»
    # — самая мутирующая в этом модуле, и она обязана быть достижима тестом
    # без живой базы и без сети.
    карта = состояние_хостов() if карта is None else карта
    счёт: dict[str, int] = {}
    мимо: dict[str, dict[str, int]] = {ЗАКРЫТ: {}}
    for факт in load_facts() if факты is None else факты:
        if факт.tier != tier:
            continue
        url = str(факт.source_url or "")
        if not url:
            continue
        хост = urlparse(url).netloc
        где = положение(хост, карта)
        if где == ЗАКРЫТ:
            мимо[ЗАКРЫТ][хост] = мимо[ЗАКРЫТ].get(хост, 0) + 1
            continue
        счёт[url] = счёт.get(url, 0) + 1
    return счёт, мимо


def прежние(путь: Path = ОСНОВАНИЕ) -> dict[str, dict[str, Any]]:
    """Последний известный отпечаток каждой страницы. Журнал, дописываемый."""
    итог: dict[str, dict[str, Any]] = {}
    if not путь.is_file():
        return итог
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if запись.get("url"):
            итог[str(запись["url"])] = запись
    return итог


def обойти(цели: dict[str, int], было: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Прочитать страницы и сравнить с основанием. Р2: три числа рядом с исходом."""
    изменились: list[dict[str, Any]] = []
    как_прежде = 0
    заведено = 0
    не_ответили: list[str] = []
    обрезаны: list[str] = []
    нестабильны: list[str] = []
    добрано = 0
    новые: list[dict[str, Any]] = []

    for номер, (url, сколько) in enumerate(sorted(цели.items(), key=lambda x: -x[1])):
        if номер:
            time.sleep(ПАУЗА)
        ответ = fetch.fetch(url)
        if ответ.get("outcome") != PASS:
            не_ответили.append(url)
            continue
        # ОБРЕЗАННЫЙ ОТВЕТ — НЕ СТРАНИЦА, И ОТПЕЧАТОК С НЕГО СНИМАТЬ НЕЛЬЗЯ.
        # ИЗМЕРЕНО 2026-09-03 на `kling.ai/quickstart/text-to-video-prompt-guide`:
        # ответ 200, ровно 400 000 байт, `truncated: True`, и в этих байтах —
        # один открывающий `<style>` без закрывающего, то есть СПЛОШНОЙ CSS.
        # Отпечаток такого куска стабилен (стили не меняются), и канал год
        # подряд говорил бы «страница не менялась» про таблицу стилей. Три
        # утверждения за этой страницей при этом перечитать нечем.
        if ответ.get("truncated"):
            # Один переспрос с большим потолком: у иных вендоров тело статьи
            # лежит за 400 КБ вёрстки, и объявлять такую страницу непрочитанной
            # значило бы терять её навсегда (см. `ПОТОЛОК_ПОВТОРА`).
            time.sleep(ПАУЗА)
            ответ = fetch.fetch(url, max_bytes=ПОТОЛОК_ПОВТОРА)
            if ответ.get("outcome") != PASS:
                не_ответили.append(url)
                continue
            if ответ.get("truncated"):
                обрезаны.append(url)
                continue
            добрано += 1
        свежий = отпечаток(str(ответ.get("text") or ""))
        строка = {
            "url": url,
            "fingerprint": свежий,
            "method": СПОСОБ,
            "claims": сколько,
            "seen_on": date.today().isoformat(),
        }
        новые.append(строка)
        предыдущая = было.get(url, {})
        # Отпечаток, снятый ДРУГИМ правилом, сравнивать не с чем: он не
        # «отличается», он посчитан иначе. Третий исход, не второй.
        прежний = предыдущая.get("fingerprint") if предыдущая.get("method") == СПОСОБ else None
        if not прежний:
            заведено += 1
        elif прежний == свежий:
            как_прежде += 1
        else:
            # СТРАНИЦА СРАВНИВАЕТСЯ САМА С СОБОЙ, ПРЕЖДЕ ЧЕМ ОБЪЯВИТЬ ЕЁ
            # ИЗМЕНИВШЕЙСЯ. Список известного шума (`ШУМ`) — это память о
            # хостах, которые уже подводили; новый хост приносит свой шум, и
            # список о нём не знает. Поэтому на расхождении делается ВТОРОЙ
            # запрос: два свежих чтения, разошедшихся между собой, означают
            # «страница нестабильна», а не «вендор что-то поменял». Это тот же
            # негативный контроль, которым 2026-09-02 был пойман CDN Google, —
            # только теперь его ставит сам канал, а не человек задним числом.
            time.sleep(ПАУЗА)
            второй = fetch.fetch(url)
            если_второй = (
                отпечаток(str(второй.get("text") or ""))
                if второй.get("outcome") == PASS and not второй.get("truncated")
                else None
            )
            if если_второй is None or если_второй != свежий:
                нестабильны.append(url)
                новые.pop()
                continue
            изменились.append({**строка, "was": прежний, "was_seen_on": было[url].get("seen_on")})
    return {
        "изменились": изменились,
        "как прежде": как_прежде,
        "заведено": заведено,
        "не ответили": не_ответили,
        "обрезаны": обрезаны,
        "нестабильны": нестабильны,
        "добрано": добрано,
        "строки": новые,
    }


def свести(итог: dict[str, Any], целей: int) -> dict[str, Any]:
    """Вердикт и три числа. Изменение — это `не годно`: работа, а не поломка."""
    изменений = len(итог["изменились"])
    не_смогли = (
        len(итог["не ответили"])
        + len(итог["обрезаны"])
        + len(итог["нестабильны"])
        + итог["заведено"]
    )
    если_первый = итог["заведено"] and not итог["как прежде"] and not изменений
    исход = FAIL if изменений else (UNMEASURED if не_смогли else PASS)
    нота = (
        f"основание заведено на {итог['заведено']} страницах; вопрос «изменилось ли» "
        "на первом прогоне честного ответа не имеет"
        if если_первый
        else (
            f"изменились {изменений} страниц(ы), за ними "
            f"{sum(с['claims'] for с in итог['изменились'])} утверждений — перечитать"
            if изменений
            else f"как прежде {итог['как прежде']} из {целей}"
        )
    )
    return {
        "outcome": исход,
        "checked": целей,
        "violations": изменений,
        "unmeasured": не_смогли,
        "note": нота,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="дописать отпечатки в основание")
    parser.add_argument("--limit", type=int, default=0, help="взять только N самых нагруженных")
    args = parser.parse_args(argv)

    цели, мимо = адреса()
    if args.limit:
        цели = dict(sorted(цели.items(), key=lambda x: -x[1])[: args.limit])
    было = прежние()
    print(f"вендорских адресов к обходу {len(цели)}, основание знает {len(было)}")
    закрытых = мимо[ЗАКРЫТ]
    if закрытых:
        # Р2: за бортом остаётся ровно одно положение, и оно печатается
        # числами. Ц3: закрытое политикой не обходится — оно называется.
        print(
            f"  не идём на закрытые политикой хосты: {len(закрытых)}, "
            f"за ними утверждений {sum(закрытых.values())}"
        )
        for хост, сколько in sorted(закрытых.items(), key=lambda x: -x[1])[:5]:
            print(f"    {сколько:4}  {хост}")

    итог = обойти(цели, было)
    вердикт = свести(итог, len(цели))
    for строка in итог["изменились"]:
        print(
            f"  ИЗМЕНИЛАСЬ ({строка['claims']} утв., виделась {строка['was_seen_on']}) {строка['url']}"
        )
    for url in итог["не ответили"][:10]:
        print(f"  не ответила: {url}")
    if итог["добрано"]:
        print(
            f"  дочитано вторым запросом с большим потолком: {итог['добрано']} "
            "страниц(ы) — тело статьи лежало за 400 КБ вёрстки"
        )
    for url in итог["обрезаны"][:10]:
        print(f"  ОБРЕЗАНА на потолке — отпечаток не снят: {url}")
    for url in итог["нестабильны"][:10]:
        print(f"  НЕСТАБИЛЬНА: два чтения подряд разошлись между собой — не изменение: {url}")

    if args.write and итог["строки"]:
        # ЖУРНАЛ, А НЕ СНИМОК: строки дописываются, прежние остаются. Отпечаток
        # позавчерашней страницы — единственный способ узнать, что вендор
        # поменял её дважды, а не один раз.
        с_ОСНОВАНИЕМ = "" if ОСНОВАНИЕ.exists() else _ШАПКА
        ОСНОВАНИЕ.write_text(
            (ОСНОВАНИЕ.read_text(encoding="utf-8") if ОСНОВАНИЕ.exists() else с_ОСНОВАНИЕМ)
            + "".join(json.dumps(с, ensure_ascii=False) + "\n" for с in итог["строки"]),
            encoding="utf-8",
        )
        print(f"дописано строк {len(итог['строки'])}: {ОСНОВАНИЕ.name}")

    print(f"\n{вердикт['note']}")
    print(
        f"\nпроверено {вердикт['checked']}\nнарушений {вердикт['violations']}\n"
        f"не смогли {вердикт['unmeasured']}"
    )
    return 0 if вердикт["outcome"] == PASS else (1 if вердикт["outcome"] == FAIL else 2)


