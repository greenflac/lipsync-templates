#!/usr/bin/env python3
"""Вендорские страницы: изменились ли те, на которых стоит база.

ЗАЧЕМ

Владелец назвал предметом мониторинга вендорские сайты. Самое дешёвое и самое
честное, что можно с них взять, — не «что нового написали», а «изменилось ли
то, на что мы уже сослались». Утверждение вендорского тира — это прочитанная
страница; страница поменялась — утверждение обязано быть перечитано, иначе оно
тихо стареет, оставаясь на вид свежим.

ИЗМЕРЕНО 2026-09-02 на живой базе:

    вендорских утверждений               618
    различных вендорских URL             212
    из них на хостах, открытых политикой  71  (за ними 276 утверждений)
    остальные 141 — хост в карте не записан или закрыт (Ц3: не обходим)

ЧТО ЭТОТ КАНАЛ СЧИТАЕТ ИЗМЕНЕНИЕМ

Отпечаток текста страницы. Не слова утверждения: 234 из 276 значений — это
пересказ в 4 и более слов, наш, а не источника, и искать их подстрокой значило
бы получить «не подтверждено» на двух сотнях честных строк. Канал, который
кричит двести раз, учит себя не читать.

ПЕРВЫЙ ПРОГОН НИЧЕГО НЕ ИЗМЕРЯЕТ, И ЭТО НАПИСАНО ЗДЕСЬ, А НЕ ОБНАРУЖИТСЯ ПОТОМ

Отпечатков со времени записи фактов у нас нет — их никто не снимал. Поэтому
первый прогон только заводит основание, и вопрос «изменилось ли» на нём имеет
ровно один честный ответ: не смогли. Со второго прогона ответ появляется.

ТРИ ИСХОДА (Р1)

    годно      страницы прочитаны, изменения посчитаны
    не годно   страница изменилась — утверждения за ней надо перечитать
    не смогли  основания ещё нет, или страница не ответила, или закрыта
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio.mcp import fetch  # noqa: E402
from studio.selfrag.facts import load_facts  # noqa: E402

ОСНОВАНИЕ = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "vendor_pages.jsonl"
КАРТА_ХОСТОВ = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "denied_hosts.jsonl"

#: Пауза между запросами к чужим хостам. ВЫБРАНО 0.5 с: канал ходит по 71
#: адресу на 32 хостах, то есть по паре страниц на хост, и торопиться некуда.
ПАУЗА = 0.5

#: Разметка и пробелы — оформление, а не текст. Без нормализации страница
#: «менялась» бы от перевёрстки, и канал сообщал бы об изменении там, где
#: вендор не поменял ни слова.
ПРОБЕЛЫ = re.compile(r"\s+")
ТЕГИ = re.compile(r"<[^>]+>")

#: СОДЕРЖИМОЕ `<script>` И `<style>` — НЕ ТЕКСТ СТРАНИЦЫ, И ЭТО ИЗМЕРЕНО.
#:
#: Первая версия снимала только разметку тегов, а тело скриптов оставляла. На
#: втором прогоне по 68 вендорским страницам канал объявил изменившимися 12 —
#: за десять минут, то есть заведомо ложно. Диагноз снят сравнением одной
#: страницы с самой собой (`ai.google.dev/gemini-api/docs/embeddings`, два
#: запроса подряд):
#:
#:     "profiles__enable_profile_collections","concierge__enable_actions_menu"
#:  -> "profiles__enable_completequiz_endpoint","profiles__enable_complete_pl"
#:
#: Это список флагов эксперимента, который CDN тасует на каждый запрос. Текст
#: страницы при этом не менялся ни на слово.
СКРИПТЫ = re.compile(r"<(script|style)\b[^>]*>.*?</\1\s*>", re.I | re.S)

#: Как посчитан отпечаток. Едет в журнал вместе с ним: правило нормализации
#: меняется (и уже поменялось один раз), а отпечатки, снятые разными
#: правилами, сравнивать нельзя — иначе смена правила прочитается как смена
#: ВСЕХ страниц разом. Отпечаток чужого способа — это «не смогли», а не
#: «изменилось».
СПОСОБ = "text-2026-09-02-без-скриптов"

#: Числа, даты и идентификаторы сессии, которые страницы печатают сами по себе
#: и которые меняются при каждом запросе. Не вычистив их, канал сообщал бы об
#: изменении на КАЖДОМ прогоне — то есть не сообщал бы ни о чём.
ШУМ = (
    re.compile(r"\b\d{4}-\d{2}-\d{2}T[\d:.]+Z?\b"),
    # Кавычка после `=` — часть оформления, а не значения, и класс из одного
    # знака её съедал вместо разделителя: `nonce='a1b2'` чистилось до
    # `'a1b2'`, то есть не чистилось. Поймано собственным тестом.
    re.compile(r"\bnonce\s*[=:]\s*[\"']?[\w-]+[\"']?", re.I),
    re.compile(r"\bcsrf[\w-]*\s*[=:]\s*[\"']?[\w-]+[\"']?", re.I),
    re.compile(r"\b[0-9a-f]{32,}\b", re.I),
)


def отпечаток(текст: str) -> str:
    """Отпечаток СОДЕРЖАНИЯ страницы: без тегов, без пробелов, без шума."""
    очищено = СКРИПТЫ.sub(" ", текст or "")
    очищено = ТЕГИ.sub(" ", очищено)
    for образец in ШУМ:
        очищено = образец.sub(" ", очищено)
    очищено = ПРОБЕЛЫ.sub(" ", очищено).strip().casefold()
    return hashlib.sha256(очищено.encode("utf-8")).hexdigest()


def открытые_хосты(путь: Path = КАРТА_ХОСТОВ) -> set[str]:
    """Хосты, про которые карта говорит `open`. Журнал: побеждает последняя строка."""
    состояние: dict[str, str] = {}
    if not путь.is_file():
        return set()
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        хост = str(запись.get("host") or "")
        if хост:
            состояние[хост] = str(запись.get("state") or "")
    return {х for х, с in состояние.items() if с == "open"}


def адреса(*, tier: str = "vendor") -> dict[str, int]:
    """Вендорские URL базы, за которыми стоит хотя бы одно утверждение.

    Возвращает `url -> сколько утверждений на нём стоит`: число едет вместе с
    адресом, потому что изменение страницы с двадцатью утверждениями и с одним
    — разной величины работа, и сортировать очередь без него нечем.
    """
    открыты = открытые_хосты()
    счёт: dict[str, int] = {}
    for факт in load_facts():
        if факт.tier != tier:
            continue
        url = str(факт.source_url or "")
        if not url or urlparse(url).netloc not in открыты:
            continue
        счёт[url] = счёт.get(url, 0) + 1
    return счёт


def прежние(путь: Path = ОСНОВАНИЕ) -> dict[str, dict[str, Any]]:
    """Последний известный отпечаток каждой страницы. Журнал, дописываемый."""
    итог: dict[str, dict[str, Any]] = {}
    if not путь.is_file():
        return итог
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if запись.get("url"):
            итог[str(запись["url"])] = запись
    return итог


def обойти(цели: dict[str, int], было: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Прочитать страницы и сравнить с основанием. Р2: три числа рядом с исходом."""
    изменились: list[dict[str, Any]] = []
    как_прежде = 0
    заведено = 0
    не_ответили: list[str] = []
    новые: list[dict[str, Any]] = []

    for номер, (url, сколько) in enumerate(sorted(цели.items(), key=lambda x: -x[1])):
        if номер:
            time.sleep(ПАУЗА)
        ответ = fetch.fetch(url)
        if ответ.get("outcome") != PASS:
            не_ответили.append(url)
            continue
        свежий = отпечаток(str(ответ.get("text") or ""))
        строка = {
            "url": url,
            "fingerprint": свежий,
            "method": СПОСОБ,
            "claims": сколько,
            "seen_on": date.today().isoformat(),
        }
        новые.append(строка)
        предыдущая = было.get(url, {})
        # Отпечаток, снятый ДРУГИМ правилом, сравнивать не с чем: он не
        # «отличается», он посчитан иначе. Третий исход, не второй.
        прежний = предыдущая.get("fingerprint") if предыдущая.get("method") == СПОСОБ else None
        if not прежний:
            заведено += 1
        elif прежний == свежий:
            как_прежде += 1
        else:
            изменились.append({**строка, "was": прежний, "was_seen_on": было[url].get("seen_on")})
    return {
        "изменились": изменились,
        "как прежде": как_прежде,
        "заведено": заведено,
        "не ответили": не_ответили,
        "строки": новые,
    }


def свести(итог: dict[str, Any], целей: int) -> dict[str, Any]:
    """Вердикт и три числа. Изменение — это `не годно`: работа, а не поломка."""
    изменений = len(итог["изменились"])
    не_смогли = len(итог["не ответили"]) + итог["заведено"]
    если_первый = итог["заведено"] and not итог["как прежде"] and not изменений
    исход = FAIL if изменений else (UNMEASURED if не_смогли else PASS)
    нота = (
        f"основание заведено на {итог['заведено']} страницах; вопрос «изменилось ли» "
        "на первом прогоне честного ответа не имеет"
        if если_первый
        else (
            f"изменились {изменений} страниц(ы), за ними "
            f"{sum(с['claims'] for с in итог['изменились'])} утверждений — перечитать"
            if изменений
            else f"как прежде {итог['как прежде']} из {целей}"
        )
    )
    return {
        "outcome": исход,
        "checked": целей,
        "violations": изменений,
        "unmeasured": не_смогли,
        "note": нота,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="дописать отпечатки в основание")
    parser.add_argument("--limit", type=int, default=0, help="взять только N самых нагруженных")
    args = parser.parse_args(argv)

    цели = адреса()
    if args.limit:
        цели = dict(sorted(цели.items(), key=lambda x: -x[1])[: args.limit])
    было = прежние()
    print(f"вендорских адресов на открытых хостах {len(цели)}, основание знает {len(было)}")

    итог = обойти(цели, было)
    вердикт = свести(итог, len(цели))
    for строка in итог["изменились"]:
        print(
            f"  ИЗМЕНИЛАСЬ ({строка['claims']} утв., виделась {строка['was_seen_on']}) {строка['url']}"
        )
    for url in итог["не ответили"][:10]:
        print(f"  не ответила: {url}")

    if args.write and итог["строки"]:
        # ЖУРНАЛ, А НЕ СНИМОК: строки дописываются, прежние остаются. Отпечаток
        # позавчерашней страницы — единственный способ узнать, что вендор
        # поменял её дважды, а не один раз.
        с_ОСНОВАНИЕМ = "" if ОСНОВАНИЕ.exists() else _ШАПКА
        ОСНОВАНИЕ.write_text(
            (ОСНОВАНИЕ.read_text(encoding="utf-8") if ОСНОВАНИЕ.exists() else с_ОСНОВАНИЕМ)
            + "".join(json.dumps(с, ensure_ascii=False) + "\n" for с in итог["строки"]),
            encoding="utf-8",
        )
        print(f"дописано строк {len(итог['строки'])}: {ОСНОВАНИЕ.name}")

    print(f"\n{вердикт['note']}")
    print(
        f"\nпроверено {вердикт['checked']}\nнарушений {вердикт['violations']}\n"
        f"не смогли {вердикт['unmeasured']}"
    )
    return 0 if вердикт["outcome"] == PASS else (1 if вердикт["outcome"] == FAIL else 2)


_ШАПКА = (
    "// Отпечатки вендорских страниц, на которые ссылается база. Журнал:\n"
    "// строки дописываются, прежние не трогаются. Зачем и что считается\n"
    "// изменением — в шапке scripts/recheck_vendor.py.\n"
)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
