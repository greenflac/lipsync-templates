#: Формы, которые НЕ являются наблюдением, чем бы ни выглядели: стектрейс,
#: строка лога, дамп конфига. В них есть и «условия», и слово про исход, но
#: наблюдения нет — есть машинный вывод. Поймано на живой выдаче: тред #58
#: у LTX-2.5 дал `File "/Users/.../ComfyUI/execution.py", line 344`.
МАШИННЫЙ_ВЫВОД = re.compile(
    r"(traceback|File \"|, line \d+|0x[0-9a-f]{6,}|\| INFO \||\| DEBUG \|"
    r"|^\s*(at|in) [\w./\\]+:\d+|Error: \w+Error|\bself\.\w+\(|>>> )",
    re.I | re.M,
)

#: КОД — не наблюдение, даже когда он не падал. Первая редакция ловила только
#: АВАРИЙНЫЙ машинный вывод (стектрейс, лог), и этого не хватило: разбор
#: собственного улова 2026-09-02 глазами (П3) нашёл среди пяти находок две
#: строки кода, прошедшие все фильтры, —
#:     `export MODEL_BASE=FastVideo/FastWan2.2-TI2V-5B-Full-Diffusers`
#:     `output_np = (output_np * 0.5 * 127).astype(np.int8) # Adjust the factor`
#: Обе несут и «условия прогона» (имя модели, числа), и слово про исход, и обе
#: не рассказывают НИЧЕГО о том, что вышло. Признаки взяты по этим двум и
#: проверены на обратную сторону: предложение о том, что человек ЗАПУСТИЛ
#: командой, остаётся наблюдением, если он сказал, что получилось.
КОД = re.compile(
    r"(^\s*(export|set|cd|pip|conda|git|python[23]?|bash|sudo|npm|apt(-get)?)\s+\S+=?"
    r"|^\s*[\w.\[\]]+\s*=\s*[^=\s].*[()\[\]]"
    r"|\.astype\(|\.to\(|\bimport\s+\w+|\bdef\s+\w+\(|--\w[\w-]+\s+\S)",
    re.M,
)

#: ПРЕДПОЛОЖЕНИЕ — не наблюдение. «If quantized to ~1.5GB, LTX could
#: potentially generate short clips on Snapdragon 865» — это прикидка человека,
#: а не то, что он видел; записанная как `observed_behaviour`, она становится
#: свидетельством, которого не было. Найдена там же и тем же способом.
#: Сослагательное наклонение ловится по модальным глаголам ВМЕСТЕ с
#: неопределённостью: «it should work» без «I ran» — прогноз.
ПРЕДПОЛОЖЕНИЕ = re.compile(
    r"\b(could|would|might|may|should)\s+(potentially|probably|possibly|maybe|in theory)?\s*"
    r"\w+|\b(i (guess|assume|expect|believe)|in theory|probably|presumably|hopefully)\b",
    re.I,
)

#: Обратная сторона ПРЕДПОЛОЖЕНИЯ: если человек СКАЗАЛ, что запускал, его
#: «should» — это оговорка внутри отчёта, а не прогноз вместо отчёта.
ПРОГНАЛ = re.compile(
    r"\b(i (ran|tried|tested|used|got|trained|generated|rendered)|works? for me|on my "
    r"(rtx|gtx|mac|pc|gpu|card)|i(\'m| am) (running|using)|managed to|ended up)\b",
    re.I,
)

#: ВОПРОС — не наблюдение, чем бы ни был обставлен. «Is there a way to
#: implement this in a comfyui workflow?» несёт и условия, и слово про исход,
#: но человек не рассказывает, что вышло, — он спрашивает. ИЗМЕРЕНО
#: независимым оценщиком (`studio/harvest_quality.py`) на 123 строках этого
#: канала: 21 из 27 осуждённых были именно вопросами. Прибор, который ловит
#: своего же сборщика, для того и заведён.
#: Признаков два, и оба узкие. Первый — знак вопроса в конце. Второй —
#: ИНВЕРСИЯ вспомогательного глагола в начале («Can we…», «Is there…»),
#: которая по-английски бывает только вопросом.
#:
#: Вопросительных слов how/what/why/when/where в начале здесь НЕТ намеренно, и
#: это исправление собственной первой редакции: она отвергала «When using the
#: official model, generating a 15-second 720p video takes only 3 minutes» —
#: то есть настоящее наблюдение, начатое придаточным. ИЗМЕРЕНО: с ними
#: отвергалось 22 сохранённые строки из 123, без них 15, и семь разницы —
#: ложные срабатывания.
ВОПРОС = re.compile(
    r"\?\s*$"
    r"|^\s*(can|could|is|are|was|were|does|do|did|would|should|will|has|have"
    r"|any|anyone|anybody|somebody|is there|можно ли|есть ли)\b",
    re.I,
)

#: Сколько слов чужого текста дословно допускается в записи. Число НЕ моё:
#: оно взято из `scripts/check_craft.py`, где ВЫБРАНО с замером под ним —
#: на 1020 фрагментах первого урожая медиана 1 слово, самый длинный 13. Это
#: не юридический порог, а растяжка, срабатывающая задолго до копирования
#: страницы. Импортировать константу отсюда нельзя без обратной зависимости
#: скрипта от скрипта, поэтому она продублирована ЧИСЛОМ и сторожится тестом,
#: который сверяет её с оригиналом (Е1: расхождение обязано краснеть).
ДОСЛОВНО_СЛОВ = 15

#: Минимальная длина извлечённого предложения. ВЫБРАНО 40: ниже этого порога
#: на живых телах не помещается «условие плюс исход» — а именно их пара и
#: отличает наблюдение от реплики. Сторожится мутацией в обе стороны (Т1).
МИН_ДЛИНА_НАБЛЮДЕНИЯ = 40

#: Сколько предложений берётся из одного тела. ВЫБРАНО 2: одно почти всегда
#: несёт либо условия, либо исход, но не оба.
ПРЕДЛОЖЕНИЙ_ИЗ_ТЕЛА = 2

#: Границей предложения считается точка, за которой НЕ стоит цифра: иначе
#: «LTX 2.5» рвётся пополам и значение начинается с «5 on my RTX 3060» — то
#: есть перестаёт быть словами источника. Поймано на первом же живом теле.
_ГРАНИЦА = re.compile(r"(?<=[.!?])(?!\d)\s+|\n+")
_КАРТИНКА = re.compile(r"!?\[[^\]]*\]\([^)]*\)|https?://\S+")


def первое_сообщение(payload: dict[str, Any]) -> tuple[str, str]:
    """Текст первого комментария треда и имя его автора.

    Именно первый: он принадлежит тому, кто пришёл с наблюдением. Ответы —
    это уже обсуждение, и там чаще догадки, чем прогоны.
    """
    for событие in payload.get("events") or []:
        if событие.get("type") != "comment":
            continue
        данные = событие.get("data") or {}
        сырое = (данные.get("latest") or {}).get("raw") or данные.get("raw") or ""
        автор = (событие.get("author") or {}).get("name") or ""
        if str(сырое).strip():
            return str(сырое), str(автор)
    return "", ""


#: Имя, отличное от разбираемой модели, делает предложение утверждением О
#: ДРУГОЙ МОДЕЛИ. Записать его под нашим именем — это ровно тот класс дефекта,
#: который абляция назвала самой глубокой дырой базы. Поймано на живой выдаче:
#: тред #61 у LTX-2.5 говорит про Seedance 2.5, и заявка ушла бы к LTX.
ЧУЖОЕ_ИМЯ = re.compile(
    r"\b(seedance|kling|veo|runway|sora|wan[- ]?\d|hunyuan|minimax|hailuo|pika"
    r"|luma|flux|sdxl|stable[- ]diffusion|midjourney|dall[- ]?e|qwen|gemini|gpt)\b",
    re.I,
)


def про_чужую_модель(фраза: str, model_id: str) -> bool:
    """Названо ли в предложении имя модели, отличное от разбираемой.

    Сравнение по КУСКАМ имени репозитория, а не по полному совпадению: у
    `Lightricks/LTX-2.5` своим считается «ltx», а «seedance» — чужим.
    """
    своё = re.split(r"[-_./ ]", model_id.lower())
    for найдено in ЧУЖОЕ_ИМЯ.findall(фраза):
        имя = найдено.lower()
        if not any(имя.startswith(ч) or ч.startswith(имя) for ч in своё if len(ч) > 2):
            return True
    return False


def наблюдение(тело: str, model_id: str = "") -> str:
    """Слова автора, в которых названы И условия прогона, И исход.

    Пустая строка — третий исход (Р1): тело есть, наблюдения в нём нет. Это
    НЕ то же самое, что «тред плохой»: вопрос без прогона — законное
    содержимое обсуждения, просто не факт о модели.
    """
    чистое = _КАРТИНКА.sub(" ", тело or "")
    годные = []
    for кусок in _ГРАНИЦА.split(чистое):
        фраза = " ".join(кусок.split())
        if len(фраза) < МИН_ДЛИНА_НАБЛЮДЕНИЯ:
            continue
        if ВОПРОС.search(фраза) or МАШИННЫЙ_ВЫВОД.search(фраза) or КОД.search(фраза):
            continue
        # Прикидка — не наблюдение. Но «should» внутри отчёта человека,
        # который сказал, что запускал, оговоркой и остаётся.
        if ПРЕДПОЛОЖЕНИЕ.search(фраза) and not ПРОГНАЛ.search(фраза):
            continue
        if model_id and про_чужую_модель(фраза, model_id):
            continue
        if УСЛОВИЯ_ПРОГОНА.search(фраза) and ИСХОД_ПРОГОНА.search(фраза):
            годные.append(фраза)
        if len(годные) >= ПРЕДЛОЖЕНИЙ_ИЗ_ТЕЛА:
            break
    return " ".join(годные)


def знак(текст: str) -> str:
    """`удача`, `провал` или `неясно`. Решает АТРИБУТ, под которым писать.

    Три исхода и здесь: текст, где нет ни одного знака, не записывается вовсе,
    потому что записать его провалом — это выдумать провал.
    """
    удача, провал = bool(ЗНАК_УДАЧИ.search(текст)), bool(ЗНАК_ПРОВАЛА.search(текст))
    if удача and not провал:
        return "удача"
    if провал and not удача:
        return "провал"
    return "неясно"


#: Атрибут выбирается ЗНАКОМ наблюдения, а не предполагается. Третья строка
#: существует потому, что «неясно» — это 6 наблюдений из 11 на живом замере, и
#: выбросить их значит потерять больше половины выхода, а записать провалом —
#: выдумать провал. `observed_behaviour` не утверждает ни того, ни другого:
#: практик описал прогон, знак не назван.
АТРИБУТ_ПО_ЗНАКУ = {
    "удача": "runs_on",
    "провал": "failure_mode",
    "неясно": "observed_behaviour",
}


def наблюдения_модели(
    model_id: str, get: Callable[[str], tuple[str, bytes]] = _get
) -> tuple[list[dict[str, Any]], dict[str, int], dict[str, Any]]:
    """Наблюдения из ТЕЛ всех тредов модели, и рядом — счётчики отсева (Р2).

    ОТБОР ИДЁТ ПО ТЕЛУ, А НЕ ПО ЗАГОЛОВКУ, и это главное решение всей функции.
    Отбор по заголовку выбирает треды со словами «error», «problem», «fail» —
    то есть ровно ту популяцию, где гуще всего проблем установки и реже всего
    отчётов о поведении модели. ИЗМЕРЕНО на Lightricks/LTX-2.5, 50 тредов:
    фильтр по заголовку отобрал 8, чтение тел нашло 11, и это ДРУГИЕ 11.
    Отчёт «LTX 2.5 on RTX 3060 ... 15-second video in about 5 minutes»
    заголовочный фильтр записал ПРОВАЛОМ, потому что в названии было слово
    «Quality».

    Цена названа честно: один запрос на тред вместо одного на модель.
    """
    состояние, тело = get(f"{API}{model_id}/discussions")
    if состояние != "ok":
        return [], {"канал не ответил": 1}, {}
    try:
        листинг = json.loads(тело)
        треды = (листинг.get("discussions") or [])[:DISCUSSIONS_SCANNED]
    except json.JSONDecodeError:
        return [], {"выдача не разобралась": 1}, {}

    найдено: list[dict[str, Any]] = []
    счёт: dict[str, int] = {}

    def плюс(имя: str) -> None:
        счёт[имя] = счёт.get(имя, 0) + 1

    for тред in треды:
        номер = тред.get("num")
        состояние, сырое = get(f"{API}{model_id}/discussions/{номер}")
        if состояние != "ok":
            плюс("тред не прочли")
            continue
        try:
            разобранное = json.loads(сырое)
        except json.JSONDecodeError:
            плюс("тред не разобрался")
            continue
        текст, автор = первое_сообщение(разобранное)
        if not текст.strip():
            плюс("тело пустое")
            continue
        видно = наблюдение(текст, model_id)
        if not видно:
            плюс("условия и исход не названы вместе")
            continue
        з = знак(видно)
        плюс(f"наблюдение: {з}")
        найдено.append(
            {
                "num": номер,
                "title": str(тред.get("title") or ""),
                "status": тред.get("status"),
                "author": автор,
                "sign": з,
                "attribute": АТРИБУТ_ПО_ЗНАКУ[з],
                "observation": видно,
            }
        )
    return найдено, счёт, листинг


def license_paths(model_id: str, get: Callable[[str], tuple[str, bytes]] = _get) -> list[str]:
    """Файлы репозитория, похожие на лицензию, короткое имя первым.

    Короткое первым потому, что `LICENSE` — это лицензия модели, а
    `ltx-video-2b-v0.9.1.license.txt` — лицензия одного веса из многих.
    """
    state, body = get(f"{API}{model_id}/tree/main")
    if state != "ok":
        return []
    try:
        rows = json.loads(body)
    except json.JSONDecodeError:
        return []
    paths = [
        str(row.get("path") or "")
        for row in rows
        if isinstance(row, dict)
        and LICENSE_IN_NAME.search(str(row.get("path") or ""))
        and not LICENSE_SKIP.search(str(row.get("path") or ""))
    ]
    return sorted(set(paths), key=lambda p: (len(p), p))


def survey(model_id: str, get: Callable[[str], tuple[str, bytes]] = _get) -> dict[str, Any]:
    """Всё, что HuggingFace знает об одной модели. Три исхода, как везде."""
    state, body = get(API + model_id)
    if state != "ok":
        return {"model_id": model_id, "outcome": "не смогли", "note": f"карточка: {state}"}
    meta = json.loads(body)
    card_data = meta.get("cardData") or {}

    readme_state, readme = get(f"{WEB}{model_id}/raw/main/README.md")
    licences: list[dict[str, Any]] = []
    for name in license_paths(model_id, get)[:LICENCES_READ]:
        state_here, body_here = get(f"{WEB}{model_id}/raw/main/{name}")
        if state_here == "ok" and body_here.strip():
            licences.append(
                {
                    "file": name,
                    "flags": license_flags(body_here.decode("utf-8", "replace")),
                    "chars": len(body_here),
                }
            )
    # Листинг обсуждений берётся ОДИН раз и передаётся дальше. Прежде его
    # тянули дважды на каждую модель — здесь и внутри `наблюдения_модели`, —
    # то есть 82 лишних запроса за заход. Это Е1: одно знание, одно место.
    наблюдения, счёт_наблюдений, разобрано = наблюдения_модели(model_id, get)
    talk_state = "ok" if разобрано else "не отдался"
    talk = json.dumps(разобрано) if разобрано else ""
    found = troubles(разобрано) if разобрано else []
    установочные = troubles(разобрано, setup=True) if разобрано else []
    return {
        "model_id": model_id,
        "outcome": "годно",
        "author": meta.get("author", ""),
        "created": str(meta.get("createdAt", ""))[:10],
        "downloads": meta.get("downloads"),
        "likes": meta.get("likes"),
        "gated": meta.get("gated"),
        "pipeline": meta.get("pipeline_tag", ""),
        "license": card_data.get("license", ""),
        "license_name": card_data.get("license_name", ""),
        "licences": licences,
        "license_read": bool(licences),
        "card_read": readme_state == "ok",
        "card_chars": len(readme),
        "discussions_total": (json.loads(talk).get("count") if talk_state == "ok" else None),
        # Отдельным полем, потому что «обсуждений ноль» и «обсуждения нам не
        # отдали» — разные исходы (Р1), а вместе они читаются как «модель без
        # опыта практиков». ИЗМЕРЕНО 2026-08-31: из 12 моделей 11 отдали
        # обсуждения, одна (hexgrad/Kokoro-82M) ответила 403 — обсуждения на
        # ней просто выключены, и это не отсутствие опыта.
        "discussions_state": talk_state,
        "troubles": found,
        "observations": наблюдения,
        "observation_counts": счёт_наблюдений,
        "setup_troubles": установочные,
        "card_url": f"{WEB}{model_id}",
        "license_url": f"{WEB}{model_id}/tree/main",
    }


def licences_disagree(licences: list[dict[str, Any]]) -> bool:
    """Разные файлы лицензий дают разные оговорки — значит, права зависят от веса.

    ИЗМЕРЕНО на Lightricks/LTX-Video 2026-08-31: четыре файла, и два из них
    («2b-v0.9», «2b-v0.9.1») содержат оговорку «только для исследований», а
    два других — нет. Прочитавший ОДИН файл получит неверный ответ в любую из
    двух сторон, и это ровно тот случай, ради которого правило Ц5 требует
    читать лицензию, а не поле карточки.
    """
    # Файл, который мы не смогли прочитать, в сравнении НЕ участвует: иначе
    # непрочитанная китайская версия «расходится» с прочитанной английской, и
    # прибор поднимает тревогу там, где просто не хватило языка.
    наборы = {
        frozenset(lic["flags"])
        for lic in licences
        if not any(str(f).startswith(CANNOT_READ) for f in lic["flags"])
    }
    return len(наборы) > 1


def already_known(model_id: str, store: FactStore | None = None) -> dict[str, Any]:
    """Что база УЖЕ знает про эту модель. Спрашивается ДО записи «нового».

    ЗАЧЕМ ЭТО ЗДЕСЬ. 2026-08-31 я объявил семейство `latentsync`, написав в
    комментарии к исходнику, что выделенных липсинк-моделей в базе нет. Их было
    двадцать фактов, с 27 августа, включая вендорские режимы отказа. Повтор
    ключа поймал ЛИНТЕР, а не я, и записанный «новый» факт оказался СЛАБЕЕ
    стоявшего из того же источника. Инструмент спросить базу был под рукой.
    Намерение «сначала спрашивать» — это строка правил, которая забывается;
    поэтому оно здесь, в выдаче, рядом с находками.
    """
    склад = store or FactStore()
    короткое = model_id.rsplit("/", 1)[-1].lower()
    свои = [m for m in склад.models() if m == короткое]
    соседи = склад.near(короткое)
    return {
        "exact": свои,
        "neighbours": соседи,
        "attributes": sorted({a for m in свои for a in склад.attributes(m)}),
    }


def report(rows: list[dict[str, Any]], store: FactStore | None = None) -> int:
    """Печать числами и три исхода (правила Р1, Р2, Е3)."""
    done = [r for r in rows if r.get("outcome") == "годно"]
    for row in rows:
        if row.get("outcome") != "годно":
            print(f"  НЕ СМОГЛИ  {row['model_id']}: {row.get('note', '')}")
            continue
        print(f"\n=== {row['model_id']}  ({row['author']}, с {row['created']})")
        print(f"    принятость: скачиваний {row['downloads']}, лайков {row['likes']}")
        лиц = row["license_name"] or row["license"] or "не указана"
        print(f"    лицензия:   {лиц}  (файлов прочитано {len(row['licences'])})")
        if not row["license_read"] and str(row["license"]).lower() in ("other", "", "unknown"):
            print(
                "       ВНИМАНИЕ: поле говорит 'other', а текста нет —"
                " до встраивания читать нельзя (Ц5)"
            )
        for lic in row["licences"]:
            метки = "; ".join(lic["flags"]) or "особых оговорок не нашли"
            print(f"       {lic['file']} ({lic['chars']} симв.): {метки}")
        if licences_disagree(row["licences"]):
            print(
                "       ВНИМАНИЕ: файлы лицензий РАСХОДЯТСЯ — права зависят от того,"
                " какой вес вы грузите, и один файл ответа не даёт (Ц5)"
            )
        print(f"    карточка:   {row['card_chars']} символов, задача {row['pipeline'] or '—'}")
        знание = already_known(row["model_id"], store)
        if знание["exact"]:
            print(f"    В БАЗЕ УЖЕ ЭТА: {', '.join(знание['exact'])}")
            print(
                f"       атрибутов записано {len(знание['attributes'])}: "
                f"{', '.join(знание['attributes'][:8])}"
            )
            print("       новым записывать только то, чего здесь НЕТ")
        else:
            print("    в базе этой модели нет")
        if знание["neighbours"]:
            # ПОХОЖИЕ, а не «уже есть». `omnigen2` и `omnihuman-1` делят четыре
            # первые буквы и не имеют друг к другу отношения — разные вендоры,
            # разные задачи. Печатать их как «уже в базе» значит подсказывать
            # неверно (поймано на живой выдаче 2026-08-31).
            print(f"    похожие имена (могут быть ЧУЖИЕ): {', '.join(знание['neighbours'][:5])}")
        всего = row["discussions_total"]
        сказано = (
            f"{всего}"
            if row.get("discussions_state") == "ok"
            else f"НЕ СМОГЛИ прочесть ({row.get('discussions_state')})"
        )
        print(
            f"    обсуждений: {сказано},"
            f" про поведение модели {len(row['troubles'])},"
            f" про установку {len(row.get('setup_troubles', []))}"
        )
        сч = row.get("observation_counts") or {}
        печать = ", ".join(f"{k} {v}" for k, v in sorted(сч.items()))
        print(f"    наблюдений из тел: {len(row.get('observations') or [])}  ({печать})")
        for н in (row.get("observations") or [])[:6]:
            print(f"       #{н['num']} [{н['sign']}->{н['attribute']}] {н['observation'][:76]}")
    print(f"\nпроверено {len(rows)}, разобрано {len(done)}, не смогли {len(rows) - len(done)}")
    if not rows:
        print("исход: не смогли — не назвали ни одной модели")
        return 2
    if not done:
        print("исход: не смогли — ни одна карточка не открылась")
        return 2
    if len(done) < len(rows):
        print(f"исход: не смогли полностью — {len(done)} из {len(rows)}")
        return 2
    return 0


#: Тиры, которые перебираются, пока `advice.record` не примет заявку. Порядок
#: не важен: тир всё равно решает URL внутри `record`, здесь лишь перебор.
#: Важна ПОЛНОТА — все три опознаваемые ступени идентичности.
#:
#: ИЗМЕРЕНО, и это цена неполноты: с лесенкой из двух ступеней
#: (`portal`, `vendor`), выбранной по замеру на 10 моделях, заход на 45
#: моделях потерял 59 заявок из 151 (39%) — и это была РОВНО применимость:
#: страница обсуждения на huggingface.co опознаётся как `blog`, а его в
#: лесенке не было. Применимость не сдвинулась ни на единицу при 92 новых
#: фактах, и это единственное, чем дефект себя выдал.
ТИРЫ_ПО_ОЧЕРЕДИ: tuple[str, ...] = ("portal", "vendor", "blog")


#: Порядки величины, которыми называется принятость. ВЫБРАНО, и выбрано из
#: наблюдённого дефекта (И2): точное число скачиваний и лайков — это СЧЁТЧИК,
#: он тикает между двумя прогонами, и база честно объявляла два своих же
#: чтения ПРОТИВОРЕЧИЕМ. «1 182 585 скачиваний, 2328 лайков» против
#: «1 182 585 скачиваний, 2331 лайк» — спорная пара из ничего. Решение,
#: которое это число поддерживает, — «промышленный стандарт или диковина», и
#: его решает порядок, а не единицы. Точные числа никуда не деваются: они
#: уходят в ноту, где счётчиком и остаются.
ПОРЯДКИ: tuple[tuple[int, str], ...] = (
    (10_000_000, "более 10 млн скачиваний"),
    (1_000_000, "более 1 млн скачиваний"),
    (100_000, "более 100 тыс. скачиваний"),
    (10_000, "более 10 тыс. скачиваний"),
    (1_000, "более 1 тыс. скачиваний"),
)


def принятость(downloads: int) -> str:
    """Порядок величины скачиваний словами. Ниже младшего порога — так и скажем."""
    for порог, слова in ПОРЯДКИ:
        if downloads >= порог:
            return слова
    return "менее 1 тыс. скачиваний"


def заявки(row: dict) -> list[tuple[str, str, str, str, str]]:
    """Находки одной модели как утверждения: модель, атрибут, значение, URL, нота.

    Значение — СЛОВА ИСТОЧНИКА и ничего больше: имя лицензии как оно записано
    в поле, заголовок треда как его написал автор треда. Своё рассуждение
    уходит в ноту. Правило оплачено: приписанное к значению «— у Runway»
    развело этот же файл с гейтом атрибуции на четырёх строках.
    """
    имя = row["model_id"].split("/")[-1].lower()
    карточка, out = row["card_url"], []
    лиц = row.get("license_name") or row.get("license")
    if лиц:
        out.append((имя, "license", str(лиц), карточка, "поле лицензии карточки HuggingFace"))
    for L in row.get("licences") or []:
        if L.get("flags"):
            out.append(
                (
                    имя,
                    "license_restriction",
                    "; ".join(L["flags"]),
                    row["license_url"],
                    f"прочитан файл {L['file']}, {L['chars']} символов",
                )
            )
    out.append(
        (
            имя,
            "adoption",
            принятость(row["downloads"]),
            карточка,
            f"счётчик HuggingFace: {row['downloads']} скачиваний, {row['likes']} лайков",
        )
    )
    # ЧУЖИЕ СЛОВА НЕ КОММИТЯТСЯ ДОСЛОВНО. Правило проекта уже измерено и
    # сторожится в `scripts/check_craft.py`: фрагмент длиннее 15 слов — это уже
    # чужой текст, а не токен. К `model_facts.jsonl` оно не применялось, и
    # ИЗМЕРЕНО 2026-09-02: в публичном репозитории лежало 576 цитат из
    # обсуждений HuggingFace, 291 из них длиннее 15 слов, максимум 354 слова,
    # и 117 ников живых людей. ToS HuggingFace даёт другим пользователям право
    # использовать контент «through our Services and functionalities» —
    # воспроизведение в стороннем репозитории под своей лицензией в эту
    # формулировку не входит.
    #
    # Длинное наблюдение не режется по слову: обрезок перестаёт быть словами
    # источника и не становится пересказом. Он не пишется вовсе — это третий
    # исход (Р1), и он считается, чтобы потеря была видна, а не молчалива.
    # НИК АВТОРА не пишется никуда: он не нужен ни одному ответу.
    #
    # НАБЛЮДЕНИЯ ИЗ ТЕЛ, а не заголовки. Заголовок — это вопрос, который человек
    # задал; тело — то, что он выяснил. Атрибут выбирает ЗНАК наблюдения, и
    # положительный отчёт больше не может попасть под `failure_mode`.
    for н in row.get("observations") or []:
        if len(str(н["observation"]).split()) > ДОСЛОВНО_СЛОВ:
            continue
        out.append(
            (
                имя,
                н["attribute"],
                н["observation"],
                f"{карточка}/discussions/{н['num']}",
                f"тело треда #{н['num']}, знак {н['sign']}",
            )
        )
    return out


def записать(rows: list[dict], today: str) -> dict:
    """Провести находки через `advice.record`. Р2: три числа рядом с исходом.

    Тир не выбирается здесь и не подаётся как истина: он ПРЕДЛАГАЕТСЯ, а
    решает URL внутри `advice.record`. Отказ по несовпадению тира — не ошибка
    канала, а работа гейта, поэтому заявка повторяется вторым тиром, и только
    отказ обоими считается неудачей.
    """
    from studio.mcp import advice  # локально: без записи модуль не нужен

    записано = отказано = 0
    причины: dict[str, int] = {}
    for row in rows:
        if row.get("outcome") != "годно":
            continue
        for модель, атрибут, значение, url, нота in заявки(row):
            for тир in ТИРЫ_ПО_ОЧЕРЕДИ:
                out = advice.record(
                    модель, атрибут, значение, url, тир, today, note=нота, read_directly=True
                )
                if out["outcome"] == "pass":
                    записано += 1
                    break
            else:
                отказано += 1
                причины[str(out["note"])[:100]] = причины.get(str(out["note"])[:100], 0) + 1
    return {"записано": записано, "отказано": отказано, "причины": причины}


