#!/usr/bin/env python3
"""Голден-сет задач GenAI-инженера: продукт против набора, собранного заранее.

    python scripts/check_golden.py            # таблица по задачам
    python scripts/check_golden.py --check    # для гейта: только числа и исход

ЗАЧЕМ

Владелец поставил условие: набор задач собирается ДО того, как тратятся
деньги на измерения. Причина простая и проверенная на этом проекте: без
заранее зафиксированного набора любая правка выглядит улучшением, потому что
её меряют тем же, что под неё и подгоняли.

ЧТО ЭТО НЕ ДУБЛИРУЕТ (Е1)

`scripts/check_headline.py` сверяет ОТВЕТ С БАЗОЙ. `frozen_questions.jsonl`
меряет вопросы о ФАКТЕ. Здесь меряется РАБОТА ЦЕЛИКОМ: от слов заказчика до
плана, вместе с тем, чего продукт делать не должен.

ТРИ ИСХОДА (Р1)

    годно      каждая машинно проверяемая задача прошла
    не годно   хоть одна проверка не прошла
    не смогли  задача есть, но машинно не проверяется («оценка глазами»)

ТРЕТИЙ ИСХОД НЕ СВОРАЧИВАЕТСЯ НИ В ОДИН ИЗ ДВУХ. Задача, которую видит
только человек, — не пропуск и не успех: она печатается своим числом. Набор,
из которого такие задачи выкинуты, меряет лёгкую половину продукта, а
тяжёлая — та самая, ради которой всё затевалось.

СЕТИ ЗДЕСЬ НЕТ: и планировщик, и советчик читают записанную базу.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lipsync.fork_identity import FAIL, PASS, UNMEASURED  # noqa: E402
from studio import planner  # noqa: E402
from studio.mcp import advice  # noqa: E402
from studio.mcp import server as mcp_server  # noqa: E402

НАБОР = Path(__file__).resolve().parents[1] / "studio" / "knowledge" / "golden_tasks.jsonl"

#: Оценка строки: чем она проверяется.
МАШИННО = "машинная"
ГЛАЗАМИ = "глазами"

#: Чего ждём от продукта на этой задаче. КОНСТАНТА-РЕШЕНИЕ, ВЫБРАНО
#: 2026-09-03: без этой оси набор либо весь зелёный — и тогда описывает
#: сделанное, а не нужное, — либо весь красный, и тогда его выключат на второй
#: день. Провал СТОРОЖА красит гейт (это регресс). Провал ЦЕЛИ печатается
#: числом и гейт не красит: это работа, которую ещё предстоит сделать, и
#: подгонять под неё гейт значило бы сначала объявить цель, а потом снять её.
СТОРОЖ = "сейчас"
ЦЕЛЬ = "цель"
ЖДЁМ: tuple[str, ...] = (СТОРОЖ, ЦЕЛЬ)

#: Виды проверок. Список — не украшение: он делает состав проверяемым тестом,
#: а опечатку в наборе — красной, а не молча пропущенной.
ВИДЫ: tuple[str, ...] = (
    "шаги_включают",
    "шагов_нет",
    "причина",
    "вопрос_ось",
    "исход",
    "исход_среди",
    "в_тексте",
    "не_в_тексте",
    "источник_у_утверждения",
)


#: Виды, которые УТВЕРЖДАЮТ (что-то обязано быть). Их можно проверить на
#: холостом ходу: проверка, проходящая на ПУСТОМ ответе, не меряет ничего.
#: Отрицательные виды (`не_в_тексте`, `шагов_нет`) на пустом ответе проходят
#: по своей природе, и требовать от них обратного было бы бессмыслицей.
УТВЕРЖДАЮЩИЕ: tuple[str, ...] = (
    "шаги_включают",
    "причина",
    "вопрос_ось",
    "исход",
    "исход_среди",
    "в_тексте",
    "источник_у_утверждения",
)


def холостые(набор: list[dict[str, Any]]) -> list[str]:
    """Проверки, которые проходят на ЛЮБОМ ответе своего канала.

    И5, негативный контроль ПРИБОРА, а не продукта: проверка, проходящая
    всегда, не меряет ничего, но выглядит как измерение.

    ЧТО ЭТОТ КОНТРОЛЬ ПОЙМАЛ И ЧЕГО НЕ ЛОВИТ — ИЗМЕРЕНО 2026-09-03, обе
    цифры записаны, а не одна (И6).

    ПОЙМАЛ: задача g10 требовала подстроку «http». Она есть в ОТВЕТЕ КАЖДОГО
    из 11 вопросов канала `advice` — проверка не различала ничего и при этом
    выглядела как проверка источника. Заменена на разбор `claims`.

    НЕ ЛОВИТ: задачу g29, ради которой контроль и затевался. Она искала в
    плане слова «дороже потолка», стоящие в строке счётчиков Р2 у каждого
    плана СО ШАГАМИ, — но пять планов набора шагов не имеют вовсе, строки не
    печатают, и правило «проходит на всех» не срабатывает. Ту проверку нашло
    чтение выдачи глазами (П3), а не этот контроль. Первая редакция —
    сравнение с ПУСТЫМ ответом — не ловила ни того, ни другого.

    Значит, контроль ловит холостую проверку только там, где канал отвечает
    ОДНОРОДНО. Это половина работы, и вторая половина по-прежнему на глазах.
    """
    машинные = [з for з in набор if з.get("оценка") == МАШИННО]
    ответы: dict[str, list[tuple[dict[str, Any], str]]] = {}
    for з in машинные:
        ответы.setdefault(з["канал"], []).append(ответ(з))

    беды: list[str] = []
    for з in машинные:
        соседи = ответы[з["канал"]]
        if len(соседи) < 2:
            continue
        for п in з.get("обязано", []):
            if п["вид"] not in УТВЕРЖДАЮЩИЕ:
                continue
            прошло = sum(
                проверка_прошла(п["вид"], п.get("что"), итог, текст) for итог, текст in соседи
            )
            if прошло == len(соседи):
                беды.append(
                    f"{з['id']}: обязано {п['вид']}={п.get('что')!r} проходит на всех "
                    f"{len(соседи)} ответах канала «{з['канал']}» — не различает ничего"
                )
    return беды


def задачи(путь: Path = НАБОР) -> list[dict[str, Any]]:
    строки: list[dict[str, Any]] = []
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        строки.append(json.loads(строка))
    return строки


def неизвестные_виды(набор: list[dict[str, Any]]) -> list[str]:
    """Опечатка в виде проверки тихо превращает строку в пройденную.

    Поймано на себе при первом прогоне соседнего счётчика (2026-09-03):
    неизвестное имя в фикстуре не краснеет, а исчезает из счёта.
    """
    виды = {
        п.get("вид", "")
        for з in набор
        for ключ in ("обязано", "запрещено")
        for п in з.get(ключ, [])
    }
    return sorted(в for в in виды if в not in ВИДЫ)


#: Инструменты сервера, которые НЕ ходят в сеть и НИЧЕГО НЕ ПИШУТ. Список
#: закрытый, и это не осторожность, а два разных запрета:
#:
#:   сеть   — набор гоняется в гейте, а гейт не ходит в сеть (Т4). `search_web`,
#:            `fetch_url`, `probe_model_limit`, `reachable_hosts` сюда не входят;
#:   запись — `record_model_fact`, `withdraw_model_fact`, `propose_measurement`
#:            меняют живые журналы. Набор задач, который на каждом прогоне
#:            дописывает базу, к третьему дню меряет собственные следы.
#:
#: ИЗМЕРЕНО 2026-09-03: у сервера 15 инструментов, набор трогал 2. Эти пять
#: доводят охват до 7 из 15, и вслух названо, почему остальные восемь не здесь.
ИНСТРУМЕНТЫ: tuple[str, ...] = (
    "analyse_creative",
    "check_lipsync_prompt",
    "stale_model_facts",
    "blocked_hosts",
    "measurement_proposals",
)


def _зов(имя: str, аргументы: dict[str, Any]) -> dict[str, Any]:
    """Вызов инструмента сервера по имени — только из закрытого списка."""
    if имя not in ИНСТРУМЕНТЫ:
        raise KeyError(f"инструмент {имя!r} не в списке офлайновых: {ИНСТРУМЕНТЫ}")
    орудие = getattr(mcp_server, имя)
    # У инструмента MCP настоящая функция лежит в `.fn`; вызывать обёртку
    # напрямую нельзя, а второй копии этого знания в наборе не заводится (Е1).
    return json.loads(getattr(орудие, "fn", орудие)(**аргументы))


def ответ(задача: dict[str, Any]) -> tuple[dict[str, Any], str]:
    """Ответ продукта и его ПЕЧАТНАЯ форма.

    Печать берётся та же, что видит человек (`planner.render`): проверять
    текст, которого никому не показывают, значило бы мерить не продукт.
    """
    вход = задача["вход"]
    if задача["канал"] == "plan":
        итог = planner.plan(вход["brief"], creative=вход.get("creative", ""))
        return итог, planner.render(итог)
    if задача["канал"] == "tool":
        итог = _зов(вход["tool"], вход.get("args", {}))
        return итог, json.dumps(итог, ensure_ascii=False)
    итог = advice.advise(вход["model"], вход["attribute"])
    return итог, json.dumps(итог, ensure_ascii=False)


def проверка_прошла(вид: str, что: Any, итог: dict[str, Any], текст: str) -> bool:
    if вид == "шаги_включают":
        имена = {ш["step"] for ш in итог.get("steps", [])}
        return set(что) <= имена
    if вид == "шагов_нет":
        return not итог.get("steps")
    if вид == "причина":
        return итог.get("reason") == что
    if вид == "вопрос_ось":
        вопрос = итог.get("question") or {}
        return вопрос.get("axis") == что
    if вид == "исход":
        return итог.get("outcome") == что
    if вид == "исход_среди":
        return итог.get("outcome") in что
    if вид == "источник_у_утверждения":
        # Утверждение без адреса источника — это мнение продукта, а не факт
        # базы, и различать их обязан прибор, а не читатель.
        утв = (итог.get("claims") or {}).get(что) or {}
        return any(
            и.get("url") for з in (утв.get("claims") or []) for и in (з.get("sources") or [])
        )
    if вид == "в_тексте":
        return str(что) in текст
    if вид == "не_в_тексте":
        return str(что) not in текст
    raise KeyError(вид)


def оценить(задача: dict[str, Any]) -> dict[str, Any]:
    """Одна задача: прошла, не прошла или не проверяется машинно."""
    if задача.get("оценка") != МАШИННО:
        return {
            "id": задача["id"],
            "ждём": задача["ждём"],
            "исход": UNMEASURED,
            "беды": [],
            "почему": задача["почему"],
        }
    итог, текст = ответ(задача)
    беды: list[str] = []
    for п in задача.get("обязано", []):
        if not проверка_прошла(п["вид"], п.get("что"), итог, текст):
            беды.append(f"обязано {п['вид']}={п.get('что')!r} — не выполнено")
    for п in задача.get("запрещено", []):
        if проверка_прошла(п["вид"], п.get("что"), итог, текст):
            беды.append(f"запрещено {п['вид']}={п.get('что')!r} — выполнилось")
    return {
        "id": задача["id"],
        "ждём": задача["ждём"],
        "исход": FAIL if беды else PASS,
        "беды": беды,
        "почему": задача["почему"],
    }


def свести(набор: list[dict[str, Any]]) -> dict[str, Any]:
    чужие = неизвестные_виды(набор)
    if чужие:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": len(набор),
            "строки": [],
            "цели открыты": [],
            "холостые": [],
            "неизвестные виды": чужие,
            "по классам": {},
        }
    пустые = холостые(набор)
    строки = [оценить(з) for з in набор]
    # Провал СТОРОЖА — регресс, он красит. Провал ЦЕЛИ — открытая работа, он
    # печатается числом. Свернуть их в одно значило бы либо объявить регресс
    # нормой, либо запретить ставить цели.
    провалы = [с for с in строки if с["исход"] == FAIL and с["ждём"] == СТОРОЖ]
    # Холостая проверка — беда НАБОРА, и она красит так же, как регресс: набор,
    # который не может не пройти, хуже отсутствующего, потому что его показывают.
    цели_открыты = [с for с in строки if с["исход"] == FAIL and с["ждём"] == ЦЕЛЬ]
    глазами = [с for с in строки if с["исход"] == UNMEASURED]
    по_классам: dict[str, dict[str, int]] = {}
    for з, с in zip(набор, строки):
        счёт = по_классам.setdefault(з["класс"], {"всего": 0, "прошло": 0, "глазами": 0, "цель": 0})
        счёт["всего"] += 1
        счёт["прошло"] += с["исход"] == PASS
        счёт["глазами"] += с["исход"] == UNMEASURED
        счёт["цель"] += з["ждём"] == ЦЕЛЬ
    return {
        "outcome": FAIL
        if (провалы or пустые)
        else (UNMEASURED if (глазами or цели_открыты) else PASS),
        "checked": len(строки) - len(глазами),
        "violations": len(провалы) + len(пустые),
        "холостые": пустые,
        "unmeasured": len(глазами) + len(цели_открыты),
        "цели открыты": [с["id"] for с in цели_открыты],
        "строки": строки,
        "неизвестные виды": [],
        "по классам": по_классам,
    }


def main(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--check", action="store_true", help="кратко, для гейта")
    аргс = р.parse_args(argv)

    итог = свести(задачи())
    for имя in итог["неизвестные виды"]:
        print(f"  НЕТ ТАКОГО ВИДА ПРОВЕРКИ: {имя} — набор сломан, а не продукт")
    if not аргс.check:
        for с in итог["строки"]:
            метка = {PASS: "ok  ", FAIL: "ПЛОХО", UNMEASURED: "глаз"}[с["исход"]]
            if с["исход"] == FAIL and с["ждём"] == ЦЕЛЬ:
                метка = "ЦЕЛЬ "
            print(f"  {метка} {с['id']}")
            for б in с["беды"]:
                print(f"        {б}")
    for класс, с in sorted(итог["по классам"].items()):
        print(
            f"  {класс:22} задач {с['всего']:2}, прошло {с['прошло']:2}, "
            f"из них цели {с['цель']:2}, смотрится глазами {с['глазами']:2}"
        )
    for с in итог["строки"]:
        if с["исход"] == FAIL and с["ждём"] == СТОРОЖ:
            print(f"  РЕГРЕСС {с['id']}: {'; '.join(с['беды'])}")
    for б in итог["холостые"]:
        print(f"  ХОЛОСТАЯ ПРОВЕРКА: {б}")
    if итог["цели открыты"]:
        print(
            f"  ЦЕЛИ ЕЩЁ НЕ ВЗЯТЫ ({len(итог['цели открыты'])}): {', '.join(итог['цели открыты'])}"
        )
    print()
    print(f"проверено {итог['checked']}")
    print(f"нарушений {итог['violations']}")
    print(f"не смогли {итог['unmeasured']}")
    print()
    print(
        f"{итог['outcome']}: голден-сет из {len(итог['строки'])} задач; "
        f"машинно проверено {итог['checked']}, регрессов {итог['violations']}, "
        f"целей не взято {len(итог['цели открыты'])}, "
        f"смотрится глазами {итог['unmeasured'] - len(итог['цели открыты'])}"
    )
    return 1 if итог["outcome"] == FAIL else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
