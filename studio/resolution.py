from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

#: Имена ступеней, которыми вендоры называют разрешение вместо чисел. ВЫБРАНО
#: по живой базе: `720p`, `1080p`, `4K`, `2K`, `480P`, `768P`. Значения —
#: ВЫСОТА кадра в пикселях для `p`-форм и ШИРИНА для `K`-форм, как это принято
#: в отрасли; ширина при `p` зависит от соотношения сторон и потому не
#: угадывается (см. `СТОРОНА_НЕ_УГАДЫВАЕТСЯ`).
СТУПЕНИ: dict[str, tuple[int, str]] = {
    "360p": (360, "высота"),
    "480p": (480, "высота"),
    "540p": (540, "высота"),
    "576p": (576, "высота"),
    "580p": (580, "высота"),
    "720p": (720, "высота"),
    "768p": (768, "высота"),
    "1080p": (1080, "высота"),
    "1440p": (1440, "высота"),
    "2160p": (2160, "высота"),
    "2k": (2048, "ширина"),
    "4k": (3840, "ширина"),
    "8k": (7680, "ширина"),
}

#: Пара чисел, которой источники пишут кадр: `3840x2160`, `1920:1080`,
#: `1104 x 832`, `1280*704`. Все четыре разделителя равноправны — вендоры
#: пишут по-разному на соседних строках одного документа, и звёздочка нашлась
#: не в голове, а в базе: `wan-2.2-ti2v-5b` = «1280*704 or 704*1280 at 24 FPS»
#: не разбиралась, пока её там не было.
ПАРА = re.compile(r"\b(\d{3,5})\s*[x:×*]\s*(\d{3,5})\b", re.I)

#: Ступень: `720p`, `4K`. Граница слева обязательна, иначе `1080p` внутри
#: `21080px` дало бы ступень из середины числа.
СТУПЕНЬ = re.compile(r"\b(\d{3,4}p|[248]k)\b", re.I)

#: Диапазон, которым пишут пределы генератора картинок: «width and height
#: between 512 and 2048 px». Берётся ВЕРХНЯЯ граница: вопрос «влезет ли мой
#: кадр» — про потолок, а не про пол.
ДИАПАЗОН = re.compile(r"between\s+(\d{3,5})\s+and\s+(\d{3,5})\s*(?:px|pixels?)?", re.I)

#: Слово, после которого число — НЕ предел, а отрицание предела: «no 4K»,
#: «4K EXISTS» тоже встречается, поэтому ловится именно отрицание.
НЕТ_СТУПЕНИ = re.compile(r"\bno\s+(\d{3,4}p|[248]k)\b", re.I)


@dataclass(frozen=True)
class Предел:
    """Разобранный предел кадра. `outcome` — три исхода, как везде."""

    длинная: int | None
    короткая: int | None
    outcome: str
    note: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "long_side": self.длинная,
            "short_side": self.короткая,
            "outcome": self.outcome,
            "note": self.note,
        }


#: Почему у ступени известна только одна сторона. `720p` — это высота 720 при
#: ЛЮБОЙ ширине: 1280x720 и 720x1280 оба «720p», и вертикальный кадр 720x1280
#: имеет длинную сторону 1280. Подставить вторую сторону по 16:9 значило бы
#: решить за вендора, какое соотношение он допускает, — а `veo-3.1` в базе
#: перечисляет и 16:9, и 9:16 одной строкой.
СТОРОНА_НЕ_УГАДЫВАЕТСЯ = "вторая сторона не названа: ступень задаёт только одну"


def разобрать(значение: str) -> Предел:
    """Предел кадра из строки источника. Не разобралось — третий исход.

    Порядок не случаен: явная ПАРА чисел сильнее ступени, потому что источник,
    написавший `1920:1080 (1080p max, no 4K)`, назвал числа сам, и брать за
    него ступень значит терять точность, которая уже есть в строке.
    """
    текст = str(значение or "").strip()
    if not текст:
        return Предел(None, None, "не смогли", "значение пустое")

    пары = [(int(a), int(b)) for a, b in ПАРА.findall(текст)]
    if пары:
        # Самая крупная пара строки: источники перечисляют enum от меньшего к
        # большему и наоборот, а вопрос «влезет ли» — про потолок.
        длинная = max(max(a, b) for a, b in пары)
        короткая = max(min(a, b) for a, b in пары)
        return Предел(
            длинная, короткая, "годно", f"пар чисел в строке {len(пары)}, взята крупнейшая"
        )

    диапазон = ДИАПАЗОН.search(текст)
    if диапазон:
        верх = int(диапазон.group(2))
        return Предел(верх, верх, "годно", "верхняя граница диапазона сторон")

    отрицания = {с.lower() for с in НЕТ_СТУПЕНИ.findall(текст)}
    ступени = [с.lower() for с in СТУПЕНЬ.findall(текст) if с.lower() not in отрицания]
    if ступени:
        лучшая = max(ступени, key=lambda с: СТУПЕНИ.get(с, (0, ""))[0])
        размер, что = СТУПЕНИ.get(лучшая, (0, ""))
        if not размер:
            return Предел(None, None, "не годно", f"ступень {лучшая} неизвестна")
        if что == "ширина":
            return Предел(размер, None, "годно", f"ступень {лучшая}: {СТОРОНА_НЕ_УГАДЫВАЕТСЯ}")
        return Предел(None, размер, "годно", f"ступень {лучшая}: {СТОРОНА_НЕ_УГАДЫВАЕТСЯ}")

    return Предел(None, None, "не годно", "ни пары чисел, ни известной ступени")


def влезает(кадр: tuple[int, int], предел: Предел) -> dict[str, Any]:
    """Влезает ли кадр в предел. Три исхода, и третий — самый частый.

    Сравниваются ДЛИННАЯ с длинной и КОРОТКАЯ с короткой, а не ширина с
    шириной: вертикальный кадр 1536x2752 и горизонтальный 2752x1536 — один и
    тот же запрос к модели, которая объявляет обе ориентации. Сторону, которой
    предел не назвал, сравнивать не с чем, и это НЕ «влезает».
    """
    if предел.outcome != "годно":
        return {"outcome": "не смогли", "note": f"предел не разобран: {предел.note}"}
    длинная, короткая = max(кадр), min(кадр)
    сравнили: list[str] = []
    if предел.длинная is not None:
        if длинная > предел.длинная:
            return {
                "outcome": "не годно",
                "note": f"длинная сторона {длинная} больше предела {предел.длинная}",
            }
        сравнили.append(f"длинная {длинная} <= {предел.длинная}")
    if предел.короткая is not None:
        if короткая > предел.короткая:
            return {
                "outcome": "не годно",
                "note": f"короткая сторона {короткая} больше предела {предел.короткая}",
            }
        сравнили.append(f"короткая {короткая} <= {предел.короткая}")
    if not сравнили:
        return {"outcome": "не смогли", "note": "предел не назвал ни одной стороны"}
    return {"outcome": "годно", "note": "; ".join(сравнили) + f" ({предел.note})"}
