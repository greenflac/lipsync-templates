#!/usr/bin/env python3
"""Один уточняющий вопрос вместо догадки.

ЗАЧЕМ

Владелец назвал два входа продукта: пайплайн «на основе готового креатива» и
«с нуля». Второй вход формулируется РЕЗУЛЬТАТОМ, и у части таких брифов не
хватает не подсказок, а СВЕДЕНИЙ. ИЗМЕРЕНО 2026-09-03 (`scripts/check_brief_cues.py`):

    «Курс на английском: те же уроки, но чтобы преподаватель говорил
     по-английски»                                   -> шагов 0
    «Сделайте нам вертикальный ролик для маркетплейса:
     товар, музыка, без речи»                        -> шагов 0
    «Портрет клиента должен ожить и поприветствовать
     по имени»                                       -> не хватило липсинка и озвучки
    «Нужен рекламный ролик с закадровым текстом
     по нашему сценарию»                             -> не хватило генерации видео

Все четыре упираются в одну и ту же развилку: заказчик не сказал, ЕСТЬ ЛИ У
НЕГО ИСХОДНОЕ ВИДЕО и ДОЛЖЕН ЛИ ПЕРСОНАЖ ГОВОРИТЬ ВСЛУХ. Инженер на месте
задал бы один вопрос и получил бы полный план. Владелец выбрал именно это
(решение от 2026-09-03, ответ «второе»): спросить, а не угадать моделью.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ

Не достраивает план по догадке — этим занимается `planner.замкнуть`, и там
дописанный шаг помечается `inferred`. Здесь развилка НЕ РЕШАЕТСЯ вовсе:
возвращается вопрос, который обязан задать продукт. Вопрос ровно один: два
вопроса подряд — это уже анкета, а заказчик, которому прислали анкету, уходит.

ТРИ ИСХОДА (Р1) У ВЫЗЫВАЮЩЕГО

    план собран        -> вопрос не нужен, `спросить` вернёт None
    план собран не весь-> вопрос назван, план при этом остаётся как есть
    план пуст          -> вопрос назван вместо пустоты

Второй случай важен: вопрос НЕ отменяет уже выведенные шаги и не меняет
исход плана. Он добавляет строку «чего мы не знаем», а не переписывает
измеренное.

ЧТО ЭТО ДАЛО — И ГДЕ ГРАНИЦА (И6)

ИЗМЕРЕНО 2026-09-03, П3, чтением выдачи глазами. На четырёх брифах, ради
которых механизм заведён, ОДИН ответ закрывает план у трёх:

    «вертикальный ролик для маркетплейса» + «снимать нечего»
        -> [генерация_видео]
    «портрет должен ожить и поприветствовать» + «должен говорить вслух»
        -> [озвучка, оживление, липсинк]
    «рекламный ролик с закадровым текстом» + «снимать нечего»
        -> [озвучка, генерация_видео]

Четвёртый — «курс на английском» — после ответа про исходник переходит ко
ВТОРОЙ оси (а не переспрашивает первую) и закрывается вторым ответом. Но
собирается он как [озвучка, липсинк], а не как [дубляж, липсинк]: словарь
подсказок не знает оборота «чтобы преподаватель говорил по-английски». Это
ЗАПИСАННАЯ ГРАНИЦА, а не починка: подогнать подсказки под один бриф значило бы
подогнать и счётчик, который его меряет. Пайплайн при этом рабочий — речь
синтезируется заново вместо перевода имеющейся, — но выбран не лучший, и это
сказано вслух, а не спрятано.

НЕГАТИВНЫЙ КОНТРОЛЬ (И5)

В наборе `studio/knowledge/brief_wordings.jsonl` есть десять брифов не про
нашу работу. На них вопрос обязан НЕ задаваться: «есть ли у вас отснятое
видео?» в ответ на просьбу посчитать юнит-экономику — та же ложь продукта,
что и лишний шаг в плане, только вежливее. Счётчик меряет это отдельной
цифрой.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Sequence

#: Оси, по которым продукт умеет спрашивать. Имя оси — ключ, а не текст:
#: текст правится, ключ живёт в тестах и в отчётах.
ОСЬ_ИСХОДНИК = "есть_ли_исходное_видео"
ОСЬ_РЕЧЬ = "должен_ли_говорить"

#: Порядок опроса. КОНСТАНТА-РЕШЕНИЕ, ВЫБРАНО 2026-09-03: исходник спрашивается
#: первым, потому что ответ на него меняет БОЛЬШЕ плана — «видео уже снято»
#: убирает генерацию и приводит дубляж, тогда как ответ про речь добавляет или
#: снимает пару шагов. Спрашивать сначала о меньшем значит потратить
#: единственный вопрос дешевле, чем можно.
ПОРЯДОК: tuple[str, ...] = (ОСЬ_ИСХОДНИК, ОСЬ_РЕЧЬ)

#: Слова, которыми называют ВИДЕОРЕЗУЛЬТАТ.
#:
#: «липсинк» и «губ» ДОБАВЛЕНЫ 2026-09-07: на брифе из одного слова «липсинк»
#: продукт молча достраивал три шага и не спрашивал ничего, тогда как заказ
#: липсинка — это ровно тот случай, где видео либо уже снято, либо его надо
#: сделать, и разница в цене между этими путями наибольшая во всём продукте.
ВИДЕОРЕЗУЛЬТАТ: tuple[str, ...] = (
    "ролик",
    "видео",
    "клип",
    "урок",
    "курс",
    "визитк",
    "липсинк",
    "lipsync",
    "lip sync",
    "губ",
    # АНГЛИЙСКИЕ СЛОВА РЕЗУЛЬТАТА. ИЗМЕРЕНО 2026-09-07: брифы «I need a 30
    # second product video for my skincare brand» и «We want a short clip for
    # instagram» — точные близнецы русских, на которых продукт СПРАШИВАЕТ
    # «видео уже снято?», — получали «шаги не выведены» и никакого вопроса.
    # Ось у них та же, и разница в цене между «снято» и «снимать» та же.
    "video",
    "clip",
    "reel",
    "commercial",
)

#: Слова, которыми называют РЕЧЬ персонажа.
РЕЧЬ_ЖДУТ: tuple[str, ...] = ("приветств", "здорова", "по имени", "говор", "обращ", "отвеча")

#: Заказчик сам закрыл ось речи.
БЕЗ_РЕЧИ: tuple[str, ...] = ("без речи", "без слов", "без голоса", "немо", "молча")

#: Результат ЧУЖОГО ремесла, названный теми же словами. Список короткий
#: нарочно: в нём только то, без чего негативный контроль краснеет, — иначе
#: это словарь, который никто не мерил. ИЗМЕРЕНО: без «статью» вопрос
#: задавался на «статью в блог про рынок генеративного видео», без
#: «смонтиров» — на «смонтировать ролик из уже отснятого материала».
ЧУЖОЙ_РЕЗУЛЬТАТ: tuple[str, ...] = (
    "стать",
    # `blog post` ЗАВЕДЁН ПО ТОМУ ЖЕ ПРАВИЛУ, что и «стать»: без него
    # негативный контроль `en09` («Write a blog post about the generative
    # video market») краснеет — английское `video` в ВИДЕОРЕЗУЛЬТАТ добавлено,
    # и продукт начинает спрашивать про исходное видео у того, кто заказывал
    # текст. ИЗМЕРЕНО 2026-09-07.
    "blog post",
    "смонтиров",
    "монтаж",
    "ничего не генерир",
    "снимать будем сами",
    "снимаем сами",
)

#: Чем режется первая фраза. Главный результат заказчик называет в ней, а
#: дальше идут обстоятельства: «Начитка диктора по нашему тексту, один голос
#: на весь ролик» — просят начитку, а ролик лишь упомянут. ИЗМЕРЕНО: без этого
#: реза вопрос про исходное видео задавался на брифе про начитку, где план
#: уже полон.
РЕЗ = re.compile(r"[,;:!?\n]|\s—\s|\s-\s")


@dataclass(frozen=True)
class Вопрос:
    """Один вопрос заказчику и то, что от ответа зависит."""

    ось: str
    текст: str
    почему: str
    варианты: tuple[str, ...]
    #: ТОТ ЖЕ ВОПРОС ПО-АНГЛИЙСКИ. Не перевод «на всякий случай»: НАЙДЕНО
    #: седьмой приёмкой 2026-09-07, что английский бриф получает вопрос
    #: по-русски — то есть заказчик не может прочесть единственную строку, по
    #: которой он способен что-то сделать. Поле обязательное и без значения по
    #: умолчанию нарочно: новый вопрос, заведённый без английской половины,
    #: обязан не собраться, а не тихо заговорить по-русски.
    english: tuple[str, str, tuple[str, ...]]

    def строка(self) -> str:
        return f"вопрос [{self.ось}]: {self.текст} ({' / '.join(self.варианты)}) — {self.почему}"

    def row(self, по_английски: bool = False) -> dict:
        """Строка вопроса. Язык — по языку брифа, а не по языку кода."""
        текст, почему, варианты = (
            self.english if по_английски else (self.текст, self.почему, self.варианты)
        )
        return {
            "axis": self.ось,
            "text": текст,
            "why": почему,
            "options": list(варианты),
        }

    def сказать(self, по_английски: bool = False) -> str:
        """Только текст вопроса, на нужном языке."""
        return self.english[0] if по_английски else self.текст


ВОПРОСЫ: dict[str, Вопрос] = {
    ОСЬ_ИСХОДНИК: Вопрос(
        ось=ОСЬ_ИСХОДНИК,
        текст="Видео уже снято — или ролик нужно сделать с нуля?",
        почему=(
            "от этого зависит весь состав плана: снятое переозвучивают и "
            "пересинхронизируют, ненаснятое сначала генерируют"
        ),
        варианты=("видео есть", "снимать нечего, делаем с нуля"),
        english=(
            "Do you already have the video shot — or do we make the clip from scratch?",
            "this decides the whole plan: footage you have gets re-voiced and "
            "re-synced, footage you do not have has to be generated first",
            ("I have the video", "nothing is shot, make it from scratch"),
        ),
    ),
    ОСЬ_РЕЧЬ: Вопрос(
        ось=ОСЬ_РЕЧЬ,
        текст="Персонаж должен говорить вслух — или это немая анимация?",
        почему="речь добавляет в план озвучку и липсинк, немая анимация обходится без них",
        варианты=("должен говорить", "без речи"),
        english=(
            "Does the character speak out loud — or is it a silent animation?",
            "speech adds voiceover and lip sync to the plan; a silent animation needs neither",
            ("it speaks", "no speech"),
        ),
    ),
}


def первая_фраза(brief: str) -> str:
    """Часть брифа до первого реза. Пустой бриф даёт пустую строку."""
    return РЕЗ.split(brief.strip().lower(), maxsplit=1)[0]


def _чужое(низ: str) -> bool:
    return any(с in низ for с in ЧУЖОЙ_РЕЗУЛЬТАТ)


def спросить(
    brief: str,
    производится: Sequence[str],
    есть: Sequence[str],
    *,
    артефакт_видео: str,
    артефакт_аудио: str,
    дописано: Sequence[str] = (),
) -> Вопрос | None:
    """Один вопрос — или None, если спрашивать не о чем.

    :param производится: артефакты, которые ПРОИЗВОДЯТ уже собранные шаги
        (после `planner.замкнуть`, а не до: дописанный шаг закрывает нехватку,
        и спрашивать о ней второй раз значит переспрашивать решённое).
    :param есть: артефакты, которые у заказчика уже на входе.

    Имена артефактов передаются ПАРАМЕТРАМИ, а не импортируются: словарь
    артефактов живёт у планировщика (Е1), и второй его копии тут не заводится.
    """
    низ = brief.strip().lower()
    if not низ or _чужое(низ):
        return None
    голова = первая_фраза(brief)
    доступно = set(производится) | set(есть)

    # АРТЕФАКТ, ПОЯВИВШИЙСЯ ТОЛЬКО ИЗ ДОПИСАННОГО ШАГА, ВОПРОСА НЕ СНИМАЕТ.
    #
    # ВОСПРОИЗВЕДЕНО продуктовой проверкой 2026-09-07: на брифе из ОДНОГО
    # СЛОВА «липсинк» продукт молча достраивал три шага (озвучка, генерация
    # видео, липсинк) и вопроса не задавал — потому что дописанный шаг
    # «генерация видео» сам же и закрыл нехватку видео. А на опечатанном, но
    # содержательном брифе продукт спрашивал: «Видео уже снято — или ролик
    # нужно сделать с нуля?». Развилка «спросить или достроить» была
    # несогласована ровно наоборот: чем МЕНЬШЕ сказал заказчик, тем увереннее
    # отвечал продукт.
    #
    # Дописанный шаг — это НАША ДОГАДКА, а не ответ заказчика. Догадка не
    # может служить основанием не спрашивать: у заказчика вполне может быть
    # своё видео, и тогда шага генерации не нужно вовсе.
    только_догадка = set(дописано) - set(есть)
    for ось in ПОРЯДОК:
        if ось == ОСЬ_ИСХОДНИК:
            if артефакт_видео in доступно and артефакт_видео not in только_догадка:
                continue
            if any(с in голова for с in ВИДЕОРЕЗУЛЬТАТ):
                return ВОПРОСЫ[ось]
        elif ось == ОСЬ_РЕЧЬ:
            if артефакт_аудио in доступно:
                continue
            if any(с in низ for с in БЕЗ_РЕЧИ):
                continue
            if any(с in низ for с in РЕЧЬ_ЖДУТ):
                return ВОПРОСЫ[ось]
    return None
