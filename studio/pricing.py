_RES = re.compile(
    r"(?<![\w.])(?:(\d{3,4})\s*p\b|(\d{3,4})\s*[x×]\s*(\d{3,4})|(0\.5|[1248])\s*k\b(?!\s*(?:characters?|chars?|tokens?|credits?)\b)|(fhd|uhd|full hd|hd|sd)\b)",
    re.I,
)
#: Сумма в строке: доллары, кредиты или голое число (последнее — только там,
#: где в куске нет ни одного `$`, а единицу назвало имя атрибута).
_AMOUNT = re.compile(
    r"\$\s*~?\s*(\d+(?:\.\d+)?)"
    # «0.08$» — но не «1024x1024 $0.211»: число перед `$` и числом за ним —
    # это подпись следующей суммы, а не сумма (круг 4: читалось 1024 usd).
    r"|~?(\d+(?:\.\d+)?)\s*\$(?!\s*~?\d)"
    r"|(\d+(?:\.\d+)?)\s*(?:credits?|cr)\b"
    # Голое число — но не кусок «4,096» (разделитель тысяч, круг 4).
    r"|(?<![\w.$-])(?<!\d,)~?(\d+(?:\.\d+)?)(?![\w.%])(?!,\d{3})",
    re.I,
)
#: Количество, которое НЕ сумма: «40 seconds», «1–7 supported», «5s».
_НЕ_СУММА_ПОСЛЕ = re.compile(
    r"^\s*(?:-?\s*)?(?:seconds?|secs?|s\b|minutes?|mins?|characters?|chars?|frames?|fps|images?|"
    r"megapixels?|mp\b|tokens?|k\b|m\b|x\b|supported|second\b|credit\b)",
    re.I,
)
_ПРИМЕР = re.compile(r"^\s*(?:for example|for instance|e\.g\.|a\s+\d|so\s+\d)", re.I)
_ЗВУК_ДА = re.compile(r"with audio|audio on|with sound|sound on", re.I)
_ЗВУК_НЕТ = re.compile(r"no audio|audio off|without(?: audio| sound)?\b|sound off", re.I)
#: Слова, после которых ставка — не вся цена: минимум, доплата, «если».
_УСЛОВИЕ_СТАВКИ = re.compile(r"\b(?:minimum|upfront|if|when|rounded|rolling|billed)\b", re.I)
_ЛЕГЕНДА_ЗВУКА = re.compile(r"\(\s*(?:no audio|audio off)\s*/\s*(?:with audio|audio on)\s*\)", re.I)

_РЕЗ_СЛОВО = r"(?:\d{3,4}\s*p|\d{3,4}\s*[x×]\s*\d{3,4}|(?:0\.5|[1248])\s*k(?!\s*(?:characters?|chars?|tokens?|credits?)\b)|fhd|uhd|full hd|hd|sd)"
#: Разрешение ВПЛОТНУЮ после суммы: «$0.05 480p», «$0.17/s hd», «$0.13 2K».
_РЕЗ_ВПЛОТНУЮ_ПОСЛЕ = re.compile(
    r"^\s*(?:/\s*s(?:ec(?:ond)?)?\b\s*|per\s+)?(" + _РЕЗ_СЛОВО + r")(?![\w])", re.I
)
#: «at / for / (» после суммы, но В ТОЙ ЖЕ части фразы: до предлога нет
#: запятой, точки и слов, начинающих следующую часть («and», «or», «charged»).
#: Без этой границы «$0.3034/second and for 1080p you will be charged $0.682»
#: отдавало 1080p первой сумме.
_РЕЗ_ПОСЛЕ = re.compile(
    r"^(?:(?!\b(?:and|or|charged|costs?|will|then|plus)\b)[^$;,.])*?(?:\bat\b|\bfor\b|\bup to\b|\()\s*([^$;]*)",
    re.I,
)
#: Метка «за что не названо у этой суммы» — внутренняя, в `per` не попадает.
_НЕ_НАЗВАНО = "\0"
#: «За что», которое соседняя сумма без своего «за что» наследует. Прогон не
#: наследуется: «$0.2 for videos up to 40 seconds» не говорит о соседе.
_ОБЩИЕ_ЕДИНИЦЫ = frozenset({"second", "minute", "megapixel", "image", "1000_chars"})


@dataclass(frozen=True)
class Rate:
    """Одна ставка из строки-таблицы. `per` — из `PER` или пусто."""

    amount: float
    unit: str
    per: str
    tier: str = ""
    resolutions: tuple[int, ...] = ()
    audio: bool | None = None
    #: Ставка «за прогон», который покрывает столько секунд («5s: $0.15»,
    #: «$0.2 for videos up to 40 seconds»).
    run_seconds: float | None = None
    #: Доплата за каждую секунду сверх `run_seconds` («then $0.005 per second»).
    over_per_second: float | None = None
    #: Разовая плата за прогон сверх посекундной («2 credits upfront»).
    upfront: bool = False
    #: Доплата СВЕРХ прогона («then $0.005 per second», «for longer videos»):
    #: приклеивается к предыдущей ставке-прогону, а не встаёт отдельной.
    over: bool = False
    mode: str = ""
    conditional: bool = False
    source: str = ""
    #: Размер БЛОКА, которым вендор считает («per 10 seconds», «per started 2
    #: megapixels»): `amount` — за ЕДИНИЦУ `per`, а платится за каждый начатый
    #: блок целиком (2026-10-15, круг 4). None — блока нет, счёт линейный.
    block: float | None = None
    #: Частота кадров, к которой относится ставка («At 60 fps, the same job
    #: costs $6.00»). None — не названа (2026-10-15, круг 4).
    fps: float | None = None


def _разрешения(текст: str) -> tuple[int, ...]:
    """Все разрешения в куске текста, короткой стороной."""
    итог: list[int] = []
    for м in _RES.finditer(текст):
        if м.group(1):
            итог.append(int(м.group(1)))
        elif м.group(2):
            итог.append(min(int(м.group(2)), int(м.group(3))))
        elif м.group(4):
            итог.append(RESOLUTION_WORDS[f"{м.group(4)}k"])
        elif м.group(5):
            итог.append(RESOLUTION_WORDS[м.group(5).lower()])
    # «720p-1080p» — диапазон: обе ступени и всё между ними мы не выдумываем.
    return tuple(dict.fromkeys(итог))


def вид_доплаты(голова: str) -> str:
    """'over', если текст после суммы говорит о доплате сверх прогона."""
    return "over" if re.search(r"additional|then|longer|beyond", голова[:40]) else ""


def _за_что(после: str, по_умолчанию: str) -> tuple[str, float, float | None, str]:
    """«За что» ставки по тексту ПОСЛЕ суммы: (per, множитель суммы, секунд в прогоне, вид).

    Размер блока («per 10 seconds» -> 10) отдаёт `_блок` — отдельно, чтобы
    форма ответа не менялась для всех прочих ветвей.

    Множитель нужен там, где вендор назвал не ту меру, что у нас: «per 100
    characters» — это десятая доля «за 1000 знаков», «per 30 seconds» — за
    тридцать секунд. Вид — '' | 'over' | 'upfront' | 'minimum' | 'skip'.
    """
    п = после.lower()
    голова = п[:60]
    if re.match(r"^\s*(?:credit\s+)?minimum", голова) or re.match(
        r"^\s*(?:credits?\s+)?minimum", голова
    ):
        return "", 1.0, None, "minimum"
    if re.match(r"^\s*(?:credits?\s+)?upfront", голова):
        return "run", 1.0, None, "upfront"
    # «per 1K characters» — ТЫСЯЧА ЗНАКОВ, а не токены (2026-10-15, по
    # независимому валидатору): строка вендора `eleven_v3` «$0.08 per 1K
    # characters (API)» уходила в правило токенов ниже и давала пустой список —
    # то есть цена ПРЯМОГО маршрута пропадала, и смета брала пересказ
    # агрегатора. Проверяется ДО правила токенов, потому что то ловит «per 1K».
    # «per 1 million characters», «per million characters», «per 1,000,000
    # characters» — МИЛЛИОН знаков, то есть тысячная доля на 1000 знаков
    # (интеграция седьмого круга): «$30 per 1 million characters» читалось
    # правилом «per <N> <слово> characters» ниже как N=1 и давало $30000 за
    # 1000 знаков, а две другие записи теряли ставку вовсе.
    if re.match(
        r"^\s*(?:/|per)\s*(?:(?:1\s*)?million|1[\s,]?000[\s,]?000)\s*(?:characters?|chars?)\b",
        голова,
    ):
        return "1000_chars", 0.001, None, вид_доплаты(голова)
    м = re.match(r"^\s*(?:/|per)\s*1\s*([km])\s*(?:characters?|chars?)\b", голова)
    if м:
        return "1000_chars", 1.0 if м.group(1) == "k" else 0.001, None, вид_доплаты(голова)
    if (
        re.match(r"^\s*(?:/\s*1\s*[km]\b|per\s+1\s*[km]\b|/\s*1k|per\s+(?:1m|million))", голова)
        or "token" in голова[:30]
    ):
        return "token", 1.0, None, "skip"
    if re.match(r"^[^$]{0,20}?per\s+(?:\w+\s+)?megapixels?\s+per\s+(?:second|sec|frame)", голова):
        # «$0.10 per megapixel per second» — мера из двух множителей, которой в
        # `PER` нет; прочесть её «за секунду» значило бы потерять мегапиксели
        # (круг 4). Ставка не читается: шаг честно остаётся без цены.
        return "", 1.0, None, "skip"
    if re.match(r"^\s*per\s+(?:clone|created voice)", голова):
        return "clone", 1.0, None, вид_доплаты(голова)
    if re.match(r"^\s*per\s+credit", голова):
        return "", 1.0, None, "skip"
    вид = вид_доплаты(голова)
    if re.match(r"^[^$]{0,30}?(?:/|per)\s*(?:gpu\s+)?compute[\s-]+seconds?\b", голова):
        return "compute_second", 1.0, None, вид
    м = re.match(r"^\s*(?:/|per|for every|a|each)?\s*(\d+)\s*(?:seconds?|s)\b", голова)
    if м and not re.match(r"^\s*for\b", голова):
        return "second", 1.0 / float(м.group(1)), None, вид
    # «per 1000 preview characters» — слово между числом и знаками (шестой круг).
    м = re.match(
        r"^\s*(?:/|per|for every|every)?\s*(\d+)\s*(?:[a-z]+\s+)?(?:characters?|chars?)\b", голова
    )
    if м:
        return "1000_chars", 1000.0 / float(м.group(1)), None, вид
    if re.match(
        r"^[^$]{0,30}?(?:/\s*s(?:ec)?\b|per\s+(?:\w+\s+){0,2}seconds?|per\s+sec\b|for every (?:\w+\s+){0,2}seconds?|/sec)",
        голова,
    ):
        return "second", 1.0, None, вид
    if re.match(r"^[^$]{0,30}?(?:/\s*min\b|per\s+(?:\w+\s+){0,2}minutes?)", голова):
        return "minute", 1.0, None, вид
    м = re.match(r"^[^$]{0,20}?per\s+(?:started\s+)?(\d+(?:\.\d+)?)\s*(?:megapixels?|mp)\b", голова)
    if м:
        return "megapixel", 1.0 / float(м.group(1)), None, вид
    if re.match(r"^[^$]{0,20}?per\s+(?:\w+\s+)?(?:processed\s+)?megapixel", голова):
        return "megapixel", 1.0, None, вид
    if re.match(r"^[^$]{0,20}?(?:per|/)\s*(?:\w+\s+)?image", голова):
        return "image", 1.0, None, вид
    м = re.match(
        r"^[^$]{0,25}?for (?:a |videos? )?(?:up to )?(\d+)\s*-?\s*(?:s|sec|seconds?)\b", голова
    )
    if м:
        return "run", 1.0, float(м.group(1)), вид
    м = re.match(r"^\s*per\s+(?:\d{3,4}\s*p\s+)?(\d+)\s*s(?:\s+video|\s*$|\s*[;,.])", голова)
    if м:
        return "run", 1.0, float(м.group(1)), вид
    if re.match(r"^[^$]{0,25}?per\s+(?:video\s+)?(?:run|generation|video)\b", голова):
        return "run", 1.0, None, вид
    return по_умолчанию, 1.0, None, вид


def _блок(после: str) -> float | None:
    """«per 10 seconds», «/10s», «per started 2 megapixels» -> 10, 10, 2. Иначе None.

    ЗАЧЕМ (2026-10-15, круг 4): «$0.10 per 10 seconds» считалось линейно, то
    есть 15 с стоили $0.15, а вендор берёт за НАЧАТЫЙ блок — $0.20. Линейный
    счёт занижает; блочный — не ниже правды, когда вендор считает блоками, и
    равен линейному на кратной длине.
    """
    голова = после.lower()[:60]
    м = re.match(r"^\s*(?:/|per|for every|every|each)\s*(\d+)\s*(?:seconds?|secs?|s)\b", голова)
    if м and float(м.group(1)) > 1:
        return float(м.group(1))
    м = re.match(r"^[^$]{0,20}?per\s+(?:started\s+)?(\d+(?:\.\d+)?)\s*(?:megapixels?|mp)\b", голова)
    if м and float(м.group(1)) > 1:
        return float(м.group(1))
    return None


def rates(value: str, attribute: str = "") -> list[Rate]:
    """Строка цены -> список ставок. Пустой список — «не смогли», а не «бесплатно».

    Порядок ставок — порядок строки: вендор ставит флагманский тариф первым,
    и `estimate` этим пользуется, чтобы назвать тариф ПО УМОЛЧАНИЮ.
    """
    текст = str(value or "").strip()
    if not текст:
        return []
    единица_имени, за_имени = unit_and_per(attribute)
    if за_имени in ("token", "") and _ЗА_МИЛЛИОН.search(текст):
        return []
    # «Your request will cost $X» без «за что» — цена ЗАПРОСА, то есть прогона:
    # так площадка пишет цену генерации, и другого прочтения у фразы нет.
    if not за_имени and re.search(r"request will (?:cost|be priced)", текст, re.I):
        за_имени = "run"
    if за_имени in ("token", "1m_tokens"):
        return []
    if _ЕДИНИЦА_НЕ_НАЗВАНА.search(текст):
        # «$1 per unit (billing unit 'units')» — единица биллинга площадки, о
        # которой не сказано, ЧТО она (шестой круг): у `gpt-image-2` и
        # `nano-banana-2.1` это заглушка $1 рядом с ценой за токены. Неизвестная
        # единица — третий исход, а не ставка.
        return []
    легенда = bool(_ЛЕГЕНДА_ЗВУКА.search(текст))
    # Легенда «(no audio / with audio)» описывает ПАРЫ чисел, а не последнее из
    # них: вынимается из текста, чтобы её «no audio» не прилипло к соседу.
    текст = _ЛЕГЕНДА_ЗВУКА.sub(" ", текст)
    итог: list[Rate] = []
    # Предложения-ПРИМЕРЫ («For example, a 5s video will cost $0.70», «A
    # 5-second 480p clip costs $0.40») — арифметика вендора над той же
    # ставкой, а не вторая ставка.
    предложения = [п for п in re.split(r"(?<=[.!?])\s+(?=[A-Z])", текст) if not _ПРИМЕР.match(п)]
    for предложение in предложения:
        for кусок in re.split(r";", предложение):
            for r in _ставки_куска(кусок, единица_имени, за_имени, легенда, итог):
                # ДОПЛАТА СВЕРХ ПРОГОНА живёт часто в соседнем предложении
                # («$0.2 for videos up to 40 seconds. For longer videos ...
                # $0.005 per second») — и приклеивается к прогону, а не
                # становится второй, дешёвой ставкой «за секунду».
                прогон = next(
                    (
                        i
                        for i in range(len(итог) - 1, -1, -1)
                        if итог[i].run_seconds and итог[i].over_per_second is None
                    ),
                    None,
                )
                if r.over and r.per == "second" and прогон is not None:
                    итог[прогон] = Rate(**{**итог[прогон].__dict__, "over_per_second": r.amount})
                    continue
                итог.append(r)
    if _ВВЕРХ_ДО_МИНУТЫ.search(текст):
        # «The audio will be rounded up to the closest minute» (ElevenLabs Music
        # на fal, шестой круг): 30 с платятся как минута. Блок — минута.
        итог = [
            Rate(**{**r.__dict__, "block": 1.0}) if r.per == "minute" and not r.block else r
            for r in итог
        ]
    return _привязать_повтор(итог)


#: «per compute second» в тексте цены.
_ЗА_ВЫЧИСЛЕНИЕ = re.compile(r"per\s+(?:gpu\s+)?compute[\s-]+seconds?\b", re.I)

#: «rounded up to the closest minute» — счёт минутами, начатая минута целиком.
#: Восьмой круг (x25, w24): та же строка у fal пишется и без артикля —
#: «$0.6, rounded up to closest minute», — и словами «the closest minute after
#: rounding upwards»; ни одна из них прежде не узнавалась, и 30 с дубляжа
#: стоили 0.30 usd вместо 0.60.
_ВВЕРХ_ДО_МИНУТЫ = re.compile(
    r"rounded up to (?:the )?(?:closest|nearest|next) (?:full )?minute"
    r"|(?:closest|nearest|next) (?:full )?minute after rounding up(?:wards?)?",
    re.I,
)

#: Цена за НЕНАЗВАННУЮ единицу биллинга площадки: ставкой не становится.
_ЕДИНИЦА_НЕ_НАЗВАНА = re.compile(r"\bper\s+units?\b|billing unit\s*'units?'", re.I)


def compute_twins(по_строкам: list[tuple[str, list[Rate]]]) -> list[Rate]:
    """Ставки модели одним списком; «за секунду», равная ставке «за секунду
    ВЫЧИСЛЕНИЯ» того же маршрута, — та же ставка (шестой круг).

    `rife-video`: страница fal пишет «$0.0013 per compute second», pricing API
    той же площадки — «$0.0013 per second». Это одна цена в одной единице, и
    единица — секунда GPU; прочесть вторую строку «за секунду ролика» значило
    бы посчитать шаг так, будто GPU работает ровно столько, сколько длится ролик.

    :param по_строкам: (маршрут строки, её ставки) по каждой ценовой строке.
    """
    вычисления = {
        (маршрут, round(r.amount, 9))
        for маршрут, ставки in по_строкам
        for r in ставки
        if r.per == "compute_second"
    }
    итог: list[Rate] = []
    for маршрут, ставки in по_строкам:
        for r in ставки:
            if r.per == "second" and (маршрут, round(r.amount, 9)) in вычисления:
                r = Rate(**{**r.__dict__, "per": "compute_second"})
            итог.append(r)
    return итог


def _привязать_повтор(ставки: list[Rate]) -> list[Rate]:
    """«$0.3034; 1080p $0.682; 480p $0.1346; 720p $0.3034»: голая первая сумма
    сводки — ПОВТОР одной из привязанных (цена по умолчанию), и она получает её
    разрешение (круг 4). Сумма, равная привязанным с РАЗНЫМИ разрешениями или
    не равная ни одной, остаётся без разрешения — выдумывать пару нельзя.
    """
    итог = list(ставки)
    for i, r in enumerate(итог):
        if r.resolutions or r.conditional:
            continue
        двойники = {
            x.resolutions
            for x in итог
            if x is not r
            and x.resolutions
            and x.amount == r.amount
            and (x.per, x.tier, x.unit, x.mode, x.audio) == (r.per, r.tier, r.unit, r.mode, r.audio)
        }
        if len(двойники) == 1:
            итог[i] = Rate(**{**r.__dict__, "resolutions": next(iter(двойники))})
    return итог


def _ставки_куска(
    кусок: str, единица_имени: str, за_имени: str, легенда: bool, прежние: list[Rate] | None = None
) -> list[Rate]:
    прежние = прежние or []
    низ = кусок.lower()
    голова = низ.lstrip(" ,—-")
    tier = ""
    mode = ""
    # «v4 Turbo $0.04»: номер версии перед словом тарифа тарифом не мешает
    # (иначе Turbo ложился в безымянный тариф рядом с основной ценой).
    м = re.match(r"^(?:v\d+(?:\.\d+)?\s+)?([a-z0-9/,]+)\b", голова)
    if м:
        слово = м.group(1)
        if слово.split("/")[0] in TIER_WORDS:
            слово = слово.split("/")[0]
            tier = "draft" if слово == "drafts" else слово
        elif any(р in слово.split("/") for р in MODE_WORDS):
            mode = слово
    # «5s:» / «HDR 5s» в начале куска — цена за прогон столько-то секунд.
    # «For a 6s 480p video your request will cost $0.36» — тоже прогон (круг 4).
    # «For a 10-second 30→60 fps job, … costs $0.30» — тоже прогон (шестой круг).
    м_прогон = re.match(r"^(?:[a-z]+\s+)?(?:a\s+)?(\d+)\s*(?:s|-\s*seconds?)\b\s*:?", голова)
    прогон_куска = float(м_прогон.group(1)) if м_прогон else None
    есть_доллар = "$" in кусок
    найдены = [
        м
        for м in _AMOUNT.finditer(кусок)
        if not (м.group(4) and (есть_доллар or единица_имени != "usd" and not единица_имени))
    ]
    # Голое число — только при единице из имени атрибута и без `$` в куске.
    найдены = [
        м
        for м in найдены
        if not (м.group(4) and (есть_доллар or единица_имени != "usd"))
        and not _НЕ_СУММА_ПОСЛЕ.match(кусок[м.end() :])
        and not re.match(r"^\s*[–-]\s*\d", кусок[м.end() :])
        and not (м.group(4) and прогон_куска is not None and float(м.group(4)) == прогон_куска)
        # Множитель формулы («(height * width * duration * 24) / 1024») — не
        # сумма: голое число рядом со знаком умножения (круг 4: читалось $24/с).
        and not re.search(r"[*×=]\s*~?\$?\s*$", кусок[: м.start()])
        and not re.match(r"^\s*[*×=]", кусок[м.end() :])
    ]
    ставки: list[Rate] = []
    #: (после, разрешение привязано ПОСЛЕ суммы) — для каждой ставки `ставки`.
    следы: list[tuple[str, bool]] = []
    общее: tuple[str, float, float | None] | None = None
    for i, м in enumerate(найдены):
        конец_след = найдены[i + 1].start() if i + 1 < len(найдены) else len(кусок)
        начало_пред = найдены[i - 1].end() if i > 0 else 0
        после = кусок[м.end() : конец_след]
        до = кусок[начало_пред : м.start()]
        if re.match(r"^\s*per credit", после, re.I):
            continue
        if м.group(1) or м.group(2):
            сумма, единица = float(м.group(1) or м.group(2)), "usd"
        elif м.group(3):
            сумма, единица = float(м.group(3)), "credits"
        else:
            сумма, единица = float(м.group(4)), единица_имени
        # «За что» НЕ НАЗВАНО у суммы — оно общее с соседней суммой куска
        # (2026-10-15, круг 4): «$0.10 per 10 seconds of output at 720p, $0.20 at
        # 1080p, and $0.60 at 4K» — вторая и третья суммы тоже за 10 секунд, а
        # читались «за прогон» по имени атрибута: 4K выходил дешевле 720p.
        за, множитель, прогон, вид = _за_что(после, _НЕ_НАЗВАНО)
        блок = _блок(после)
        м_до_блок = re.search(
            r"(?:(\d+)|every|each)\s*(?:seconds?|secs?|s)\s+(?:of\s+\w+\s+)?(?:costs?|is|=)\s*~?\$?\s*$",
            до,
            re.I,
        )
        if за == _НЕ_НАЗВАНО and м_до_блок:
            # «10 seconds costs $3.00», «every second costs $0.05» — «за что»
            # стоит ПЕРЕД суммой (круг 4).
            n = float(м_до_блок.group(1) or 1)
            за, множитель, блок = "second", 1.0 / n, (n if n > 1 else None)
            if вид == "":
                общее = (за, множитель, блок)
        по_имени = False
        if за == _НЕ_НАЗВАНО:
            if общее is not None:
                за, множитель, блок = общее
            else:
                за = за_имени
                по_имени = True
        elif вид == "" and за in _ОБЩИЕ_ЕДИНИЦЫ and прогон is None:
            общее = (за, множитель, блок)
        if re.match(r"^\s*,?\s*you can run\b", после, re.I):
            # «For $1.00, you can run this model 12 times» — арифметика, не ставка.
            continue
        открыта = кусок.rfind("(", 0, м.start())
        if открыта > кусок.rfind(")", 0, м.start()) and any(
            н.start() < открыта for н in найдены[:i]
        ):
            # «$0.28/second ($0.14 per input second and 0.14 per output
            # second)» — РАСКЛАДКА суммы в скобках, а не вторая ставка (круг 4).
            continue
        if re.search(r"\bminimum(?:\s+of)?\s*$", до, re.I):
            # «(minimum 1 credit)» — порог, а не ставка (круг 4: иначе сумма
            # наследовала «за что» соседа и становилась второй ставкой).
            continue
        if вид in ("skip", "minimum") or not единица:
            continue
        # «with TURBO» после суммы — тариф этой ставки.
        м_тариф = re.search(r"with\s+([a-z]+)", после, re.I)
        тариф = tier
        if м_тариф and м_тариф.group(1).lower() in TIER_WORDS:
            тариф = м_тариф.group(1).lower()
        # Разрешение (переписано 2026-10-15, круг 4: «$0.05 480p, $0.10 720p, or
        # $0.20 1080p» не связывалось вовсе, и шаг 1080p платил по 480p).
        # Порядок: вплотную ПОСЛЕ суммы («$0.05 480p», «$0.17/s hd»); «at /
        # for / (» после суммы, но в той же части фразы («$0.40/s at 720p»,
        # «$0.40 with audio for 720p or 1080p»); вплотную ПЕРЕД («720p $0.08»,
        # «480p at $0.08»); наконец — единственное разрешение в тексте между
        # прошлой суммой и этой («For every second of 720p video … $0.14»), если
        # прошлая сумма это разрешение не забрала себе.
        разрешения: tuple[int, ...] = ()
        после_привязано = False
        м_рядом = _РЕЗ_ВПЛОТНУЮ_ПОСЛЕ.match(после)
        if м_рядом:
            разрешения = _разрешения(м_рядом.group(1))
        if not разрешения:
            м_после = _РЕЗ_ПОСЛЕ.match(после)
            if м_после:
                разрешения = _разрешения(
                    м_после.group(1).split(",")[0]
                    if "(" not in м_после.group(0)
                    else м_после.group(1).split(")")[0]
                )
        после_привязано = bool(разрешения)
        if not разрешения:
            хвост_до = до[-24:]
            м_до = re.search(
                r"((?:\d{3,4}\s*p|\d{3,4}\s*[x×]\s*\d{3,4}|[248]\s*k|fhd|uhd|hd)\b)\s*(?:at|-|–|:|costs?)?\s*~?\$?\s*$",
                хвост_до,
                re.I,
            )
            if м_до:
                разрешения = _разрешения(м_до.group(1))
            elif re.search(r"(?:^|[\s,])(?:or|/)\s*$", до) and ставки:
                разрешения = ставки[-1].resolutions
            elif not (следы and следы[-1][1]):
                в_до = _разрешения(до)
                if len(в_до) == 1:
                    разрешения = в_до
        звук: bool | None = None
        около = после[:40]
        if _ЗВУК_НЕТ.search(около):
            звук = False
        elif _ЗВУК_ДА.search(около):
            звук = True
        if (
            звук is None
            and re.match(r"^\s*with\b\s*[.,;)]?\s*$", после)
            and ставки
            and ставки[-1].audio is False
        ):
            # «$0.40 per second without audio, or $0.60 with.» (круг 4)
            звук = True
        if легенда and звук is None:
            звук = до.strip() == "/"
        сверх = вид == "over" or bool(
            re.search(r"\b(?:then|longer|additional|beyond|plus)\b", до, re.I)
        )
        ставки.append(
            Rate(
                # Ставка с блоком не округляется: «$0.08 per started 24 MP» —
                # это 0.08/24 за Мп, и округлённое до 6 знаков давало 0.079992.
                amount=сумма * множитель if блок else round(сумма * множитель, 6),
                unit=единица,
                # Прогон куска («5s:», «For a 6s 480p video … $0.36») сильнее
                # «за что» из ИМЕНИ атрибута: имя «за секунду» не делает
                # цену прогона посекундной (круг 4: $0.36 за 6 с читалось $/с).
                per="run"
                if прогон_куска is not None
                and (за in ("", "run") or по_имени or (за == за_имени and за != "second"))
                else за,
                tier=тариф,
                resolutions=разрешения,
                audio=звук,
                run_seconds=прогон
                if прогон is not None
                else (
                    прогон_куска
                    if прогон_куска is not None and (за != "second" or по_имени)
                    else None
                ),
                upfront=вид == "upfront",
                over=сверх,
                mode=_режим_в_скобках(после) or mode,
                # «if voice control is used … $0.154» — условие стоит ПЕРЕД
                # суммой (круг 4); раньше смотрели только после неё.
                # Условие ПОСЛЕ суммы — до запятой, если за ней есть ещё сумма:
                # «$0.126 (audio on), if voice control … $0.154» — «if» о третьей.
                conditional=bool(
                    _УСЛОВИЕ_СТАВКИ.search(
                        (после if i + 1 == len(найдены) else re.split(r"[,;]", после)[0])[:60]
                    )
                )
                or bool(re.search(r"\b(?:if|when)\b", до, re.I))
                # Доплата за ВХОД («image input $0.01», «+ $0.01 per second of
                # video input») — надбавка, а не цена шага.
                or bool(re.search(r"\binput\s*$|\+\s*$|\bplus\s*$", до[-20:], re.I))
                # «each additional image costs $0.08», «Each input image costs
                # $0.01» — доплата за вход, а не цена шага (круг 4).
                or bool(
                    re.search(
                        r"\b(?:each|every|per)\s+(?:\w+\s+){0,2}(?:image|reference|input)s?\b[^$]{0,25}$",
                        до,
                        re.I,
                    )
                )
                # «$0.02–$0.04 each» — верхний край диапазона наследует условие.
                or bool(ставки and ставки[-1].conditional and до.strip() in ("–", "-", "to"))
                # «0.196 with voice control» — доплата за функцию, не за звук.
                or bool(
                    (доплата := re.match(r"^\s*\(?\s*with\s+(?!audio|sound)(\w+)", после, re.I))
                    and доплата.group(1).lower() not in TIER_WORDS
                ),
                source=кусок.strip()[:120],
                block=блок,
                fps=_кадры_в_секунду(кусок[: м.start()]),
            )
        )
        следы.append((после, после_привязано))
    _общее_разрешение_пары(ставки, следы)
    return _по_порядку(_режим_куска(низ, ставки), кусок, прежние)


def _кадры_в_секунду(до: str) -> float | None:
    """Последняя частота кадров, названная ПЕРЕД суммой в куске: «At 60 fps, … $6.00» -> 60."""
    найдены = re.findall(r"(\d{2,3})\s*-?\s*fps\b", до, re.I)
    return float(найдены[-1]) if найдены else None


def _режим_в_скобках(после: str) -> str:
    """«$0.06/s (t2v,i2v)» -> 't2v/i2v': режим, названный в скобках сразу после суммы."""
    м = re.match(r"^\s*(?:/\s*s(?:ec)?\b)?\s*\(\s*([a-z0-9,/ ]+)\)", после, re.I)
    if not м:
        return ""
    слова = [с for с in re.split(r"[,/ ]+", м.group(1).lower()) if с]
    return "/".join(слова) if слова and all(с in MODE_WORDS for с in слова) else ""


def _общее_разрешение_пары(ставки: list[Rate], следы: list[tuple[str, bool]]) -> None:
    """«$0.20 without audio or $0.40 with audio for 720p or 1080p»: разрешение
    названо ОДИН раз после пары и относится к обеим (2026-10-15, круг 4).

    Сумма без разрешения, за которой идёт только «or» / «/» и соседняя сумма с
    разрешением, получает его разрешение. Правит список на месте.
    """
    for i in range(len(ставки) - 2, -1, -1):
        после = следы[i][0]
        if (
            not ставки[i].resolutions
            and ставки[i + 1].resolutions
            and re.search(r"(?:^|\s)(?:or|/)\s*$", после)
            and not _разрешения(после)
        ):
            ставки[i] = Rate(**{**ставки[i].__dict__, "resolutions": ставки[i + 1].resolutions})


#: «in `pro` mode», «Creative mode», «In precise mode»: РЕЖИМ, которым вендор
#: подписывает часть таблицы. Становится тарифом ставки.
_РЕЖИМ_ВЕНДОРА = re.compile(r"(?:^|\bin\s+)`?([a-z][a-z0-9-]*)`?\s+mode\b", re.I)
#: Режим, который ДОРОЖЕ обычного («10 times of the normal price», «costs
#: more», «doubles»): его ставка — условие, а не цена по умолчанию.
_РЕЖИМ_ДОРОЖЕ = re.compile(r"\b(?:\d+(?:\.\d+)?\s*(?:times|x)\b|more\b|doubles?\b|double\b)", re.I)


def _режим_куска(низ: str, ставки: list[Rate]) -> list[Rate]:
    """Ставки куска, подписанного режимом вендора, получают этот режим ТАРИФОМ.

    ЗАЧЕМ (2026-10-15, независимый валидатор). `bytedance-upscaler`: «Processing
    in `pro` mode makes the price 10 times of the normal price ($0.072/s, …,
    $0.288/s …)». Без этой ветки pro-ставки ложились в безымянный тариф рядом с
    обычными, и 1080p оценивался по pro-4K — $0.288/s вместо $0.0072/s, в сорок
    раз дороже правды. Режим, который назван ДОРОЖЕ обычного, — условие
    (`conditional`): тарифом по умолчанию он не становится никогда, потому что
    у планировщика по умолчанию — безымянный тариф.
    """
    м = _РЕЖИМ_ВЕНДОРА.search(низ.lstrip(" ,—-("))
    if not м or not ставки:
        return ставки
    слово = м.group(1).lower()
    if слово in MODE_WORDS:
        return ставки
    дороже = bool(_РЕЖИМ_ДОРОЖЕ.search(низ))
    return [
        Rate(
            **{
                **r.__dict__,
                "tier": r.tier or слово,
                "conditional": r.conditional or дороже,
            }
        )
        for r in ставки
    ]


def _по_порядку(ставки: list[Rate], кусок: str, прежние: list[Rate]) -> list[Rate]:
    """«$a, $b, $c for 1080p, 2K, 4K respectively» — разрешения ПО ПОРЯДКУ.

    ЗАЧЕМ (2026-10-15, независимый валидатор). Список разрешений после
    последней суммы прилипал к ней одной («$0.288/s for 1080p» — а это 4K), и
    1080p получал цену 4K. Здесь i-я сумма получает i-е разрешение. Если списка
    нет («Creative mode costs more at each tier: $0.20, $0.35, and $0.79 per
    second respectively»), берутся разрешения стольких же ПРЕДЫДУЩИХ ставок
    строки, по порядку, — «each tier» отсылает к ним. Не сошлось число — не
    сопоставляется ничего (выдумывать пары хуже, чем оставить без разрешения).
    «За что» у сумм списка общее: его называет последняя («per second»).
    """
    if not ставки or not re.search(r"\brespectively\b", кусок, re.I):
        return ставки
    последняя_сумма = list(_AMOUNT.finditer(кусок))
    хвост = кусок[последняя_сумма[-1].end() :] if последняя_сумма else ""
    хвост = re.split(r"\brespectively\b", хвост, maxsplit=1, flags=re.I)[0]
    разрешения: list[tuple[int, ...]] = [(р,) for р in _разрешения(хвост)]
    if not разрешения:
        с_кадром = [r.resolutions for r in прежние if r.resolutions]
        разрешения = с_кадром[-len(ставки) :] if len(с_кадром) >= len(ставки) else []
    if len(разрешения) != len(ставки):
        return ставки
    за = next((r.per for r in reversed(ставки) if r.per), "")
    return [
        Rate(**{**r.__dict__, "resolutions": разрешения[i], "per": r.per or за})
        for i, r in enumerate(ставки)
    ]


@dataclass(frozen=True)
class Need:
    """Что шаг должен выдать: от этого зависит, какая ставка из таблицы — его."""

    seconds: float | None = None
    #: Короткая сторона заказанного кадра (1080 для 1080x1920). None — не назван.
    resolution: int | None = None
    #: Нужен ли звук из самой модели. None — шагу всё равно.
    audio: bool | None = None
    #: Знаков текста (для синтеза речи). None — не знаем.
    chars: float | None = None
    images: float = 1.0
    megapixels: float = 1.0
    #: Предел одного прогона модели: ролик длиннее режется на клипы.
    max_run_seconds: float | None = None
    #: Режим шага (`t2v`, `i2v`, `v2v`), чтобы чужой кусок таблицы не стал ценой.
    mode: str = ""
    #: Частота кадров ролика (круг 4): нужна цене «за мегапиксель» у видео —
    #: мегапиксели кадра × кадров (fps × секунды). None — не названа.
    fps: float | None = None
    #: На сколько ШОТОВ режется `seconds` (2026-10-15): три шота по 5 с — три
    #: прогона, даже если прогон модели покрывает 10 с. 1 — ролик одним куском.
    shots: int = 1
    #: ОТКУДА `max_run_seconds`, если не из записи самой модели (пятый круг):
    #: длина прогона семьи или осторожное допущение. Печатается в расчёте цены
    #: за прогон — допущение не подставляется молча. Пусто — запись своя.
    run_basis: str = ""
    #: Секунд вычисления на секунду ролика — ЗАПИСАННОЕ (`COMPUTE_RATIO_ATTRIBUTE`)
    #: для этой модели. None — не записано, и ставка «за секунду вычисления»
    #: цены шага не даёт (шестой круг).
    compute_ratio: float | None = None
    #: Двенадцатый круг: откуда отношение, если это ОЦЕНКА, а не запись модели —
    #: тогда цена шага — нижняя граница с этим основанием. Пусто — записано.
    compute_ratio_basis: str = ""
    #: Откуда частота кадров, если не из брифа: допущение печатается в расчёте.
    fps_basis: str = ""
    #: Сколько клонов голоса делает шаг (ставка «за клон»): один голос — один
    #: клон, сколько бы языков он ни читал.
    clones: int = 1
    #: Сколько ОТДЕЛЬНЫХ заказов делает шаг — по одному на язык (восьмой круг,
    #: w24): счёт «начатая минута целиком» округляется в КАЖДОМ, и 90 с на два
    #: языка — 2 × ⌈1.5⌉ = 4 минуты, а не ⌈3⌉ = 3.
    jobs: int = 1


@dataclass(frozen=True)
class Option:
    """Сколько стоит шаг на одном тарифе: число, тариф, разрешение и расчёт словами.

    `lower_bound` — почему это НИЖНЯЯ граница, а не цена (пусто — цена полная):
    за прогон, когда длина прогона не записана, ролик дороже одного прогона.
    `ambiguous` — какие ставки не удалось привязать к брифу; тогда `usd` —
    наибольшая из них (осторожная), а `usd_min` — наименьшая: «не влезает»
    доказывает только наименьшая, «влезает» — только наибольшая (круг 4).
    """

    usd: float
    tier: str
    resolution: int | None
    formula: str
    conditional: bool = False
    lower_bound: str = ""
    ambiguous: str = ""
    usd_min: float | None = None
    #: Звук ставки (True / False / не сказано) — часть ступени тарифа: ставки с
    #: разным звуком или разрешением — РАЗНЫЕ ступени, а не спор источников.
    audio: bool | None = None
    #: Насколько ставка ПРО ЗАКАЗ (меньше — точнее): кадр, звук, частота,
    #: безусловность, полнота. Две строки одного маршрута сравниваются сначала
    #: этим, и только равные по привязке спорят (шестой круг).
    fit: tuple = ()
    #: Ставка за единицу и единица, по которым посчитано (`usd` — уже деньги
    #: шага). Две строки с ОДНОЙ ставкой — не спор, даже если одна знает
    #: округление вендора, а другая нет (шестой круг).
    rate: float | None = None
    per: str = ""

    @property
    def least(self) -> float:
        """Наименьшая сумма, которую эта ставка может стоить."""
        return self.usd if self.usd_min is None else min(self.usd, self.usd_min)


#: Сколько знаков в секунде речи. КОНСТАНТА-РЕШЕНИЕ, ВЫБРАНО 15: дикторская
#: речь 140–160 слов в минуту по ~6 знаков с пробелом. Это ОЦЕНКА объёма
#: текста, а не цена: она печатается в расчёте, чтобы её можно было оспорить.
CHARS_PER_SECOND = 15.0

#: Знаков в секунде речи для письма БЕЗ пробелов, где знак — слог или морфема
#: (интеграция седьмого круга: японский и китайский бриф считались латинскими
#: 15 зн/с, то есть текста выходило в ~3 раза больше, чем вендор возьмёт).
#: ОЦЕНКИ, а не измерения этого проекта. Опора: Pellegrino, Coupé, Marsico,
#: «A cross-language perspective on speech information rate», Language 87(3),
#: 2011 — средняя скорость чтения: мандаринский 5.18 слога/с (иероглиф = слог,
#: отсюда 5), японский 7.84 моры/с (кандзи покрывает в среднем больше моры,
#: отсюда 6 знаков смешанного письма). Корейский (слог хангыля = знак) в той
#: работе не мерился: 6 — оценка по соседям, не цитата.
SPEECH_CHARS_PER_SECOND: dict[str, float] = {
    "zh": 5.0,
    "yue": 5.0,
    "cmn": 5.0,
    "ja": 6.0,
    "ko": 6.0,
    # Плановщик держит языки ИМЕНАМИ базы (`brief_spec.CODE_TO_LANGUAGE`).
    "chinese": 5.0,
    "japanese": 6.0,
    "korean": 6.0,
}


def speech_chars_per_second(language: str) -> float:
    """Знаков в секунде речи: тег BCP-47 (`ja`, `zh-Hans`, `ko-KR`) или имя базы (`japanese`); иначе `CHARS_PER_SECOND`."""
    звенья = re.split(r"[-_]", str(language or "").strip().lower())
    for звено in звенья[1:]:
        if звено in ("hans", "hant", "hani"):
            return SPEECH_CHARS_PER_SECOND["zh"]
        if звено in ("jpan", "hira", "kana"):
            return SPEECH_CHARS_PER_SECOND["ja"]
        if звено in ("kore", "hang"):
            return SPEECH_CHARS_PER_SECOND["ko"]
    return SPEECH_CHARS_PER_SECOND.get(звенья[0], CHARS_PER_SECOND) if звенья else CHARS_PER_SECOND


def speech_chars(
    seconds: float, languages: Sequence[str] = (), per_language: bool = False
) -> float:
    """Сколько знаков текста в `seconds` речи.

    `per_language` — шаг делается заново на КАЖДЫЙ язык, и `seconds` уже
    умножены на их число: знаки складываются по языкам, каждый по своей
    скорости. Иначе — скорость единственного языка (или общая для всех
    названных); языки разной скорости без разбивки — латинская.
    """
    if per_language and languages:
        доля = seconds / len(languages)
        return sum(доля * speech_chars_per_second(я) for я in languages)
    скорости = {speech_chars_per_second(я) for я in languages}
    return seconds * (скорости.pop() if len(скорости) == 1 else CHARS_PER_SECOND)


#: Причина «нижней границы» у цены за прогон без записанной длины прогона.
LOWER_BOUND_RUN = "сколько секунд даёт прогон — не записано: посчитан один прогон"

#: Атрибут, где записано, сколько секунд вычисления уходит на секунду ролика.
COMPUTE_RATIO_ATTRIBUTE = "compute_seconds_per_output_second"

#: Двенадцатый круг: секунд вычисления на секунду ролика, когда модель отношения
#: НЕ записала. КОНСТАНТА-РЕШЕНИЕ, ОЦЕНКА, ВЫБРАНО 1.0: RIFE, самый быстрый из
#: записанных интерполяторов, по своему README даёт 30+ кадров/с 2x на 720p на
#: 2080Ti — около секунды вычисления на секунду ролика; FILM и AMT медленнее, а
#: генераторы — на порядки. Цена по оценке — НИЖНЯЯ граница («≥»), а не цена:
#: прежде ставка «за секунду вычисления» без записи не давала цены вовсе.
COMPUTE_RATIO_ESTIMATE = 1.0
#: Основание нижней границы по оценке отношения.
LOWER_BOUND_COMPUTE = (
    "секунд вычисления на секунду ролика модель не записала: принята оценка "
    f"{COMPUTE_RATIO_ESTIMATE:g} с/с (самый быстрый записанный интерполятор) — нижняя граница"
)
#: Двенадцатый круг: ставка записана только за МЕНЬШУЮ частоту, чем заказана
#: (интерполяция 30→60, заказано 120): больше новых кадров — дороже. Цена по
#: ней — нижняя граница, а не «цены нет».
LOWER_BOUND_FPS = "ставка записана за меньшую частоту кадров, чем заказана: больше кадров — дороже, нижняя граница"

#: Частота кадров, которая ДОПУСКАЕТСЯ для цены видео «за мегапиксель», когда
#: бриф её не назвал. КОНСТАНТА-РЕШЕНИЕ, ВЫБРАНО 30: генераторы отдают 24–30
#: fps, и 30 — верхний край, то есть смета не занижена. Печатается в расчёте.
ASSUMED_FPS = 30.0


def _подходит_звук(r: Rate, нужно: bool | None) -> int:
    """0 — подходит, 1 — о звуке не сказано, 2 — не тот звук.

    «Не сказано» при ИЗВЕСТНОЙ нужде шага — 1, а не 0 (шестой круг): прежде
    голая $0.14 pricing API у `kling-3.0-standard-t2v` была равна по привязке
    странице «$0.084 (audio off)», и шаг без звука платил $0.14.
    """
    if нужно is None:
        return 0
    if r.audio is None:
        return 1
    return 0 if r.audio == нужно else 2


def _подходит_fps(r: Rate, нужно: float | None) -> int | None:
    """0 — подходит, 1 — не та, но не меньше; None — ставка за меньшую частоту.

    Ставка без частоты — обычная (её пишут за 30 fps); ставка за НЕзаказанную
    частоту выше обычной — штраф 1 (это доплата, а не цена по умолчанию).
    """
    if r.fps is None:
        return 0 if нужно is None or нужно <= 30 else 1
    if нужно is None:
        return 0 if r.fps <= 30 else 1
    if r.fps == нужно:
        return 0
    return 1 if r.fps > нужно else None


#: Штраф ставки БЕЗ разрешения, когда заказанный кадр выше всех ступеней
#: тарифа (восьмой круг, x17/w15). КОНСТАНТА-РЕШЕНИЕ: старше «выше всех
#: ступеней» (3) — голая `$0.0072 per second` у `bytedance-upscaler` (это
#: ставка 1080p) обгоняла верхнюю ступень 4K, и 8K считалось по цене 1080p.
UNTIERED_ABOVE_TOP = 4


def _подходит_кадр(
    r: Rate, нужно: int | None, верх: int | None = None
) -> tuple[int, int] | None:
    """(штраф, выбранное разрешение) или None, если ставка кадр не даёт.

    `верх` — наибольшая ступень разрешения среди ВСЕХ ставок шага. Заказанный
    кадр выше неё — ставка без разрешения не обгоняет верхнюю ступень
    (`UNTIERED_ABOVE_TOP`): о ней не известно, что она дороже 1080p.
    """
    if not r.resolutions:
        if нужно is not None and верх is not None and нужно > верх:
            return (UNTIERED_ABOVE_TOP, 0)
        return (1, 0) if нужно is not None else (0, 0)
    if нужно is None:
        return (0, min(r.resolutions))
    if нужно in r.resolutions:
        return (0, нужно)
    выше = [р for р in r.resolutions if р > нужно]
    if выше:
        return (2, min(выше))
    # Заказанного кадра в таблице нет и выше нет: считается по наибольшему, что
    # модель отдаёт, — до заказанного кадр поднимает апскейл (шаг плана), а
    # «цена не считается» здесь была бы неправдой о том, что модель стоит.
    return (3, max(r.resolutions))


def _блоками(количество: float, r: Rate) -> tuple[float, str]:
    """Сумма за `количество` единиц `r.per` блоками `r.block`: (деньги, расчёт)."""
    assert r.block  # зовётся только для ставки с блоком
    блоков = math.ceil(количество / r.block - 1e-9)
    за_блок = round(r.amount * r.block, 6)
    return (
        блоков * за_блок,
        f"⌈{количество:g}/{r.block:g}⌉ = {блоков} блок(ов) × {за_блок:g} usd",
    )


def _основание(r: Rate, need: Need) -> str:
    """Откуда длина прогона, если не из ставки и не из своей записи модели: «; <основание>»."""
    return f"; {need.run_basis}" if need.run_basis and not r.run_seconds else ""


def _деньги(r: Rate, need: Need) -> tuple[float, str, str] | None:
    """Стоимость шага по одной ставке: (деньги, расчёт словами, почему нижняя граница).

    None — не на что умножать. Третье поле пусто, когда цена полная.
    """
    сек = need.seconds
    if r.per == "second":
        if сек is None:
            return None
        if r.block and need.shots > 1:
            # Шоты — отдельные прогоны, и блок округляется В КАЖДОМ шоте.
            сумма, расчёт = _блоками(сек / need.shots, r)
            return (
                сумма * need.shots,
                f"{need.shots} шот(ов) × ({сек / need.shots:g} с: {расчёт}) (блок = {r.block:g} с)",
                "",
            )
        if r.block:
            сумма, расчёт = _блоками(сек, r)
            return сумма, f"{сек:g} с: {расчёт} (блок = {r.block:g} с)", ""
        return r.amount * сек, f"{сек:g} с × {r.amount:g} usd/с", ""
    if r.per == "minute":
        if сек is None:
            return None
        if r.block and need.jobs > 1:
            сумма, расчёт = _блоками(сек / need.jobs / 60.0, r)
            return (
                сумма * need.jobs,
                f"{need.jobs} заказ(ов) по языкам × ({сек / need.jobs:g} с = "
                f"{сек / need.jobs / 60.0:g} мин: {расчёт}) (блок = {r.block:g} мин)",
                "",
            )
        if r.block:
            сумма, расчёт = _блоками(сек / 60.0, r)
            return сумма, f"{сек:g} с = {сек / 60.0:g} мин: {расчёт} (блок = {r.block:g} мин)", ""
        return r.amount * сек / 60.0, f"{сек:g} с × {r.amount:g} usd/мин ÷ 60", ""
    if r.per == "compute_second":
        # Секунда GPU — не секунда ролика: без записанного отношения цены нет.
        if сек is None:
            return None
        отношение = need.compute_ratio
        основание = need.compute_ratio_basis
        if отношение is None:
            отношение, основание = COMPUTE_RATIO_ESTIMATE, LOWER_BOUND_COMPUTE
        вычисление = сек * отношение
        return (
            r.amount * вычисление,
            f"{сек:g} с ролика × {отношение:g} с вычисления/с"
            + (" (ОЦЕНКА)" if основание else "")
            + f" = {вычисление:g} с GPU × {r.amount:g} usd",
            основание,
        )
    if r.per in ("run", "generation"):
        if сек and need.shots > 1:
            # ШОТЫ — ОТДЕЛЬНЫЕ ПРОГОНЫ: прогон не склеивает два шота, поэтому
            # число прогонов — шоты × прогонов на шот, а не ceil(всего / прогон).
            на_шот = сек / need.shots
            покрывает = r.run_seconds or need.max_run_seconds
            if r.run_seconds and r.over_per_second is not None:
                лишние = max(0.0, на_шот - r.run_seconds)
                за_шот = r.amount + лишние * r.over_per_second
                return (
                    за_шот * need.shots,
                    f"{need.shots} шот(ов) × ({r.amount:g} usd за первые {r.run_seconds:g} с"
                    f" + {лишние:g} с × {r.over_per_second:g} usd/с)",
                    "",
                )
            прогонов_на_шот = math.ceil(на_шот / покрывает) if покрывает else 1
            прогонов = need.shots * прогонов_на_шот
            return (
                r.amount * прогонов,
                f"{need.shots} шот(ов) по {на_шот:g} с × {прогонов_на_шот} прогон(ов) × {r.amount:g} usd"
                + (f" (прогон = {покрывает:g} с{_основание(r, need)})" if покрывает else ""),
                # Длина прогона не записана — шот мог занять больше прогона:
                # это НИЖНЯЯ граница, как и у ролика одним куском.
                "" if покрывает else LOWER_BOUND_RUN,
            )
        if r.run_seconds and r.over_per_second is not None:
            лишние = max(0.0, (сек or 0.0) - r.run_seconds)
            return (
                r.amount + лишние * r.over_per_second,
                f"{r.amount:g} usd за первые {r.run_seconds:g} с + {лишние:g} с × {r.over_per_second:g} usd/с",
                "",
            )
        if сек is None and need.images > 1:
            # Картиночный шаг с ценой «за запрос»: прогон — один кадр, и шесть
            # заказанных кадров — шесть прогонов (2026-10-15, аудит третьего круга).
            прогонов = math.ceil(need.images)
            return (
                r.amount * прогонов,
                f"{прогонов} прогон(ов) × {r.amount:g} usd (прогон = 1 кадр)",
                "",
            )
        покрывает = r.run_seconds or need.max_run_seconds
        if сек and not покрывает:
            # ДЛИНА ПРОГОНА НЕ ЗАПИСАНА — ЭТО НИЖНЯЯ ГРАНИЦА (круг 4). Раньше
            # $0.49 «за генерацию» стояли ценой и 120-секундного, и
            # 300-секундного ролика, а бюджет объявлялся «укладывается».
            return (
                r.amount,
                f"{r.amount:g} usd за прогон (сколько секунд даёт прогон — не записано)",
                LOWER_BOUND_RUN,
            )
        прогонов = math.ceil(сек / покрывает) if сек and покрывает else 1
        return (
            r.amount * прогонов,
            f"{прогонов} прогон(ов) × {r.amount:g} usd"
            + (f" (прогон = {покрывает:g} с{_основание(r, need)})" if покрывает else ""),
            "",
        )
    if r.per == "megapixel" and need.images <= 0:
        # ВИДЕО «ЗА МЕГАПИКСЕЛЬ» (круг 4): мегапиксели кадра × кадров, а кадров
        # — fps × секунды. Чего-то из трёх нет — не на что умножать, и шаг
        # остаётся без цены, а не «0.001 usd за megapixel» рядом с «укладывается».
        if not (сек and need.resolution):
            return None
        частота = need.fps or ASSUMED_FPS
        кадров = math.ceil(частота * сек)
        мп = need.megapixels * кадров
        if r.block:
            сумма, расчёт = _блоками(мп, r)
        else:
            сумма, расчёт = r.amount * math.ceil(мп), f"⌈{мп:g}⌉ Мп × {r.amount:g} usd"
        return (
            сумма,
            f"{need.megapixels:g} Мп/кадр × {кадров} кадров ({частота:g} fps"
            + ("" if need.fps else f" — {need.fps_basis or 'частота не названа, допущено'}")
            + f" × {сек:g} с): {расчёт}",
            "",
        )
    if r.per == "image" and need.images <= 0:
        return None
    if r.per == "image":
        return r.amount * need.images, f"{need.images:g} кадр(ов) × {r.amount:g} usd", ""
    if r.per == "megapixel":
        if r.block:
            сумма, расчёт = _блоками(need.megapixels, r)
            return сумма * need.images, f"{need.images:g} кадр(ов) × ({расчёт})", ""
        мп = math.ceil(need.megapixels)
        return (
            r.amount * мп * need.images,
            f"{need.images:g} кадр(ов) × {мп} Мп × {r.amount:g} usd",
            "",
        )
    if r.per == "clone":
        return r.amount * need.clones, f"{need.clones} клон(ов) × {r.amount:g} usd", ""
    if r.per in ("1000_chars", "character"):
        if need.chars is None:
            return None
        за_тысячу = r.amount * (1000.0 if r.per == "character" else 1.0)
        return (
            за_тысячу * need.chars / 1000.0,
            f"≈{need.chars:g} знаков × {за_тысячу:g} usd за 1000_chars"
            + (f" ({r.amount:g} usd за знак)" if r.per == "character" else ""),
            "",
        )
    return None


def estimate(ставки: list[Rate], need: Need, top: int | None = None) -> list[Option]:
    """Сколько стоит шаг на КАЖДОМ тарифе, где ставка подходит брифу. Дешёвые первыми не ставятся:
    порядок — порядок вендора (флагман первым), чтобы тариф по умолчанию был его, а не наш.

    Только доллары: кредиты в доллары не переводятся (курс — решение вендора).

    ВЫБОР ВНУТРИ ТАРИФА (переписано 2026-10-15, круг 4). Ставки тарифа
    сравниваются по тому, насколько они ПРО ЗАКАЗ: разрешение (точное, ближайшее
    выше, не названо), звук, частота кадров, безусловность, полнота цены. Раньше
    при равенстве брался МИНИМУМ суммы — и три непривязанные ставки «$0.05 480p,
    $0.10 720p, $0.20 1080p» отдавали шагу 1080p цену 480p. Теперь равные по
    привязке, но разные по сумме ставки — НЕОДНОЗНАЧНОСТЬ: берётся наибольшая
    (осторожно), наименьшая кладётся в `usd_min`, и это сказано в расчёте.
    Разрешение в брифе НЕ названо — разные разрешения не неоднозначность, а
    выбор заказчика: берётся наименьшее разрешение, как и прежде, с подписью.
    """
    # РАЗОВАЯ ПЛАТА «ЗА КЛОН» СКЛАДЫВАЕТСЯ с ценой шага (седьмой круг): клон
    # голоса и начитка им — одна работа, и «$1.5 за клон + $0.3 за 1000 знаков»
    # — сумма двух ставок, а не две спорящие ставки.
    клоны = [
        r for r in ставки if r.per == "clone" and r.unit == "usd" and r.amount > 0 and not r.upfront
    ]
    if клоны:
        прочие = [r for r in ставки if r not in клоны]
        клон = max(клоны, key=lambda r: r.amount)
        плата, расчёт_клона, _ = _деньги(клон, need) or (0.0, "", "")
        варианты = estimate(прочие, need)
        if not варианты:
            return [
                Option(
                    round(плата, 4),
                    клон.tier,
                    None,
                    f"{расчёт_клона} = {плата:.2f} usd",
                    клон.conditional,
                    lower_bound=(
                        "посчитана только плата за клон: прочие ставки шага к брифу не привязались"
                        if any(r.unit == "usd" and r.amount > 0 for r in прочие)
                        else ""
                    ),
                    rate=клон.amount,
                    per="clone",
                )
            ]
        return [
            replace(
                в,
                usd=round(в.usd + плата, 4),
                formula=f"{расчёт_клона} + ({в.formula}) = {в.usd + плата:.2f} usd",
                usd_min=round(в.usd_min + плата, 4) if в.usd_min is not None else None,
            )
            for в in варианты
        ]
    по_тарифу: dict[str, list[tuple[tuple, Rate, int, tuple[float, str, str]]]] = {}
    # `top` — верхняя ступень по ВСЕМ строкам цены модели: ставка без
    # разрешения часто стоит отдельной строкой (`price_unit_second_usd`).
    верх = max(
        (р for r in ставки if r.unit == "usd" and r.amount > 0 for р in r.resolutions),
        default=top,
    )
    if top is not None and верх is not None:
        верх = max(верх, top)
    реже: list[Rate] = []
    for r in ставки:
        if r.unit != "usd" or r.upfront or r.amount <= 0:
            # Ноль — не цена: бесплатным не считается ничего (запись «$0» —
            # артефакт сводки, а не тариф).
            continue
        if r.mode and need.mode and need.mode not in r.mode.split("/"):
            continue
        звук = _подходит_звук(r, need.audio)
        if звук == 2:
            continue
        кадр = _подходит_кадр(r, need.resolution, верх)
        if кадр is None:
            continue
        частота = _подходит_fps(r, need.fps)
        if частота is None:
            реже.append(r)
            continue
        деньги = _деньги(r, need)
        if деньги is None:
            continue
        разница = abs(кадр[1] - need.resolution) if need.resolution and кадр[1] else кадр[1]
        ключ = (кадр[0], разница, звук, частота, r.conditional, bool(деньги[2]))
        по_тарифу.setdefault(r.tier, []).append((ключ, r, кадр[1], деньги))
    if not по_тарифу:
        # ДВЕНАДЦАТЫЙ КРУГ: годной ставки нет, а ставка за МЕНЬШУЮ частоту есть —
        # она нижняя граница (`LOWER_BOUND_FPS`), а не «цены нет».
        for r in реже:
            кадр = _подходит_кадр(r, need.resolution, верх)
            деньги = _деньги(r, need)
            if кадр is None or деньги is None:
                continue
            деньги = (деньги[0], деньги[1], деньги[2] or LOWER_BOUND_FPS)
            разница = abs(кадр[1] - need.resolution) if need.resolution and кадр[1] else кадр[1]
            ключ = (кадр[0], разница, _подходит_звук(r, need.audio), 2, r.conditional, True)
            по_тарифу.setdefault(r.tier, []).append((ключ, r, кадр[1], деньги))
    варианты = []
    for тариф, пары in по_тарифу.items():
        лучший = min(п[0] for п in пары)
        равные = [п for п in пары if п[0] == лучший]
        суммы = sorted({round(п[3][0], 6) for п in равные})
        ключ, r, разрешение, (сумма, расчёт, нижняя) = max(равные, key=lambda п: п[3][0])
        неоднозначно = ""
        if len(суммы) > 1:
            неоднозначно = (
                f"ставки не различить по брифу ({', '.join(f'{с:g}' for с in суммы)} usd), "
                "взята наибольшая"
            )
        подпись = " ".join(
            ч
            for ч in (
                тариф.capitalize() if тариф else "",
                f"{разрешение}p" if разрешение else "",
                (
                    f"ниже заказанного {need.resolution}p — нужен апскейл; "
                    f"{разрешение}p — максимум тарифов эндпоинта: {need.resolution}p — другим "
                    "эндпоинтом или вторым проходом"
                    if ключ[0] == 3
                    else ""
                ),
                "со звуком" if r.audio else "без звука" if r.audio is False else "",
                f"{r.fps:g} fps" if r.fps else "",
            )
            if ч
        )
        варианты.append(
            Option(
                round(сумма, 4),
                тариф,
                разрешение or None,
                (f"[{подпись}] " if подпись else "")
                + f"{расчёт} = {сумма:.2f} usd"
                + (f"; НЕОДНОЗНАЧНО: {неоднозначно}" if неоднозначно else ""),
                r.conditional,
                lower_bound=нижняя,
                ambiguous=неоднозначно,
                usd_min=round(суммы[0], 4) if неоднозначно else None,
                audio=r.audio,
                fit=ключ,
                rate=r.amount,
                per=r.per,
            )
        )
    return варианты
