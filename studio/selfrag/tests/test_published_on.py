"""Дата статьи против дня, когда её прочитали мы.

ЗАЧЕМ. `stated_on` на 2560 строках из 4400 — ДЕНЬ НАШЕГО ЧТЕНИЯ. Для живой
страницы вендора это правда: страница говорила это в тот день. Для СТАТЬИ — нет:
препринт `2311.17982` вышел в ноябре 2023, а в базе стоит 2026-08-27.

ИЗМЕРЕНО 2026-09-05: из 223 строк с идентификатором статьи у 173 записанная
дата ПОЗЖЕ месяца публикации; расхождение доходит до 2 лет 9 месяцев.
Утверждение трёхлетней давности выглядело ровно как вчерашнее.

И4: происхождение выведенного значения — РАСЧЁТ по правилу площадки, а не
измерение. Ожидаемое — литералы (Т2), сети нет (Т4), входы с обоих краёв (Т3).
"""

from __future__ import annotations

import unittest

from studio.selfrag.facts import дата_публикации


class ДатаВыводитсяИзИдентификатора(unittest.TestCase):
    def test_arxiv(self):
        self.assertEqual("2023-11", дата_публикации("https://arxiv.org/abs/2311.17982"))
        self.assertEqual("2024-03", дата_публикации("https://arxiv.org/pdf/2403.11821"))
        self.assertEqual("2026-06", дата_публикации("https://arxiv.org/html/2606.31711v1"))

    def test_зеркала_названы_поимённо(self):
        """19 живых строк лежат не на arxiv.org, и без зеркал половина статей
        осталась бы без даты источника."""
        self.assertEqual(
            "2024-12",
            дата_публикации(
                "https://huggingface.co/buckets/huggingchat/papers-content/resolve/2412/2412.09262.md"
            ),
        )
        self.assertEqual("2025-02", дата_публикации("https://huggingface.co/papers/2502.01234"))

    def test_чужое_число_датой_не_становится(self):
        """Негативный контроль (И5). Искать «четыре цифры, точка, пять цифр» где
        угодно в адресе нельзя: под правило попадёт версия библиотеки и номер
        сборки, и дата статьи будет выведена из чужого числа."""
        self.assertEqual("", дата_публикации("https://fal.ai/models/v2.5.10001"))
        self.assertEqual("", дата_публикации("https://example.test/build/2412.09262"))
        self.assertEqual("", дата_публикации("https://fal.ai/api/openapi/queue"))
        self.assertEqual("", дата_публикации(""))

    def test_невозможный_месяц_не_становится_датой(self):
        """`2399.00001` — не декабрь 99-го года: месяц 99 не существует."""
        self.assertEqual("", дата_публикации("https://arxiv.org/abs/2399.00001"))

    def test_день_не_выдумывается(self):
        """Идентификатор дня не содержит, и дописать `-01` значило бы отдать
        расчёт за прочитанное. Значение короче ровно потому, что точнее мы не
        знаем."""
        self.assertEqual(7, len(дата_публикации("https://arxiv.org/abs/2311.17982")))


if __name__ == "__main__":
    unittest.main()
