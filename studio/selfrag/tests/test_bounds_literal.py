"""Пороги проверяются ЛИТЕРАЛОМ, а не значением из проверяемого модуля.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ (Ц2): соседние наборы писал другой автор.

ЧТО ЭТО ЗАКРЫВАЕТ. Мутационный прогон 2026-09-04 дал четыре молчуна, и все
четыре — по одной причине, названной в правиле Т2: ожидаемое в тесте не должно
импортироваться из проверяемого модуля.

    STALE_AFTER_DAYS = 90 -> 36500   промолчал
    STALE_AFTER_DAYS = 90 -> 1       промолчал
    MIN_PHRASE_WORDS = 3 -> 1        промолчал
    MAX_PHRASE_WORDS = 6 -> 60       промолчал

Первые два — потому что соседний тест СЧИТАЕТ дату протухания от самой
константы (`GATHERED_ON + STALE_AFTER_DAYS + 1`): подвинь константу — подвинется
и ожидание, и тест останется зелёным при любом её значении. Вторые два — потому
что границы фразы не проверял никто.

Здесь даты и длины написаны руками. Если порог изменится ПО РЕШЕНИЮ, эти тесты
покраснеют — и это ровно то, чего от них ждут: решение должно быть видно.
"""

from __future__ import annotations

import unittest
from datetime import date

from studio.selfrag.evidence import _clauses
from studio.selfrag.registry import GATHERED_ON, availability


class ГраницыФразы(unittest.TestCase):
    """Фраза — от трёх слов до шести. Числа литералами (Т2)."""

    def test_два_слова_фразой_не_считаются(self) -> None:
        self.assertEqual([], _clauses("soft light"))

    def test_три_слова_считаются(self) -> None:
        self.assertEqual(["soft window light"], _clauses("soft window light"))

    def test_шесть_слов_считаются(self) -> None:
        фраза = "soft window light on a face"
        self.assertEqual([фраза], _clauses(фраза))

    def test_семь_слов_фразой_не_считаются(self) -> None:
        """Верхняя граница: без неё «фразой» станет целое предложение, и
        подсказка из корпуса превратится в чужой промпт целиком."""
        self.assertEqual([], _clauses("soft window light on a young face"))


class ПротуханиеКарточки(unittest.TestCase):
    """Карточка старше 90 дней помечается протухшей. Даты — литералами.

    Соседний тест берёт дату у самой константы; такой тест зелен при любом её
    значении. Здесь обе даты написаны руками относительно `GATHERED_ON`
    (2026-08-26), и число 90 не импортировано ниоткуда.
    """

    СВЕЖАЯ = date(2026, 11, 20)  # 86 дней после сбора — до порога
    ПРОТУХШАЯ = date(2026, 11, 30)  # 96 дней после сбора — за порогом

    def test_дата_сбора_не_сдвинулась(self) -> None:
        """И5: если карточки пересобрали, обе даты ниже перестанут значить то,
        что задумано, и тест обязан сказать об этом первым."""
        self.assertEqual(date(2026, 8, 26), GATHERED_ON)

    def test_за_восемьдесят_шесть_дней_карточка_ещё_свежая(self) -> None:
        # Предупреждения печатаются одной строкой `note`, а не списком; читаем
        # оттуда, где они на самом деле лежат (Е2: имя выводится из того, что
        # исполнилось, а не из того, что ожидалось).
        self.assertNotIn("days old", availability("veo-3.1", today=self.СВЕЖАЯ)["note"])

    def test_за_девяносто_шесть_дней_карточка_протухла(self) -> None:
        нота = availability("veo-3.1", today=self.ПРОТУХШАЯ)["note"]
        self.assertIn("days old", нота)
        self.assertIn("96 days old", нота, "возраст обязан называться числом")


if __name__ == "__main__":
    unittest.main()
