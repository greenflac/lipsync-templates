from __future__ import annotations

import re

from lipsync.fork_identity import FAIL, PASS
from studio.mcp.contract import ЧУЖИЕ_УКАЗАНИЯ
from studio.style import banned_topics

__all__ = ["РУССКИЕ_ГРУППЫ", "РУССКИЕ_УКАЗАНИЯ", "просеять", "чисто"]

#: Русские слова тех же четырёх групп, что и у студии. Список КОРОТКИЙ и
#: закрытый по той же причине: широкий ловил бы слово внутри честного описания
#: света.
#:
#: ДВА СПОСОБА СРАВНЕНИЯ, И ЭТО РЕШЕНИЕ, А НЕ УДОБСТВО. Русский склоняется, и
#: «обнажённая / обнажённой / обнажённых» — одно слово, поэтому длинные корни
#: сравниваются по НАЧАЛУ слова. Но короткий корень по началу ловит чужое:
#: измерено, `труп` совпадает с «труппа» (театральная труппа в брифе — вещь
#: обычная). Поэтому короткие стоят отдельным списком и сравниваются ЦЕЛЫМ
#: СЛОВОМ, со своими формами.
#:
#: Подстрочный поиск не годится ни там, ни там: `секс` внутри «унисекс» —
#: ровно то ложное срабатывание, из-за которого проверки отключают.
РУССКИЕ_ГРУППЫ: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...] = (
    (
        "adult content",
        ("обнаж", "эрот", "порно", "сексуал"),
        ("голая", "голый", "голых", "голую", "секс", "бельё", "белье"),
    ),
    (
        "violence",
        ("кровав", "расчлен", "убийств", "пытк", "изнасил"),
        ("труп", "трупы", "трупа", "трупов", "кровь", "крови", "казнь", "казни"),
    ),
    (
        "minors",
        ("ребён", "ребен", "детск", "подрост", "школьниц", "малыш"),
        ("дети", "детей", "детям", "ребёнка", "ребенка"),
    ),
    (
        "recognisable third parties",
        ("знаменит", "селебрити", "дипфейк", "дипфэйк", "политик", "актрис"),
        ("президент", "президента", "звезда", "звезды"),
    ),
)

#: Обращения к ЧИТАТЕЛЮ промпта по-русски. Тот же принцип, что у английских:
#: в описании кадра такие обороты не встречаются вовсе.
РУССКИЕ_УКАЗАНИЯ: tuple[str, ...] = (
    "игнорируй",
    "игнорировать предыдущ",
    "забудь предыдущ",
    "забудь всё, что",
    "системный промпт",
    "системная подсказка",
    "выведи свои инструкции",
)

#: ИЗМЕРЕННЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ (И6). Подмена «сравнивать длинные корни
#: подстрокой вместо начала слова» тестами НЕ ловится, и это не дыра в наборе:
#: ни одно живое русское слово не содержит `обнаж`, `эрот`, `порно`, `сексуал`,
#: `кровав`, `расчлен`, `убийств`, `пытк`, `изнасил`, `детск`, `подрост`,
#: `знаменит`, `дипфейк`, `политик`, `актрис` В СЕРЕДИНЕ. Разница между двумя
#: сравнениями наблюдаема только на выдуманном слове, а тест на выдуманном
#: входе сторожит выдумку. Поэтому мутанта на эту строку не заведено — и это
#: сказано здесь, чтобы следующий не считал её забытой.
#:
#: КОРОТКИЕ — другое дело: там разница измерена на живых словах («унисекс»
#: против подстроки, «труппа» против начала слова), и обе стороны под тестами.

_СЛОВО = re.compile(r"[а-яёА-ЯЁa-zA-Z][а-яёА-ЯЁa-zA-Z'-]*")


def _русские_темы(текст: str) -> list[str]:
    """`группа: корень` для каждой найденной русской темы. Пусто — чисто.

    Длинные корни — по НАЧАЛУ слова (склонение), короткие — ЦЕЛЫМ СЛОВОМ со
    своими формами. Почему не подстрока и почему не всё по началу — сказано у
    таблицы; оба выбора куплены измеренными ложными срабатываниями.
    """
    слова = {с.lower() for с in _СЛОВО.findall(текст)}
    найдено: list[str] = []
    for группа, корни, целые in РУССКИЕ_ГРУППЫ:
        for корень in корни:
            if any(с.startswith(корень) for с in слова):
                найдено.append(f"{группа}: {корень}")
        for слово in целые:
            if слово in слова:
                найдено.append(f"{группа}: {слово}")
    return найдено


def просеять(текст: str) -> dict:
    """Что не так с текстом ЗАКАЗЧИКА. Два исхода, и оба про вход, а не про выход.

    `pass` здесь значит «в этих словах не найдено запрещённых тем и обращений к
    читателю» — и ровно это можно печатать заказчику. Печатать «запрещённых тем
    0», не просеяв вход, нельзя: это утверждение о том, чего никто не смотрел.
    """
    низ = str(текст or "").lower()
    темы = list(banned_topics(текст)) + _русские_темы(текст)
    указания = [о for о in ЧУЖИЕ_УКАЗАНИЯ if о in низ]
    указания += [о for о in РУССКИЕ_УКАЗАНИЯ if о in низ]
    беды = len(темы) + len(указания)
    return {
        "outcome": FAIL if беды else PASS,
        "checked": len(_СЛОВО.findall(текст or "")),
        "violations": беды,
        "unmeasured": 0,
        "banned": темы,
        "injection": указания,
        "note": (
            f"в словах заказчика найдено запрещённое: {'; '.join(темы + указания)}"
            if беды
            else "в словах заказчика запрещённых тем и обращений к читателю не найдено"
        ),
    }


def чисто(текст: str) -> bool:
    """Короткий ответ для вызывающего, которому нужен только знак."""
    return просеять(текст)["outcome"] == PASS
