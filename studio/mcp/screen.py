#: Группа, к которой применимо послабление выше. Одна, и названа вслух: у
#: «крови для детей» смысл не тот, что у «ролика для детей».
АУДИТОРИЯ_ГРУППА = "minors"


def _для_аудитории(по_порядку: list[str], место: int, текст: str = "") -> bool:
    """Стоит ли НЕПОСРЕДСТВЕННО перед словом предлог аудитории.

    И ОБОРОТА КАДРА В БРИФЕ НЕТ. НАЙДЕНО двенадцатой приёмкой 2026-09-08 как
    РЕГРЕССИЯ предыдущего коммита: «видео ДЛЯ детей В КАДРЕ», «clip for
    children on camera», «клип для детей 10 лет, снимаем их в студии» —
    послабление снимало самый охраняемый заслон продукта словом «для».
    Правило «„для“ называет зрителя» ложно ровно тогда, когда следом сказано,
    что эти же дети в кадре.
    """
    if место <= 0 or по_порядку[место - 1] not in АУДИТОРИЯ_ВПЕРЕДИ:
        return False
    низ = привести(текст)
    return not any(о in низ for о in ОБОРОТ_КАДРА)


def _русские_темы(текст: str) -> list[str]:
    """`группа: признак` для каждой найденной темы. Пусто — чисто.

    Длинные корни — по НАЧАЛУ слова (русский склоняется), короткие — ЦЕЛЫМ
    СЛОВОМ со своими формами, обороты — по подстроке. Три способа выбраны не
    для красоты: у каждого своя цена ложного срабатывания, измеренная на живых
    словах («унисекс» против подстроки, «труппа» против начала слова).
    """
    # ПОРЯДОК СЛОВ НУЖЕН, А НЕ ТОЛЬКО ИХ НАБОР: без него не видно, что перед
    # находкой стоит отказ заказчика от этой темы («без обнажённых плеч»).
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    низ = привести(текст)
    найдено: list[str] = []
    for группа, корни, целые in РУССКИЕ_ГРУППЫ:
        # Слово, названное аудиторией, вообще не считается вхождением — ровно
        # так же, как вхождение под отрицанием заказчика.
        аудитория = группа == АУДИТОРИЯ_ГРУППА

        def снято(i: int, аудитория: bool = аудитория) -> bool:
            return _отменено(по_порядку, i, текст) or (
                аудитория and _для_аудитории(по_порядку, i, текст)
            )

        for корень in корни:
            места = [i for i, с in enumerate(по_порядку) if с.startswith(корень)]
            if места and not all(снято(i) for i in места):
                найдено.append(f"{группа}: {корень}")
        for слово in целые:
            места = [i for i, с in enumerate(по_порядку) if с == слово]
            if места and not all(снято(i) for i in места):
                найдено.append(f"{группа}: {слово}")
    # ОТРИЦАНИЕ ДЕЙСТВУЕТ И НА ОБОРОТЫ. Приёмка 2026-09-07: «no face swap,
    # just my own footage» и «без 18+ контента, детская аудитория не наша»
    # отвергались — фильтр отрицаний не доходил до этого списка вовсе.
    похоже_целиком = привести_буквы(текст)
    for группа, оборот in ОПИСАТЕЛЬНЫЕ:
        for где in (низ, похоже_целиком):
            место = где.find(оборот)
            if место == -1:
                continue
            до = где[:место].split()
            if _отменено(до + [оборот], len(до), текст):
                break
            найдено.append(f"{группа}: {оборот}")
            break
    return найдено


