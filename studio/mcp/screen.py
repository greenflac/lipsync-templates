    "известн",
    "селебрити",
    "звезда",
    "звезды",
    "звёзд",
    "famous",
    "celebrity",
    "celebrities",
    # `привести()` заменяет дефис пробелом, поэтому в списке слово БЕЗ дефиса:
    # «well-known» не находилось никогда (найдено двенадцатой приёмкой).
    "well known",
