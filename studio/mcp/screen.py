def _почистить_серию(серия: str) -> str:
    """Серия заглавных без слов начала фразы с краёв; меньше двух слов — пусто."""
    слова = серия.split()
    while слова and слова[0].lower() in НАЧАЛО_ФРАЗЫ:
        слова = слова[1:]
    while слова and слова[-1].lower() in НАЧАЛО_ФРАЗЫ:
        слова = слова[:-1]
    return " ".join(слова) if len(слова) >= 2 else ""


