#: ОКОНЧАНИЯ РОДИТЕЛЬНОГО ПАДЕЖА — ТЕМ САМЫМ ГРАНИЦА ПЕРЕЧИСЛЕНИЯ.
#:
#: НАЙДЕНО СОБСТВЕННЫМ ПРОГОНОМ 2026-09-07, сразу после починки перечислений:
#: правило «запятая переходится» открыло дыру
#:
#:     «без цензуры, обнажёнка крупным планом»  -> проходило как запрет
#:
#: тогда как соседнее «без крови, обнажёнки и мата» — настоящий запрет. Обе
#: строки одной формы «без X, ТЕМА», и различает их РУССКИЙ ПАДЕЖ: под общим
#: «без» тема стоит в родительном («обнажёнКИ»), а в просьбе — в именительном
#: («обнажёнКА»). Признак наблюдаемый и ровно тот, которым язык это и метит.
#:
#: `а` и `е` СЮДА НЕ ВХОДЯТ НАРОЧНО: они омонимичны именительному, и включить
#: их значило бы вернуть дыру.
#: `ы` и `я` УБРАНЫ 2026-09-07 по седьмой приёмке: они омонимичны
#: ИМЕНИТЕЛЬНОМУ ровно так же, как `а` и `е`, которые сюда не вошли с самого
#: начала. Рассуждение было применено к двум окончаниям из пяти и на остальных
#: не проверено — приёмка показала цену: «без спешки, ТРУПЫ в кадре» и «без
#: правок, ГОЛАЯ модель» (просьбы) проходили как запреты.
РОДИТЕЛЬНЫЕ: tuple[str, ...] = ("и", "ей", "ов")


def _разделители(текст: str, сколько: int) -> list[str]:
    """Знак препинания сразу ПОСЛЕ каждого слова; пусто — знака нет.

    Запятая невидима для `_СЛОВО`, а решает она много: «без крови, обнажёнки»
    — одно «без» на оба слова, тогда как «без цензуры обнажёнка» — просьба.
    Считается отдельно и по тому же тексту, из которого набраны слова, так что
    места совпадают по построению.
    """
    знаки = re.findall(r"[а-яёА-ЯЁa-zA-Z][а-яёА-ЯЁa-zA-Z']*\s*([,;:]?)", str(текст or ""))
    знаки = знаки[:сколько]
    return знаки + [""] * (сколько - len(знаки))


def _отменено(слова: list[str], место: int, весь_текст: str = "") -> bool:
    """Стоит ли перед находкой ОТКАЗ заказчика от этой темы.

    ОКНО РАСТЯЖИМОЕ, НО ТОЛЬКО ЧЕРЕЗ СЛУЖЕБНЫЕ СЛОВА. Приёмка 2026-09-07:
    «без обнажённых плеч» чинилось, а «без ВСЯКОЙ обнажёнки», «не должно быть
    обнажёнки» и «без КАКОЙ-ЛИБО обнажёнки» по-прежнему отвергались — то есть
    заказчик, сказавший то же самое чуть иначе, получал отказ.

    ДВОЙНОЕ ОТРИЦАНИЕ ВОЗВРАЩАЕТ ТЕМУ. «Без обнажёнки не обойтись» — это
    просьба, и просев пропускал её целиком.
    """
    # ДВОЙНОЕ ОТРИЦАНИЕ СМОТРИТСЯ РЯДОМ С НАХОДКОЙ, А НЕ ПО ВСЕМУ БРИФУ.
    # Цена бесконечного окна измерена приёмкой 2026-09-07 и стоит выше, у
    # причине, что и назад: до слова, которое говорит о другом.
    # Хвост обрывается на СЛЕДУЮЩЕМ «без»: дальше начинается речь о другом.
    # ХВОСТ ОБРЫВАЕТСЯ НА ПЕРВОМ СОДЕРЖАТЕЛЬНОМ СЛОВЕ, а не через N любых.
    #
    # ТРИ КОНСТАНТЫ ОТСЮДА УДАЛЕНЫ 2026-09-07, А НЕ ПОКРЫТЫ ТЕСТАМИ, и это
    # решение с прогоном. Мутации показали, что они молчат, и проверка каждой
    # по отдельности сказала почему:
    #
    #   `ЗАЧИН_ДРУГОГО` (обрыв на следующем «без») — 0 входов из 7 меняются
    #     при её снятии: отсечка по содержательному слову делает то же самое,
    #     «без» ею и обрывается. Мёртвая проверка;
    #   `ОКНО_ДВОЙНОГО = 4` — САМА СОЗДАВАЛА ПРОПУСК: «без обнажёнки и вообще
    #     там любой всякой НИКАК НЕ ОБОЙТИСЬ» (просьба) проходило как запрет,
    #     потому что оборот стоял шестым словом;
    #   `ОКНО_НАЗАД = 6` — САМА СОЗДАВАЛА ЛОЖНЫЙ ОТКАЗ: «без крови, насилия,
    #     мата, брани, ругани, шума, обнажёнки» — перечисление из шести
    #     запретов — отвергалось за порнографию, потому что «без» оказывалось
    #     за краем окна.
    #
    # Граница осталась одна и она содержательная: и вперёд, и назад проход
    # идёт ровно до слова, которое говорит О ДРУГОМ. Число слов при этом ни
    # при чём — оно и было выдумкой, которую нечем измерить. ВОСПРОИЗВЕДЕНО шестой приёмкой 2026-09-07 — шесть ложных
    # отказов, все на самых обычных формулировках запрета:
    #
    #     «без обнажёнки, НИКАКОЙ ЭРОТИКИ»      -> отказ за порнографию
    #     «никакой обнажёнки и НИКАКОГО НАСИЛИЯ» -> то же
    #     «без обнажёнки, КОСТЮМ ОБЯЗАТЕЛЬНЫЙ»  -> то же
    #
    # Оборот `никак` сравнивался ПОДСТРОКОЙ и находился внутри «никакой»,
    # «никакого», «никаких» — слов, которые этот же модуль десятью строками
    # выше держит как ЗАПРЕТ. Одно слово означало и «заказчик запрещает», и
    # «заказчик требует», в зависимости от того, какой список посмотрели
    # первым. Теперь обороты сравниваются ЦЕЛЫМИ СЛОВАМИ, а хвост набирается
    # только из слов самих оборотов и прокладок: «костюм» его обрывает, и
    # «обязательный» до сравнения не доходит.
    хвост_слова: list[str] = []
    for с in слова[место + 1 :]:
        низкое = с.lower()
        if низкое not in СЛОВА_ДВОЙНОГО and низкое not in ПРОКЛАДКИ:
            break
        хвост_слова.append(низкое)
    хвост = " ".join(хвост_слова)
    # СРАВНЕНИЕ ЦЕЛЫМИ СЛОВАМИ: пробелы по краям делают `никак` неспособным
    # найтись внутри `никакой`.
    if any(f" {о} " in f" {хвост} " for о in ДВОЙНОЕ_ПОСЛЕ):
        return False
    # ОТРИЦАНИЕ БЫВАЕТ И ПОСЛЕ ТЕМЫ: «обнажёнки быть НЕ ДОЛЖНО» — это тот же
    # отказ, что «не должно быть обнажёнки», и приёмка 2026-09-07 показала, что
    # первый порядок слов отвергался.
    после = " ".join(слова[место + 1 : место + 5]).lower()
    if any(
        f" {о} " in f" {после} " for о in ("не должно", "не надо", "не нужно", "быть не должно")
    ):
        return True
    # ПЕРЕЧИСЛЕНИЯ И ОПРЕДЕЛЕНИЯ ПЕРЕХОДЯТСЯ, СОСЕДНЕЕ СУЩЕСТВИТЕЛЬНОЕ — НЕТ.
    #
    # ВОСПРОИЗВЕДЕНО шестой приёмкой 2026-09-07, шесть ложных отказов, и это
    # не регресс дня, а старая дыра тех же денег:
    #
    #     «без насилия И обнажёнки»          -> отказ за порнографию
    #     «без крови, обнажёнки и мата»      -> то же
    #     «without nudity OR violence»       -> то же
    #     «без ЛИШНЕЙ обнажёнки»             -> то же
    #     «без совсем НЕНУЖНОЙ НАМ обнажёнки» -> то же
    #
    # Закрытый список прокладок держал только служебные слова, а заказчик
    # ставит между «без» и темой ещё две вещи: соседний член перечисления и
    # определение. Обе теперь переходятся, и обе — по НАБЛЮДАЕМОМУ признаку,
    # а не по списку: член перечисления опознаётся по запятой или связке
    # ПОСЛЕ него, определение — по адъективному окончанию.
    #
    # ИЗМЕРЕННЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ (И6). Правило пропускает просьбу вида
    # «без ограничений, полная обнажёнка»: «ограничений» кончается на -ий и
    # переходится как определение. Это ПРОПУСК, и он выбран сознательно —
    # доктрина модуля (см. шапку `РУССКИЕ_ГРУППЫ`) говорит, в какую сторону
    # ошибаться: пропуск ловится движком, валидатором и человеком, ложный
    # отказ не ловится ничем. Сказано здесь, чтобы следующий не считал это
    # недосмотром.
    разделители = _разделители(весь_текст, len(слова)) if весь_текст else [""] * len(слова)
    тема = слова[место].lower() if место < len(слова) else ""
    шаг = место - 1
    while шаг >= 0:
        слово = слова[шаг].lower()
        if слово in ОТРИЦАНИЯ:
            # «НЕВОЗМОЖНО без ТЕМА» — отрицание отменено, но только если за
            # «без» идёт НАША тема (шаг == место - 1), а не соседняя.
            перед = слова[шаг - 1].lower() if шаг > 0 else ""
            if шаг == место - 1 and any(о in перед for о in ДВОЙНОЕ_ПЕРЕД):
                return False
            return True
        следующее = слова[шаг + 1].lower() if шаг + 1 < len(слова) else ""
        # ТРИ РАЗНЫХ МОСТА, И ОНИ РАЗНОЙ ШИРИНЫ. Перестроено 2026-09-07 по
        # седьмой приёмке, нашедшей 24 расхождения из 27:
        #
        #   СОЮЗ («и», «или», «либо», «а также», «or», «nor») переходится
        #   БЕЗУСЛОВНО: перечисление под одним «без» им и метится, падеж темы
        #   тут ни при чём. «Без крови и НЮ», «без крови и ОБНАЖЁНКА», «без
        #   крови и УБИЙСТВ» отвергались только потому, что тема не кончалась
        #   на нужную букву;
        #
        #   ЗАПЯТАЯ — ТОЛЬКО при теме в родительном: одна она слишком широка и
        #   пропускала просьбы «без затей, ЭРОТИКА», «без ограничений, полная
        #   ОБНАЖЁНКА»;
        #
        #   СОСЕДНЕЕ СЛОВО без знака между ним и темой — определение: по
        #   адъективному окончанию для русского («без ЛИШНЕЙ обнажёнки») и
        #   любое для латиницы («no EXPLICIT nudity»), где окончаний нет
        #   вовсе. Латиница при этом НЕ переходит запятую — иначе вернулись бы
        #   «without censorship, nudity closeup» и «no limits, nudity closeup».
        союз = следующее in СВЯЗКИ
        запятая = разделители[шаг] == "," and тема.endswith(РОДИТЕЛЬНЫЕ)
        перечисление = союз or запятая
        рядом = разделители[шаг] == ""
        определение = рядом and (тема.isascii() or any(слово.endswith(о) for о in АДЪЕКТИВНЫЕ))
        if слово not in ПРОКЛАДКИ and not перечисление and not определение:
            return False
        шаг -= 1
    return False


