#: ИЗМЕРЕННЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ (И6). Подмена «сравнивать длинные корни
#: подстрокой вместо начала слова» тестами НЕ ловится, и это не дыра в наборе:
#: ни одно живое русское слово не содержит `обнаж`, `эрот`, `порно`, `сексуал`,
#: `кровав`, `расчлен`, `убийств`, `пытк`, `изнасил`, `детск`, `подрост`,
#: `знаменит`, `дипфейк`, `политик`, `актрис` В СЕРЕДИНЕ. Разница между двумя
#: сравнениями наблюдаема только на выдуманном слове, а тест на выдуманном
#: входе сторожит выдумку. Поэтому мутанта на эту строку не заведено — и это
#: сказано здесь, чтобы следующий не считал её забытой.
#:
#: КОРОТКИЕ — другое дело: там разница измерена на живых словах («унисекс»
#: против подстроки, «труппа» против начала слова), и обе стороны под тестами.

#: ДЕФИС РАЗДЕЛЯЕТ СЛОВА, А НЕ СКЛЕИВАЕТ. «ню-съёмка» при склейке остаётся
#: одним токеном, и целое слово `ню` в нём не находится — пропуск, измеренный
#: приёмкой 2026-09-06. Апостроф внутри слова оставлен: он часть слова.
_СЛОВО = re.compile(r"[а-яёА-ЯЁa-zA-Z][а-яёА-ЯЁa-zA-Z']*")


#: КАК ТЕКСТ ПРИВОДИТСЯ ПЕРЕД ПОИСКОМ ОБОРОТОВ. Приёмка 2026-09-06 обошла
#: проверку чужих указаний ДВОЙНЫМ ПРОБЕЛОМ и дефисами: «ignore  all  previous»
#: и «ignore-all-previous-instructions» получали `pass` и ноту «instructions to
#: the reader 0» — утверждение о тексте, который их буквально содержит.
#:
#: Гомоглиф закрывается тем же: кириллическая «е» в `nudе` снимала запрет.
#: Полной защиты от подмены букв тут не бывает, и обещать её нельзя — но самые
#: частые пары приводятся, и это измеримо лучше, чем ничего.
_ПОХОЖИЕ = str.maketrans(
    {"е": "e", "о": "o", "а": "a", "с": "c", "р": "p", "х": "x", "у": "y", "к": "k", "і": "i"}
)


def привести(текст: str) -> str:
    """Текст для поиска ОБОРОТОВ: один пробел, дефисы как пробелы, нижний регистр.

    ОДНА функция на проект (Е1): раньше `contract.gate` искал обороты в сыром
    `text.lower()`, а `screen.просеять` — в приведённом, и один и тот же текст
    получал два разных вердикта. Комментарий в `contract.py` про такой случай
    говорит прямо: «Два ответа на один вопрос — это и есть дефект».
    """
    низ = str(текст or "").lower().replace("-", " ").replace("_", " ")
    return " ".join(низ.split())


def привести_буквы(текст: str) -> str:
    """То же плюс приведение похожих кириллических букв к латинским."""
    return привести(текст).translate(_ПОХОЖИЕ)


#: Слова, которыми заказчик ОТКАЗЫВАЕТСЯ от темы, а не просит её.
#:
#: ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой: бриф «ролик 15 сек,
#: женщина, БЕЗ обнажённых плеч, деловой костюм» получал
#: `fail: adult content: обнаж` — то есть отказ ровно за то, что заказчик
#: сам исключил. Это самая дорогая ошибка продукта: клиент не спорит, он
#: закрывает вкладку.
#:
#: ОКНО В ОДНО СЛОВО, И ЭТО ИЗМЕРЕННЫЙ ВЫБОР. Отрицание снимает ТОЛЬКО ту
#: находку, перед которой стоит вплотную. Окно в два слова открыло бы дыру
#: «без цензуры обнажёнка»: там «без» относится к цензуре, а не к теме.
#: Проверено обоими входами.
ОТРИЦАНИЯ: frozenset[str] = frozenset(
    {
        "без",
        "не",
        "нет",
        "никаких",
        "никакой",
        "никакого",
        "исключить",
        "избегать",
        "no",
        "without",
        "avoid",
        "exclude",
    }
)


def _отменено(слова: list[str], место: int) -> bool:
    """Стоит ли перед находкой отказ заказчика от этой темы."""
    return место > 0 and слова[место - 1].lower() in ОТРИЦАНИЯ


def _метка_отменена(метка: str, текст: str) -> bool:
    """Все ли вхождения признака из метки стоят под отрицанием заказчика."""
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if not признак:
        return False
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    места = [i for i, с in enumerate(по_порядку) if с.startswith(признак)]
    return bool(места) and all(_отменено(по_порядку, i) for i in места)


def _русские_темы(текст: str) -> list[str]:
    """`группа: признак` для каждой найденной темы. Пусто — чисто.

    Длинные корни — по НАЧАЛУ слова (русский склоняется), короткие — ЦЕЛЫМ
    СЛОВОМ со своими формами, обороты — по подстроке. Три способа выбраны не
    для красоты: у каждого своя цена ложного срабатывания, измеренная на живых
    словах («унисекс» против подстроки, «труппа» против начала слова).
    """
    # ПОРЯДОК СЛОВ НУЖЕН, А НЕ ТОЛЬКО ИХ НАБОР: без него не видно, что перед
    # находкой стоит отказ заказчика от этой темы («без обнажённых плеч»).
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    низ = привести(текст)
    найдено: list[str] = []
    for группа, корни, целые in РУССКИЕ_ГРУППЫ:
        for корень in корни:
            места = [i for i, с in enumerate(по_порядку) if с.startswith(корень)]
            if места and not all(_отменено(по_порядку, i) for i in места):
                найдено.append(f"{группа}: {корень}")
        for слово in целые:
            места = [i for i, с in enumerate(по_порядку) if с == слово]
            if места and not all(_отменено(по_порядку, i) for i in места):
                найдено.append(f"{группа}: {слово}")
    for группа, оборот in ОПИСАТЕЛЬНЫЕ:
        if оборот in низ or оборот in привести_буквы(текст):
            найдено.append(f"{группа}: {оборот}")
    return найдено


def просеять(текст: str) -> dict:
    """Что не так с текстом ЗАКАЗЧИКА. ТРИ исхода, и третий не украшение.

    `pass` — «в этих словах не найдено запрещённых тем и обращений к читателю»,
    и ровно это можно печатать заказчику. `could not measure` — текста нет,
    смотреть было не на что: непроверенный текст не является чистым, и сосед по
    пакету (`contract.gate`) отвечает так же и теми же словами.

    `checked` — число ПРОВЕРОК, как у соседа, а не число слов: одно имя с двумя
    разными величинами в одном пакете — это Е1 наоборот (приёмка 2026-09-06).
    """
    слова = _СЛОВО.findall(str(текст or ""))
    if not слова:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "banned": [],
            "injection": [],
            "words": 0,
            "note": (
                "в тексте нет ни одного слова — просеивать нечего. "
                "Непроверенный текст не является чистым"
            ),
        }
    низ = привести(текст)
    похоже = привести_буквы(текст)
    # `str(... or "")` ВЕЗДЕ, а не только там, где падало: приёмка подала
    # `None` и `123`, и модуль валился AttributeError вместо ответа (Р1: у
    # прибора нет исхода «исключение»).
    строка = str(текст or "")
    # ОТРИЦАНИЕ ПРИМЕНЯЕТСЯ И К ЧУЖОЙ ПОЛОВИНЕ СПИСКА. `banned_topics` живёт в
    # `studio/style.py`, у которого другой писатель (Ц2), поэтому фильтр стоит
    # здесь, на его ответе: метка вида «adult content: nudity» несёт сам
    # признак после двоеточия, и его вхождения ищутся в тех же словах.
    # Без этого «no nudity, business suit» отвергалось так же, как русское
    # «без обнажёнки» до починки.
    чужие = [м for м in banned_topics(строка) if not _метка_отменена(м, строка)]
    темы = чужие + _русские_темы(строка)
    указания = [о for о in ЧУЖИЕ_УКАЗАНИЯ if о in низ or о in похоже]
    указания += [о for о in РУССКИЕ_УКАЗАНИЯ if о in низ or о in похоже]
    беды = len(темы) + len(указания)
    return {
        "outcome": FAIL if беды else PASS,
        # Три проверки: запрещённые темы студии, русские темы и обороты, чужие
        # указания. Число проверок, а не слов.
        "checked": ПРОВЕРОК,
        "violations": беды,
        "unmeasured": 0,
        "banned": темы,
        "injection": указания,
        "words": len(слова),
        "note": (
            f"в словах заказчика найдено запрещённое: {'; '.join(темы + указания)}"
            if беды
            else "в словах заказчика запрещённых тем и обращений к читателю не найдено"
        ),
    }


def чисто(текст: str) -> bool:
    """Короткий ответ для вызывающего, которому нужен только знак.

    Пустой текст НЕ чист: там нечего было смотреть. Сворачивать третий исход в
    первый ради удобства вызывающего — тот самый Р1, ради которого весь пакет.
    """
    return просеять(текст)["outcome"] == PASS
