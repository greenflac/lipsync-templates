#: КАК ТЕКСТ ПРИВОДИТСЯ ПЕРЕД ПОИСКОМ ОБОРОТОВ. Приёмка 2026-09-06 обошла
#: проверку чужих указаний ДВОЙНЫМ ПРОБЕЛОМ и дефисами: «ignore  all  previous»
#: и «ignore-all-previous-instructions» получали `pass` и ноту «instructions to
