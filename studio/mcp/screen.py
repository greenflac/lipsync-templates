#: Признаки, к которым это послабление применимо. ТОЛЬКО «актёр»: «своя
#: знаменитость» и «мой дипфейк» — не менее чужие лица, чем без притяжательного.
СВОЙ_ЧЕЛОВЕК_ПРИЗНАКИ: frozenset[str] = frozenset({"actor", "actress", "актёр", "актер", "актрис"})


def _свой_человек(метка: str, текст: str) -> bool:
    """Заказчик снимает СВОЕГО актёра — это не «узнаваемое третье лицо».

    ВОСПРОИЗВЕДЕНО приёмкой 2026-09-07: бриф «no deepfake, my own actor»
    отвергался за слово `actor`, то есть за упоминание собственной съёмочной
    группы. Список запрещённых тем живёт в `studio/style.py`, у которого
    другой писатель (Ц2), поэтому послабление стоит здесь, на его ответе, — и
    оно узкое: только «актёр» и только с притяжательным.
    """
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if признак not in СВОЙ_ЧЕЛОВЕК_ПРИЗНАКИ:
        return False
    низ = привести(текст)
    return any(о in низ for о in СВОЙ_ЧЕЛОВЕК)


def _метка_отменена(метка: str, текст: str) -> bool:
    """Все ли вхождения признака из метки стоят под отрицанием заказчика."""
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if not признак:
        return False
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    места = [i for i, с in enumerate(по_порядку) if с.startswith(признак)]
    return bool(места) and all(_отменено(по_порядку, i, текст) for i in места)


def _русские_темы(текст: str) -> list[str]:
    """`группа: признак` для каждой найденной темы. Пусто — чисто.

    Длинные корни — по НАЧАЛУ слова (русский склоняется), короткие — ЦЕЛЫМ
    СЛОВОМ со своими формами, обороты — по подстроке. Три способа выбраны не
    для красоты: у каждого своя цена ложного срабатывания, измеренная на живых
    словах («унисекс» против подстроки, «труппа» против начала слова).
    """
    # ПОРЯДОК СЛОВ НУЖЕН, А НЕ ТОЛЬКО ИХ НАБОР: без него не видно, что перед
    # находкой стоит отказ заказчика от этой темы («без обнажённых плеч»).
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    низ = привести(текст)
    найдено: list[str] = []
    for группа, корни, целые in РУССКИЕ_ГРУППЫ:
        for корень in корни:
            места = [i for i, с in enumerate(по_порядку) if с.startswith(корень)]
            if места and not all(_отменено(по_порядку, i, текст) for i in места):
                найдено.append(f"{группа}: {корень}")
        for слово in целые:
            места = [i for i, с in enumerate(по_порядку) if с == слово]
            if места and not all(_отменено(по_порядку, i, текст) for i in места):
                найдено.append(f"{группа}: {слово}")
    # ОТРИЦАНИЕ ДЕЙСТВУЕТ И НА ОБОРОТЫ. Приёмка 2026-09-07: «no face swap,
    # just my own footage» и «без 18+ контента, детская аудитория не наша»
    # отвергались — фильтр отрицаний не доходил до этого списка вовсе.
    похоже_целиком = привести_буквы(текст)
    for группа, оборот in ОПИСАТЕЛЬНЫЕ:
        for где in (низ, похоже_целиком):
            место = где.find(оборот)
            if место == -1:
                continue
            до = где[:место].split()
            if _отменено(до + [оборот], len(до), текст):
                break
            найдено.append(f"{группа}: {оборот}")
            break
    return найдено


#: ЗАЯВЛЕНИЯ, ЗА КОТОРЫЕ ОТВЕЧАЕТ ЗАКАЗЧИК. Не запрет, а КОММЕНТАРИЙ.
#:
#: ВОСПРОИЗВЕДЕНО 2026-09-07: на бриф «наш БАД излечивает диабет за две недели,
#: липсинк, 20 секунд» продукт собирал план из трёх шагов и жаловался ТОЛЬКО на
#: применимость модели. Про то, что заказан ролик с утверждением, за которое в
#: рекламе отвечают по закону, не было сказано ни слова — ни заказчику, ни в
#: ноте. Студия молча становилась соавтором.
#:
#: ПОЧЕМУ НЕ ОТКАЗ, И ЭТО ГЛАВНОЕ ПРО ЭТОТ СПИСОК. Мы не можем судить, правда
#: ли препарат лечит: у заказчика может быть регистрационное удостоверение и
#: клиническое исследование. Отказ здесь был бы ЛОЖНЫМ ОТКАЗОМ — тем самым,
