def _метка_про_аудиторию(метка: str, текст: str) -> bool:
    """Все ли вхождения признака чужой метки названы АУДИТОРИЕЙ, а не кадром.

    Тот же разбор, что у русской половины списка, но по ответу `style.py` (Ц2:
    правим не чужой модуль, а его ответ у себя). Без этого «educational clip
    for kids about space» продолжало отказывать по-английски ровно там, где
    русский эквивалент уже проходил, — и разъехавшееся поведение двух половин
    одного заслона хуже обоих исходов по отдельности.
    """
    группа, _, признак = str(метка).partition(":")
    признак = признак.strip().lower()
    if группа.strip().lower() != АУДИТОРИЯ_ГРУППА or not признак:
        return False
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    места = [i for i, с in enumerate(по_порядку) if с.startswith(признак)]
    return bool(места) and all(_для_аудитории(по_порядку, i, текст) for i in места)


def _признак_это_имя(метка: str, текст: str) -> bool:
    """Все ли вхождения признака лежат ВНУТРИ пары заглавных, то есть в имени.

    НАЙДЕНО двенадцатой приёмкой 2026-09-08: «promo for Burger King, talking
    head presenter» отказывалось по признаку `king` — по слову, которого
    заказчик как ТЕМУ не называл: он назвал сеть быстрого питания. Тот же
    приём, которым планировщик отличает вывеску от заказа: слово внутри
    названия — часть названия.

    ПОСЛАБЛЕНИЕ СНИМАЕТСЯ, как только то же слово встречается в тексте ЕЩЁ И
    вне имени: «Burger King, нужен king в кадре» — это уже тема.
    """
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if not признак:
        return False
    строка = str(текст or "")
    имена = " ".join(м.group(0) for м in _ИМЯ_ФАМИЛИЯ.finditer(строка))
    if признак not in привести(имена):
        return False
    вне = _ИМЯ_ФАМИЛИЯ.sub(" ", строка)
    слова = [с.lower() for с in _СЛОВО.findall(вне)]
    return not any(с.startswith(признак) for с in слова)


#: ТИТУЛЫ, КОТОРЫЕ ЧУЖОЙ СПИСОК (`studio/style.py`, Ц2) ОТКАЗЫВАЕТ ГОЛЫМ
#: СЛОВОМ, а политика людей (конец модуля) решает по человеку. Валидатор
#: 6-го круга: «a fictional president of a made-up country announces
#: elections» и «King prawns on the grill» получали отказ по слову, а «the
#: president announces a new tax» — отказ там, где правило — вопрос «кто это».
#: Титул с именем или с глаголом речи ловит `титулованные`; публичный с
#: заявлением или рекламой — отказ по двум признакам, как и прежде.
ТИТУЛЫ_ПОД_ПОЛИТИКОЙ: frozenset[str] = frozenset({"president", "pope", "king", "queen"})


def _титул_под_политикой(метка: str) -> bool:
    группа, _, признак = str(метка).partition(":")
    return (
        группа.strip() == "recognisable third parties"
        and признак.strip().lower() in ТИТУЛЫ_ПОД_ПОЛИТИКОЙ
    )


def _роль_без_имени(метка: str, текст: str) -> bool:
    """Названа профессия — и ни имени человека, ни слова о известности рядом.

    Послабление СНИМАЕТСЯ, как только заказчик называет имя («a video of Elon
    Musk, our singer») или говорит о знаменитости: тогда речь о конкретном
    лице, и предупреждение обязано остаться.
    """
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if признак not in ПРОФЕССИИ:
        return False
    низ = привести(текст)
    if any(о in низ for о in ИЗВЕСТНОСТЬ):
        return False
    # ПАРА ЗАГЛАВНЫХ РЯДОМ СО СЛОВОМ ПРОФЕССИИ — ЭТО ЧЕЛОВЕК, И ГЛАГОЛА ЗДЕСЬ
    # ТРЕБОВАТЬ НЕ НАДО. НАЙДЕНО двенадцатой приёмкой 2026-09-08 как РЕГРЕССИЯ
    # предыдущего коммита: «a video of singer Elon Musk» и «music video with
    # the singer Taylor Swift» проходили с пустыми `banned` и `risks` —
    # послабление снимало заслон, а `_люди_в_заказе` молчал, потому что
    # глагола появления в брифе нет. Обе половины сторожа молчали разом, и
    # именно на том входе, ради которого они существуют.
    #
    # Слово профессии САМО говорит, что соседнее имя — человек: это и есть
    # недостающий признак, и он в брифе уже стоит.
    if _ИМЯ_ФАМИЛИЯ.search(str(текст or "")):
        return False
    # ХВОСТ УДАЛЁН 2026-09-08, А НЕ ПОКРЫТ ТЕСТОМ. Здесь стояло
    # `return not _люди_в_заказе(текст)`, и мутационный прогон показал его
    # ЭКВИВАЛЕНТНЫМ: `_люди_в_заказе` без пары заглавных пуст всегда, а с парой
    # сюда уже не доходят — строка выше вернула False. Мёртвая проверка,
    # которую нельзя отличить от её отсутствия, — это не охрана, а вид охраны
    # (И5), и она уходит.
    return True


def _метка_отменена(метка: str, текст: str) -> bool:
    """Все ли вхождения признака из метки стоят под отрицанием заказчика."""
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if not признак:
        return False
    по_порядку = [с.lower() for с in _СЛОВО.findall(str(текст or ""))]
    места = [i for i, с in enumerate(по_порядку) if с.startswith(признак)]
    return bool(места) and all(_отменено(по_порядку, i, текст) for i in места)


#: ПРЕДЛОГ АУДИТОРИИ ПЕРЕД СЛОВОМ ГРУППЫ. «Ролик ДЛЯ детей» называет зрителя,
#: а не того, кто в кадре, и это разные заказы.
