#: разъехалась бы с первой на первой же правке.
try:  # pragma: no cover - подстраховка на случай кругового импорта
    from studio.planner import ФОРМЫ_КОМПАНИЙ as _ФОРМЫ_КОМПАНИЙ
except Exception:  # pragma: no cover
    _ФОРМЫ_КОМПАНИЙ = frozenset({"inc", "ltd", "llc", "studio", "studios"})


def _заявления(текст: str) -> list[str]:
    """`группа: предмет + утверждение` для каждой найденной пары. Пусто — тихо.

    Сравнение по ПОДСТРОКЕ, а не по началу слова, и это осознанно слабее
    соседа: цена ложного срабатывания здесь — одна лишняя строка совета, а не
    потерянный заказ, и потому здесь можно ловить шире. Обратной стороной
    список ОБЯЗАН оставаться комментарием: если его когда-нибудь подключат к
    исходу, эту строку надо переписать вместе с ним.
    """
    низ = привести(текст)
    найдено: list[str] = []
    for группа, предметы, утверждения in ЗАЯВЛЕНИЯ:
        предмет = next((п for п in предметы if п in низ), "")
        утверждение = next((у for у in утверждения if у in низ), "")
        if предмет and утверждение:
            найдено.append(f"{группа}: {предмет} + {утверждение}")
    return найдено


def предупреждение(риски: Sequence[str]) -> str:
    """Одна строка заказчику про его же заявления. Одно знание — одно место.

    Текст живёт ЗДЕСЬ, а не у вызывающего: предупреждение печатают и просев, и
    планировщик, и две редакции одного текста разъехались бы на первой же
    правке (Е1).
    """
    if not риски:
        return ""
    # ФОРМУЛИРОВКА ПРАВЛЕНА СРАЗУ ЖЕ, НА ПЕРВОМ ЖЕ ПРОГОНЕ. Первая редакция
    # говорила «План собран, работа не отклонена» — и печаталась на ответе с
    # `outcome: fail`, где план как раз отвергнут валидатором. Строка про
    # заявление заказчика не имеет права утверждать что-либо об ИСХОДЕ: она о
    # другом и приписывается к любому.
    имена = [р.split(": ", 1)[1] for р in риски if р.startswith("person's likeness: ")]
    if имена:
        прочее = [р for р in риски if not р.startswith("person's likeness: ")]
        хвост = f" Кроме того: {'; '.join(прочее)}." if прочее else ""
        return (
            "в заказе назван живой человек — "
            + ", ".join(имена)
            + ". Права на образ и голос человека принадлежат ему: студия не может судить, "
            "есть ли у вас письменное согласие, и потому не отказывает — но без согласия "
            "такой ролик снимать нельзя, и отвечает за это заказчик." + хвост
        )
    return (
        "в брифе есть утверждение, за которое в рекламе отвечает заказчик, а не студия "
        f"({'; '.join(риски)}). Из-за него работа не отклонена: правда ли это, студия не "
        "судит — но проверьте, чем утверждение подтверждается. В большинстве стран такая "
        "реклама требует документа, а ролик остаётся у вас"
    )


#: Имена групп ПО-РУССКИ. Группы приходят из двух мест — `studio/style.py`
