#: ИЗМЕРЕННЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ (И6). Подмена «сравнивать длинные корни
#: подстрокой вместо начала слова» тестами НЕ ловится, и это не дыра в наборе:
#: ни одно живое русское слово не содержит `обнаж`, `эрот`, `порно`, `сексуал`,
#: `кровав`, `расчлен`, `убийств`, `пытк`, `изнасил`, `детск`, `подрост`,
#: `знаменит`, `дипфейк`, `политик`, `актрис` В СЕРЕДИНЕ. Разница между двумя
#: сравнениями наблюдаема только на выдуманном слове, а тест на выдуманном
#: входе сторожит выдумку. Поэтому мутанта на эту строку не заведено — и это
#: сказано здесь, чтобы следующий не считал её забытой.
#:
#: КОРОТКИЕ — другое дело: там разница измерена на живых словах («унисекс»
#: против подстроки, «труппа» против начала слова), и обе стороны под тестами.

#: ДЕФИС РАЗДЕЛЯЕТ СЛОВА, А НЕ СКЛЕИВАЕТ. «ню-съёмка» при склейке остаётся
#: одним токеном, и целое слово `ню` в нём не находится — пропуск, измеренный
#: приёмкой 2026-09-06. Апостроф внутри слова оставлен: он часть слова.
_СЛОВО = re.compile(r"[а-яёА-ЯЁa-zA-Z][а-яёА-ЯЁa-zA-Z']*")


def _русские_темы(текст: str) -> list[str]:
    """`группа: признак` для каждой найденной темы. Пусто — чисто.

    Длинные корни — по НАЧАЛУ слова (русский склоняется), короткие — ЦЕЛЫМ
    СЛОВОМ со своими формами, обороты — по подстроке. Три способа выбраны не
    для красоты: у каждого своя цена ложного срабатывания, измеренная на живых
    словах («унисекс» против подстроки, «труппа» против начала слова).
    """
    слова = {с.lower() for с in _СЛОВО.findall(str(текст or ""))}
    низ = " ".join(str(текст or "").lower().split())
    найдено: list[str] = []
    for группа, корни, целые in РУССКИЕ_ГРУППЫ:
        for корень in корни:
            if any(с.startswith(корень) for с in слова):
                найдено.append(f"{группа}: {корень}")
        for слово in целые:
            if слово in слова:
                найдено.append(f"{группа}: {слово}")
    for группа, оборот in ОПИСАТЕЛЬНЫЕ:
        if оборот in низ:
            найдено.append(f"{группа}: {оборот}")
    return найдено


def просеять(текст: str) -> dict:
    """Что не так с текстом ЗАКАЗЧИКА. ТРИ исхода, и третий не украшение.

    `pass` — «в этих словах не найдено запрещённых тем и обращений к читателю»,
    и ровно это можно печатать заказчику. `could not measure` — текста нет,
    смотреть было не на что: непроверенный текст не является чистым, и сосед по
    пакету (`contract.gate`) отвечает так же и теми же словами.

    `checked` — число ПРОВЕРОК, как у соседа, а не число слов: одно имя с двумя
    разными величинами в одном пакете — это Е1 наоборот (приёмка 2026-09-06).
    """
    слова = _СЛОВО.findall(str(текст or ""))
    if not слова:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "banned": [],
            "injection": [],
            "words": 0,
            "note": (
                "в тексте нет ни одного слова — просеивать нечего. "
                "Непроверенный текст не является чистым"
            ),
        }
    низ = " ".join(str(текст or "").lower().split())
    # `str(... or "")` ВЕЗДЕ, а не только там, где падало: приёмка подала
    # `None` и `123`, и модуль валился AttributeError вместо ответа (Р1: у
    # прибора нет исхода «исключение»).
    строка = str(текст or "")
    темы = list(banned_topics(строка)) + _русские_темы(строка)
    указания = [о for о in ЧУЖИЕ_УКАЗАНИЯ if о in низ]
    указания += [о for о in РУССКИЕ_УКАЗАНИЯ if о in низ]
    беды = len(темы) + len(указания)
    return {
        "outcome": FAIL if беды else PASS,
        # Три проверки: запрещённые темы студии, русские темы и обороты, чужие
        # указания. Число проверок, а не слов.
        "checked": ПРОВЕРОК,
        "violations": беды,
        "unmeasured": 0,
        "banned": темы,
        "injection": указания,
        "words": len(слова),
        "note": (
            f"в словах заказчика найдено запрещённое: {'; '.join(темы + указания)}"
            if беды
            else "в словах заказчика запрещённых тем и обращений к читателю не найдено"
        ),
    }


def чисто(текст: str) -> bool:
    """Короткий ответ для вызывающего, которому нужен только знак.

    Пустой текст НЕ чист: там нечего было смотреть. Сворачивать третий исход в
    первый ради удобства вызывающего — тот самый Р1, ради которого весь пакет.
    """
    return просеять(текст)["outcome"] == PASS
