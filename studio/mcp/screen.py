#: частые пары приводятся, и это измеримо лучше, чем ничего.
_ПОХОЖИЕ = str.maketrans(
    {"е": "e", "о": "o", "а": "a", "с": "c", "р": "p", "х": "x", "у": "y", "к": "k", "і": "i"}
)


def привести(текст: str) -> str:
    """Текст для поиска ОБОРОТОВ: один пробел, дефисы как пробелы, нижний регистр.

    ОДНА функция на проект (Е1): раньше `contract.gate` искал обороты в сыром
    `text.lower()`, а `screen.просеять` — в приведённом, и один и тот же текст
    получал два разных вердикта. Комментарий в `contract.py` про такой случай
    говорит прямо: «Два ответа на один вопрос — это и есть дефект».
    """
    низ = str(текст or "").lower().replace("-", " ").replace("_", " ")
    return " ".join(низ.split())


def привести_буквы(текст: str) -> str:
    """То же плюс приведение похожих кириллических букв к латинским."""
    return привести(текст).translate(_ПОХОЖИЕ)


