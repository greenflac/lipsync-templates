СВОЙ_ЧЕЛОВЕК_ПРИЗНАКИ: frozenset[str] = frozenset({"actor", "actress", "актёр", "актер", "актрис"})


def _свой_человек(метка: str, текст: str) -> bool:
    """Заказчик снимает СВОЕГО актёра — это не «узнаваемое третье лицо».

    ВОСПРОИЗВЕДЕНО приёмкой 2026-09-07: бриф «no deepfake, my own actor»
    отвергался за слово `actor`, то есть за упоминание собственной съёмочной
    группы. Список запрещённых тем живёт в `studio/style.py`, у которого
    другой писатель (Ц2), поэтому послабление стоит здесь, на его ответе, — и
    оно узкое: только «актёр» и только с притяжательным.
    """
    признак = str(метка).split(":", 1)[-1].strip().lower()
    if признак not in СВОЙ_ЧЕЛОВЕК_ПРИЗНАКИ:
        return False
    низ = привести(текст)
    return any(о in низ for о in СВОЙ_ЧЕЛОВЕК)


#: НАЗВАНИЕ ПРОФЕССИИ — ЭТО РОЛЬ, А НЕ ЧЕЛОВЕК. Список запрещённых тем
