def _люди_в_заказе(текст: str) -> list[str]:
    """Имена живых людей, которых просят показать. Пусто — никого не назвали.

    ДВА ПРИЗНАКА СРАЗУ, и это не осторожность, а различение: пара заглавных
    сама по себе — чаще всего название («Нижний Новгород», «Talking Tom»), и
    человеком её делает глагол появления рядом. Название компании при этом
    снимается формой компании и словами вроде «сеть», «студия», «бренд».
    """
    строка = str(текст or "")
    низ = привести(строка)
    if not any(г in низ for г in ПОЯВЛЯЕТСЯ):
        return []
    найдено: list[str] = []
    for м in _ИМЯ_ФАМИЛИЯ.finditer(строка):
        пара = м.group(0)
        до = привести(строка[: м.start()])
        if any(н in до[-24:] for н in НЕ_ЧЕЛОВЕК):
            continue
        if пара.split()[-1].strip(".,").lower() in _ФОРМЫ_КОМПАНИЙ:
            continue
        if пара not in найдено:
            найдено.append(пара)
    return найдено


