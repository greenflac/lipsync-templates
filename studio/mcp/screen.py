#: по-английски, потому что так они записаны в коде. Заказчику это показывать
#: нельзя: НАЙДЕНО продуктовой проверкой 2026-09-07, в отказе стояло
#: «recognisable third parties: его лицо на мо» — английское имя посреди
#: русского текста и вдобавок цитата, обрезанная посреди слова.
ПО_РУССКИ: dict[str, str] = {
    "adult content": "обнажённое тело",
    "violence": "насилие",
    "minors": "несовершеннолетние",
    "recognisable third parties": "узнаваемые люди без их согласия",
}


#: Имена групп ПО-АНГЛИЙСКИ. В коде они и так английские, но их РЕДАКЦИЯ —
#: наша: «recognisable third parties» заказчику говорит меньше, чем «people
#: who can be recognised, without their consent».
ПО_АНГЛИЙСКИ: dict[str, str] = {
    # НЕ ПРОСТО «nudity»: группа ловит и `erotic`, и `porn`, и `sexual`, и
    # заказчику сказали бы «мы не делаем nudity» о том, чего он не писал
    # (найдено девятой приёмкой). Имя группы обязано покрывать её содержимое.
    "adult content": "nudity or sexual content",
    "violence": "violence",
    "minors": "minors",
    "recognisable third parties": "people who can be recognised, without their consent",
}


def _назвать(метка: str, словарь: dict[str, str]) -> str:
    """`группа: признак` человеческими словами по заданному словарю имён.

    ОДНО ТЕЛО НА ДВА ЯЗЫКА (Е1). До 2026-09-07 `по_русски` и `по_английски`
    совпадали построчно, и правка одной молча разошлась бы с другой — ровно
    тот дефект, который этот файл ловит в чужом коде.

    Молча проглотить незнакомую группу нельзя: список групп живёт в чужом
    модуле и может пополниться без нашего ведома, и тогда лучше показать
    английское имя, чем не показать ничего.
    """
    группа, _, признак = str(метка).partition(":")
    имя = словарь.get(группа.strip(), группа.strip())
    признак = признак.strip()
    return f"{имя}: {признак}" if признак else имя


def по_английски(метка: str) -> str:
    """То же, что `по_русски`, на языке заказчика, писавшего латиницей."""
    return _назвать(метка, ПО_АНГЛИЙСКИ)


def по_русски(метка: str) -> str:
    """`группа: признак` человеческими словами. Неизвестная группа — как есть."""
    return _назвать(метка, ПО_РУССКИ)


def просеять(текст: str) -> dict:
    """Что не так с текстом ЗАКАЗЧИКА. ТРИ исхода, и третий не украшение.

    `pass` — «в этих словах не найдено запрещённых тем и обращений к читателю»,
    и ровно это можно печатать заказчику. `could not measure` — текста нет,
    смотреть было не на что: непроверенный текст не является чистым, и сосед по
    пакету (`contract.gate`) отвечает так же и теми же словами.

    `checked` — число ПРОВЕРОК, как у соседа, а не число слов: одно имя с двумя
    разными величинами в одном пакете — это Е1 наоборот (приёмка 2026-09-06).
    """
    слова = _СЛОВО.findall(str(текст or ""))
    if not слова:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "banned": [],
            "injection": [],
            # ПОЛЕ ЕСТЬ НА ВСЯКОМ ОТВЕТЕ, включая этот. Поле, появляющееся
            # через раз, вызывающий читает через `.get(...)` — и молчание
            # становится неотличимо от «нечего сказать».
            "risks": [],
            "risky": 0,
            "words": 0,
            "note": (
                "в тексте нет ни одного слова — просеивать нечего. "
                "Непроверенный текст не является чистым"
            ),
        }
    низ = привести(текст)
    похоже = привести_буквы(текст)
    # `str(... or "")` ВЕЗДЕ, а не только там, где падало: приёмка подала
    # `None` и `123`, и модуль валился AttributeError вместо ответа (Р1: у
    # прибора нет исхода «исключение»).
    строка = str(текст or "")
    # ОТРИЦАНИЕ ПРИМЕНЯЕТСЯ И К ЧУЖОЙ ПОЛОВИНЕ СПИСКА. `banned_topics` живёт в
    # `studio/style.py`, у которого другой писатель (Ц2), поэтому фильтр стоит
    # здесь, на его ответе: метка вида «adult content: nudity» несёт сам
    # признак после двоеточия, и его вхождения ищутся в тех же словах.
    # Без этого «no nudity, business suit» отвергалось так же, как русское
    # «без обнажёнки» до починки.
    чужие = [
        м
        for м in banned_topics(строка)
        if not _метка_отменена(м, строка) and not _свой_человек(м, строка)
    ]
    темы = чужие + _русские_темы(строка)
    указания = [о for о in ЧУЖИЕ_УКАЗАНИЯ if о in низ or о in похоже]
    указания += [о for о in РУССКИЕ_УКАЗАНИЯ if о in низ or о in похоже]
    беды = len(темы) + len(указания)
    # ЧЕТВЁРТАЯ ПРОВЕРКА НЕ ВХОДИТ В `violations` И НЕ МЕНЯЕТ ИСХОД. Это
    # решение, а не недоделка: см. длинный комментарий у `ЗАЯВЛЕНИЯ`.
    риски = _заявления(строка)
    # ИМЯ ЖИВОГО ЧЕЛОВЕКА — ТОТ ЖЕ КАНАЛ, ЧТО И ЗАЯВЛЕНИЯ: комментарий, а не
    # отказ. Исход не меняется, счёт `risky` растёт.
    # СВОЙ ЧЕЛОВЕК ПРЕДУПРЕЖДЕНИЯ НЕ ПОЛУЧАЕТ: у «нашего актёра» согласие есть
    # по определению договора, и говорить о нём то же самое — шум, из-за
    # которого перестанут читать и настоящий случай.
    низ_текста = привести(строка)
    свой = any(о in низ_текста for о in СВОЙ_ЧЕЛОВЕК)
    if not свой:
        риски += [f"person's likeness: {имя}" for имя in _люди_в_заказе(строка)]
    return {
        "outcome": FAIL if беды else PASS,
        # Три проверки: запрещённые темы студии, русские темы и обороты, чужие
        # указания. Число проверок, а не слов.
        "checked": ПРОВЕРОК,
        "violations": беды,
        "unmeasured": 0,
        "banned": темы,
        "injection": указания,
        "risks": риски,
        "risky": len(риски),
        "words": len(слова),
        "note": (
            (
                f"в словах заказчика найдено запрещённое: {'; '.join(темы + указания)}"
                if беды
                else "в словах заказчика запрещённых тем и обращений к читателю не найдено"
            )
            # ПРЕДУПРЕЖДЕНИЕ ПЕЧАТАЕТСЯ И ПРИ `pass`, и это единственный способ
            # его увидеть: исход оно не меняет, а `note` читают всегда.
            + (f". {предупреждение(риски)}" if риски else "")
        ),
    }


def чисто(текст: str) -> bool:
    """Короткий ответ для вызывающего, которому нужен только знак.

    Пустой текст НЕ чист: там нечего было смотреть. Сворачивать третий исход в
    первый ради удобства вызывающего — тот самый Р1, ради которого весь пакет.
    """
    return просеять(текст)["outcome"] == PASS
