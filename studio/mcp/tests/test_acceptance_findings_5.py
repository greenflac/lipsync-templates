"""Пятая приёмка: починка четвёртой создала новый ложный отказ.

САМАЯ ДОРОГАЯ ИЗ НАХОДОК, ВОСПРОИЗВЕДЕНА ПРИЁМКОЙ 2026-09-07:

    plan_pipeline("ролик 15 секунд, деловой костюм, без обнажёнки,
                   и без спешки не обойтись")
    -> outcome fail, «в словах заказчика найдено запрещённое:
       adult content: обнаж. План не строится...»

Заказчик САМ запретил тему и просто сказал, что у него горит срок, — и
получил отказ за порнографию. Причина: проверка двойного отрицания искала
свои обороты ПО ВСЕМУ БРИФУ, без окна и без связи с темой, то есть «не
обойтись» про что угодно отменяло любое отрицание в тексте.

Остальное из того же захода: ложный отказ по цене переехал с «за секунду» на
«за минуту» и «за кадр»; отказ по чужой валюте превратился в ложное «годно»
при НУЛЕ сравнений; `expanduser` стоял в одном месте из трёх, и «файла нет»
стало «файл битый»; соседние формы отрицания и `actress` по-прежнему
отвергались.

Т2: ожидаемое — литералы. Т3: обе стороны каждой развилки. Т4: сети нет.
"""

from __future__ import annotations

import os
import pathlib
import unittest

from studio.mcp import creative, screen
from studio.planner import в_ролик


def _ставка(значение: float = 0.0225, единица: str = "usd") -> dict:
    return {
        "outcome": "годно",
        "lower_bound": {f"{единица} за second": значение},
        "note": "n",
    }


class ОкноДвойногоОтрицания(unittest.TestCase):
    ЧЕСТНЫЕ = (
        "без обнажёнки, деловой костюм, без спешки не обойтись",
        "без обнажёнки, но без правок не обойтись",
        "без обнажёнки; без монтажа никак не обойтись",
        "без обнажёнки, невозможно без хорошего света",
        "обнажёнки быть не должно",
        "исключить любую обнажёнку",
        "no deepfake, my own actress",
    )
    ПРОСЬБЫ = (
        "без обнажёнки не обойтись",
        "без обнажёнки не получится",
        "без обнажёнки никак",
        "без обнажёнки тут не выйдет",
        "without nudity it wont work",
        "без цензуры обнажёнка",
    )

    def test_честный_бриф_проходит(self) -> None:
        for текст in self.ЧЕСТНЫЕ:
            self.assertEqual("pass", screen.просеять(текст)["outcome"], текст)

    def test_просьба_остаётся_отказом(self) -> None:
        for текст in self.ПРОСЬБЫ:
            self.assertEqual("fail", screen.просеять(текст)["outcome"], текст)

    def test_оборот_дальше_окна_чужой_теме_не_помогает(self) -> None:
        """Именно на этом входе бесконечное окно и ломалось: «не обойтись»
        стоит в конце брифа и относится к спешке, а не к теме."""
        итог = screen.просеять("без обнажёнки, деловой костюм, без спешки не обойтись")
        self.assertEqual([], итог["banned"])


class ПотолокСравнимТолькоСЦенойРолика(unittest.TestCase):
    def test_за_минуту_и_за_кадр_не_сравниваются(self) -> None:
        """Ложный отказ переехал сюда после починки «за секунду»: заказчик с
        потолком 3 usd за минуту и ставкой 0.84 usd/мин получал «дороже в 2.8
        раза»."""
        for за_что in (("minute",), ("image",), ("second",), ("1000_chars",)):
            итог = в_ролик(_ставка(0.014), 600.0, 3.0, за_что)
            self.assertEqual("годно", итог["outcome"], за_что)
            self.assertIn("величины разного рода", итог["note"], за_что)

    def test_за_прогон_сравнивается(self) -> None:
        """Вторая сторона (И5): прибор, который не сравнивает ничего, ничего и
        не защищает."""
        итог = в_ролик(_ставка(), 600.0, 3.0, ("run",))
        self.assertEqual("не годно", итог["outcome"])
        self.assertIn("ПРЕВЫШЕН", итог["note"])


class НольСравненийЭтоНеГодно(unittest.TestCase):
    """Р2 дословно: ноль отработавших сравнений — не успех. Прошлая редакция
    отказывала по кредитам, новая говорила «годно», сравнив НОЛЬ позиций из
    одной, — ошибка сменила сторону на ту, по которой заказчик действует."""

    def test_цена_целиком_в_чужой_валюте(self) -> None:
        итог = в_ролик(_ставка(500.0, "credits"), 600.0, 3.0, ("run",))
        self.assertEqual("не смогли", итог["outcome"])
        self.assertIn("НЕ СРАВНЕНО НИЧЕГО", итог["note"])

    def test_есть_доллары_сравнение_идёт(self) -> None:
        цена = {
            "outcome": "годно",
            "lower_bound": {"usd за second": 0.0225, "credits за second": 500.0},
            "note": "n",
        }
        итог = в_ролик(цена, 600.0, 3.0, ("run",))
        self.assertEqual("не годно", итог["outcome"])
        self.assertIn("не сравнивалась", итог["note"], "кредиты названы и не сравнены")


class ТильдаРаскрываетсяВезде(unittest.TestCase):
    """И7: `expanduser` стоял в ОДНОМ месте из трёх, строящих Path из пути
    заказчика. Из-за этого «мы не нашли твой файл» превращалось в «твой файл
    битый» — первое заказчик чинит, со вторым идёт пересохранять исправный
    ролик."""

    def setUp(self) -> None:
        from PIL import Image

        self.файл = pathlib.Path(os.path.expanduser("~/приёмка-5.png"))
        Image.new("RGB", (64, 64)).save(self.файл)
        self.addCleanup(self.файл.unlink)

    def test_разбор_открывает_файл_с_тильдой(self) -> None:
        итог = creative.analyse("~/приёмка-5.png")
        self.assertIn("opened and measured", итог["note"], итог["note"][:120])

    def test_каталог_кадров_с_тильдой(self) -> None:
        каталог = pathlib.Path(os.path.expanduser("~/приёмка-5-кадры"))
        каталог.mkdir(exist_ok=True)
        self.addCleanup(каталог.rmdir)
        итог = creative.frames_in("~/приёмка-5-кадры")
        self.assertNotIn("каталога", итог["why"], "каталог есть, его нашли")


if __name__ == "__main__":
    unittest.main()
