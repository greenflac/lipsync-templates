"""Дверь от русского намерения к английским спискам движка.

Т2: ожидаемое — литералы. Английские слова написаны руками; импорт списков
движка используется ТОЛЬКО в проверке «новых слов не заводим», где сверка с
источником и есть смысл теста.
"""

from __future__ import annotations

import unittest

from studio import ruwords
from studio.mcp.lipsync_prompt import SATURATION_CUES, read_intent
from studio.style import LIGHT_WORDS, MOOD_WORDS, PALETTE_WORDS, TEXTURE_WORDS


class НовогоСловаряНеЗаводим(unittest.TestCase):
    def test_каждая_подстановка_ведёт_к_слову_движка(self) -> None:
        """Списки движка малы НАРОЧНО: слово, которое никто не мерил, никто не
        защитит. Дверь ведёт к уже защищённым словам, а не заводит свои."""
        свои = (
            set(PALETTE_WORDS)
            | set(LIGHT_WORDS)
            | set(TEXTURE_WORDS)
            | set(MOOD_WORDS)
            | {слово for слова in SATURATION_CUES.values() for слово in слова}
        )
        чужие = sorted({анг for анг in ruwords.ПЕРЕВОД.values() if анг not in свои})
        self.assertEqual([], чужие, "подстановка ведёт к слову, которого движок не знает")


class ПодстановкаВидна(unittest.TestCase):
    def test_подставленное_возвращается_списком(self) -> None:
        _, подставлено = ruwords.подставить("тёплый янтарный свет, мягкие тени")
        self.assertEqual("amber", подставлено["янтарн"])
        self.assertEqual("soft", подставлено["мягк"])

    def test_разбор_намерения_называет_подстановку(self) -> None:
        """Подстановка, о которой не сказано, — второй способ узнать, что понял
        продукт."""
        разбор = read_intent("тёплый янтарный свет, мягкие тени, приглушённые цвета")
        self.assertEqual(["amber"], разбор["palette"])
        self.assertEqual("muted", разбор["saturation"])
        self.assertIn("янтарн", разбор["translated"])

    def test_русское_слово_остаётся_в_тексте(self) -> None:
        """Замена стёрла бы вход заказчика, а он ещё нужен соседним
        разборщикам, которые про эту таблицу не знают."""
        текст, _ = ruwords.подставить("янтарный")
        self.assertIn("янтарный", текст)
        self.assertIn("amber", текст)


class ГраницыТаблицы(unittest.TestCase):
    def test_английский_текст_проходит_без_подстановок(self) -> None:
        """И5: дверь, которая срабатывает всегда, дописывает шум в любой вход."""
        текст, подставлено = ruwords.подставить("warm amber light, soft shadows")
        self.assertEqual({}, подставлено)
        self.assertEqual("warm amber light, soft shadows", текст)

    def test_длинная_основа_съедает_место_короткой(self) -> None:
        """«золотой час» — это СВЕТ, и палитрой он быть не должен.

        НАЙДЕНО МУТАЦИЕЙ 2026-09-04: до починки подставлялись СРАЗУ ОБА —
        `golden-hour` и `gold`, — то есть из одной фразы получались и свет, и
        палитра, а константа порядка не меняла ничего.
        """
        _, подставлено = ruwords.подставить("золотой час")
        self.assertEqual({"золотой час": "golden-hour"}, подставлено)

    def test_короткая_основа_вне_длинной_работает(self) -> None:
        """И5, обратная сторона: съедание не должно глушить своё же слово там,
        где длинной основы нет."""
        _, подставлено = ruwords.подставить("золотая палитра")
        self.assertEqual({"золот": "gold"}, подставлено)

    def test_короткая_основа_не_ловит_чужие_слова(self) -> None:
        """НАЙДЕНО МУТАЦИЕЙ: основа «сер» ловила «сервер», «серьёзный» и
        «середину» — намерение получало палитру, которой никто не называл."""
        for чужое in ("сервер упал", "серьёзный разговор", "середина кадра"):
            _, подставлено = ruwords.подставить(чужое)
            self.assertEqual({}, подставлено, f"{чужое} дало подстановку")
        _, своё = ruwords.подставить("серый фон")
        self.assertEqual({"серый": "slate"}, своё)

    def test_незнакомое_русское_слово_не_выдумывается(self) -> None:
        """Слово, которого таблица не знает, остаётся как есть: дверь ведёт к
        известным словам, а не угадывает неизвестные."""
        текст, подставлено = ruwords.подставить("вертолётный")
        self.assertEqual({}, подставлено)
        self.assertEqual("вертолётный", текст)

    def test_основа_ловится_только_с_начала_слова(self) -> None:
        """Основа внутри чужого слова — не то слово. «незерновой» содержит
        «зерн», но начинается не с него."""
        _, подставлено = ruwords.подставить("незерновой")
        self.assertEqual({}, подставлено)


if __name__ == "__main__":
    unittest.main()


class ЗапросКорпусаТожеПроходитЧерезДверь(unittest.TestCase):
    """Корпус примеров английский, и русский запрос доставал из него единицы.

    ИЗМЕРЕНО 2026-09-04 на шести русских намерениях: примеров корпуса было 1,
    стало 30. Сети здесь нет — корпус лежит на диске.
    """

    def test_запрос_дополняется_а_не_подменяется(self) -> None:
        """Слова заказчика остаются в запросе: поиск, потерявший их, ищет не
        то, что просили."""
        запрос, подставлено = ruwords.подставить("тёплый янтарный свет, мягкие тени")
        self.assertIn("янтарный", запрос)
        self.assertIn("amber", запрос)
        self.assertIn("янтарн", подставлено)

    def test_инструмент_ищет_по_дополненному_запросу(self) -> None:
        """Мало иметь дверь — сервер обязан ею пользоваться.

        Первая редакция этого набора проверяла только `подставить`, и мутант,
        возвращавший серверу русский запрос, ПРОМОЛЧАЛ: дверь была цела, а
        никто в неё не входил.
        """
        from studio.mcp.server import запрос_корпуса

        self.assertIn("amber", запрос_корпуса("тёплый янтарный свет"))
        self.assertIn("янтарный", запрос_корпуса("тёплый янтарный свет"))
        self.assertEqual("warm amber light", запрос_корпуса("warm amber light"))

    def test_английский_запрос_не_меняется(self) -> None:
        """И5: дверь, срабатывающая всегда, дописывала бы шум в любой поиск."""
        запрос, подставлено = ruwords.подставить("warm amber light")
        self.assertEqual("warm amber light", запрос)
        self.assertEqual({}, подставлено)
