class ЗапасНадСлучайностьюРешает(unittest.TestCase):
    """Обе развилки приёмки жили ВНУТРИ `report`, достижимые только через полный
    индекс, — то есть через вход, который меняется вместе с корпусом. Ни один
    тест не мог подменить в них константу, и обе стояли без охраны: поймано
    ратчетом R7 2026-09-05.

    Ожидаемое — ЛИТЕРАЛЫ (Т2): 0.10 и 0.05 написаны руками. Импортированные из
    проверяемого модуля, они поехали бы вместе с ним и промолчали.
    """

    def test_запас_на_допуск_ровно_десять_сотых(self):
        """Ровно на границе — годно; на волос ниже — беда. Мутация в обе
        стороны (Т1) держится этими двумя входами."""
        беды, _ = ev.судить(real=0.60, admission=0.50, ranking=0.0, wider=0)
        self.assertEqual(беды, [], "0.60 против 0.50 — ровно запас, это проходит")
        беды, _ = ev.судить(real=0.599, admission=0.50, ranking=0.0, wider=0)
        self.assertEqual(len(беды), 1)
        self.assertIn("ADMISSION", беды[0])

    def test_запас_на_порядок_ровно_пять_сотых(self):
        # ЧИСЛА ВЫБРАНЫ ТАК, ЧТОБЫ СЛОЖЕНИЕ БЫЛО ТОЧНЫМ В ДВОИЧНОЙ ДРОБИ:
        # `0.55 + 0.05` даёт 0.6000000000000001, и «ровно запас» на таких
        # числах не проходит. Это свойство самой границы, а не теста, и здесь
        # оно названо вслух, чтобы следующий не «починил» тест сдвигом порога.
        беды, _ = ev.судить(real=0.55, admission=0.0, ranking=0.50, wider=3)
        self.assertEqual(беды, [])
        беды, _ = ev.судить(real=0.549, admission=0.0, ranking=0.50, wider=3)
        self.assertEqual(len(беды), 1)
        self.assertIn("RANKING", беды[0])

    def test_без_широкого_пула_порядок_не_судится(self):
        """Третий исход, а не успех: у выдачи длина ровно k по построению, и
        перемешивать нечего. Объявить это успехом значило бы зачесть
        неизмеренное."""
        беды, измеримо = ev.судить(real=0.10, admission=0.0, ranking=0.99, wider=0)
        self.assertFalse(измеримо)
        self.assertEqual(беды, [], "порядок не судится вовсе")

    def test_обе_беды_называются_обе(self):
        """Е3: частичный результат печатается числами, а не одним флагом."""
        беды, измеримо = ev.судить(real=0.10, admission=0.50, ranking=0.50, wider=3)
        self.assertTrue(измеримо)
        self.assertEqual(len(беды), 2)


