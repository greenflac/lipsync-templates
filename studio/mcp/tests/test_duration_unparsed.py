"""«Не разобрали» — не то же самое, что «не спрашивали» (Р1 на входе заказчика).

ЗАЧЕМ, ИЗМЕРЕНО ПРОВЕРКОЙ ПРОДУКТА 2026-09-06 (глазами заказчика, не по тестам):

    '…вертикаль, 15 секунд'          -> «названо '15 секунд'», отброшено 6 моделей
    '…вертикаль, 15-секундный ролик' -> «длительность в брифе не названа», 0
    '…вертикаль, полторы минуты'     -> «длительность в брифе не названа», 0

Два разных греха в одном месте. Первый: неразобранное подано как НЕСКАЗАННОЕ —
утверждение о входе заказчика, где оно ложно. Второй: вместе с ним молча
исчезала проверка длины, отбраковывавшая на соседней формулировке шесть
кандидатов, и в выдаче не оставалось ни одного признака, что она не отработала.

Ожидаемое — литералы (Т2), сети и диска нет (Т4).
"""

from __future__ import annotations

import unittest

from studio import duration as dur
from studio import planner

БРИФ = "Говорящая голова по фото и моей дорожке, вертикаль"


class ТриОтветаПроДлительностьБрифа(unittest.TestCase):
    def test_цифрами_с_пробелом_разбирается(self):
        z = dur.просят(f"{БРИФ}, 15 секунд")
        self.assertEqual(15, z.секунды)
        self.assertTrue(z.разобрано)

    def test_цифрами_через_дефис_разбирается_тоже(self):
        """Ровно та формулировка, на которой прибор молчал: «15-секундный»."""
        z = dur.просят(f"{БРИФ}, 15-секундный ролик")
        self.assertEqual(15, z.секунды)
        self.assertTrue(z.разобрано)

    def test_числительное_словом_это_НЕ_РАЗОБРАЛИ(self):
        z = dur.просят(f"{БРИФ}, полторы минуты")
        self.assertIsNone(z.секунды)
        self.assertFalse(z.разобрано)
        self.assertIn("РАЗОБРАТЬ НЕ СМОГЛИ", z.нота)

    def test_молчание_остаётся_молчанием(self):
        """Негативный контроль (И5): если всякий бриф объявлять неразобранным,
        различие исчезает во вторую сторону."""
        z = dur.просят(БРИФ)
        self.assertIsNone(z.секунды)
        self.assertTrue(z.разобрано)
        self.assertIn("не названа", z.нота)

    def test_минуты_считаются_раньше_секунд(self):
        """Порядок образцов — решение: иначе «2 минуты 30 секунд» это 30 с."""
        self.assertEqual(120, dur.просят("ролик 2 минуты 30 секунд").секунды)


class ПланПризнаётсяВНеразобранном(unittest.TestCase):
    def test_неразобранная_длительность_поднимает_неизмеримость(self):
        молча = planner.plan(БРИФ)
        словами = planner.plan(f"{БРИФ}, полторы минуты")
        self.assertEqual(молча["unmeasured"] + 1, словами["unmeasured"])

    def test_и_говорится_вслух_в_ноте(self):
        план = planner.plan(f"{БРИФ}, полторы минуты")
        self.assertIn("ВНИМАНИЕ", план["note"])
        self.assertIn("длина не проверена", план["note"])

    def test_разобранная_длительность_ноту_не_засоряет(self):
        """Негативный контроль: предупреждение обязано появляться только там,
        где ему место, иначе его перестают читать."""
        план = planner.plan(f"{БРИФ}, 15 секунд")
        self.assertNotIn("ВНИМАНИЕ", план["note"])


class ВердиктШагаНеВрётПроБриф(unittest.TestCase):
    """И7: та же фраза жила в ТРЁХ местах, починка остановилась на первом.

    Приёмка 2026-09-06: при неразобранной длительности вердикт кандидата
    говорил «длительность не спрашивали», печать плана подавляла строку о
    пределе (у модели он ЕСТЬ и записан), а «оси без ответа» посылали чинить
    сбор фактов вместо разборщика — ровно то смешение, которое шапка
    `studio/duration.py` объявляет недопустимым.
    """

    def _состояние(self, бриф: str, шаг: str) -> str:
        for с in planner.plan(бриф)["steps"]:
            if шаг in с["step"]:
                return str((с.get("chosen") or {}).get("dur_state"))
        return ""

    def test_неразобранное_называется_неразобранным(self):
        self.assertEqual(dur.DUR_ASK_UNPARSED, self._состояние(f"{БРИФ}, полторы минуты", "оживл"))

    def test_молчание_называется_молчанием(self):
        """Негативный контроль (И5) к предыдущему."""
        self.assertEqual(dur.DUR_NOT_ASKED, self._состояние(БРИФ, "оживл"))

    def test_разобранное_сравнивается(self):
        self.assertEqual(dur.DUR_IN, self._состояние(f"{БРИФ}, 15 секунд", "оживл"))

    def test_ранг_неразобранного_такой_же_как_у_молчания(self):
        """Иначе отбор наказывал бы за ЧУЖУЮ аккуратность: модель с записанным
        пределом падала бы ниже модели без предела из-за НАШЕГО непонимания."""
        self.assertEqual(dur.DUR_ORDER[dur.DUR_NOT_ASKED], dur.DUR_ORDER[dur.DUR_ASK_UNPARSED])

    def test_выбор_модели_от_неразобранного_не_едет(self):
        """Проверка того же наблюдением, а не только через таблицу рангов."""
        молча = self._модель(БРИФ)
        словами = self._модель(f"{БРИФ}, полторы минуты")
        self.assertEqual(молча, словами)

    def _модель(self, бриф: str) -> str:
        for с in planner.plan(бриф)["steps"]:
            if "оживл" in с["step"]:
                return str((с.get("chosen") or {}).get("model"))
        return ""


if __name__ == "__main__":
    unittest.main()
