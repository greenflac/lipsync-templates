"""Ставка за секунду — это не цена ролика, и путать их дороже всего.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой, на брифе живого заказчика
«хочу чтобы человек говорил вслух 10 минут подряд в 8K, бюджет 3 доллара».
В ОДНОМ ответе продукта стояло:

    dur_asked       «в брифе названо "10 минут" — это 600 с»
    pipeline_price  {"outcome": "годно", "lower_bound": {"usd за second": 0.0225}}
    budget          {"amount": 3.0, "outcome": "pass"}

600 × 0.0225 = 13.50 USD при потолке 3.00. Оба множителя лежали в одном
словаре, продукт их не перемножал и печатал «годно». Заказчик читает «не
менее 0.0225» и уходит подписывать бюджет — узнает он об этом по счёту.

Т2: ожидаемое — литералы, арифметика написана руками. Т3: входы с обоих краёв
(влезает в потолок / не влезает) и середина (длительность не разобрана).
Т4: сети нет.
"""

from __future__ import annotations

import unittest

from studio.planner import в_ролик

#: Ставка в том виде, в каком её кладёт `pipeline_price` (ключ — строка).
СТАВКА = {
    "outcome": "годно",
    "lower_bound": {"usd за second": 0.0225},
    "note": "не менее 0.0225 usd за second",
}


def _ставка() -> dict:
    нижняя: dict[str, float] = {"usd за second": 0.0225}
    return {**СТАВКА, "lower_bound": нижняя}


class СтавкаУмножаетсяНаДлительность(unittest.TestCase):
    def test_цена_ролика_посчитана(self) -> None:
        итог = в_ролик(_ставка(), 600.0, None)
        self.assertEqual({"usd": 13.5}, итог["за_ролик"])
        self.assertIn("600 с × 0.0225", итог["note"])

    def test_потолок_превышен_это_не_годно(self) -> None:
        итог = в_ролик(_ставка(), 600.0, 3.0)
        self.assertEqual("не годно", итог["outcome"])
        self.assertIn("ПОТОЛОК 3 ПРЕВЫШЕН", итог["note"])
        self.assertIn("дороже в 4.5 раза", итог["note"])

    def test_влезающий_ролик_остаётся_годным(self) -> None:
        """Вторая сторона (И5): прибор, объявляющий всё дорогим, ловит все
        превышения и не измеряет ничего. 15 с × 0.0225 = 0.34 при потолке 3."""
        итог = в_ролик(_ставка(), 15.0, 3.0)
        self.assertEqual("годно", итог["outcome"])
        self.assertEqual({"usd": 0.3375}, итог["за_ролик"])
        self.assertNotIn("ПРЕВЫШЕН", итог["note"])


class ЧегоНеЗнаемТогоНеСчитаем(unittest.TestCase):
    """Р1: третий исход не сворачивается ни в первый, ни во второй."""

    def test_длительность_не_разобрана_ставка_остаётся_ставкой(self) -> None:
        итог = в_ролик(_ставка(), None, 3.0)
        self.assertNotIn("за_ролик", итог)
        self.assertEqual("годно", итог["outcome"], "исход не портится молча")
        self.assertIn("это СТАВКА ЗА СЕКУНДУ, а не цена ролика", итог["note"])

    def test_ставка_не_за_секунду_не_переводится(self) -> None:
        """«за картинку» в «за ролик» перевести нельзя: числа картинок никто
        не называл, а догадка — это выдуманное число в счёте заказчика."""
        цена = {
            "outcome": "годно",
            "lower_bound": {"usd за image": 0.04},
            "note": "не менее 0.04 usd за image",
        }
        итог = в_ролик(цена, 600.0, 3.0)
        self.assertNotIn("за_ролик", итог)
        self.assertEqual("годно", итог["outcome"])

    def test_нечего_складывать_нечего_и_умножать(self) -> None:
        пусто = {"outcome": "не смогли", "lower_bound": {}, "note": "сложить нечего"}
        self.assertEqual(пусто, в_ролик(dict(пусто), 600.0, 3.0))


class ПродуктОтвечаетТемЖеЧислом(unittest.TestCase):
    """П3: то, что увидит человек, а не только то, что вернёт функция."""

    def test_бриф_с_превышением_печатает_цену_ролика(self) -> None:
        import json

        from studio.mcp import server

        ответ = json.loads(
            server.plan_pipeline(
                "хочу чтобы человек говорил вслух 10 минут подряд в 8K, "
                "бюджет 3 доллара, видео снимать нечего, делаем с нуля"
            )
        )
        цена = ответ["pipeline_price"]
        self.assertEqual("не годно", цена["outcome"], цена)
        self.assertEqual({"usd": 13.5}, цена["за_ролик"], цена)


if __name__ == "__main__":
    unittest.main()
