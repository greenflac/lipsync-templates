"""Что уезжает в репозиторий вместе с заявкой на открытие хоста.

ЗАЧЕМ. `studio/knowledge/denied_hosts.jsonl` лежит в git и уезжает в публичный
репозиторий. Поле `why_wanted` до 2026-09-05 писалось ДОСЛОВНО — в том числе
из `search.py`, где оно строилось как «web search for: {текст запроса}», и из
параметра инструмента MCP, который заполняет клиент. Текст, который печатал
заказчик, мог уехать в коммит.

ИЗМЕРЕНО 2026-09-05 на живом файле: 605 строк, из них с текстом поискового
запроса — НОЛЬ. Сегодня это ничего не стоило, и ровно поэтому прошло бы дальше.

Ожидаемое — литералы (Т2), сети нет (Т4), развилка вызывается функцией (Т5).
Входы с обоих краёв и из середины (Т3): наша обычная формулировка, текст с
узнаваемо личным, слишком длинный текст, пустой.
"""

from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from studio.mcp import fetch
from studio.mcp.fetch import ПОТОЛОК_ПРИЧИНЫ, причина_для_записи


class ЧужойТекстВРепозиторийНеУезжает(unittest.TestCase):
    def test_почта_вырезается_и_это_сказано_вслух(self):
        строка = причина_для_записи("пишет ivan.petrov+zakaz@example.com про ролик")
        self.assertNotIn("ivan.petrov", строка)
        self.assertNotIn("@example.com", строка)
        self.assertIn("<почта>", строка)
        self.assertIn("вырезано", строка, "молчаливая правка чужого текста — тоже подмена")

    def test_телефон_вырезается(self):
        строка = причина_для_записи("перезвонить +7 900 123-45-67 после сдачи")
        self.assertNotIn("900 123", строка)
        self.assertIn("<телефон>", строка)

    def test_длинная_цепочка_цифр_вырезается(self):
        строка = причина_для_записи("заказ 123456789012 висит")
        self.assertNotIn("123456789012", строка)
        self.assertIn("<длинное число>", строка)

    def test_короткое_число_остаётся(self):
        """Негативный контроль (И5): вырезать всякую цифру значит стереть
        `403`, `2026` и номер версии — то есть саму причину."""
        строка = причина_для_записи("хост отвечает 403 с 2026-08-27")
        self.assertIn("403", строка)
        self.assertIn("2026", строка)
        self.assertNotIn("вырезано", строка)

    def test_наша_обычная_формулировка_не_трогается(self):
        """Второй негативный контроль: 605 живых строк обязаны пережить правку
        неизменными, иначе заявка на открытие хостов потеряет смысл."""
        живая = "read a page this fact base cites but nobody opened"
        self.assertEqual(живая, причина_для_записи(живая))

    def test_слишком_длинное_обрезается_и_говорит_об_этом(self):
        строка = причина_для_записи("я" * 900)
        self.assertLess(len(строка), 900)
        self.assertIn("обрезано с 900 символов", строка)

    def test_ровно_потолок_не_обрезается(self):
        """Граница включительно — записанное решение, а не случайность."""
        строка = причина_для_записи("я" * ПОТОЛОК_ПРИЧИНЫ)
        self.assertNotIn("обрезано", строка)

    def test_пустая_причина_остаётся_пустой(self):
        self.assertEqual("", причина_для_записи(""))
        self.assertEqual("", причина_для_записи(None))  # type: ignore[arg-type]


class ЗаписьВФайлПроходитЧерезОчистку(unittest.TestCase):
    """Проверять только очистку мало: она может быть цела, а запись — мимо неё.
    Тест, который не идёт через `note_denial`, промолчал бы ровно на той правке,
    ради которой всё это писалось."""

    def test_в_файл_попадает_очищенное(self):
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / "denied_hosts.jsonl"
            with mock.patch.object(fetch, "DENIED_PATH", путь):
                fetch.note_denial(
                    "https://закрытый.test/страница",
                    "Tunnel connection failed: 403 Forbidden",
                    "клиент ivan@example.com просил",
                )
            строки = [
                json.loads(с) for с in путь.read_text(encoding="utf-8").splitlines() if с.strip()
            ]
        self.assertEqual(len(строки), 1)
        причина = строки[0]["why_wanted"]
        self.assertNotIn("ivan@example.com", причина)
        self.assertIn("<почта>", причина)


if __name__ == "__main__":
    unittest.main()
