"""Описание навыка не смеет обещать того, чего у продукта нет.

ЗАЧЕМ ЭТОТ ТЕСТ. Описание `SKILL.md` — это первое, что читает и человек, и
модель, выбирающая инструмент. Оно говорило: корпус состоит из промптов,
«that were actually run and rated». ИЗМЕРЕНО 2026-09-04: записей в корпусе
13 446, оценённых — НОЛЬ, прогонов в журнале — ноль. Промпты собраны из
галерей вендоров и Civitai; их никто не запускал и не оценивал.

Это не мелкая неточность формулировки: на этом обещании строится доверие ко
всей выдаче навыка. «Обкатано и оценено» и «собрано из чужих галерей» — разные
основания, и второе честнее ровно настолько, насколько оно скромнее.

ТЕСТ СТОРОЖИТ РАСХОЖДЕНИЕ, А НЕ ТЕКСТ. Пока оценённых записей ноль, описание не
имеет права утверждать, что корпус оценён. Появятся оценки — тест перестанет
запрещать это слово, и его надо будет переписать вместе с описанием.

Т2: ожидаемое — литералы. Т4: сети нет.
"""

from __future__ import annotations

import unittest
from pathlib import Path

from studio.selfrag.replay import ReplayBuffer

КОРЕНЬ = Path(__file__).resolve().parents[3]
НАВЫК = КОРЕНЬ / ".claude" / "skills" / "prompt-engineer" / "SKILL.md"
КОРПУС = (
    КОРЕНЬ / "studio" / "knowledge" / "gallery_prompts.jsonl",
    КОРЕНЬ / "studio" / "knowledge" / "civitai_prompts.jsonl",
)

#: Слова, которыми описание обещало бы ОЦЕНЁННЫЙ корпус. Закрытый список: он
#: должен ловить обещание, а не любое употребление слова «rate».
ОБЕЩАНИЕ_ОЦЕНКИ = ("run and rated", "actually rated", "оценённых промптов")


def _оценённых() -> int:
    буфер = ReplayBuffer()
    try:
        return int(буфер.stats()["rated"])
    finally:
        буфер.close()


def _записей() -> int:
    всего = 0
    for файл in КОРПУС:
        if файл.exists():
            всего += sum(
                1
                for с in файл.read_text(encoding="utf-8").splitlines()
                if с.strip() and not с.startswith("//")
            )
    return всего


class ОписаниеНавыкаСоответствуетИзмеренному(unittest.TestCase):
    def test_описание_не_обещает_оценок_пока_их_ноль(self) -> None:
        оценено = _оценённых()
        текст = НАВЫК.read_text(encoding="utf-8").lower()
        for оборот in ОБЕЩАНИЕ_ОЦЕНКИ:
            if оборот in текст and оценено == 0:
                self.fail(
                    f"описание обещает «{оборот}», а оценённых записей {оценено} "
                    f"из {_записей()}: обещание не подтверждено ничем"
                )

    def test_корпус_на_месте_и_не_пуст(self) -> None:
        """И5: тест обязан УМЕТЬ покраснеть по существу, а не только молчать.

        Если корпус вдруг исчезнет, «обещания нет» станет верным по пустой
        причине, и проверка перестанет что-либо значить.
        """
        self.assertGreater(_записей(), 1000, "корпус подозрительно мал или не найден")

    def test_журнал_прогонов_и_оценки_считаются_одним_способом(self) -> None:
        """Е1: число оценённых берётся у буфера, а не пересчитывается по файлам.

        Второй способ узнать то же самое разъехался бы с первым — это ровно
        тот дефект, который на этом проекте уже стоил 1.7 ГБ.
        """
        буфер = ReplayBuffer()
        try:
            свод = буфер.stats()
        finally:
            буфер.close()
        self.assertIn("rated", свод)
        self.assertIn("entries", свод)
        self.assertLessEqual(свод["rated"], свод["entries"])


class ФайлыНаМесте(unittest.TestCase):
    def test_описание_навыка_читается(self) -> None:
        self.assertTrue(НАВЫК.exists(), f"нет файла {НАВЫК}")
        self.assertIn("description:", НАВЫК.read_text(encoding="utf-8")[:400])

    def test_проверяемые_обороты_записаны_литералом(self) -> None:
        self.assertEqual(3, len(ОБЕЩАНИЕ_ОЦЕНКИ))


if __name__ == "__main__":
    unittest.main()
