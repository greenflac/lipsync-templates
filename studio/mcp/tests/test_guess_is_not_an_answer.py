"""Догадка продукта не может служить основанием не спрашивать заказчика.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой, два брифа рядом:

    plan_pipeline("липсинк")
      -> три шага (озвучка, генерация_видео, липсинк), question: null

    plan_pipeline("нужин ролик жен щина гаварит в камиру 15 сек кафейня")
      -> вопрос «Видео уже снято — или ролик нужно сделать с нуля?»

То есть на опечатанном, но содержательном брифе продукт уточнял, а на брифе
из ОДНОГО СЛОВА достраивал целый пайплайн молча. Развилка «спросить или
достроить» была несогласована ровно наоборот: чем МЕНЬШЕ сказал заказчик, тем
увереннее отвечал продукт.

Причина в коде: вопрос об исходном видео снимался, если видео «доступно», —
а доступно оно становилось из ДОПИСАННОГО ШАГА генерации, то есть из нашей
же догадки. Догадка закрывала вопрос о самой себе.

ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ ПРАВКИ — ЛОЖНЫЙ ВОПРОС. Как только догадка перестала
закрывать вопрос, продукт начал переспрашивать «видео уже снято?» у того, кто
первой строкой написал «у меня есть своё видео»: список слов о готовом видео
не знал самых обычных оборотов. Ложный вопрос дешевле ложного отказа, но
платит за него тот же человек.

Т2: ожидаемое — литералы. Т3: края и середина. Т4: сети нет.
"""

from __future__ import annotations

import json
import unittest

from studio.mcp import server
from studio.planner import inputs_of


def _план(бриф: str) -> dict:
    return json.loads(server.plan_pipeline(бриф))


class ДогадкаНеЗакрываетВопрос(unittest.TestCase):
    def test_бриф_из_одного_слова_спрашивает(self) -> None:
        итог = _план("липсинк")
        вопрос = итог.get("question") or {}
        self.assertIn("Видео уже снято", вопрос.get("text", ""), итог.get("note"))

    def test_шаги_при_этом_остаются(self) -> None:
        """Вопрос не отменяет выведенных шагов: план, собранный не весь, —
        это то, что измерено, а вопрос стоит рядом с ним."""
        self.assertEqual(3, len(_план("липсинк")["steps"]))


class СловаЗаказчикаСильнееДогадки(unittest.TestCase):
    """Вторая сторона (И5): прибор, спрашивающий всегда, ничего не знает."""

    def test_сказал_что_видео_есть_вопроса_нет(self) -> None:
        for бриф in (
            "у меня есть своё видео, надо переозвучить",
            "мы сняли ролик, надо попасть в губы",
            "видео уже есть, нужен липсинк",
        ):
            итог = _план(бриф)
            self.assertIsNone(итог.get("question"), f"{бриф!r} -> {итог.get('question')}")
            self.assertIn("видео", inputs_of(бриф), бриф)

    def test_похожие_обороты_не_считаются_готовым_видео(self) -> None:
        """Списки закрытые и с притяжательным нарочно: «есть видео» без
        «своё/моё» поймало бы просьбу ДОБАВИТЬ видео в конец, а «сняли» без
        «мы/уже» — «сняли ограничение»."""
        self.assertEqual(frozenset(), inputs_of("нужно чтобы в конце было видео с логотипом"))
        self.assertEqual(frozenset(), inputs_of("сняли ограничение по бюджету, снимаем с нуля"))


class АнглийскийБрифПонятИлиОбъяснён(unittest.TestCase):
    """«Мы вас не поняли» без причины — это тупик, а не честность."""

    def test_канонический_английский_заказ_разбирается(self) -> None:
        итог = _план("need a talking head ad for our SaaS, 30 seconds, budget $2 per clip")
        self.assertEqual(3, len(итог["steps"]), итог["note"])

    def test_невнятный_английский_бриф_объясняет_причину(self) -> None:
        нота = _план("make something nice for us, cheap")["note"]
        self.assertIn("НЕ ПО-РУССКИ", нота)
        self.assertIn("назовите работу по-русски", нота)

    def test_невнятный_русский_бриф_такой_приписки_не_получает(self) -> None:
        """И5: приписка про язык обязана отличать один случай от другого."""
        self.assertNotIn("НЕ ПО-РУССКИ", _план("нужно что-то этакое, красивое")["note"])


if __name__ == "__main__":
    unittest.main()
