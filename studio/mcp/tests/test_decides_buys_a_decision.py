"""Заявка на платный замер: «оба ответа ведут к одному шагу» больше не слова.

ВОСПРОИЗВЕДЕНО 2026-09-07 (И2). Пакет обещает: «если оба ответа ведут к одному
шагу, измерение не покупает ничего», а проверялась ОДНА ДЛИНА в 20 символов.
Три текста подавались одинаково, все с исходом `could not measure` и номером:

    «если держит личность — берём latentsync,
      если не держит — всё равно берём latentsync»      подана
    «просто для общего понимания вопроса»               подана
    «если рот вставленный — sync-lipsync, если чисто — latentsync»  подана

ЧТО ПРИБОР УМЕЕТ, СКАЗАНО УЗКО. Судить «ведут ли ответы к разному» в общем
виде — значит понимать задачу. Машине доступен один случай, зато безошибочно:
ветви разобраны и ДЕЙСТВИЯ в них совпадают. Остальное — третий исход, и он
печатается рядом с заявкой, а не выдаётся за проверенное: ложный отказ здесь
дороже пропуска, потому что отвергнутая заявка — это НЕ СДЕЛАННЫЙ замер, а
замеров у проекта и так нет (R5 стоит ровно на этом).

Т2: ожидаемое — литералы. Т4: сети нет. Ц2: файл новый.
"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from studio.mcp import proposal

ТЕСТ = (
    "послать один запрос на 5 секунд в fal-ai/latentsync и посмотреть кадры "
    "0, 50 и 100 на швы и на квадратные зубы"
)

ОДИН_ШАГ = "если держит личность — берём latentsync, если не держит — всё равно берём latentsync"
РАЗНЫЕ_ШАГИ = (
    "если рот читается вставленным — липсинк идёт на sync-lipsync, "
    "если чисто — остаёмся на latentsync"
)
НЕ_РАЗБИРАЕТСЯ = "будет полезно узнать это на будущее, просто для общего понимания вопроса"


def _подать(decides: str) -> dict:
    база = Path(tempfile.mkdtemp()) / "facts.jsonl"
    база.write_text("", encoding="utf-8")
    return proposal.propose(
        "kling-3.0",
        "holds_identity",
        task="ролик для клиента на 12 секунд",
        gap="в базе нет ни одной строки применимости",
        test=ТЕСТ,
        cost_usd=0.4,
        cost_basis="опубликованный прайс fal 0.08 за секунду",
        decides=decides,
        path=Path(tempfile.mkdtemp()) / "ledger.jsonl",
        facts_path=база,
    )


class ОдинаковыеВетвиНеПодаются(unittest.TestCase):
    def test_заявка_отвергнута(self) -> None:
        итог = _подать(ОДИН_ШАГ)
        self.assertEqual("fail", итог["outcome"], итог)
        self.assertEqual("", итог["id"], "отвергнутая заявка номера не получает")

    def test_названо_какое_именно_действие_совпало(self) -> None:
        """Р2: отказ без названной причины чинить нечем."""
        нота = _подать(ОДИН_ШАГ)["note"]
        self.assertIn("ОДНОМУ И ТОМУ ЖЕ действию", нота)
        self.assertIn("берём latentsync", нота)

    def test_по_английски_тоже(self) -> None:
        итог = _подать(
            "if it holds identity -> we ship latentsync, otherwise -> we still ship latentsync"
        )
        self.assertEqual("fail", итог["outcome"], итог)


class РазныеВетвиПодаются(unittest.TestCase):
    """Вторая сторона (И5): прибор, отвергающий всё, ловит все одинаковые
    ветви на отлично и не измеряет ничего."""

    def test_настоящее_решение_проходит(self) -> None:
        итог = _подать(РАЗНЫЕ_ШАГИ)
        self.assertEqual("could not measure", итог["outcome"], итог)
        self.assertTrue(итог["id"])
        self.assertIs(True, итог["branches_differ"])

    def test_у_поданной_заявки_пометки_нет(self) -> None:
        self.assertNotIn("ПРОВЕРКА НЕ СДЕЛАНА", _подать(РАЗНЫЕ_ШАГИ)["note"])


class НеРазобралосьЭтоТретийИсход(unittest.TestCase):
    def test_заявка_подаётся(self) -> None:
        """Не отказ: отвергнутая заявка — это не сделанный замер."""
        итог = _подать(НЕ_РАЗБИРАЕТСЯ)
        self.assertEqual("could not measure", итог["outcome"], итог)
        self.assertTrue(итог["id"])

    def test_но_сказано_что_не_проверено(self) -> None:
        итог = _подать(НЕ_РАЗБИРАЕТСЯ)
        self.assertIs(False, итог["branches_differ"])
        self.assertIn("ПРОВЕРКА НЕ СДЕЛАНА", итог["note"])
        self.assertIn("прочитайте это глазами перед оплатой", итог["note"])


class ПриборРазличаетТриСлучая(unittest.TestCase):
    """Развилка вынесена функцией (Т5) и проверяется отдельно от заявки."""

    def test_три_исхода(self) -> None:
        self.assertIs(True, proposal.один_и_тот_же_шаг(ОДИН_ШАГ))
        self.assertIs(False, proposal.один_и_тот_же_шаг(РАЗНЫЕ_ШАГИ))
        self.assertIsNone(proposal.один_и_тот_же_шаг(НЕ_РАЗБИРАЕТСЯ))

    def test_условия_разные_а_действие_одно_это_один_шаг(self) -> None:
        """Сравнивается ДЕЙСТВИЕ, а не условие: условия у двух ветвей разные
        всегда, и сравнение целых ветвей не поймало бы ничего."""
        self.assertIs(
            True,
            proposal.один_и_тот_же_шаг(
                "если предел 5 секунд — режем ролик на две части, "
                "если предел 10 секунд — тоже режем ролик на две части"
            ),
        )


if __name__ == "__main__":
    unittest.main()
