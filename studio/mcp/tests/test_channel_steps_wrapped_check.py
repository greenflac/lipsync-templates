"""Третий исход канала не имеет права красить сборку — и это сторожит тест.

ЧТО СЛУЧИЛОСЬ. Восемь офлайновых проверок каналов зовутся из `scripts/check`,
который работает под `set -euo pipefail`. Код 2 у этих приборов значит «НЕ
СМОГЛИ ПРОВЕРИТЬ» — данных нет на диске, часть цен не показана, ключа к
каталогу не выдают, — и под `set -e` он роняет весь гейт ровно так же, как код
1, то есть настоящая порча собранного. Один такой случай уже произошёл
2026-09-07: непокрытый код 2 у `ingest_portal` остановил ВЕСЬ гейт, и «не
смогли» по данным прочиталось как провал прибора.

ПОЧЕМУ ЭТО ТЕСТ, А НЕ СТРОКА ПРАВИЛ (Ц7). Обёртка из трёх строк — ровно то,
что забывают дописать при добавлении девятого канала, и забытая она видна
только тогда, когда гейт уже покраснел не за то. Здесь она названа вслух за
миллисекунды и без сети (Т4).

НЕГАТИВНЫЙ КОНТРОЛЬ ДВУСТОРОННИЙ (И5): прибор обязан промолчать на нынешнем
`scripts/check` и сказать «нет» на подделанном тексте, где обёртку сняли.
Ожидаемое — литералы (Т2).
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]
ГЕЙТ = КОРЕНЬ / "scripts" / "check"

#: Восемь каналов сбора со своим офлайновым `--check`. Литералы (Т2): список
#: импортированный из гейта поехал бы вместе с ним и промолчал.
КАНАЛЫ: tuple[str, ...] = (
    "find_signals",
    "collect_civitai",
    "poll_catalogs",
    "ingest_portal",
    "ingest_schema",
    "discover_models",
    "recheck_vendor",
    "ingest_hf",
)


def незавёрнутые(текст: str) -> list[str]:
    """Каналы, чей `--check` зовётся без обёртки «код 2 — не провал».

    Обёрткой считается то, что видно в тексте вокруг вызова: `set +e` перед
    ним, снятие кода возврата в переменную сразу после и ветка на «= 2».
    """
    строки = текст.splitlines()
    плохие: list[str] = []
    for канал in КАНАЛЫ:
        образец = re.compile(rf"python scripts/{re.escape(канал)}\.py --check\b")
        места = [н for н, с in enumerate(строки) if образец.search(с)]
        if not места:
            плохие.append(f"{канал}: в гейте не зовётся вовсе")
            continue
        for н in места:
            до = строки[max(0, н - 2) : н]
            после = строки[н + 1 : н + 6]
            имя = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)=\$\?", после[0] if после else "")
            ветка_на_два = имя is not None and any(
                f'"${имя.group(1)}"' in с and '= "2"' in с for с in после
            )
            есть_обёртка = (
                any(с.strip() == "set +e" for с in до)
                and any(с.strip() == "set -e" for с in после)
                and ветка_на_два
            )
            if not есть_обёртка:
                плохие.append(f"{канал}: код 2 роняет гейт (строка {н + 1})")
    return плохие


class Проверка(unittest.TestCase):
    def test_гейт_на_диске_завёрнут_целиком(self):
        """Половина «прибор обязан промолчать» (И5)."""
        self.assertEqual(незавёрнутые(ГЕЙТ.read_text(encoding="utf-8")), [])

    def test_снятая_обёртка_названа_вслух(self):
        """Вторая половина: прибор, который не умеет сказать «нет», не прибор.

        Подделка ровно та, что была в дереве до 2026-09-07: строка вызова без
        `set +e` и без ветки на код 2.
        """
        текст = ГЕЙТ.read_text(encoding="utf-8")
        подделка = re.sub(
            r"set \+e\npython scripts/ingest_hf\.py --check\nHF=\$\?\nset -e\n"
            r'\[ "\$HF" = "1" \][^\n]*\n\[ "\$HF" = "2" \][^\n]*\n',
            "python scripts/ingest_hf.py --check\n",
            текст,
        )
        self.assertNotEqual(подделка, текст, "подделка не применилась — образец разъехался")
        плохие = незавёрнутые(подделка)
        self.assertEqual(len(плохие), 1)
        self.assertIn("ingest_hf", плохие[0])

    # ПЯТЫЙ ДЕФЕКТ ПРИЁМКИ, ТОТ ЖЕ КЛАСС «ЗАБЫЛИ ВПИСАТЬ ФАЙЛ В ШАГ». Восемь
    # каналов не видел НИ ОДИН из двух шагов mypy: подложенный в `ingest_hf.py`
    # вызов `load_facts("лишний", 2)` дал «Success» у обоих. Строгий шаг
    # называет файлы поимённо, и поимённый список — ровно то, что разъезжается
    # молча (Е1).
    def test_каналы_под_строгим_mypy(self):
        текст = ГЕЙТ.read_text(encoding="utf-8")
        шаг = текст.split('step "mypy (приборы гейта, strict)"', 1)
        self.assertEqual(len(шаг), 2, "строгий шаг mypy пропал из гейта")
        тело = шаг[1].split("\nstep ", 1)[0]
        for канал in КАНАЛЫ:
            with self.subTest(канал=канал):
                self.assertIn(f"scripts/{канал}.py", тело)

    def test_все_восемь_каналов_в_гейте_есть(self):
        """Р2 для самого этого теста: «нарушений 0» не значит «искали»."""
        текст = ГЕЙТ.read_text(encoding="utf-8")
        for канал in КАНАЛЫ:
            with self.subTest(канал=канал):
                self.assertIn(f"python scripts/{канал}.py --check", текст)


if __name__ == "__main__":
    unittest.main()
