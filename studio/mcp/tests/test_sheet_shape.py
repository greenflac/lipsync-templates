"""Форма контактного листа не должна выдавать источник кейса.

ЗАЧЕМ. Слепой оценщик смотрит на пиксели. Если ЛИСТ одного источника всегда
1024 пикселя шириной, а другого 768, читателю не нужно смотреть на картинку:
форма сортирует кейсы по источнику вместо содержания, и измерение перестаёт
измерять то, ради чего собрано.

ИЗМЕРЕНО 2026-09-06 независимой приёмкой: я объявил эту константу
непокрываемой «без банка» — и ошибся. Шаг гейта действительно отвечает «не
смогли» (банка на машине нет), но развилка ВЫНЕСЕНА функцией именно затем,
чтобы её можно было проверить на четырёх наблюдениях в памяти (Т5).

Ожидаемое — литералы (Т2), диска и сети нет (Т4).
"""

from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path

_SPEC = importlib.util.spec_from_file_location(
    "check_sheet_shape", Path(__file__).resolve().parents[3] / "scripts" / "check_sheet_shape.py"
)
assert _SPEC and _SPEC.loader
форма = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(форма)

#: Четыре наблюдения, два источника: доля сортирующих признак «ширина» ровно
#: 0.25 — то есть РОВНО допуск, и это край, на котором стоит решение.
ЧЕТВЕРТЬ = [
    ("civitai", "image", {"ширина": "1024", "высота": "1024"}),
    ("civitai", "image", {"ширина": "768", "высота": "1024"}),
    ("openfake", "image", {"ширина": "768", "высота": "1024"}),
    ("openfake", "image", {"ширина": "768", "высота": "1024"}),
]

#: Тот же набор, но признак сортирует ПОЛОВИНУ разборов: выше допуска.
ПОЛОВИНА = [
    ("civitai", "image", {"ширина": "1024", "высота": "1024"}),
    ("civitai", "image", {"ширина": "1280", "высота": "1024"}),
    ("openfake", "image", {"ширина": "768", "высота": "1024"}),
    ("openfake", "image", {"ширина": "768", "высота": "1024"}),
]


class ФормаНеДолжнаСортироватьПоИсточнику(unittest.TestCase):
    def test_допуск_названо_числом(self):
        self.assertEqual(0.25, форма.TOLERATED_UNIQUE)

    def test_на_самом_допуске_ещё_годно(self):
        """Граница снизу (Т3): сравнение строгое, ровно допуск — не течь."""
        self.assertEqual("pass", форма.check(ЧЕТВЕРТЬ)["outcome"])

    def test_выше_допуска_уже_течь(self):
        """Граница сверху. Между этими двумя фикстурами и стоит константа."""
        итог = форма.check(ПОЛОВИНА)
        self.assertEqual("fail", итог["outcome"])
        self.assertEqual(1, итог["violations"])
        self.assertIn("image: ширина", итог["протекают"])

    def test_среда_с_одним_источником_это_третий_исход(self):
        """Р1: при одном источнике любое значение «сортирует» тривиально, и
        считать это течью значит красить гейт на пустом месте."""
        итог = форма.check([("civitai", "video", {"ширина": "1024"})])
        self.assertEqual("could not measure", итог["outcome"])
        self.assertEqual(0, итог["violations"])
        self.assertGreaterEqual(итог["unmeasured"], 1)

    def test_числа_печатаются_рядом_с_вердиктом(self):
        """Р2: ноль нарушений при нуле проверенных — не успех, и по отчёту это
        обязано быть видно."""
        итог = форма.check(ПОЛОВИНА)
        self.assertEqual(4, итог["checked"])
        self.assertIn("допуске", итог["note"])
        self.assertIsNotNone(итог["worst"])


if __name__ == "__main__":
    unittest.main()
