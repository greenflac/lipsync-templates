"""У ответа заказчику есть строка «что дальше», а не только телеметрия.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой. Главное поле ответа на
обычном брифе:

    "outcome": "fail",
    "note": "валидатор-2 отверг план: слабейшее звено: липсинк — применимость;
             шагов 3, без кандидата 0, кандидат без применимости 1, дороже
             потолка 0, проверенный вытеснен ценой 0, проверенных нет вовсе 1,
             кадр не принимают 0, вход запрещён 0, уже снятых выбрано 0,
             выход не тот 0",
    "question": null

Заказчик видит `fail`, девять нулей и ни одного действия. При этом `fail`
означает не «нельзя сделать», а «у выбранной модели записан ОДИН случай, где
шаг ломается» — план работоспособен, а вердикт читается как отказ.

СТРОКА СТРОИТСЯ ИЗ ИЗМЕРЕННОГО. Ниже проверено, что она не выдумывает: где
записи о поломке нет — там нет и обещаний.

Т2: ожидаемое — литералы. Т4: сети нет.
"""

from __future__ import annotations

import unittest

from studio.planner import PASS, что_дальше


class СтрокаБерётсяИзИзмеренного(unittest.TestCase):
    def test_измеренный_провал_назван_и_показан_выход(self) -> None:
        итог = {
            "outcome": "fail",
            "classes": ["применимость"],
            "steps": [
                {
                    "step": "липсинк",
                    "alternatives": [{}, {}],
                    "chosen": {
                        "model": "sync-lipsync",
                        "against": 1,
                        "evidence": [{"attribute": "failure_mode", "value": "рот вставленный"}],
                    },
                }
            ],
        }
        строка = что_дальше(итог)
        self.assertIn("липсинк", строка)
        self.assertIn("sync-lipsync", строка)
        self.assertIn("рот вставленный", строка)
        self.assertIn("их 2", строка, "число живых альтернатив берётся из ответа")

    def test_применимость_не_мерена_это_другой_совет(self) -> None:
        """Р1: «плохо» и «неизвестно» — разные новости, и советы к ним разные."""
        строка = что_дальше(
            {
                "outcome": "fail",
                "classes": ["применимость"],
                "steps": [
                    {
                        "step": "озвучка",
                        "chosen": {"model": "x", "against": 0, "mark": "применимость не измерена"},
                    }
                ],
            }
        )
        self.assertIn("никто не мерил", строка)
        self.assertIn("озвучка", строка)
        self.assertNotIn("провал", строка)

    def test_шаги_не_выведены_совет_про_бриф(self) -> None:
        строка = что_дальше({"outcome": "could not measure", "reason": "шаги_не_выведены"})
        self.assertIn("назовите, что нужно сделать", строка)


class ГдеСказатьНЕЧЕГО_МОЛЧИМ(unittest.TestCase):
    """Вторая сторона (И5): совет, выданный без данных, — это выдумка, и она
    дороже молчания. Прибор, у которого строка есть всегда, не измеряет ничего.
    """

    def test_годный_план_советов_не_получает(self) -> None:
        """ФИКСТУРА С НАСТОЯЩЕГО КРАЯ (Т3), И ПЕРВАЯ БЫЛА НЕ ОТТУДА.
        Мутация «советовать и на годном плане» её НЕ красила: в первой
        редакции у годного плана не было шагов, и совет всё равно выходил
        пустым по другой причине. Здесь у плана есть и класс, и шаг с
        записанным провалом — то есть всё, из чего совет строится, — и
        молчание обеспечивается ИМЕННО исходом.
        """
        годный = {
            "outcome": PASS,
            "classes": ["применимость"],
            "steps": [
                {
                    "step": "липсинк",
                    "alternatives": [{}],
                    "chosen": {
                        "model": "sync-lipsync",
                        "against": 1,
                        "evidence": [{"attribute": "failure_mode", "value": "рот вставленный"}],
                    },
                }
            ],
        }
        self.assertEqual("", что_дальше(годный))

    def test_чужой_класс_отказа_без_данных_молчит(self) -> None:
        self.assertEqual("", что_дальше({"outcome": "fail", "classes": ["лицензия"], "steps": []}))

    def test_есть_вопрос_и_нет_класса_отсылаем_к_вопросу(self) -> None:
        строка = что_дальше(
            {"outcome": "could not measure", "classes": [], "question": {"text": "видео есть?"}}
        )
        self.assertIn("ответьте на вопрос", строка)


class ЧеловекВидитЭтоНаПервомЭкране(unittest.TestCase):
    """П3: строка печатается, а не только лежит в ответе."""

    def test_строка_есть_в_выдаче_и_стоит_до_шагов(self) -> None:
        from studio.planner import plan, render

        текст = render(plan("нужен ролик, женщина говорит в камеру, 15 секунд, для кофейни"))
        self.assertIn("ЧТО ДАЛЬШЕ:", текст)
        строки = текст.split("\n")
        место_совета = next(i for i, с in enumerate(строки) if с.startswith("ЧТО ДАЛЬШЕ:"))
        место_шагов = next(i for i, с in enumerate(строки) if с.strip().startswith("шаг "))
        self.assertLess(место_совета, место_шагов, "совет ниже шагов читатель не увидит")


if __name__ == "__main__":
    unittest.main()
