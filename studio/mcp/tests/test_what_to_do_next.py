class ЧеловекВидитЭтоНаПервомЭкране(unittest.TestCase):
    """П3: строка печатается, а не только лежит в ответе."""

    def test_строка_есть_в_выдаче_и_стоит_до_шагов(self) -> None:
        from studio.planner import plan, render

        текст = render(plan("нужен ролик, женщина говорит в камеру, 15 секунд, для кофейни"))
        self.assertIn("ЧТО ДАЛЬШЕ:", текст)
        строки = текст.split("\n")
        место_совета = next(i for i, с in enumerate(строки) if с.startswith("ЧТО ДАЛЬШЕ:"))
        место_шагов = next(i for i, с in enumerate(строки) if с.strip().startswith("шаг "))
        self.assertLess(место_совета, место_шагов, "совет ниже шагов читатель не увидит")


if __name__ == "__main__":
    unittest.main()


class ПланНеСтроитсяНаНевидимомВходе(unittest.TestCase):
    """Заказчик назвал видео, файла по пути нет — план останавливается вопросом.

    ВОСПРОИЗВЕДЕНО продуктовой проверкой 2026-09-07: бриф «у меня есть своё
    видео» с несуществующим путём давал план из ДВУХ шагов и строку «креатив
    не измерен». Хуже того, `inputs_of` выводит «видео у заказчика ЕСТЬ» из
    РАСШИРЕНИЯ СТРОКИ — то есть план не молчал, а утверждал наличие исходника
    и снимал шаг съёмки.

    Цена правки измерена, а не предположена: на голден-сете 45 задач, с файлом
    из них 5, и все пять файлов существуют — ветка не срабатывает ни разу.
    """

    ПУТИ_НЕТ = "/home/user/lipsync-templates/assets/нет-такого-файла.mp4"

    def _план(self, путь: str) -> dict:
        from studio.planner import plan

        return plan(
            "у меня есть своё видео, переозвучить и попасть в губы, 12 секунд", creative=путь
        )

    def test_несуществующий_файл_останавливает_план_вопросом(self) -> None:
        итог = self._план(self.ПУТИ_НЕТ)
        self.assertEqual("could not measure", итог["outcome"], итог["note"])
        self.assertEqual("нужен_ответ_заказчика", итог["reason"])
        self.assertEqual([], итог["steps"], "шаги на невидимом входе не строятся")
        self.assertIn("файла по этому пути нет", (итог.get("question") or {})["text"])

    def test_и_сказано_что_делать(self) -> None:
        self.assertIn("поправьте путь", self._план(self.ПУТИ_НЕТ)["что_дальше"])

    def test_настоящий_файл_план_строит(self) -> None:
        """Вторая сторона (И5): прибор, останавливающий всё, ничего не решает."""
        from pathlib import Path

        файлы = sorted(Path("studio/fixtures").glob("*.png"))
        self.assertTrue(файлы, "фикстур нет — проверять нечем")
        итог = self._план(str(файлы[0]))
        self.assertNotEqual("нужен_ответ_заказчика", итог["reason"], итог["note"])
        self.assertTrue(итог["steps"], "на настоящем файле шаги обязаны быть")

    def test_креатив_не_назван_вовсе_это_не_отсутствие_файла(self) -> None:
        """Третий случай: заказчик ничего не приносил — и это не ошибка пути."""
        итог = self._план("")
        self.assertNotEqual("нужен_ответ_заказчика", итог.get("reason"))
