"""Имя ценового атрибута обязано называть ЕДИНИЦУ, которую читает разборщик.

ЗАЧЕМ. Имя `price_per_...` ОБЕЩАЕТ единицу. Если разборщик её не читает, строка
для продукта невидима: цена не сравнится с бюджетом шага и не войдёт в сумму
пайплайна — при этом в отчётах о размере базы она есть.

НАЙДЕНО НА СВОЕЙ ЖЕ ЗАПИСИ 2026-09-04. Я записал цену ElevenLabs как
`price_per_1000_characters_usd`, тогда как база называет это свойство
`price_per_1000_chars` (8 строк против моей одной). Разборщик ищет единицу
подстрокой, `1000_chars` в `1000_characters` не входит — и строка выпала из
всего. Отозвана и записана заново по конвенции; этот тест — сторож, чтобы
следующее такое имя нашлось машиной, а не через день.

Т2: ожидаемое — литералы. Т4: сеть не нужна, база читается с диска.
"""

from __future__ import annotations

import collections
import unittest

from studio import pricing
from studio.selfrag.facts import load_facts

#: Имена, которые обещают единицу и не называют её. ДОЛГ, А НЕ РАЗРЕШЕНИЕ:
#: список закрытый, и каждое имя здесь — строки, невидимые продукту.
#:
#: `price_per_million_input_usd` (ИЗМЕРЕНО: 6 строк) — цена за миллион входных
#: ТОКЕНОВ, и слова `token` в имени нет. Читать её как «за миллион» нельзя:
#: миллион чего — из имени не следует, а поставить это число рядом с бюджетом
#: шага значило бы сложить разное, ровно как с кредитами вендора. Чинится
#: переименованием строк канала, а не правкой разборщика.
ДОЛГ = {"price_per_million_input_usd"}


class ЦеновоеИмяНазываетЕдиницу(unittest.TestCase):
    def test_каждое_price_per_читается_разборщиком(self) -> None:
        немые: collections.Counter[str] = collections.Counter()
        for факт in load_facts():
            имя = факт.attribute.lower()
            if not имя.startswith("price_per_") or имя in ДОЛГ:
                continue
            if not pricing.parse(str(факт.value), факт.attribute).per:
                немые[факт.attribute] += 1
        self.assertEqual(
            {},
            dict(немые),
            "имя обещает единицу, а разборщик её не читает: строка невидима продукту",
        )

    def test_долг_назван_поимённо_и_он_настоящий(self) -> None:
        """И5: список долга обязан описывать то, что в базе ЕСТЬ.

        Иначе он тихо станет свалкой имён, которых давно нет, и перестанет
        что-либо значить.
        """
        живые = {ф.attribute for ф in load_facts()}
        for имя in ДОЛГ:
            self.assertIn(имя, живые, f"{имя} в долге, но в базе его нет")

    def test_конвенционное_имя_читается(self) -> None:
        """Положительный контроль: прибор обязан ШЕВЕЛИТЬСЯ, а не только молчать."""
        разбор = pricing.parse("0.1", "price_per_1000_chars")
        self.assertEqual("1000_chars", разбор.per)
        self.assertEqual("usd", разбор.unit)

    def test_имя_с_другим_написанием_единицы_НЕ_читается(self) -> None:
        """Тот самый случай: `1000_characters` не содержит `1000_chars`."""
        self.assertEqual("", pricing.parse("0.1", "price_per_1000_characters_usd").per)


if __name__ == "__main__":
    unittest.main()
