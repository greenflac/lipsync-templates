"""Мутационный прогон обязан ВЛИЯТЬ на код возврата — иначе он украшение.

ВОСПРОИЗВЕДЕНО 2026-09-05 независимым аудитом. `scripts/mutate_planner.py`
печатал «ПРОМОЛЧАЛИ: …» и заканчивался безусловным `return 0`. Это самый
большой мутационный набор проекта (113 мутантов), он гоняется ТОЛЬКО в CI
(`scripts/check`: `if [ "$CI" = "true" ]`), и покраснеть он не мог никогда:

    мутантов 1, промолчали на 1
      ПРОМОЛЧАЛИ: контрольный молчащий мутант
    rc = 0

Сосед `scripts/mutate_channels.py` в тот же день возвращал `1 if молчали else 0`.
Одно правило, два разных исполнения — и живёт то, которое ничего не требует.

ЧЕМ ЭТО ОПАСНО. Сторож константы-решения планировщика можно снять, и гейт
останется зелёным: таблица напечатает «НИКТО — константу не сторожат», CI
скажет «пройдено». Ровно тот случай, ради которого правило Т6 говорит, что
пропущенное — не пройденное.

ТУТ ПРОВЕРЯЕТСЯ КОД ВОЗВРАТА, А НЕ ПЕЧАТЬ. Печать была правильной и до
починки — она и создавала впечатление работающего прибора.
"""

from __future__ import annotations

import subprocess
import sys
import textwrap
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]

#: Литералы (Т2): договор с гейтом — ноль значит «все мутанты пойманы».
ВСЕ_ПОЙМАНЫ = 0
КТО_ТО_ПРОМОЛЧАЛ = 1


def _прогон(скрипт: str, подмена: str) -> int:
    """Запустить мутатор с ОДНИМ мутантом, подменённым на заведомо молчащий."""
    код = textwrap.dedent(f"""
        import runpy, sys
        from pathlib import Path
        sys.path.insert(0, {str(КОРЕНЬ / "scripts")!r})
        import {скрипт} as м
        # один мутант, который заведомо никто не сторожит: подменяем строку,
        # которой нет ни в одном исходнике, — прибор обязан назвать его
        # промолчавшим И вернуть ненулевой код.
        м.MUTANTS = [{подмена}]
        sys.exit(м.main())
    """)
    готово = subprocess.run([sys.executable, "-c", код], cwd=КОРЕНЬ, capture_output=True, text=True)
    return готово.returncode


class МутаторКраснеет(unittest.TestCase):
    def test_планировщик_возвращает_ненуль_на_промолчавшем(self) -> None:
        rc = _прогон(
            "mutate_planner",
            '("studio/planner.py", "СТРОКИ-КОТОРОЙ-НЕТ", "ЗАМЕНА", "контрольный молчун")',
        )
        self.assertEqual(rc, КТО_ТО_ПРОМОЛЧАЛ)

    def test_каналы_возвращают_ненуль_на_промолчавшем(self) -> None:
        """Негативный контроль (И5): у соседа это работало и обязано работать дальше."""
        rc = _прогон(
            "mutate_channels",
            '("studio/planner.py", "СТРОКИ-КОТОРОЙ-НЕТ", "ЗАМЕНА", "контрольный молчун", '
            '"studio.tests.test_planner")',
        )
        self.assertEqual(rc, КТО_ТО_ПРОМОЛЧАЛ)


if __name__ == "__main__":
    unittest.main()
