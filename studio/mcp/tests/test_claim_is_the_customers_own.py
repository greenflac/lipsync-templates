"""Заявление заказчика получает КОММЕНТАРИЙ, а не отказ и не молчание.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой: бриф «наш БАД излечивает
диабет за две недели, липсинк, 20 секунд» проходил просев, собирал три шага и
получал замечание только про применимость модели. Ни строки о том, что заказан
ролик с утверждением, за которое в рекламе отвечают по закону.

ТРИ СТОРОНЫ ПРОВЕРЯЮТСЯ ВМЕСТЕ, И ЭТО ГЛАВНОЕ. Отдельно каждую легко
удовлетворить неправильно: «предупреждает» — отказом; «не отказывает» —
молчанием. Здесь обе стороны в одном наборе, плюс негативный контроль (И5) на
честном брифе о медицине, где предупреждения быть НЕ ДОЛЖНО.
"""

from __future__ import annotations

import json
import unittest

from studio.mcp import screen, server


def _план(бриф: str) -> dict:
    return json.loads(server.plan_pipeline(бриф))


ЗАЯВЛЕНИЕ = "Ролик: наш БАД излечивает диабет за две недели, липсинк, 20 секунд"
ЧЕСТНЫЙ = "Ролик для клиники: врач рассказывает о приёме, липсинк, 20 секунд"


class ЗаявлениеКомментируется(unittest.TestCase):
    def test_медицинское_заявление_названо(self) -> None:
        итог = screen.просеять(ЗАЯВЛЕНИЕ)
        self.assertEqual(1, итог["risky"])
        self.assertEqual(["medical claim: диабет + излечива"], итог["risks"])

    def test_заявление_НЕ_отказ(self) -> None:
        """Ложный отказ здесь дороже пропуска: студия не судит о медицине."""
        итог = screen.просеять(ЗАЯВЛЕНИЕ)
        # Литералы, а не импорт из проверяемого модуля (Т2).
        self.assertEqual("pass", итог["outcome"])
        self.assertEqual(0, итог["violations"])
        self.assertEqual([], итог["banned"])

    def test_предупреждение_видно_в_ноте(self) -> None:
        нота = screen.просеять(ЗАЯВЛЕНИЕ)["note"]
        self.assertIn("отвечает заказчик", нота)
        self.assertIn("диабет", нота)

    def test_предупреждение_ничего_не_говорит_об_исходе(self) -> None:
        """Первая редакция писала «План собран, работа не отклонена» — на
        ответе, где план как раз отвергнут валидатором."""
        текст = screen.предупреждение(["medical claim: диабет + излечива"])
        self.assertNotIn("План собран", текст)

    def test_финансовое_заявление_тоже(self) -> None:
        итог = screen.просеять("гарантируем доход 200% в месяц на крипте")
        self.assertEqual(["financial claim: доход + гарантиру"], итог["risks"])

    def test_английское_заявление_тоже(self) -> None:
        итог = screen.просеять("our supplement cures cancer, doctor recommends it")
        self.assertEqual(1, итог["risky"])


class НегативныйКонтроль(unittest.TestCase):
    """И5: вход, где прибор обязан промолчать. Без него список ловит что попало."""

    ТИХИЕ = (
        ЧЕСТНЫЙ,
        "Ролик про новый крем, говорящий аватар, 20 секунд",
        "Обучающий ролик: врач рассказывает, как работает наш прибор",
        "Ролик про инвестиции в наш фонд: ведущий зачитывает условия",
        "Реклама средства для суставов: показываем упаковку и цену",
    )

    def test_один_предмет_без_утверждения_молчит(self) -> None:
        шумят = [т for т in self.ТИХИЕ if screen.просеять(т)["risky"]]
        self.assertEqual([], шумят)

    def test_счёт_проверок_вырос_вместе_с_проверкой(self) -> None:
        """Р2: проверка, которой нет в `checked`, читается как непроведённая."""
        self.assertEqual(4, screen.просеять("тёплый янтарный свет")["checked"])

    def test_поле_есть_и_на_пустом_тексте(self) -> None:
        итог = screen.просеять("")
        self.assertEqual([], итог["risks"])
        self.assertEqual(0, итог["risky"])


class ПродуктГоворитЭтоЗаказчику(unittest.TestCase):
    """Проверка в модуле ничего не стоит, если продукт её не печатает."""

    def test_план_несёт_предупреждение(self) -> None:
        итог = _план(ЗАЯВЛЕНИЕ)
        self.assertEqual(["medical claim: диабет + излечива"], итог["risks"])
        self.assertIn("отвечает заказчик", итог["note"])

    def test_план_всё_же_собран(self) -> None:
        self.assertTrue(_план(ЗАЯВЛЕНИЕ)["steps"])

    def test_честный_бриф_предупреждения_не_получает(self) -> None:
        """ПОЛЕ ЕСТЬ ВСЕГДА, А ПУСТО ОНО ИЛИ НЕТ — ЭТО И ЕСТЬ НОВОСТЬ.

        Утверждение переписано 2026-09-07 после седьмой приёмки: прежняя
        редакция требовала ОТСУТСТВИЯ поля на честном брифе, то есть ровно
        того, что `screen.просеять` в своём докстринге запрещает — поле,
        появляющееся через раз, вызывающий читает через `.get`, и молчание
        становится неотличимо от «нечего сказать». Тест сторожил дефект.
        """
        итог = _план(ЧЕСТНЫЙ)
        self.assertIn("risks", итог)
        self.assertEqual([], итог["risks"])
        self.assertEqual(0, итог["risky"])
        self.assertNotIn("отвечает заказчик", итог["note"])

    def test_четвёртая_проверка_попадает_в_счёт_ответа(self) -> None:
        """Р2: проверка, которой нет в `checked`, читается как непроведённая.

        УТВЕРЖДЕНИЕ ПЕРЕПИСАНО 2026-09-07 ПОСЛЕ ВОСЬМОЙ ПРИЁМКИ: прежняя
        редакция сравнивала `x > x - screen.ПРОВЕРОК`, то есть была ИСТИННА
        ВСЕГДА, да ещё и брала ожидаемое из проверяемого пакета (Т2). Обе
        мутации счёта — «не прибавлять» и «прибавить лишнее» — на ней молчали.

        Теперь ожидаемое — литерал: четыре проверки просева плюс проверки
        валидатора, которых на честном плане ровно столько, сколько их шагов
        умножено на число оракулов. Второе число берётся у самого ответа, а
        сверяется РАЗНОСТЬ: она обязана быть равна четырём.
        """
        итог = _план(ЧЕСТНЫЙ)
        отчёт = итог.get("validator") or {}
        валидатором = int(отчёт.get("checked") or 0)
        self.assertEqual(4, итог["checked"] - валидатором)


if __name__ == "__main__":
    unittest.main()
