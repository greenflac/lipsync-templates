class ЗаказчикНазываетРезультат(unittest.TestCase):
    """Вход «с нуля» из задачи владельца: у человека нет ничего, и операций он
    не называет. ИЗМЕРЕНО 2026-09-03: до этих подсказок 8 из 10 таких брифов
    давали ПУСТОЙ план."""

    def test_говорящий_аватар_даёт_три_шага(self):
        бриф = "Нужен говорящий аватар для рекламы, английская речь, вертикаль под TikTok"
        self.assertEqual(
            sorted(оп.name for оп in planner.derive(бриф)),
            ["генерация_видео", "липсинк", "озвучка"],
        )

    def test_каждая_подсказка_о_результате_держит_свой_бриф(self):
        """Мутации показали, что подсказки перекрывают друг друга: убери
        `говорящ` — бриф про аватар всё равно выводит липсинк по `аватар`, и
        мутант молчит. Заслон, который нельзя наблюдать, не заслон: здесь у
        каждой подсказки бриф, где работает ТОЛЬКО она."""
        поодиночке = [
            ("Нужен говорящий персонаж в ролике", "липсинк"),
            ("Ролик по сценарию, съёмок нет", "генерация_видео"),
            ("Ведущий зачитывает прогноз погоды", "липсинк"),
            ("Английская речь поверх готового видео", "озвучка"),
        ]
        for бриф, ждём in поодиночке:
            with self.subTest(бриф=бриф):
                self.assertIn(ждём, [оп.name for оп in planner.derive(бриф)])

    def test_съёмок_нет_это_генерация_видео(self):
        бриф = "Реклама на 15 секунд по описанию товара, актёров и съёмок нет"
        self.assertIn("генерация_видео", [оп.name for оп in planner.derive(бриф)])

    def test_закадровый_текст_это_озвучка(self):
        бриф = "Нужен рекламный ролик с закадровым текстом по нашему сценарию"
        self.assertIn("озвучка", [оп.name for оп in planner.derive(бриф)])


class СчётчикМеритТоЧтоНадо(unittest.TestCase):
    def test_опечатка_в_ожидании_это_третий_исход(self):
        """Имя операции, которого в планировщике нет, тихо раздувает дыру:
        счётчик рапортует о непокрытом брифе, который на самом деле покрыт.
        Поймано на себе при первом прогоне."""
        итог = cbc.свести(
            [{"бриф": "озвучить текст", "ждём": ["перевод_речи"], "как_сказано": "операциями"}]
        )
        self.assertEqual(итог["outcome"], "could not measure")
        self.assertEqual(итог["неизвестные"], ["перевод_речи"])

    def test_операция_на_чужой_задаче_это_нарушение(self):
        итог = cbc.свести([{"бриф": "нужна озвучка", "ждём": [], "как_сказано": "мимо"}])
        self.assertEqual((итог["outcome"], итог["violations"]), ("fail", 1))

    def test_пустой_план_на_нашей_задаче_это_не_нарушение_а_третий_исход(self):
        """Р1: пустой план — честное «не знаю», лишний шаг — ложь. Свернуть их
        в один исход значило бы не различать эти две беды."""
        итог = cbc.свести(
            [{"бриф": "нужен вектор логотипа", "ждём": ["озвучка"], "как_сказано": "результатом"}]
        )
        self.assertEqual(
            (итог["outcome"], итог["violations"], итог["unmeasured"]),
            (
                "could not measure",
                0,
                1,
            ),
        )

    def test_контроль_в_наборе_есть_и_он_не_пустой(self):
        """И5: без брифов «мимо» покрытие 100% берётся строкой «выводить всё
        всегда», и счётчик перестаёт мерить."""
        набор = cbc.фикстуры()
        мимо = [с for с in набор if с["как_сказано"] == "мимо"]
        self.assertGreaterEqual(len(мимо), 8)
        self.assertTrue(all(с["ждём"] == [] for с in мимо))

    def test_живой_набор_без_лжи(self):
        итог = cbc.свести(cbc.фикстуры())
        self.assertEqual(итог["violations"], 0, итог["лишние"])


if __name__ == "__main__":
    unittest.main()
