    def test_права_на_голос_не_озвучка(self):
        бриф = "Проверить, не нарушает ли наш ролик права на голос актёра"
        self.assertEqual([оп.name for оп in planner.derive(бриф)], [])

    def test_оживить_фото_по_прежнему_оживление(self):
        """Негативный контроль к заслону (И5): заслон обязан НЕ мешать своей
        же операции, иначе «нарушений 0» достигается выключением подсказки."""
