"""Голден-сет задач и его оценщик: что обязано держаться у самого прибора.

Т2: ожидаемое — литералы. Имена видов проверок и слова исходов написаны
руками, а не импортированы из проверяемого модуля.
"""

from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[3]


def _модуль():
    сп = importlib.util.spec_from_file_location(
        "check_golden", КОРЕНЬ / "scripts" / "check_golden.py"
    )
    м = importlib.util.module_from_spec(сп)
    assert сп.loader is not None
    сп.loader.exec_module(м)
    return м


g = _модуль()


class СхемаНабора(unittest.TestCase):
    def test_каждая_строка_называет_все_поля(self) -> None:
        for з in g.задачи():
            for поле in ("id", "класс", "ждём", "задача", "канал", "вход", "оценка", "почему"):
                self.assertIn(поле, з, f"{з.get('id')}: нет поля {поле}")

    def test_ждём_только_из_двух_значений(self) -> None:
        self.assertEqual(sorted({з["ждём"] for з in g.задачи()}), ["сейчас", "цель"])

    def test_оценка_только_из_двух_значений(self) -> None:
        self.assertLessEqual({з["оценка"] for з in g.задачи()}, {"машинная", "глазами"})

    def test_идентификаторы_не_повторяются(self) -> None:
        имена = [з["id"] for з in g.задачи()]
        self.assertEqual(len(имена), len(set(имена)))

    def test_ни_одного_неизвестного_вида_проверки(self) -> None:
        """Опечатка в виде тихо превращает строку в пройденную."""
        self.assertEqual([], g.неизвестные_виды(g.задачи()))

    def test_у_каждого_контроля_есть_обратная_сторона(self) -> None:
        """И5: прибор, у которого нет второй стороны, меряет одно слово.

        Кадр: 1080x1920 обязан отвергаться пределом, 640x360 — нет.
        Снятие: у одной модели выключение позади, у другой впереди.
        """
        по_классам: dict[str, list[dict]] = {}
        for з in g.задачи():
            по_классам.setdefault(з["класс"], []).append(з)
        for класс in ("кадр", "снятая-модель"):
            строки = по_классам.get(класс, [])
            self.assertEqual(2, len(строки), f"у класса {класс} нет обратной стороны")
            запрещено = [п for з in строки for п in з.get("запрещено", [])]
            self.assertTrue(запрещено, f"у класса {класс} обе стороны только утверждают")

    def test_фикстуры_кадра_лежат_на_месте(self) -> None:
        """Задача, ссылающаяся на файл, которого нет, тихо перестаёт мерить."""
        for з in g.задачи():
            путь = (з.get("вход") or {}).get("creative")
            if путь:
                self.assertTrue((КОРЕНЬ / путь).is_file(), f"{з['id']}: нет файла {путь}")

    def test_набор_держит_обе_стороны(self) -> None:
        """Т3: и то, что продукт обязан делать, и то, чего обязан не делать."""
        классы = {з["класс"] for з in g.задачи()}
        self.assertIn("не-наша-задача", классы)
        self.assertIn("выдуманное-имя", классы)


class НегативныйКонтрольПрибора(unittest.TestCase):
    def test_здоровый_набор_без_холостых_проверок(self) -> None:
        self.assertEqual([], g.холостые(g.задачи()))

    def test_холостая_проверка_ловится(self) -> None:
        """И2: подсаживается проверка, которая проходит на КАЖДОМ плане.

        «бриф:» печатает первой строкой любой план, со шагами и без. Такая
        проверка не различает ничего и обязана быть названа.
        """
        набор = g.задачи()
        планы = [з for з in набор if з["канал"] == "plan" and з["оценка"] == "машинная"]
        подсадной = dict(планы[0])
        подсадной["id"] = "ПОДСАДНОЙ"
        подсадной["обязано"] = [{"вид": "в_тексте", "что": "бриф:"}]
        беды = g.холостые(набор + [подсадной])
        self.assertEqual(1, len(беды), беды)
        self.assertIn("ПОДСАДНОЙ", беды[0])

    def test_граница_контроля_записана_а_не_замазана(self) -> None:
        """И6: контроль НЕ ловит проверку, проходящую лишь на однородной части
        канала. Дефект g29 («дороже потолка») нашли глаза, а не он."""
        набор = g.задачи()
        планы = [з for з in набор if з["канал"] == "plan" and з["оценка"] == "машинная"]
        подсадной = dict(планы[0])
        подсадной["id"] = "ПОДСАДНОЙ-2"
        подсадной["обязано"] = [{"вид": "в_тексте", "что": "дороже потолка"}]
        self.assertEqual([], g.холостые(набор + [подсадной]))


class ЖивойПрогон(unittest.TestCase):
    """Голден-сет прогоняется НАБОРОМ ТЕСТОВ, а не только гейтом.

    Зачем дублировать шаг гейта: мутационные прогоны
    (`scripts/mutate_channels.py`) гоняют модули тестов, а не скрипты. Без
    этого теста ни одна подмена константы в продукте не покраснела бы через
    голден-сет, и набор сторожил бы только сам себя.

    Числа задач тут НЕ проверяются: набор растёт, и тест на его размер краснел
    бы от пополнения. Проверяется единственное, что обязано держаться всегда:
    ни одного РЕГРЕССА и ни одной холостой проверки.
    """

    def test_ни_одного_регресса_и_ни_одной_холостой_проверки(self) -> None:
        итог = g.свести(g.задачи())
        self.assertEqual([], итог["холостые"])
        провалы = [с["id"] for с in итог["строки"] if с["исход"] == "fail"]
        цели = set(итог["цели открыты"])
        self.assertEqual([], [i for i in провалы if i not in цели])


