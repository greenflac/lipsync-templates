"""Короткий список подсказок: перекос считается долями и требует трёх упоминаний.

ЗАЧЕМ. Скрипт ищет слова, чаще встречающиеся у ВЕРНЫХ чтений банка, и сам
говорит вслух, что это подсказка, а не находка. Но подсказка из одного
упоминания — это не подсказка, а совпадение, и список, полный совпадений,
читается как результат.

ИЗМЕРЕНО 2026-09-06: развилка жила внутри `main` и была достижима только через
настоящий прогон банка (файлов которого в репозитории нет), а `MIN_MENTIONS = 1`
держал все три набора зелёными. Развилка вынесена функцией (Т5).

Ожидаемое — литералы (Т2), диска и сети нет (Т4).
"""

from __future__ import annotations

import collections
import importlib.util
import unittest
from pathlib import Path

_SPEC = importlib.util.spec_from_file_location(
    "find_signals", Path(__file__).resolve().parents[3] / "scripts" / "find_signals.py"
)
assert _SPEC and _SPEC.loader
сигналы = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(сигналы)


def счётчик(**слова) -> collections.Counter:
    return collections.Counter(слова)


class ПерекосСчитаетсяДолями(unittest.TestCase):
    def test_слово_у_верных_чаще_попадает_в_список(self):
        найдено = сигналы.перекошенные(счётчик(мыло=6), счётчик(мыло=1), 10, 10)
        self.assertEqual(["мыло"], [с[0] for с in найдено])

    def test_равномерное_слово_подсказкой_не_считается(self):
        """Негативный контроль (И5): список, куда попадает всё, — не список."""
        self.assertEqual([], сигналы.перекошенные(счётчик(кадр=5), счётчик(кадр=5), 10, 10))

    def test_два_упоминания_это_ещё_шум(self):
        """Граница снизу (Т3) — ровно та, которую подмена делала невидимой."""
        self.assertEqual([], сигналы.перекошенные(счётчик(мыло=2), счётчик(), 10, 10))

    def test_три_упоминания_уже_подсказка(self):
        """Та же граница сверху."""
        self.assertEqual(
            ["мыло"], [с[0] for с in сигналы.перекошенные(счётчик(мыло=3), счётчик(), 10, 10)]
        )

    def test_пороги_названы_числами(self):
        self.assertEqual(3, сигналы.MIN_MENTIONS)
        self.assertEqual(1.5, сигналы.ПЕРЕВЕС)

    def test_перекос_нормируется_на_размер_стороны(self):
        """Пять упоминаний из десяти верных и три из трёх неверных — это не
        перекос в пользу верных, хотя счётчик больше. Считать надо ДОЛИ."""
        self.assertEqual([], сигналы.перекошенные(счётчик(мыло=5), счётчик(мыло=3), 10, 3))

    def test_разрыв_печатается_числом_а_не_флагом(self):
        ((слово, у_верных, у_неверных, разрыв),) = сигналы.перекошенные(
            счётчик(мыло=6), счётчик(мыло=1), 10, 10
        )
        self.assertEqual(("мыло", 6, 1), (слово, у_верных, у_неверных))
        self.assertAlmostEqual(0.5, разрыв, places=3)


if __name__ == "__main__":
    unittest.main()
