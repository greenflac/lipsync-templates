"""Молчание базы о пределе длительности — не согласие модели его взять.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой, бриф «ролик 60 секунд,
женщина говорит в камеру, делаем с нуля»:

    шаг генерация_видео -> hunyuan-video
        длительность: предел длительности не записан
        ролик перерос предел у 9 кандидат(ов) из 51
        оси без ответа (это НЕ «разрешено»): вход, срок службы

Девять кандидатов с ЗАПИСАННЫМ пределом ушли в конец как «слишком длинные»,
победила модель, у которой предела нет вовсе, — и в списке молчащих осей
длительности НЕ БЫЛО. То есть молчание продавалось как согласие ровно там,
где оно решало.

Соседняя ось этого не допускает и говорит вслух: «о запрете на вход в базе не
сказано ни строки из 18: это НЕ разрешение». И7: правило чинится во всех
местах своей формы, а не в одном.

Т2: ожидаемое — литералы. Т4: сети нет.
"""

from __future__ import annotations

import unittest

from studio import duration as dur
from studio.planner import оси_без_ответа


class МолчаниеОПределеНазвано(unittest.TestCase):
    def test_предел_не_записан_ось_молчит(self) -> None:
        self.assertIn("длительность", оси_без_ответа({"dur_state": dur.DUR_ABSENT}))

    def test_записанный_предел_ось_не_молчит(self) -> None:
        """Вторая сторона (И5): прибор, объявляющий молчащими все оси, ничего
        не различает. «Принимает» — это ответ, и он не попадает в список."""
        self.assertNotIn("длительность", оси_без_ответа({"dur_state": dur.DUR_IN}))
        self.assertNotIn("длительность", оси_без_ответа({"dur_state": dur.DUR_OVER}))

    def test_молчание_о_брифе_тоже_названо_но_это_другое(self) -> None:
        """Р1: три разных молчания. Два — про модель, одно — про бриф, и они
        лечатся разным: одно сбором, другое вопросом заказчику."""
        for состояние in (dur.DUR_NOT_ASKED, dur.DUR_ASK_UNPARSED):
            self.assertIn("длительность", оси_без_ответа({"dur_state": состояние}))


class ПродуктГоворитЭтоЧеловеку(unittest.TestCase):
    """П3: то, что увидит заказчик, а не только то, что вернёт функция."""

    def test_на_шестидесяти_секундах_длительность_среди_молчащих(self) -> None:
        from studio.planner import plan, render

        текст = render(plan("ролик 60 секунд, женщина говорит в камеру, делаем с нуля"))
        строки = [с for с in текст.split("\n") if "оси без ответа" in с]
        self.assertTrue(строки, текст[:400])
        # `any`, А НЕ `all`, И ЭТО ИЗМЕРЕННОЕ ПОСЛАБЛЕНИЕ (2026-09-07).
        # `all` требовал, чтобы база молчала о длительности у ВСЕХ кандидатов
        # разом — и покраснел от честно записанного нового факта
        # (`elevenlabs-tts-eleven-v3.max_seconds = 300`): у одного кандидата
        # ось перестала молчать, и это ровно та работа, ради которой база
        # ведётся. Требование «база молчит везде» сторожило состояние базы, а
        # не поведение прибора. Что сторожится теперь: молчащая ось названа
        # молчащей, а не подана как «разрешено». Мутант, стирающий
        # `оси_без_ответа`, оставляет список пустым и краснеет и здесь.
        self.assertTrue(
            any("длительность" in с for с in строки),
            f"молчащая ось не названа ни в одной строке: {строки}",
        )
        self.assertIn("перерос предел", текст)


if __name__ == "__main__":
    unittest.main()
