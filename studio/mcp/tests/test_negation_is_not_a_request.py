"""Заказчик, сказавший «БЕЗ обнажёнки», просит не её, а её отсутствие.

ВОСПРОИЗВЕДЕНО 2026-09-07 продуктовой проверкой, на брифе живого заказчика:

    plan_pipeline("ролик 15 сек, женщина, без обнажённых плеч, деловой костюм")
    -> outcome fail, reason «запрещённая_тема», banned ['adult content: обнаж']
       «в словах заказчика найдено запрещённое… План не строится»

То есть продукт выгонял клиента ровно за то, что клиент сам исключил. Это
самая дорогая ошибка из возможных здесь: он не спорит и не переписывает бриф —
он закрывает вкладку, и об этом никто не узнает. Пропуск ловит движок,
валидатор или человек; ложный отказ не ловит НИКТО.

ОКНО В ОДНО СЛОВО — ИЗМЕРЕННЫЙ ВЫБОР, А НЕ ОСТОРОЖНОСТЬ. Окно в два слова
открывает дыру «без цензуры обнажёнка»: там отрицание относится к цензуре.
Обе стороны проверены ниже (И5).

Т2: ожидаемое — литералы. Т3: входы с обоих краёв и из середины. Т4: сети нет.
"""

from __future__ import annotations

import unittest

from studio.mcp import contract, screen

#: Слева — что заказчик написал, справа — почему это ЧЕСТНЫЙ бриф.
ЧЕСТНЫЕ = (
    ("ролик 15 сек, женщина, без обнажённых плеч, деловой костюм", "тема прямо исключена"),
    ("никакой обнажёнки, деловой стиль", "то же другим словом"),
    ("no nudity, business suit", "английская половина списка, чужой модуль"),
    ("without gore, medical drama", "меддрама без жести"),
    ("ролик 15 сек, женщина, для бренда нижнего белья, мягкий свет", "бельё — не adult"),
    ("исключить кровь в кадре, реклама клиники", "отрицание глаголом"),
)

#: А это просьбы, и отрицание рядом их не отменяет.
ЗАПРЕЩЁННЫЕ = (
    ("эротический ролик с обнажённой моделью", "adult content: эрот"),
    ("без цензуры, обнажёнка крупным планом", "adult content: обнаж"),
    ("эротично но без обнажёнки, для бренда белья", "adult content: эрот"),
    ("nudity close-up", "adult content: nudity"),
    ("gore and blood everywhere", "violence: gore"),
    ("nude celebrity lookalike", "adult content: nude"),
)


class ОтрицаниеСнимаетТолькоСвоюНаходку(unittest.TestCase):
    def test_честный_бриф_проходит(self) -> None:
        for текст, почему in ЧЕСТНЫЕ:
            итог = screen.просеять(текст)
            self.assertEqual("pass", итог["outcome"], f"{почему}: {текст!r} -> {итог}")
            self.assertEqual([], итог["banned"], текст)

    def test_просьба_остаётся_отказом(self) -> None:
        """Вторая сторона (И5): дверь, пропускающая всё, ловит ноль ложных
        отказов и не защищает ни от чего."""
        for текст, ожидаемая_метка in ЗАПРЕЩЁННЫЕ:
            итог = screen.просеять(текст)
            self.assertEqual("fail", итог["outcome"], f"{текст!r} -> {итог}")
            self.assertIn(ожидаемая_метка, итог["banned"], текст)

    def test_без_цензуры_не_отменяет_тему(self) -> None:
        """Именно на этом входе окно в ДВА слова открыло бы дыру: «без»
        относится к цензуре, а тема стоит следующим словом."""
        self.assertIn("adult content: обнаж", screen.просеять("без цензуры обнажёнка")["banned"])

    def test_отменяется_только_отменённое(self) -> None:
        """Одно отрицание не чистит весь бриф: «эрот» здесь никто не отменял."""
        итог = screen.просеять("эротично но без обнажёнки")
        self.assertEqual(["adult content: эрот"], итог["banned"])


class ОбеДвериОтвечаютОдинаково(unittest.TestCase):
    """Е1: у промпта и у брифа один просев, значит и отрицание одно."""

    def test_промпт_с_отрицанием_не_отвергается_за_тему(self) -> None:
        итог = contract.gate(
            "no nudity, muted ivory palette, even balanced lighting, matte texture, calm"
        )
        self.assertNotIn("banned_topic", итог["broke"], итог)

    def test_промпт_с_темой_отвергается(self) -> None:
        итог = contract.gate(
            "nudity everywhere, muted ivory palette, even lighting, matte texture, calm"
        )
        self.assertIn("banned_topic", итог["broke"], итог)


if __name__ == "__main__":
    unittest.main()
