"""Когда угол разбора объявляется наложением, а когда — совпадением.

ЗАЧЕМ. Обе константы этого прибора — порог схожести 0.80 и минимум 6 пар —
жили ВНУТРИ `scan`, достижимые только через настоящие картинки на диске. Ни
один тест не мог их подменить, и обе стояли без охраны: поймано ратчетом R7
2026-09-05.

Прибор решает, не выжжен ли на разборах чужой водяной знак: угол, одинаковый у
не связанных между собой картинок, — это наложение, а не содержание.

Ожидаемое — ЛИТЕРАЛЫ (Т2): 0.80 и 6 написаны руками. Сети нет (Т4). Входы с
обоих краёв и из середины (Т3).
"""

from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path

_SPEC = importlib.util.spec_from_file_location(
    "check_burned_marks",
    Path(__file__).resolve().parents[3] / "scripts" / "check_burned_marks.py",
)
assert _SPEC and _SPEC.loader
марки = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(марки)


class ПорогИМинимумПарРешают(unittest.TestCase):
    def test_ровно_порог_это_наложение(self):
        """Граница включительно — записанное решение, а не случайность."""
        находки, оценки = марки.судить_углы({"низ-право": (0.80, 10)})
        self.assertEqual(len(находки), 1)
        self.assertIn("низ-право", находки[0])
        self.assertEqual(оценки, {"низ-право": 0.8})

    def test_на_волос_ниже_порога_это_содержание(self):
        """Негативный контроль (И5): прибор, который краснеет всегда, не
        отличается от прибора, который краснеет случайно."""
        находки, оценки = марки.судить_углы({"низ-право": (0.799, 10)})
        self.assertEqual(находки, [])
        self.assertEqual(оценки, {"низ-право": 0.799})

    def test_меньше_шести_пар_не_судится_вовсе(self):
        """Одно совпадение неотличимо от закономерности. Объявить его
        наложением значило бы выдать совпадение за находку — и в счёт такой
        угол тоже не идёт, иначе «проверено N» соврёт (Р2)."""
        находки, оценки = марки.судить_углы({"низ-право": (0.99, 5)})
        self.assertEqual(находки, [])
        self.assertEqual(оценки, {}, "не судился — значит и не проверен")

    def test_ровно_шесть_пар_уже_судится(self):
        находки, оценки = марки.судить_углы({"низ-право": (0.99, 6)})
        self.assertEqual(len(находки), 1)
        self.assertEqual(list(оценки), ["низ-право"])

    def test_каждый_угол_судится_отдельно(self):
        """Е3: частичный результат печатается числами. Один выжженный угол не
        красит остальные, и три чистых не отменяют один грязный."""
        находки, оценки = марки.судить_углы(
            {
                "низ-право": (0.95, 10),
                "низ-лево": (0.20, 10),
                "верх-право": (0.99, 3),
                "верх-лево": (0.10, 10),
            }
        )
        self.assertEqual(len(находки), 1)
        self.assertIn("низ-право", находки[0])
        self.assertEqual(sorted(оценки), ["верх-лево", "низ-лево", "низ-право"])


if __name__ == "__main__":
    unittest.main()
