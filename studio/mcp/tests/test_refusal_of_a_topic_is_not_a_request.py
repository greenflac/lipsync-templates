class ПросьбаОстаётсяПросьбой(unittest.TestCase):
    """И5: прибор, отменяющий всё подряд, ничего не сторожит."""

    def test_ни_одна_просьба_не_прошла(self) -> None:
        прошли = [т for т in ПРОСЬБЫ if screen.просеять(т)["outcome"] != "fail"]
        self.assertEqual([], прошли)

    def test_двойное_отрицание_ПЕРЕД_темой_держится(self) -> None:
        """Половина правки, которую мутация `ДВОЙНОЕ_ПЕРЕД = ()` не красила
        ничем на 2039 тестах — то есть не сторожилась вовсе (приёмка)."""
        for текст in (
            "невозможно без обнажёнки",
            "нельзя без обнажёнки",
            "тут никак без обнажёнки",
        ):
            self.assertEqual("fail", screen.просеять(текст)["outcome"], текст)

    def test_оборот_о_соседнем_слове_запрета_не_снимает(self) -> None:
        """Хвост обрывается на первом содержательном слове, и это единственная
        граница: числовые окна отсюда УДАЛЕНЫ — обе сами создавали дефекты."""
        текст = "без обнажёнки, деловой костюм, хороший свет, грим, за день это не получится"
        self.assertEqual("pass", screen.просеять(текст)["outcome"])

    def test_длинная_цепочка_прокладок_оборот_всё_же_находит(self) -> None:
        """Сторона, ради которой удалено `ОКНО_ДВОЙНОГО`: при окне в 4 слова
        эта просьба читалась как запрет."""
        текст = "без обнажёнки и вообще там любой всякой никак не обойтись"
        self.assertEqual("fail", screen.просеять(текст)["outcome"])

    def test_соседнее_существительное_не_переходится(self) -> None:
        """Граница правила про перечисления: «без ЦЕНЗУРЫ обнажёнка» —
        существительное в родительном без запятой и связки."""
        self.assertEqual("fail", screen.просеять("без цензуры обнажёнка")["outcome"])

    def test_чужое_без_не_дотягивается_через_смысл(self) -> None:
        """Проход назад ограничен не числом слов, а смыслом: «снимаем» —
        содержательное слово, и «без спешки» до темы не дотягивается."""
        далеко = "без спешки снимаем ролик про наш продукт в студии с обнажёнкой"
        self.assertEqual("fail", screen.просеять(далеко)["outcome"])


