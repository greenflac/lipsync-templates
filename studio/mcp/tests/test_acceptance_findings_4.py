def _план(бриф: str) -> dict:
    return json.loads(server.plan_pipeline(бриф))


def _ставка(значение: float = 0.0225) -> dict:
    return {"outcome": "годно", "lower_bound": {"usd за second": значение}, "note": "n"}


class ПродуктНеПадает(unittest.TestCase):
    """«Бюджет 0 долларов» роняло инструмент ZeroDivisionError: заказчик,
    который хочет понять, можно ли бесплатно, не получал НИЧЕГО."""

    def test_нулевой_бюджет_не_роняет(self) -> None:
        итог = _план("ролик 10 минут, говорящая голова, бюджет 0 долларов")
        цена = итог["pipeline_price"]
        self.assertEqual("не годно", цена["outcome"])
        self.assertIn("работа столько не стоит", цена["note"])

    def test_отрицательный_потолок_тоже(self) -> None:
        итог = в_ролик(_ставка(), 600.0, -1.0)
        self.assertNotIn("в -13.5 раза", итог["note"])


class ПотолокСравниваетсяТолькоСоСвоим(unittest.TestCase):
    """Заказчик написал «не дороже 0.10 ЗА СЕКУНДУ» и при ставке 0.0365 —
    втрое ниже своего потолка — получал «дороже в 10.9 раза»."""

    def test_посекундный_потолок_не_сравнивается_с_ценой_ролика(self) -> None:
        итог = в_ролик(_ставка(0.0365), 30.0, 0.10, ("second",))
        self.assertEqual("годно", итог["outcome"])
        self.assertIn("величины разного рода", итог["note"])

    def test_потолок_за_прогон_сравнивается_как_прежде(self) -> None:
        """Вторая сторона (И5): прибор, не сравнивающий ничего, ничего и не
        защищает."""
        итог = в_ролик(_ставка(), 600.0, 3.0, ("run",))
        self.assertEqual("не годно", итог["outcome"])
        self.assertIn("дороже в 4.5 раза", итог["note"])

    def test_отказ_выносится_по_превысившей_валюте(self) -> None:
        """{'usd': 0.6, 'credits': 300000} при потолке 3 usd давало «дороже в
        100000 раза» — отказ по кредитам, тогда как в долларах попадание."""
        цена = {
            "outcome": "годно",
            "lower_bound": {"usd за second": 0.001, "credits за second": 500.0},
            "note": "n",
        }
        итог = в_ролик(цена, 600.0, 3.0, ("run",))
        self.assertEqual("годно", итог["outcome"], "0.6 usd влезает в потолок 3 usd")
        self.assertIn("не сравнивалась", итог["note"], "кредиты названы и НЕ сравнены")
        self.assertNotIn("ПРЕВЫШЕН", итог["note"], "отказ не выносится по чужой валюте")
        self.assertIn("300000.00 credits", итог["note"], "но сама цена в кредитах названа")


class ЧтоДальшеНеВрёт(unittest.TestCase):
    #: Строки НАСТОЯЩЕЙ формы, но ЛИТЕРАЛАМИ (Т2), а не выборкой из базы.
    #: Прежняя редакция звала продукт на живом брифе — и замолчала, как только
    #: сбор данных сменил выбираемую модель: у новой осталась одна плохая
    #: строка, и порядок перестал что-либо решать. Проверка, зависящая от
    #: того, кого база ставит первой, сторожит базу, а не код.
    ЗАПИСИ = (
        {"attribute": "benchmark_score", "value": "94% on HDTF, vs 91% previous SOTA"},
        {"attribute": "metric_blind_spot", "value": "LSE-C не видит дрожания зубов"},
        {"attribute": "failure_mode", "value": "рот размывается на профиле"},
    )

    def test_цитируется_плохая_новость_а_не_первая(self) -> None:
        """Заказчику зачитывали `benchmark_score` «94% on HDTF, vs 91%
        previous SOTA» как ИЗМЕРЕННЫЙ провал — то есть похвалу модели."""
        запись = planner.худшая_новость(self.ЗАПИСИ)
        self.assertEqual("failure_mode", запись["attribute"])
        self.assertNotIn("previous SOTA", str(запись["value"]))

    def test_предметная_новость_обгоняет_оговорку_о_метрике(self) -> None:
        """Порядок среди ПЛОХИХ: «что сломалось» полезнее, чем «метрика этого
        не видит». Без сортировки первой пошла бы оговорка."""
        без_провала = (self.ЗАПИСИ[0], self.ЗАПИСИ[1])
        self.assertEqual("metric_blind_spot", planner.худшая_новость(без_провала)["attribute"])
        self.assertEqual("failure_mode", planner.худшая_новость(self.ЗАПИСИ)["attribute"])

    def test_нет_плохих_новостей_берётся_первая(self) -> None:
        только_похвала = ({"attribute": "benchmark_score", "value": "94% on HDTF"},)
        self.assertEqual("benchmark_score", planner.худшая_новость(только_похвала)["attribute"])

    def test_пусто_не_падает(self) -> None:
        """У вызывающего есть ветка «сказать нечего»; падение ею не является."""
        self.assertEqual({}, planner.худшая_новость(()))

    def test_продукт_всё_ещё_зачитывает_это_заказчику(self) -> None:
        """Функция сама по себе ничего не стоит, если продукт её не зовёт."""
        строка = _план("ролик 1 минута, говорящая голова, бюджет 100000 долларов")["что_дальше"]
        self.assertIn("ИЗМЕРЕННЫЙ провал", строка)

    def test_число_кандидатов_настоящее(self) -> None:
        """Во всех прогонах стояло «их 2» — это потолок ПОКАЗА, а не число
        живых кандидатов (на липсинке база даёт 36)."""
        строка = _план("ролик 1 минута, говорящая голова, бюджет 100000 долларов")["что_дальше"]
        self.assertNotIn("(их 2)", строка)

    def test_ранние_возвраты_тоже_несут_строку(self) -> None:
        """Обе ветки были написаны и недостижимы из `plan`: тесты звали
        функцию на рукодельных словарях и потому были зелены."""
        self.assertIn("ответьте на вопрос", _план("ролик 15 секунд для кофейни")["что_дальше"])
        self.assertIn("назовите, что нужно сделать", _план("абракадабра")["что_дальше"])


class ПутьЗаказчикаЧитаетсяКакНадо(unittest.TestCase):
    def test_тильда_раскрывается(self) -> None:
        файл = pathlib.Path(os.path.expanduser("~/тест-приёмки.mp4"))
        файл.write_bytes(b"x")
        self.addCleanup(файл.unlink)
        self.assertEqual("", missing_reason("~/тест-приёмки.mp4"))

    def test_адрес_в_сети_назван_адресом(self) -> None:
        причина = missing_reason("https://example.com/a.mp4")
        self.assertIn("адрес в сети", причина)
        self.assertIn("https://example.com/a.mp4", причина, "путь не искажён в эхо")

    def test_несуществующий_файл_по_прежнему_назван(self) -> None:
        self.assertIn("файла нет", missing_reason("/нет/такого/файла.mp4"))


class ОтрицаниеРаботаетВоВсехФормах(unittest.TestCase):
    ЧЕСТНЫЕ = (
        "ролик, без всякой обнажёнки, деловой костюм",
        "не должно быть обнажёнки, деловой костюм",
        "без какой-либо обнажёнки",
        "no face swap, just my own footage",
        "без 18+ контента, детская аудитория не наша",
        "снимаем своего актёра в студии",
    )
    ПРОСЬБЫ = (
        "без обнажёнки не обойтись",
        "без цензуры обнажёнка",
        "face swap of a celebrity",
        "deepfake крупным планом",
        "18+ контент",
    )

    def test_честные_проходят(self) -> None:
        for текст in self.ЧЕСТНЫЕ:
            self.assertEqual("pass", screen.просеять(текст)["outcome"], текст)

    def test_просьбы_отвергаются(self) -> None:
        for текст in self.ПРОСЬБЫ:
            self.assertEqual("fail", screen.просеять(текст)["outcome"], текст)

    def test_двойное_отрицание_это_просьба(self) -> None:
        """«Без обнажёнки НЕ ОБОЙТИСЬ» значит «обнажёнка обязательна», и просев
        пропускал такой бриф целиком — план строился из трёх шагов."""
        self.assertEqual("fail", screen.просеять("без обнажёнки не обойтись")["outcome"])

    def test_содержательное_слово_окно_не_растягивает(self) -> None:
        """«без ЦЕНЗУРЫ обнажёнка»: прокладками считаются только служебные
        слова, иначе отрицание отменяло бы тему через любое расстояние."""
        self.assertEqual("fail", screen.просеять("без цензуры обнажёнка")["outcome"])

    def test_послабление_для_актёра_узкое(self) -> None:
        """«Мой актёр» — не третье лицо, но «моя знаменитость» — лицо."""
        self.assertEqual("pass", screen.просеять("no deepfake, my own actor")["outcome"])
        self.assertEqual("fail", screen.просеять("моя знаменитость в кадре")["outcome"])


if __name__ == "__main__":
    unittest.main()
