"""Чужие слова в закоммиченном знании: сколько их и где они лежат.

ЗАЧЕМ ЭТОТ МОДУЛЬ ЕСТЬ. Правило «пересказ со ссылкой, никогда чужая проза»
существовало в проекте с самого начала и сторожилось ровно в одном файле —
`scripts/check_craft.py` по маске `craft_*.jsonl`. ИЗМЕРЕНО 2026-09-02: в это
же время в публичном репозитории лежали 724 строки из обсуждений HuggingFace и
Civitai, 340 из них длиннее 15 слов, максимум 354 слова, и 117 ников живых
людей. Дефект был починен ПО МЕСТУ, а не по форме — это И7, и цена ошибки в
том, что нарушение росло полгода в файле, которого правило не касалось.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, и это не то же самое, что append-only или атрибуция:
не «откуда строка» и не «не переписали ли её», а «сколько в ней чужого текста
и не названо ли в ней живое лицо».

ТРИ ИСХОДА (Р1). `не смогли` настоящий и частый: файла нет на этой машине
(корпуса намеренно не коммитятся), строка не разобралась, поля с текстом в
ней нет вовсе. Ноль нарушений при нуле прочитанных строк — не успех.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

PASS = "pass"
FAIL = "fail"
UNMEASURED = "could not measure"

#: Предел дословного фрагмента. Число НЕ выбрано здесь заново: оно взято из
#: `scripts/check_craft.py`, где под ним лежит замер на 1020 фрагментах первого
#: урожая — медиана 1 слово, самый длинный 13. Это не юридический порог, а
#: растяжка, срабатывающая задолго до копирования страницы. Совпадение всех
#: мест, знающих это число, сторожится тестом (Е1).
ДОСЛОВНО_СЛОВ = 15

#: Поле, в котором лежат СЛОВА ИСТОЧНИКА. Только оно и меряется на длину:
#: `note`, `witnessed` и `fix` пишем МЫ, и наша собственная проза чужой не
#: является. Первая редакция мерила все четыре и насчитала 3401 нарушение из
#: 5193 записей — 1543 из них были нашими же нотами. Прибор, считающий свою
#: работу нарушением, меряет не то (И5).
ПОЛЕ_ИСТОЧНИКА = "value"

#: Поля, где ищется имя живого лица. Здесь наоборот — все, потому что имя
#: попадает именно в ноту.
ПОЛЯ_С_ТЕКСТОМ: tuple[str, ...] = ("value", "note", "witnessed", "fix")

#: Хосты, где текст пишут ЛЮДИ, а не вендор. Правило про них: цитата из
#: обсуждения — чужое высказывание, на которое у нас нет прав. Вендорская
#: спецификация в 20 слов — другой класс: это изложение факта из документа,
#: который вендор публикует для чтения. Ограничение по хосту, а не по длине,
#: — единственный способ отделить одно от другого, не гадая.
ХОСТЫ_ЛЮДЕЙ: tuple[str, ...] = (
    "/discussions/",
    "/issues/",
    "civitai.com",
    "reddit.com",
    "/comments/",
    "discuss.",
    "forum.",
)

#: Формы, которыми в ноту попадает ЖИВОЕ ЛИЦО. Ни одному ответу имя автора не
#: нужно, а хранение его в публичном репозитории — отдельный разговор, которого
#: лучше не иметь. ВЫБРАНО по разбору живых нот 2026-09-02.
#: Первая редакция ловила «by the», «by family», «от ...» в обычной английской
#: прозе и насчитала 515 «имён», почти все ложные. Правило сужено до ТОЙ САМОЙ
#: формы, которой ник записывал наш собственный канал: «автор <ник>» в начале
#: или после запятой. Чужую прозу оно не трогает по построению.
ИМЯ_ЧЕЛОВЕКА = re.compile(r"(?:^|,\s*)автор\s+([^\s,;)]{2,})", re.I)

#: Файлы знания, которые коммитятся и потому проверяются. Корпуса промптов сюда
#: НЕ входят: они закрыты `.gitignore` ровно по этой причине, и проверять их
#: здесь значило бы каждый раз получать «не смогли» на машине без них.
ЗНАНИЕ = "studio/knowledge"
НЕ_ПРОВЕРЯЕМ: tuple[str, ...] = ("gallery_prompts.jsonl", "civitai_prompts.jsonl")


@dataclass
class Строка:
    """Одна запись и то, что в ней нашлось."""

    файл: str
    номер: int
    слов: int = 0
    поле: str = ""
    имя: str = ""


@dataclass
class Итог:
    outcome: str = UNMEASURED
    checked: int = 0
    violations: int = 0
    unmeasured: int = 0
    длинных: list[Строка] = field(default_factory=list)
    с_именем: list[Строка] = field(default_factory=list)
    note: str = ""


def слов_в(текст: str) -> int:
    """Сколько слов несёт поле. Пустое и не-строка дают ноль, а не исключение."""
    return len(str(текст or "").split())


def имя_в(текст: str) -> str:
    """Имя живого лица из ноты, или пустая строка.

    «автор неизвестен» именем не считается — это отсутствие имени, записанное
    словами, и путать его с настоящим ником значит красить гейт на пустоте.
    """
    найдено = ИМЯ_ЧЕЛОВЕКА.search(str(текст or ""))
    if not найдено:
        return ""
    кандидат = найдено.group(1).strip(".,:;'\"")
    return "" if кандидат.lower() in {"неизвестен", "unknown", "нет"} else кандидат


def от_людей(url: object) -> bool:
    """Написан ли текст по этому адресу человеком, а не вендором."""
    низ = str(url or "").lower()
    return any(кусок in низ for кусок in ХОСТЫ_ЛЮДЕЙ)


def проверить_файл(path: Path) -> Итог:
    """Одна книга знания. Нечитаемая строка — третий исход, а не ноль нарушений."""
    if not path.is_file():
        return Итог(outcome=UNMEASURED, unmeasured=1, note=f"{path.name}: файла нет на этой машине")
    итог = Итог()
    for номер, сырое in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        сырое = сырое.strip()
        if not сырое or сырое.startswith("//"):
            continue
        try:
            запись = json.loads(сырое)
        except json.JSONDecodeError:
            итог.unmeasured += 1
            continue
        if not isinstance(запись, dict):
            итог.unmeasured += 1
            continue
        итог.checked += 1
        if от_людей(запись.get("source_url")):
            слов = слов_в(запись.get(ПОЛЕ_ИСТОЧНИКА))
            if слов > ДОСЛОВНО_СЛОВ:
                итог.длинных.append(Строка(path.name, номер, слов=слов, поле=ПОЛЕ_ИСТОЧНИКА))
        for поле in ПОЛЯ_С_ТЕКСТОМ:
            имя = имя_в(запись.get(поле))
            if имя:
                итог.с_именем.append(Строка(path.name, номер, поле=поле, имя=имя))
    итог.violations = len(итог.длинных) + len(итог.с_именем)
    if итог.checked == 0:
        итог.outcome = UNMEASURED
        итог.note = f"{path.name}: ни одной разобранной записи"
    elif итог.violations:
        итог.outcome = FAIL
        итог.note = (
            f"{path.name}: дословных фрагментов длиннее {ДОСЛОВНО_СЛОВ} слов "
            f"{len(итог.длинных)}, записей с именем живого лица {len(итог.с_именем)}"
        )
    else:
        итог.outcome = PASS
        итог.note = f"{path.name}: {итог.checked} записей, чужой прозы и имён нет"
    return итог


def книги(корень: Path) -> list[Path]:
    """Коммитящиеся книги знания, по порядку имени."""
    каталог = корень / ЗНАНИЕ
    if not каталог.is_dir():
        return []
    return sorted(p for p in каталог.glob("*.jsonl") if p.name not in НЕ_ПРОВЕРЯЕМ)
