_ТЕГ = re.compile(r"<[^>]+>")
_БЛОК = re.compile(r"(?i)</(p|div|li|h\d|tr|td)>|<br\s*/?>")
_РАЗДЕЛ = re.compile(r"(?<=[.!?])\s+|\s+\.\s+")


def _get(url: str, cap: int = 400_000) -> tuple[str, bytes]:
    """Один запрос. Отказ — это состояние канала, а не исключение."""
    request = urllib.request.Request(url, headers={"User-Agent": "lipsync-studio/ingest"})
    try:
        with urllib.request.urlopen(request, timeout=25) as response:
            return "ok", response.read(cap)
    except urllib.error.HTTPError as error:
        return f"HTTP {error.code}", b""
    except Exception as error:  # noqa: BLE001 — состояние канала, не наша ошибка
        return type(error).__name__, b""


def текст(html: str | None) -> str:
    """HTML описания в плоский текст, границы блоков — точками.

    Точка вместо `</p>` не косметика: без неё соседние абзацы слипаются в одно
    «предложение», и условие из одного встречается с исходом из другого.
    """
    if not html:
        return ""
    plain = _ТЕГ.sub(" ", _БЛОК.sub(" . ", html))
    plain = plain.replace("&amp;", "&").replace("&nbsp;", " ").replace("&#39;", "'")
    return re.sub(r"\s+", " ", plain).strip()


def предложения(plain: str) -> list[str]:
    """Предложения годной длины. Всё, что вне границ, не рассматривается."""
    return [
        s.strip()
        for s in _РАЗДЕЛ.split(plain)
        if МИНИМУМ_СИМВОЛОВ < len(s.strip()) < МАКСИМУМ_СИМВОЛОВ
    ]


def почему_не_наблюдение(фраза: str) -> str:
    """ПОЧЕМУ это не наблюдение практика. Пустая строка — значит, наблюдение.

    Причины названы поимённо, а не сведены к одному «не подошло»: по ним
    считается, чем именно канал беден, и это единственный способ отличить
    «источник молчит» от «прибор глухой». Порядок — от самого дешёвого отказа
    к самому спорному.
    """
    if ПРОМО.search(фраза):
        return "промо, благодарность или ссылка на соцсеть"
    if УСТАНОВКА.search(фраза):
        return "про установку и окружение, а не про поведение модели"
    if not УСЛОВИЕ.search(фраза):
        return "нет условия прогона: ни числа с единицей, ни ручки, ни карты"
    if not ИСХОД.search(фраза):
        return "есть условие, но не сказано, что вышло"
    if not (ГОЛОС.search(фраза) or ЖЕЛЕЗО.search(фраза)):
        return "ни голоса практика, ни требования к железу — похоже на рекламу карточки"
    return ""


def наблюдения(описания: Sequence[str | None]) -> dict[str, Any]:
    """Наблюдения практика из описаний модели и её версий, с отчётом об отсеве.

    :param описания: сырой HTML описания модели и описаний версий.

    Отсев ПЕЧАТАЕТСЯ по причинам, а не выбрасывается молча: «нашли ноль» и
    «отсеяли сорок семь фраз, из них тридцать промо» — разные новости о
    канале, и вторая говорит, где искать дальше.
    """
    plain = " . ".join(текст(h) for h in описания if h)
    строки = предложения(plain)
    найдено: list[str] = []
    отсев: dict[str, int] = {}
    for фраза in строки:
        почему = почему_не_наблюдение(фраза)
        if почему:
            отсев[почему] = отсев.get(почему, 0) + 1
        else:
            найдено.append(фраза)
    return {"наблюдения": найдено, "предложений": len(строки), "отсев": отсев}


def права(модель: dict[str, Any]) -> list[str]:
    """Что флаги прав Civitai говорят об использовании. Три исхода внутри.

    Правило Ц5: лицензия читается ДО встраивания. У Civitai она задана не
    текстом, а набором флагов, и отсутствующее разрешение — это ограничение,
    а не умолчание в нашу пользу.

    Смысл значений `allowCommercialUse` (`Image`, `Rent`, `RentCivit`, `Sell`)
    НЕПРОВЕРЕНО: их таблицы нет ни в публичном REST, ни на
    developer.civitai.com, куда площадка сама отсылает (HTTP 200 на корне,
    HTTP 404 на `/docs/api/public-rest` — ИЗМЕРЕНО 2026-09-01). Поэтому здесь
    не толкуется, что каждое из них разрешает: считывается только то, что
    видно структурно, — ПУСТО значит не разрешено ничего.
    """
    поле = модель.get("allowCommercialUse")
    метки: list[str] = []
    if поле is None:
        метки.append(f"{НЕ_СМОГЛИ_ПРОЧИТАТЬ}: поля allowCommercialUse нет в ответе")
    else:
        значения = [str(v) for v in поле] if isinstance(поле, list) else [str(поле)]
        живые = [v for v in значения if v and v.lower() != "none"]
        if not живые:
            метки.append("НЕКОММЕРЧЕСКАЯ: allowCommercialUse пуст — коммерческого права не дано")
        elif "Sell" not in живые:
            метки.append(f"коммерческое использование ограничено: allowCommercialUse {живые}")
    if модель.get("allowDerivatives") is False:
        метки.append("производные запрещены: allowDerivatives false")
    if модель.get("allowDifferentLicense") is False:
        метки.append("производную нельзя перелицензировать: allowDifferentLicense false")
    if модель.get("allowNoCredit") is False:
        метки.append("требуется указание автора: allowNoCredit false")
    return метки


def прогонные(версия: dict[str, Any]) -> dict[str, Any]:
    """Чем ЗАПУСКАЛИ: настройки из `meta` опубликованных картинок.

    Три исхода. Картинок нет — «не смогли»; картинки есть, а `meta` пустые —
    тоже «не смогли», и это РАЗНОЕ с «настроек не публиковали»: первое значит,
    что смотреть было не на что, второе — что смотрели и не нашли.
    """
    картинки = версия.get("images") or []
    с_настройками: list[dict[str, Any]] = []
    for кадр in картинки:
        meta = кадр.get("meta") or {}
        взято = {k: meta[k] for k in НАСТРОЙКИ_ПРОГОНА if meta.get(k) not in (None, "", [])}
        if взято:
            с_настройками.append(взято)
    if not картинки:
        return {"outcome": "не смогли", "картинок": 0, "с настройками": 0, "почему": "картинок нет"}
    if not с_настройками:
        return {
            "outcome": "не смогли",
            "картинок": len(картинки),
            "с настройками": 0,
            "почему": "ни у одной картинки нет настроек прогона в meta",
        }
    сводка: dict[str, list[Any]] = {}
    for взято in с_настройками:
        for k, v in взято.items():
            сводка.setdefault(k, [])
            if v not in сводка[k]:
                сводка[k].append(v)
    return {
        "outcome": "годно",
        "картинок": len(картинки),
        "с настройками": len(с_настройками),
        "сводка": сводка,
    }


def словами(сводка: dict[str, list[Any]]) -> str:
    """Настройки прогона одной строкой, значениями источника."""
    куски = []
    for ключ in НАСТРОЙКИ_ПРОГОНА:
        if ключ in сводка:
            куски.append(f"{ключ} {', '.join(str(v) for v in сводка[ключ][:4])}")
    return "; ".join(куски)


def survey(model_id: int | str, get: Callable[[str], tuple[str, bytes]] = _get) -> dict[str, Any]:
    """Всё, что Civitai отдаёт про одну модель. Три исхода, как везде."""
    state, body = get(МОДЕЛЬ.format(id=model_id))
    if state != "ok":
        return {"model_id": str(model_id), "outcome": "не смогли", "note": f"карточка: {state}"}
    try:
        модель = json.loads(body)
    except ValueError:
        return {"model_id": str(model_id), "outcome": "не смогли", "note": "карточка: не JSON"}
    return разобрать(модель, get)


def разобрать(
    модель: dict[str, Any], get: Callable[[str], tuple[str, bytes]] = _get
) -> dict[str, Any]:
    """Разбор уже полученной карточки. Отделён от запроса, чтобы быть проверяемым.

    Правило Т5: развилка, живущая только внутри точки входа, тестом
    недостижима и потому деградирует молча.
    """
    версии = (модель.get("modelVersions") or [])[:ВЕРСИЙ_ЧИТАЕМ]
    находки = наблюдения([модель.get("description")] + [v.get("description") for v in версии])
    прогоны: list[dict[str, Any]] = []
    for версия in версии:
        vid = версия.get("id")
        if vid is None:
            continue
        state, body = get(ВЕРСИЯ.format(id=vid))
        if state != "ok":
            прогоны.append({"outcome": "не смогли", "версия": vid, "почему": state})
            continue
        try:
            полная = json.loads(body)
        except ValueError:
            прогоны.append({"outcome": "не смогли", "версия": vid, "почему": "не JSON"})
            continue
        строка = прогонные(полная)
        строка["версия"] = vid
        строка["имя версии"] = версия.get("name") or полная.get("name") or ""
        прогоны.append(строка)
    stats = модель.get("stats") or {}
    # Дата ИСТОЧНИКА, а не сегодняшняя: описание стоит в версии, и её
    # `publishedAt` — единственная дата, которую площадка про этот текст
    # сообщает. Нет её — три исхода, и наверх уходит пустая строка, а не
    # сегодняшнее число: старый текст со свежей датой перестаёт стареть.
    дата = str((версии[0].get("publishedAt") if версии else "") or "")[:10]
    return {
        "дата": дата,
        "model_id": str(модель.get("id")),
        "outcome": "годно",
        "имя": str(модель.get("name") or ""),
        "тип": str(модель.get("type") or ""),
        "автор": str((модель.get("creator") or {}).get("username") or ""),
        "базовая": str((версии[0].get("baseModel") if версии else "") or ""),
        "скачиваний": stats.get("downloadCount"),
        "права": права(модель),
        "наблюдения": находки["наблюдения"],
        "предложений": находки["предложений"],
        "отсев": находки["отсев"],
        "прогоны": прогоны,
        "url": f"{WEB}{модель.get('id')}",
    }


#: Как называется модель в базе фактов. Civitai даёт имя страницы, а база
#: живёт короткими именами (`wan-2.2`, `flux-2`), и склеивать их автоматом
#: нельзя: `merge_model_ids.py` уже сводит имена, и вторая машинка для того же
#: знания — дефект по Е1. Поэтому имя берётся из карточки как есть, приведённое
#: к нижнему регистру и дефисам, а сведение остаётся тому, чья это работа.
_ЧИСТКА = re.compile(r"[^a-z0-9]+")


def имя_модели(строка: dict[str, Any]) -> str:
    """Ключ модели для базы: имя карточки, приведённое к виду `wan2-1-14b-fusionx`."""
    return _ЧИСТКА.sub("-", str(строка.get("имя", "")).lower()).strip("-")


def заявки(строка: dict[str, Any]) -> list[tuple[str, str, str, str, str]]:
    """Находки одной модели как утверждения: модель, атрибут, значение, URL, нота.

    Значение — СЛОВА ИСТОЧНИКА: предложение автора целиком, флаги прав как они
    записаны в ответе, настройки как их опубликовал тот, кто запускал. Своё
    рассуждение — только в ноту.

    ОДНА СТРОКА НА ОДНО ЗНАНИЕ. Права уходят одной заявкой, а не по заявке на
    флаг, и настройки прогона — одной на модель, а не по одной на версию.
    Причина ИЗМЕРЕНА 2026-09-01: у `wan2-1-14b-fusionx` три версии дали три
    строки «steps 10; cfgScale 1; sampler UniPC» с одной и той же страницы, и
    база считала одно наблюдение трижды. Заодно это цена в строках: канал
    пишет ТОЛЬКО в ступень `portal`, а у базы есть инвариант «vendor — самая
    большая ступень» (`studio/selfrag/tests/test_source_hosts.py`), и запас до
    него ИЗМЕРЕН в 14 строк на 2026-09-01. Три строки об одном прогоне — это
    треть запаса, потраченная на повтор.
    """
    имя = имя_модели(строка)
    url = строка["url"]
    out: list[tuple[str, str, str, str, str]] = []
    метки = строка.get("права") or []
    if метки:
        out.append(
            (
                имя,
                "license_restriction",
                "; ".join(метки),
                url,
                "флаги прав карточки Civitai, прочитаны до встраивания (Ц5)",
            )
        )
    for фраза in строка.get("наблюдения") or []:
        out.append(
            (
                имя,
                "observed_behaviour",
                фраза,
                url,
                f"описание автора модели на Civitai, тип {строка.get('тип') or '—'},"
                f" базовая {строка.get('базовая') or '—'}",
            )
        )
    удачные = [п for п in (строка.get("прогоны") or []) if п.get("outcome") == "годно"]
    if удачные:
        сводка: dict[str, list[Any]] = {}
        картинок = настроек = 0
        for прогон in удачные:
            картинок += прогон["картинок"]
            настроек += прогон["с настройками"]
            for ключ, значения in прогон["сводка"].items():
                сводка.setdefault(ключ, [])
                for значение in значения:
                    if значение not in сводка[ключ]:
                        сводка[ключ].append(значение)
        out.append(
            (
                имя,
                "observed_behaviour",
                словами(сводка),
                f"{API}model-versions/{удачные[0]['версия']}",
                f"настройки из meta опубликованных картинок: {настроек} из {картинок}"
                f" несут их, версий {len(удачные)}",
            )
        )
    return out
