"""Находка или предмет письма: прибор, отделяющий наблюдение от заголовка треда.

ЗАЧЕМ ЭТОТ МОДУЛЬ СУЩЕСТВУЕТ

Канал сбора с HuggingFace писал в базу фактов ЗАГОЛОВОК треда обсуждения
вместо находки из его тела. ИЗМЕРЕНО владельцем 2026-09-01 на 203 строках из
обсуждений и issue:

    массовый заход `--record`   183 строки, средняя длина значения  62 символа
    ручной разбор прежних сессий 20 строк, средняя длина значения 178 символов
    моделей с применимостью     169, из них ТОЛЬКО на заголовках 80

62 символа — это subject line, то есть ВОПРОС, который человек задал, а не то,
что он выяснил. Две строки были положительными отзывами, записанными как
`failure_mode` («LTX 2.5 on RTX 3060: Impressive Speed & Quality Out of the
Box»); обе отозваны владельцем, поэтому в ЖИВОЙ базе массового захода 181, а не
183 — два его значения сняты отзывом.

Прибор принимает ЗАПИСАННОЕ УТВЕРЖДЕНИЕ и отвечает, находка это или предмет
письма. Три исхода (правило Р1): `годно` / `не годно` / `не смогли`. Третий
настоящий и на живой базе встречается: короткое осмысленное утверждение на
языке, который прибор не разбирает (китайский, японский, корейский, арабица,
тайский), — это «не смогли», а не «не годно». Свернуть его в любую сторону
значит либо забраковать чужой язык, либо пропустить мусор на нём.

ЧТО ПРИБОР УМЕЕТ И ЧЕГО НЕ УМЕЕТ

Умеет ловить ФОРМУ письма: трассировку чужой установки, вопрос, просьбу к
владельцу репозитория, лицензионный спор, ярлык-жалобу без сказуемого,
титульный регистр заголовка, перечисление вместо утверждения и расхождение
знака (похвала под отрицательным атрибутом).

НЕ умеет отличать хороший заголовок от плохого утверждения: заголовок иногда
БЫВАЕТ находкой («Vocoder produces click/pop artifact at the end of generated
audio segments»). Такие строки прибор пропускает, и это его честный предел, а
не подкрутка порога — они выписаны поимённо гейтом
`scripts/check_harvest_quality.py`.

ДВА ЯРУСА ПРАВИЛ, И ПОЧЕМУ ИХ ДВА

* УНИВЕРСАЛЬНЫЕ (трассировка, вопрос, просьба, лицензионный спор) применяются
  к любому утверждению: ни на каком атрибуте вопрос не является находкой.
* СТРОГИЕ (ярлык-жалоба, титульный регистр, длина, перечисление, знак)
  применяются только к атрибутам «что ЛОМАЕТСЯ» — `factaxis.CONTRA_ATTRIBUTES`.
  Строка про поломку обязана быть УТВЕРЖДЕНИЕМ; строка про режимы работы имеет
  право быть коротким списком, и одноярусный прибор бракует её зря. ИЗМЕРЕНО:
  одноярусная версия давала 82 ложных осуждения на 759 строк прочих каналов,
  двухъярусная — 3.

Область прибора — род факта по `studio/factaxis.py` (Е1: род считается там, а
не пересчитывается здесь). Строка рода `schema` («15», «720p», «mp4, prores»)
судится не этим прибором: это ФОРМА ВХОДА, а не рассказ о прогоне.

Сети здесь нет.
"""

