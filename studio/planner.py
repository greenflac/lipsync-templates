def frame_of(creative: str) -> tuple[tuple[int, int] | None, str]:
    """Стороны поданного креатива. Меряет ТОТ ЖЕ прибор, что `analyse_creative`.

    Вынесено отдельной функцией (Т5) и импортируется внутри неё, а не сверху
    модуля: разбор пикселей тянет numpy и Pillow, а планировщик обязан
    оставаться импортируемым там, где их нет, — без креатива он полностью
    работоспособен.

    Три исхода, и третий не сворачивается (Р1): файла нет, прибор не отработал,
    ширина с высотой не измерены — всё это «не смогли», с названной причиной, а
    не молчаливый отказ от проверки. Своего измерителя здесь нет (Е1): берётся
    ровно то поле `parts.look.measurements`, которое отдаёт `analyse_creative`,
    и если оно поедет, поедет сразу и там, где на него смотрит человек.
    """
    путь = str(creative or "").strip()
    if not путь:
        return None, "креатив не подан"
    try:
        from studio.mcp import creative as _creative

        итог = _creative.analyse(путь)
    except Exception as беда:  # pragma: no cover - зависит от окружения
        return None, f"креатив не измерен: {type(беда).__name__}: {беда}"
    замеры = ((итог.get("parts") or {}).get("look") or {}).get("measurements") or {}
    ширина, высота = замеры.get("width"), замеры.get("height")
    if not ширина or not высота:
        return None, f"креатив не измерен: {str(итог.get('note') or '')[:120]}"
    return (int(ширина), int(высота)), f"{int(ширина)}x{int(высота)}"


def limit_facts(facts: Sequence[Fact]) -> list[Fact]:
    """Строки, в которых записан ПРЕДЕЛ КАДРА модели.

    Какое имя отвечает на вопрос о разрешении, решает семья
    `studio/selfrag/attrfamily.py` — та же, из которой этот ответ берёт
    `model_advice` и `scripts/creative_fit.py`. Отбор там по подстроке, а не
    списком имён: вендоры заводят новые (`native_resolution`,
    `resolution_tiers`, `resolutions_vertex`), и список отставал бы молча;
    `training_resolution` выброшен поимённо — разрешение обучения не есть
    предел входа.
    """
    подходят = set(af.expand(LIMIT_ATTRIBUTE_MARKER, [f.attribute for f in facts]))
    return [f for f in facts if f.attribute in подходят]


def bans_in(fact: Fact, requires: Sequence[str]) -> str:
    """Какой ИЗ ВХОДОВ ЭТОГО ШАГА запрещает строка. Ни один — пустая строка.

    Вынесено отдельной функцией (Т5): это самая опасная развилка модуля —
    ошибка в обе стороны дорога. Пропустив запрет, план предлагает модель,
    которая работу физически не сделает; зажёгшись на ограничении качества,
    он вычёркивает годную модель за то, чего она не запрещала.

    Смотрит на ЗНАЧЕНИЕ, не на имя атрибута. Имя ничего не решает: запрет
    приходил под `human_face_restriction`, `failure_mode` и `resolution_enum`,
    а под теми же именами лежат строки, запретом не являющиеся.
    """
    низ = _norm(fact.value)
    for артефакт in requires:
        for фраза in BAN_FORMS.get(артефакт, ()):
            if фраза in низ:
                return артефакт
    return ""


def allows_in(fact: Fact, requires: Sequence[str]) -> bool:
    """Говорит ли строка ПРЯМО, что вход принимается («accepts_… = yes»)."""
    if not fact.attribute.startswith(ALLOW_ATTRIBUTE_PREFIX):
        return False
    if not _norm(fact.value).startswith(ALLOW_VALUE_PREFIX):
        return False
    имя = fact.attribute.lower()
    return any(
        (артефакт == ARTEFACT_VIDEO and "video" in имя)
        or (артефакт == ARTEFACT_SELFIE and ("image" in имя or "face" in имя))
        for артефакт in requires
    )


def step_inputs(op: Operation) -> tuple[str, ...]:
    """Входы шага ДЛЯ ПРОВЕРКИ ЗАПРЕТА: объявленные артефакты плюс лицо.

    Вынесено функцией (Т5) и не свёрнуто в `op.requires`: для валидатора вход
    шага — это артефакты, которые кто-то должен произвести, а лицо никто не
    производит, оно приходит с клиентом. Два разных вопроса к одному шагу.
    """
    if op.face_input and ARTEFACT_SELFIE not in op.requires:
        return tuple(op.requires) + (ARTEFACT_SELFIE,)
    return tuple(op.requires)


def ban_stance(facts: Sequence[Fact], requires: Sequence[str]) -> tuple[str, str]:
    """Запрещает ли база вход ЭТОГО шага. Три исхода, и главный из них третий.

    `BAN_UNKNOWN` — не «разрешено». Отсутствие запрета в базе не есть
    разрешение: доказать отсутствие нельзя, и выдавать молчание за согласие
    здесь значило бы повторить дефект, который уже дважды чинился в этом
    модуле — на цене и на кадре.

    Запрет ПЕРЕВЕШИВАЕТ явное разрешение: строка «accepts_input_video = yes»
    и строка «human faces cannot be uploaded» об одной модели не противоречат
    друг другу — вторая сужает первую, а не спорит с ней.
    """
    if not requires:
        return BAN_UNKNOWN, "у шага не объявлено входов — запрещать нечего"
    запреты = [(f, bans_in(f, requires)) for f in facts]
    запреты = [(f, а) for f, а in запреты if а]
    if запреты:
        факт, артефакт = запреты[0]
        return BAN_FORBIDS, (
            f"шагу нужен вход «{артефакт}», а база пишет запрет на него: "
            f"{факт.attribute}={факт.value[:90]} [{факт.tier}, {факт.stated_on or 'даты нет'}] "
            f"({факт.source_url}); строк-запретов {len(запреты)}"
        )
    разрешения = [f for f in facts if allows_in(f, requires)]
    if разрешения:
        f = разрешения[0]
        return BAN_ALLOWED, (
            f"вход принимается прямо: {f.attribute}={f.value[:70]} ({f.source_url})"
        )
    return BAN_UNKNOWN, (
        f"о запрете на вход ({', '.join(requires)}) в базе не сказано ни строки "
        f"из {len(facts)}: это НЕ разрешение"
    )


def output_kinds(facts: Sequence[Fact]) -> set[str]:
    """Виды носителей, которые модель ОТДАЁТ, по записанной схеме ответа.

    Значение — список через запятую, как и у `accepts_inputs`: одна модель
    может отдавать и видео, и звук.
    """
    виды: set[str] = set()
    for f in facts:
        if f.attribute != OUTPUT_ATTRIBUTE:
            continue
        виды.update(кусок.strip().lower() for кусок in f.value.split(",") if кусок.strip())
    return виды


def output_stance(facts: Sequence[Fact], produces: Sequence[str]) -> tuple[str, str]:
    """Отдаёт ли модель то, что шаг обязан произвести. Три исхода (Р1).

    Вынесено отдельной функцией (Т5) и симметрично `ban_stance`: там мы
    спрашивали, принимает ли модель вход шага, здесь — отдаёт ли она его выход.
    Отсутствие этой половины и было дефектом.
    """
    нужно = {OUTPUT_KINDS.get(a, a) for a in produces}
    if not нужно:
        return OUT_UNKNOWN, "шаг не объявил, что производит — сверять не с чем"
    свои = output_kinds(facts)
    if not свои:
        return OUT_UNKNOWN, (
            f"шаг производит {', '.join(sorted(нужно))}, а выход модели не записан "
            f"ни одной строкой из {len(facts)}: это НЕ «отдаёт»"
        )
    if свои & нужно:
        строка = next((f for f in facts if f.attribute == OUTPUT_ATTRIBUTE), None)
        откуда = f" ({строка.source_url})" if строка is not None else ""
        return OUT_YES, (
            f"шагу нужен {', '.join(sorted(нужно))}, модель отдаёт "
            f"{', '.join(sorted(свои))}{откуда}"
        )
    строка = next((f for f in facts if f.attribute == OUTPUT_ATTRIBUTE), None)
    откуда = f" [{строка.tier}] ({строка.source_url})" if строка is not None else ""
    return OUT_NO, (
        f"шагу нужен {', '.join(sorted(нужно))}, а модель отдаёт {', '.join(sorted(свои))}{откуда}"
    )


def life_stance(facts: Sequence[Fact], today: date | None = None) -> tuple[str, str]:
    """Кончилась ли служба модели. Разбор чужой (Е1), сведение — здесь.

    `studio/lifecycle.py` судит ОДНУ строку; у модели их много, и правило
    сведения названо вслух, потому что оно и есть решение: достаточно ОДНОЙ
    строки, у которой срок уже прошёл, чтобы модель считалась снятой, и одной
    объявленной — чтобы предупредить. Требовать согласия всех строк значило бы
    ждать, пока вендор повторит объявление в каждом документе.
    """
    сегодня = today or date.today()
    объявлено: list[tuple[Fact, life.Снятие]] = []
    for f in facts:
        снятие = life.разобрать(f.value, f.attribute, сегодня=сегодня)
        if снятие.outcome == life.ГОДНО:
            continue
        объявлено.append((f, снятие))
        if снятие.outcome == life.НЕ_ГОДНО:
            return LIFE_RETIRED, (
                f"{снятие.note}: {f.attribute}={f.value[:80]} "
                f"[{f.tier}, {f.stated_on or 'даты нет'}] ({f.source_url})"
            )
    if объявлено:
        f, снятие = объявлено[0]
        return LIFE_ANNOUNCED, (
            f"{снятие.note}: {f.attribute}={f.value[:80]} ({f.source_url}); "
            "модель ещё отвечает — это предупреждение, а не отказ"
        )
    return LIFE_LIVE, f"признаков снятия нет ни в одной из {len(facts)} строк"


def fit_stance(facts: Sequence[Fact], frame: tuple[int, int] | None) -> tuple[str, str]:
    """Где кандидат относительно поданного кадра: одно из четырёх положений и нота.

    Разбор строки и сравнение — целиком чужие (Е1): `studio/resolution.py`,
    написанный ровно для этого вопроса и уже стоящий под своим гейтом. Здесь
    только сведение НЕСКОЛЬКИХ строк одной модели в одно положение, и правило
    сведения названо вслух, потому что оно и есть решение:

    * хоть одна записанная строка кадр ПРИНИМАЕТ — `FIT_IN`. Строки модели
      описывают разные режимы и эндпоинты, и «модель предлагает режим, который
      этот кадр берёт» — достаточное основание. Брать строжайшую строку значило
      бы отвергать модель за то, что у неё есть ещё и мелкий режим;
    * ни одна не принимает, и КАЖДАЯ при этом разобрана — `FIT_OVER`. Это
      сильное утверждение и потому требует, чтобы неразобранных не осталось ни
      одной: неразобранная строка оставляет место режиму, которого мы не
      прочли;
    * строки есть, но согласия нет и что-то не разобрано — `FIT_UNPARSED`;
    * строк нет вовсе — `FIT_ABSENT`.
    """
    свои = limit_facts(facts)
    if frame is None:
        return "", "кадр не подан — сравнивать не с чем"
    if not свои:
        return FIT_ABSENT, "строк о разрешении 0: предел модели не записан"

    кадр = f"{frame[0]}x{frame[1]}"
    приняли: list[str] = []
    отвергли: list[str] = []
    не_смогли: list[str] = []
    for f in свои:
        предел = resolution.разобрать(f.value)
        итог = resolution.влезает(frame, предел)
        строка = f"{f.attribute}={f.value[:60]} -> {итог['note']} ({f.source_url})"
        {"годно": приняли, "не годно": отвергли, "не смогли": не_смогли}[итог["outcome"]].append(
            строка
        )

    счёт = (
        f"строк о разрешении {len(свои)}: принимают {len(приняли)}, "
        f"отвергают {len(отвергли)}, не разобрано {len(не_смогли)}"
    )
    if приняли:
        return FIT_IN, f"креатив {кадр}; {приняли[0]}; {счёт}"
    if отвергли and not не_смогли:
        return FIT_OVER, f"креатив {кадр}; {отвергли[0]}; {счёт}"
    образец = (отвергли or не_смогли)[0]
    return FIT_UNPARSED, f"креатив {кадр}; {образец}; {счёт}"


def to_budget_per(price: pricing.Price, budget: Budget) -> tuple[float | None, str]:
    """Цена, выраженная в «за что» бюджета. Не переводится — `None`, а не догадка.

    Вынесено отдельной функцией (Т5): здесь стоят ДВА РАЗНЫХ ЗАПРЕТА, и они
    обязаны проверяться порознь.

    ЕДИНИЦА НЕ ПЕРЕВОДИТСЯ НИКОГДА. Кредиты в доллары — курс, назначенный
    вендором, и он нигде не записан; любое число здесь было бы выдуманной
    ценой. Проверка стоит первой и не имеет исключений: таблица `PER_CONVERSION`
    единицу не содержит вовсе, и если кто-то заведёт «курс по умолчанию», ему
    придётся сломать эту строку, а не дописать словарь.

    «ЗА ЧТО» ПЕРЕВОДИТСЯ, но только внутри одного измерения и только по
    множителю-определению: шестьдесят секунд в минуте — не решение вендора.

    :returns: (число в «за что» бюджета, откуда оно взялось). Вторая половина
        пустая, когда переводить не пришлось, и НЕПУСТАЯ, когда пришлось: число,
        посчитанное нами, обязано называться посчитанным нами, а не выглядеть
        как записанное вендором.
    """
    if price.amount is None or price.unit != BUDGET_UNIT:
        return None, ""
    цели = budget.per or DEFAULT_PER
    if price.per in цели:
        return price.amount, ""
    for цель in цели:
        множитель = PER_CONVERSION.get((price.per, цель))
        if множитель is None:
            continue
        сколько = price.amount * множитель
        return сколько, (
            f"{CONVERTED_MARK}: {price.amount} {price.unit} за {price.per} "
            f"= {round(сколько, 6)} {price.unit} за {цель} "
            f"({int(SECONDS_IN_MINUTE)} секунд в минуте — определение единицы, не курс)"
        )
    return None, ""


def price_stance(facts: Sequence[Fact], budget: Budget) -> tuple[str, str]:
    """Где кандидат относительно потолка: одно из четырёх положений и нота.

    Числа разбирает `pipeline.comparable_prices`, то есть `studio/pricing.py`,
    и второго разборщика здесь нет. Своё тут одно — СРАВНЕНИЕ с тем, что назвал
    человек, и оно решает ПОРЯДОК, а не вердикт: вердикт по классу `цена`
    выносит валидатор, и он его вынесет сам.

    Приведение «за что» к бюджетному делает `to_budget_per`, и переведённое
    число называется переведённым прямо в ноте, рядом с исходной строкой.
    """
    свои = price_facts(facts)
    сравнимые, _прочие = pl.comparable_prices(свои)

    приведённые: list[tuple[Fact, pricing.Price, float, str]] = []
    for f, ц in сравнимые:
        сколько, откуда = to_budget_per(ц, budget)
        if сколько is not None:
            приведённые.append((f, ц, сколько, откуда))

    if not приведённые:
        if свои:
            образец = "; ".join(f"{f.attribute}={f.value[:48]}" for f in свои[:2])
            return (
                PRICE_INCOMPARABLE,
                f"ценовых строк {len(свои)}, сравнимых с потолком 0 ({образец})",
            )
        return (PRICE_ABSENT, "ценовых строк 0: посмотреть нечего")

    факт, дешёвая, нижняя, откуда = min(приведённые, key=lambda четыре: четыре[2])
    за_что = (budget.per or DEFAULT_PER)[0] if откуда else дешёвая.per
    счёт = (
        f"нижняя цена {round(нижняя, 6)} {дешёвая.unit} за {за_что}"
        + (f" [{откуда}]" if откуда else "")
        + f" ({факт.attribute}, {факт.source_url})"
    )
    if not budget.known:
        return (PRICE_INCOMPARABLE, f"{счёт}; потолка заказчик не назвал — сравнивать не с чем")
    потолок = float(budget.amount or 0.0)
    if нижняя > потолок:
        return (PRICE_OVER, f"{счёт} ВЫШЕ потолка {потолок} {BUDGET_UNIT}")
    условная = " (цена УСЛОВНАЯ: настоящая выше названной)" if дешёвая.conditional else ""
    return (PRICE_IN, f"{счёт} укладывается в потолок {потолок} {BUDGET_UNIT}{условная}")


def cheapest_price(facts: Sequence[Fact]) -> str:
    """Самая дешёвая СРАВНИМАЯ цена модели, словами. Нет такой — так и сказано.

    Разбор цены не повторяется здесь ни строкой: и разборщик
    (`studio/pricing.py`), и правило сравнимости (`pipeline.comparable_prices`)
    уже есть, и оба пришли из измеренного дефекта — 45 ценовых строк из 82
    разбирались неверно, когда за число выдавали первое попавшееся. Имена
    ценовых атрибутов с 2026-09-02 берутся у `attrfamily` (`price_facts`), а не
    подстрокой: под подстроку попадали `price_relative` и `storage_cost`.
    """
    свои = price_facts(facts)
    сравнимые, прочие = pl.comparable_prices(свои)
    if not сравнимые:
        сколько = len(прочие)
        хвост = f" (несравнимых ценовых строк {сколько})" if сколько else ""
        return f"{NO_PRICE}{хвост}"
    _, дешёвая = min(сравнимые, key=lambda пара: пара[1].amount or 0.0)
    return f"{дешёвая.amount} {pl.BUDGET_UNIT} за {дешёвая.per}"


def blocked_rank(c: Candidate) -> tuple[int, int]:
    """Насколько этим кандидатом НЕЛЬЗЯ воспользоваться: 0, 1 или 2.

    Одно поле ключа на всю ось невозможного, а не три соседних (Е1): «вход
    запрещён», «модель уже отключена» и «нужного вида не отдаёт» — разные
    свидетельства одного вывода, и три поля рядом означали бы, что одно из них
    старше другого, чего никто не решал.

    ЗНАЧЕНИЕ СОСТАВНОЕ, И ЭТО ПОЧИНКА, А НЕ УКРАШЕНИЕ. Сперва тут стоял просто
    МАКСИМУМ трёх ступеней — любая одна причина невозможности достаточна, и это
    верно. Но собственный тест показал (2026-09-02), что максимума МАЛО:
    `ban_state` почти у всех моделей `BAN_UNKNOWN` = 1, поэтому максимум у всех
    выходил 1, и кандидат с ПОДТВЕРЖДЁННЫМ выходом не мог обогнать того, о ком
    не известно ничего. Ось получалась двоичной: «нельзя» или «непонятно».

    Поэтому второе число — сколько ступеней ПОДТВЕРЖДЕНО (равны нулю), со
    знаком минус, чтобы больше подтверждений значило выше. Это по-прежнему ОДНО
    поле ключа (одна позиция в `KEY_FIELDS`), просто у него составное значение:
    сначала худшее препятствие, затем — сколько препятствий снято прямо.

    Три состояния при этом печатаются порознь и своими словами: в ключе они
    сходятся, в выдаче — нет, потому что чинить их надо по-разному.
    """
    ступени = (
        BAN_ORDER.get(c.ban_state, 0),
        LIFE_ORDER.get(c.life_state, 0),
        OUT_ORDER.get(c.out_state, 0),
    )
    return (max(ступени), -sum(1 for ш in ступени if ш == 0))


def by_evidence(c: Candidate) -> tuple:
    """Ключ порядка кандидатов, вынесенный из сортировки (Т5).

    Порядок ключей — это и есть решение модуля о том, что считать доводом, от
    сильного к слабому, и его поля перечислены в `KEY_FIELDS` в том же порядке:

    0. ПРИНИМАЕТ ЛИ КАДР (`FIT_ORDER`) — и только когда креатив ПОДАН. Стоит
       перед ценой, и это решение: модель, которая кадра не принимает, не
       запустится вовсе, а модель дороже потолка запустится и сделает работу,
       просто дорого. Невозможное старше нежелательного;
    1. ПОЛОЖЕНИЕ ПО ЦЕНЕ (`PRICE_ORDER`) — и только когда потолок НАЗВАН. Не
       назван — поле у всех нулевое, и цена не решает ничего: сравнивать не с
       чем, а порядок, зависящий от несравненного числа, был бы выдумкой.
       Деньги названы человеком, поэтому при названном потолке они старше
       любого нашего довода: тратит их он, а не прибор;
    2. сколько строк ПРИМЕНИМОСТИ: кто-то измерил или запустил. Одна такая
       строка обгоняет любое число вендорских — ради этого различия и заведена
       вторая ось;
    3. сколько утверждений вообще зацепилось за якоря операции: степень, с
       какой база связывает модель именно с этой работой;
    4. несёт ли имя модели якорный термин — слабое свидетельство, но
       непроизвольное, и оно решает ничью вместо алфавита;
    5. сколько строк способности;
    6. имя — чтобы порядок был воспроизводим.

    Цена названа вслух (И6): ключ 2 поднимает кандидата, о котором записано
    отрицательное наблюдение, выше кандидата, о котором не записано ничего.
    Это НЕ ошибка: валидатор увидит отрицательную применимость и скажет «не
    годно», назвав класс, — а «не смогли» на модели, о которой молчат, читатель
    не отличил бы от «годно». Молчание не лучше плохой новости, оно хуже.
    """
    запрет = blocked_rank(c)
    кадр = FIT_ORDER.get(c.fit_state, 0)
    цена = PRICE_ORDER.get(c.price_state, 0)
    return (
        запрет,
        кадр,
        цена,
        -c.applicability,
        -c.anchored,
        -int(c.named),
        -c.capability,
        c.model,
    )


def why_not(chosen: Candidate, neighbour: Candidate) -> str:
    """Почему выбран этот, а не сосед: ПЕРВОЕ поле ключа, которым они разошлись.

    Считается механически из самого ключа, а не пишется рядом словами: рядом
    написанное объяснение разъезжается с отбором молча, а это — тот же кортеж,
    по которому отбор и произошёл (Е2: имя выводится из того, что исполнилось).

    Полей ключа `len(KEY_FIELDS)`, и если разошлись не по одному из них, то не
    разошлись вовсе — так и печатается.
    """
    свой, чужой = by_evidence(chosen), by_evidence(neighbour)
    for i, (а, б) in enumerate(zip(свой, чужой)):
        if а != б:
            поле = KEY_FIELDS[i] if i < len(KEY_FIELDS) else f"поле {i}"
            return (
                f"выбран {chosen.model}, а не {neighbour.model}: разошлись по «{поле}» "
                f"({_поле(chosen, i)} против {_поле(neighbour, i)})"
            )
    return f"{chosen.model} и {neighbour.model} неразличимы всеми {len(KEY_FIELDS)} полями отбора"


def _поле(c: Candidate, i: int) -> str:
    """Значение i-го поля ключа ЧЕЛОВЕЧЕСКИМИ словами, а не числом из кортежа."""
    значения = (
        f"{c.ban_state or '—'} / {c.life_state or '—'} / {c.out_state or '—'}",
        c.fit_state or "не считалось",
        c.price_state or "не считалось",
        f"{c.applicability}",
        f"{c.anchored}",
        "да" if c.named else "нет",
        f"{c.capability}",
        c.model,
    )
    return значения[i] if i < len(значения) else "?"


def proven(found: Sequence[Candidate]) -> list[Candidate]:
    """Кандидаты, чья применимость ИЗМЕРЕНА, в порядке доводов без цены.

    Вынесено отдельной функцией (Т5): порог `RIVAL_MIN_APPLICABILITY` и способ
    выбрать сильнейшего среди проверенных — разные решения, и мутировать их
    надо порознь.

    Порядок здесь БЕЗ жёстких ограничений (`CONSTRAINT_KEYS`: запрет, кадр,
    цена), и это не
    небрежность: вопрос, на который отвечает эта функция, — «кто сильнее всех
    ДОКАЗАН», а не «кто дешевле и кто влезает». Ограничения заказчика уже
    сказали своё слово в общем отборе; повторить их здесь значило бы назвать
    вытесненным того же, кого они и вытеснили наверх.
    """
    # Запрещённый кандидат — не «проверенный, которого мы прошли мимо»: его
    # нельзя было выбрать вовсе. Назвать его вытесненным значило бы советовать
    # то, что не запустится.
    свои = [
        c
        for c in found
        if c.applicability >= RIVAL_MIN_APPLICABILITY
        and blocked_rank(c)[0] < BAN_ORDER[BAN_FORBIDS]
    ]
    свои.sort(key=lambda c: by_evidence(c)[CONSTRAINT_KEYS:])
    return свои


def banned_line(found: Sequence[Candidate]) -> str:
    """ОДНА строка на шаг о кандидатах, которыми воспользоваться НЕЛЬЗЯ.

    Одна на обе причины — запрет на вход и кончившийся срок службы, — потому
    что они лежат на одной оси (`blocked_rank`) и читателю нужен один ответ:
    кого выкинуло и почему. Причина названа своими словами, а не общими.

    Существует по той же причине, что `frame_rejects_line`: запрещённый
    кандидат по построению уходит в конец порядка и потому выпадает из
    показанных `CANDIDATES_SHOWN`. Порядок при этом верен, а видимость — нет,
    и на этом проекте это уже дважды был отдельный дефект.

    Пусто, когда запрещать некого, — негативный контроль, а не экономия.
    """
    невозможные = [c for c in found if blocked_rank(c)[0] >= BAN_ORDER[BAN_FORBIDS]]
    if not невозможные:
        return ""
    первый = невозможные[0]
    хвост = f" и ещё {len(невозможные) - 1}" if len(невозможные) > 1 else ""
    если = (
        (первый.ban_state, первый.ban_note)
        if первый.ban_state == BAN_FORBIDS
        else (первый.life_state, первый.life_note)
        if первый.life_state == LIFE_RETIRED
        else (первый.out_state, первый.out_note)
    )
    что, почему = если
    return f"{BLOCKED_MARK} ({что}): {первый.model}{хвост} — {почему}"


def frame_rejects_line(found: Sequence[Candidate]) -> str:
    """ОДНА строка на шаг о кандидатах, которых отверг поданный кадр.

    Пустая, когда отвергать некого, — и это негативный контроль, а не
    экономия: на кадре, который влезает всем, прибор обязан МОЛЧАТЬ, иначе он
    находит беду там, где её нет.

    Существует потому, что отвергнутый кандидат по построению уходит в конец
    порядка и выпадает из показанных `CANDIDATES_SHOWN`. Один — назван
    поимённо вместе с причиной; остальные — числом: список на шаг превращает
    предупреждение в шум, а число не даёт принять «показали одного» за «он
    один и был».
    """
    отвергнутые = [c for c in found if c.fit_state == FIT_OVER]
    if not отвергнутые:
        return ""
    первый = отвергнутые[0]
    хвост = f" и ещё {len(отвергнутые) - 1}" if len(отвергнутые) > 1 else ""
    return f"{REJECTED_BY_FRAME_MARK}: {первый.model}{хвост} — {первый.fit_note}"


def rival_line(chosen: Candidate | None, found: Sequence[Candidate]) -> str:
    """ОДНА строка на шаг о том, что стало с проверенными кандидатами.

    Три положения дел, и они печатаются ТРЕМЯ разными способами, а не двумя:

    * выбранный сам с измеренной применимостью — строки НЕТ. Она была бы шумом:
      читатель уже видит `применимость измерена: N строк(и)` у выбранного;
    * выбранный без измеренной, а проверенный среди найденных ЕСТЬ — строка
      `RIVAL_MARK` с именем сильнейшего проверенного и с тем, ЧЕМ он проиграл.
      Чем проиграл — берётся у `why_not`, то есть считается из того же ключа,
      по которому произошёл отбор (Е2), а не пишется рядом словами;
    * выбранный без измеренной, и проверенных НЕТ НИ ОДНОГО — строка
      `NO_RIVAL_MARK`, другими словами. Промолчать здесь значило бы сделать это
      положение неотличимым от первого, а это противоположные новости: там
      доказанное выбрано, тут доказанного не существует.

    Кандидата нет вовсе — строки нет: об этом уже сказано на месте выбранного,
    и второй раз о том же (Е1) здесь не говорится.
    """
    if chosen is None or chosen.measured:
        return ""
    проверенные = [c for c in proven(found) if c.model != chosen.model]
    if not проверенные:
        return (
            f"{NO_RIVAL_MARK}: ни у одного из {len(found)} найденных кандидатов "
            f"применимость не измерена — выбирать пришлось между непроверенными"
        )
    лучший = проверенные[0]
    return (
        f"{RIVAL_MARK}: {лучший.model} — {лучший.mark}"
        + (f", цена: {лучший.price}" if лучший.price else "")
        + f". {why_not(chosen, лучший)}"
    )


def candidates_for(
    op: Operation,
    index: FactIndex,
    overrides: dict | None = None,
    budget: Budget | None = None,
    frame: tuple[int, int] | None = None,
    today: date | None = None,
) -> list[Candidate]:
    """Кандидаты на операцию: модели, о которых база говорит СЛОВАМИ ОПЕРАЦИИ.

    Поиск здесь ровно один и он чужой (Е1): якоря подаются запросом в
    `studio.factindex.FactIndex`. Пол веса снят до нуля НАМЕРЕННО и это не
    ослабление отбора, а перенос его в другое место: запрос состоит ТОЛЬКО из
    якорных терминов, поэтому находится ровно то, что содержит якорь, и слово
    совпадения печатается у каждой строки доказательства. Порог, отделяющий
    случайное пересечение от настоящего, здесь не нужен — его работу делает
    словарь якорей, и он читается глазами, в отличие от числа.

    Пустой список — законный ответ и главная причина существования третьего
    исхода: `звук_фон` даёт его на живой базе.

    ЦЕНА СЧИТАЕТСЯ ПО ВСЕМ СТРОКАМ МОДЕЛИ, А НЕ ПО ЯКОРНЫМ. Найдено чтением
    выдачи 2026-09-02 (П3): у `latentsync` якорных строк три
    (`degrades_when` x2, `metric_blind_spot`) и цены среди них нет, а всего
    строк десять, и первая из них — `price = "$0.2 for videos up to 40
    seconds, then $0.005 per second"`. То есть цена была невидима планировщику
    целиком: якорь отвечает на вопрос «эта ли модель делает эту работу», а не
    «сколько она стоит». Полный набор строк берётся у `pipeline.facts_for` —
    там же, где разрешается написание имени (Е1).
    """
    потолок = budget or Budget(None, "", (), UNMEASURED, "бюджет не спрашивали")
    попадания = index.search(" ".join(op.anchors), k=len(index.facts) or 1, floor=0.0)
    по_модели: dict[str, list] = {}
    слова: dict[int, tuple[str, ...]] = {}
    for hit in попадания:
        if not _is_model(hit.fact.model):
            continue
        по_модели.setdefault(hit.fact.model, []).append(hit.fact)
        слова[id(hit.fact)] = hit.matched

    # Все строки модели, сгруппированные ОДНИМ проходом. `pl.facts_for` на
    # каждого кандидата давал бы обход всей базы на каждое имя: ИЗМЕРЕНО
    # 2026-09-02 — шаг липсинка вырос с 9 до 82 мс на 1781 строке. Разрешение
    # имени по-прежнему одно на проект (`modelnames.fold`, тот же, что зовёт
    # `pl.facts_for`), своей нормализации здесь нет (Е1).
    по_имени: dict[str, list[Fact]] = {}
    for f in index.facts:
        по_имени.setdefault(fold(f.model), []).append(f)

    найдены: list[Candidate] = []
    for имя, свои in по_модели.items():
        строки, применимость, способность, не_смогли = evidence_for(
            свои, слова, overrides, step_inputs(op)
        )
        # Строка-ЗАПРЕТ уходит в конец доводов: она не довод. Печатается она
        # под своим именем (`BAN_EVIDENCE_LABEL`), но и стоять первой в списке
        # оснований не должна — читают сверху.
        строки.sort(
            key=lambda e: (
                bool(e.forbids),
                e.axis != fa.APPLICABILITY_HEADER,
                e.stated_on or "",
                e.attribute,
            )
        )
        свёрнутое = имя.lower()
        все = по_имени.get(fold(имя), [])
        положение, нота = price_stance(все, потолок)
        по_кадру, нота_кадра = fit_stance(все, frame)
        по_входу, нота_входа = ban_stance(все, step_inputs(op))
        по_службе, нота_службы = life_stance(все, today)
        по_выходу, нота_выхода = output_stance(все, op.produces)
        найдены.append(
            Candidate(
                model=имя,
                evidence=tuple(строки[:EVIDENCE_SHOWN]),
                applicability=применимость,
                capability=способность,
                unresolved=не_смогли,
                price=cheapest_price(все),
                anchored=len(свои),
                named=any(якорь.lower() in свёрнутое for якорь in op.anchors),
                price_state=положение if потолок.known else "",
                price_note=нота,
                fit_state=по_кадру,
                fit_note=нота_кадра,
                ban_state=по_входу,
                ban_note=нота_входа,
                life_state=по_службе,
                life_note=нота_службы,
                out_state=по_выходу,
                out_note=нота_выхода,
            )
        )
    найдены.sort(key=by_evidence)
    return найдены


def to_pipeline(
    name: str,
    chosen: Sequence[tuple[Operation, Candidate | None]],
    have: frozenset[str] = frozenset(),
    budget_usd: float | None = None,
    use: str = pl.USE_COMMERCIAL,
) -> pl.Pipeline:
    """Собрать `pipeline.Pipeline` из выбранного. Шаг без кандидата — с пустой моделью.

    Пустая модель не прячется: валидатор увидит `нет_модели` и скажет это сам.
    Подставить сюда что-нибудь «чтобы прошло» — ровно тот запрет, ради
    которого модуль и писался.

    Артефакт, который у заказчика УЖЕ ЕСТЬ, заменяется на `референс` — вход
    плана, который валидатор признаёт таковым. Замена печатается в плане.
    """
    шаги = []
    for op, кандидат in chosen:
        требует = tuple(ARTEFACT_REFERENCE if a in have else a for a in op.requires)
        шаги.append(
            pl.Step(
                name=op.name,
                model=кандидат.model if кандидат else "",
                requirement=op.requirement,
                requires=требует,
                produces=op.produces,
                budget_usd=budget_usd,
                use=use,
            )
        )
    return pl.Pipeline(name=name, steps=tuple(шаги))


def plan(
    brief: str,
    facts: Sequence[Fact] | None = None,
    *,
    creative: str = "",
    budget_usd: float | None = None,
    use: str = pl.USE_COMMERCIAL,
    today: date | None = None,
    overrides: dict | None = None,
    index: FactIndex | None = None,
) -> dict:
    """План из брифа, тут же прогнанный через валидатор-2.

    :param facts: база утверждений. Не задана — берётся живая
        (`studio/knowledge/model_facts.jsonl`), сети при этом нет.
    :param creative: путь к поданному креативу, если он есть. Здесь читается
        только РАСШИРЕНИЕ — разбор пикселей делает `studio/mcp/creative.py`, и
        второго разборщика тут не заводится.
    :param budget_usd: потолок на шаг, если его назвал ВЫЗЫВАЮЩИЙ. Не назван —
        потолок ищется в самом брифе (`budget_from`). Названы оба — выигрывает
        параметр, и это записано в ноте: вызывающий назвал число явно, а из
        фразы оно выведено, и молча предпочесть выведенное значило бы решить
        за него.

    Числа Р2 печатаются рядом с исходом ВСЕГДА, в том числе на `годно`:
    сколько шагов выведено, у скольких есть кандидат, у скольких кандидат без
    единой строки применимости.
    """
    кадр, про_кадр = frame_of(creative)
    из_брифа = budget_from(brief)
    if budget_usd is not None:
        бюджет = Budget(
            float(budget_usd),
            BUDGET_UNIT,
            из_брифа.per,
            PASS,
            f"потолок {float(budget_usd)} {BUDGET_UNIT} назван параметром вызова"
            + (f"; в брифе при этом: {из_брифа.note}" if из_брифа.known else ""),
        )
    else:
        бюджет = из_брифа

    операции = derive(brief)
    есть = inputs_of(brief, creative)
    # Замыкание по нехватке: заказчик называет не все шаги, потому что для
    # него это одна работа. Добавленные шаги помечаются (см. `замкнуть`).
    операции, дописаны = замкнуть(операции, есть)
    if not операции:
        return {
            "outcome": UNMEASURED,
            "reason": REASON_NO_STEPS,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "note": (
                "ни одна из операций студии не выводится из этого брифа: "
                f"словарь знает {len(OPERATIONS)} операций, совпало 0. "
                "План не собирается — пустой шаг честнее выдуманного"
            ),
            "brief": brief,
            "budget": _budget_row(бюджет),
            "creative": _creative_row(creative, кадр, про_кадр),
            "steps": [],
            "classes": [],
            "validator": None,
        }

    индекс = index if index is not None else FactIndex(facts=facts) if facts else FactIndex()

    выбор: list[tuple[Operation, Candidate | None]] = []
    строки_шагов: list[dict] = []
    без_кандидата = 0
    без_применимости = 0
    дороже_потолка = 0
    кадр_не_принят = 0
    вход_запрещён = 0
    уже_снят = 0
    выход_не_тот = 0
    вытеснено_ценой = 0
    без_проверенных = 0
    for op in операции:
        предложены = candidates_for(op, индекс, overrides, бюджет, кадр, today)
        лучший = предложены[0] if предложены else None
        выбор.append((op, лучший))
        if лучший is None:
            без_кандидата += 1
        elif not лучший.measured:
            без_применимости += 1
        if лучший is not None and лучший.price_state == PRICE_OVER:
            дороже_потолка += 1
        if лучший is not None and лучший.fit_state == FIT_OVER:
            кадр_не_принят += 1
        if лучший is not None and лучший.ban_state == BAN_FORBIDS:
            вход_запрещён += 1
        if лучший is not None and лучший.life_state == LIFE_RETIRED:
            уже_снят += 1
        if лучший is not None and лучший.out_state == OUT_NO:
            выход_не_тот += 1
        строка_о_проверенных = rival_line(лучший, предложены)
        if строка_о_проверенных.startswith(RIVAL_MARK):
            вытеснено_ценой += 1
        elif строка_о_проверенных.startswith(NO_RIVAL_MARK):
            без_проверенных += 1
        подменено = sorted(a for a in op.requires if a in есть)
        строки_шагов.append(
            {
                "step": op.name,
                # Шаг, которого заказчик не называл: мы дописали его, потому
                # что иначе плану неоткуда взять артефакт. Пустая строка —
                # «шаг заказан», непустая называет ПРИЧИНУ, а не факт добавки.
                "inferred": (
                    f"дописан планом: {дописаны[op.name]} никем не производится и на входе его нет"
                    if op.name in дописаны
                    else ""
                ),
                "requirement": op.requirement,
                "anchors": list(op.anchors),
                "requires": list(op.requires),
                "produces": list(op.produces),
                "input_of_plan": подменено,
                "chosen": _candidate_row(лучший),
                "alternatives": [_candidate_row(c) for c in предложены[1:CANDIDATES_SHOWN]],
                "candidates_found": len(предложены),
                # Что стало с проверенными кандидатами: одна строка на шаг,
                # и три РАЗНЫХ положения дел в ней различимы (см. `rival_line`).
                "proven_rival": строка_о_проверенных,
                # Кандидаты, отвергнутые кадром: они уходят в конец порядка и
                # потому не попадают в показанные — одна строка на шаг.
                "rejected_by_frame": frame_rejects_line(предложены),
                # Кандидаты, чей вход база запрещает: уходят в конец порядка и
                # потому не попадают в показанные — одна строка на шаг.
                "banned_input": banned_line(предложены),
                "banned_count": sum(1 for c in предложены if c.ban_state == BAN_FORBIDS),
                "retired_count": sum(1 for c in предложены if c.life_state == LIFE_RETIRED),
                "wrong_output_count": sum(1 for c in предложены if c.out_state == OUT_NO),
                "announced_count": sum(1 for c in предложены if c.life_state == LIFE_ANNOUNCED),
                # Почему выбран этот, а не следующий за ним. Считается из того
                # же ключа, по которому произошёл отбор (Е2), а не пишется
                # рядом словами, которые с отбором разъедутся.
                "why_not_next": (
                    why_not(лучший, предложены[1])
                    if лучший is not None and len(предложены) > 1
                    else ""
                ),
            }
        )

    # ПОТОЛОК УХОДИТ ВАЛИДАТОРУ ТОЛЬКО КОГДА ОН «ЗА ПРОГОН ШАГА».
    # `pipeline.Step.budget_usd` документирован как бюджет ШАГА, и его ценовой
    # оракул сравнивает с ним самую дешёвую цену НЕЗАВИСИМО от её «за что».
    # Значит потолок «$0.10 за секунду», отданный туда как есть, сравнивается с
    # ценой «$0.6 за минуту» — и валидатор законно, по своим правилам, называет
    # класс `цена` там, где модель укладывается в потолок десятикратно.
    # Наблюдено 2026-09-02 в одной выдаче: наша строка говорила «в бюджете», а
    # строкой выше стоял класс `цена`. Одно противоречащее себе сообщение хуже
    # обоих по отдельности.
    #
    # Чинится НА СВОЕЙ СТОРОНЕ и вычитанием, а не добавлением: посекундный
    # потолок в поле пошагового бюджета — категорийная ошибка ЗДЕСЬ, а не в
    # валидаторе, и второго ценового оракула ради неё не заводится (Е1).
    # Валидатор в этом случае говорит «бюджет шага не заявлен» и считает это
    # ОТДЕЛЬНО от проверенного (Р2), а не молча зачитывает как успех.
    пошаговый = бюджет.known and bool(set(бюджет.per or DEFAULT_PER) & set(DEFAULT_PER))
    трубa = to_pipeline(
        brief.strip()[:80] or "план", выбор, есть, бюджет.amount if пошаговый else None, use
    )
    отчёт = pl.pipeline_report(трубa, list(индекс.facts), today, overrides)

    if без_кандидата:
        исход, причина = UNMEASURED, REASON_NO_CANDIDATES
        нота = (
            f"шагов выведено {len(операции)}, из них без единого кандидата {без_кандидата}: "
            "модель по умолчанию не подставляется"
        )
    elif отчёт["outcome"] == FAIL:
        исход, причина = FAIL, REASON_PLAN_REFUSED
        нота = f"валидатор-2 отверг план: {отчёт['note']}"
    elif отчёт["outcome"] == UNMEASURED:
        исход, причина = UNMEASURED, REASON_PLAN_UNCONFIRMED
        нота = f"валидатор-2 не смог подтвердить план: {отчёт['note']}"
    else:
        исход, причина = PASS, REASON_PLAN_STANDS
        нота = f"валидатор-2 не опроверг план: {отчёт['note']}"

    строка_бюджета = _budget_row(бюджет)
    if бюджет.known and not пошаговый:
        строка_бюджета["note"] += (
            f". Валидатору потолок НЕ передан: его поле — бюджет ШАГА "
            f"({', '.join(DEFAULT_PER)}), а этот назван за {', '.join(бюджет.per)}; "
            "подставить одно в другое значило бы сравнить разное. В отборе "
            "кандидатов потолок при этом участвует полностью"
        )
    return {
        "outcome": исход,
        "reason": причина,
        "checked": отчёт["checked"],
        "violations": отчёт["violations"],
        "unmeasured": отчёт["unmeasured"] + без_кандидата,
        "note": (
            f"{нота}; шагов {len(операции)}, без кандидата {без_кандидата}, "
            f"кандидат без применимости {без_применимости}, "
            f"дороже потолка {дороже_потолка}, "
            f"проверенный вытеснен ценой {вытеснено_ценой}, "
            f"проверенных нет вовсе {без_проверенных}, "
            f"кадр не принимают {кадр_не_принят}, "
            f"вход запрещён {вход_запрещён}, "
            f"уже снятых выбрано {уже_снят}, "
            f"выход не тот {выход_не_тот}"
        ),
        "brief": brief,
        "budget": строка_бюджета,
        "creative": _creative_row(creative, кадр, про_кадр),
        "steps": строки_шагов,
        "classes": list(отчёт["classes"]),
        "validator": отчёт,
    }


def _budget_row(b: Budget) -> dict:
    """Бюджет в выдаче ВСЕГДА, даже когда его нет: отсутствие — это ответ.

    Поле, появляющееся только при удаче, читается как «раз не написано —
    значит неважно», а тут ровно наоборот: «потолка нет» и «потолок 0.5» ведут
    к разным планам, и разница обязана быть видна без чтения ноты.
    """
    return {
        "amount": b.amount,
        "unit": b.unit,
        "per": list(b.per),
        "outcome": b.outcome,
        "note": b.note,
    }


def _creative_row(creative: str, frame: tuple[int, int] | None, note: str) -> dict:
    """Замер креатива в выдаче ВСЕГДА, даже когда креатива нет.

    По той же причине, что и бюджет: поле, появляющееся только при удаче,
    читается как «раз не написано — значит неважно», а «кадр не подан» и «кадр
    1536x2752» ведут к разным планам.
    """
    return {
        "path": creative,
        "width": frame[0] if frame else None,
        "height": frame[1] if frame else None,
        "outcome": PASS if frame else UNMEASURED,
        "note": note,
    }


def _candidate_row(c: Candidate | None) -> dict | None:
    if c is None:
        return None
    return {
        "model": c.model,
        "mark": c.mark,
        "applicability": c.applicability,
        "capability": c.capability,
        "unresolved": c.unresolved,
        "price": c.price,
        "price_state": c.price_state,
        "price_note": c.price_note,
        "fit_state": c.fit_state,
        "fit_note": c.fit_note,
        "ban_state": c.ban_state,
        "ban_note": c.ban_note,
        "life_state": c.life_state,
        "life_note": c.life_note,
        "out_state": c.out_state,
        "out_note": c.out_note,
        "evidence": [
            {
                "attribute": e.attribute,
                "value": e.value,
                "tier": e.tier,
                "stated_on": e.stated_on,
                "kind": e.kind,
                "axis": e.axis,
                "source_url": e.source_url,
                "matched": list(e.matched),
                "forbids": e.forbids,
            }
            for e in c.evidence
        ],
    }


def render(итог: dict) -> str:
    """Печать плана. Пометка о неизмеренной применимости — в строке модели.

    Она стоит там нарочно: читатель видит имя модели и решает по этой строке,
    а не по вложенному списку доказательств, до которого он может не дойти.
    """
    строки = [
        f"бриф: {итог['brief']}",
        (
            f"исход: {fa.OUTCOME_WORDS.get(итог['outcome'], итог['outcome'])} "
            f"[{итог['reason']}] — {итог['note']}"
        ),
        f"классы валидатора: {', '.join(итог['classes']) or 'ни один не сработал'}",
        (
            f"проверено {итог['checked']}, нарушений {итог['violations']}, "
            f"не смогли {итог['unmeasured']}"
        ),
    ]
    креатив = итог.get("creative") or {}
    if креатив.get("path"):
        строки.append(
            f"креатив: {креатив.get('width')}x{креатив.get('height')} "
            f"[{fa.OUTCOME_WORDS.get(str(креатив.get('outcome')), креатив.get('outcome'))}]"
            f" — {креатив.get('note', '')}"
        )
    бюджет = итог.get("budget") or {}
    if бюджет:
        сумма = бюджет.get("amount")
        сколько = "не назван" if сумма is None else f"{сумма} {бюджет.get('unit', '')}"
        исход = str(бюджет.get("outcome", ""))
        строки.append(
            f"бюджет: {сколько} [{fa.OUTCOME_WORDS.get(исход, исход)}] — {бюджет.get('note', '')}"
        )
    for s in итог["steps"]:
        выбран = s["chosen"]
        if выбран is None:
            строки.append(
                f"  шаг {s['step']}: КАНДИДАТА НЕТ — база молчит о якорях {', '.join(s['anchors'])}"
            )
            continue
        строки.append(f"  шаг {s['step']}: {выбран['model']} — {выбран['mark']}")
        # СРАЗУ под именем модели, до цены и до доказательств: читателя, который
        # дальше первой строки шага не пойдёт, это касается больше всего.
        if s.get("proven_rival"):
            строки.append(f"      {s['proven_rival']}")
        по_входу = выбран.get("ban_state") or ""
        if по_входу and по_входу != BAN_UNKNOWN:
            строки.append(f"      вход шага: {по_входу} — {выбран.get('ban_note', '')}")
        по_службе = выбран.get("life_state") or ""
        if по_службе and по_службе != LIFE_LIVE:
            строки.append(f"      срок службы: {по_службе} — {выбран.get('life_note', '')}")
        по_выходу = выбран.get("out_state") or ""
        if по_выходу:
            строки.append(f"      выход шага: {по_выходу} — {выбран.get('out_note', '')}")
        if s.get("banned_input"):
            строки.append(f"      {s['banned_input']}")
        по_кадру = выбран.get("fit_state") or ""
        if по_кадру:
            строки.append(f"      кадр: {по_кадру} — {выбран.get('fit_note', '')}")
        if s.get("rejected_by_frame"):
            строки.append(f"      {s['rejected_by_frame']}")
        положение = выбран.get("price_state") or ""
        строки.append(
            f"      цена: {выбран['price']}"
            + (f" — {положение}: {выбран.get('price_note', '')}" if положение else "")
        )
        if s.get("why_not_next"):
            строки.append(f"      почему не сосед: {s['why_not_next']}")
        if s["input_of_plan"]:
            строки.append(
                f"      вход плана (у заказчика уже есть): {', '.join(s['input_of_plan'])}"
            )
        for e in выбран["evidence"]:
            подпись = BAN_EVIDENCE_LABEL if e.get("forbids") else "чем выбран"
            строки.append(
                f"      {подпись}: {e['attribute']}={e['value'][:70]} "
                f"[{e['tier']}, {e['stated_on'] or 'даты нет'}, {e['kind'] or 'род не выведен'}]"
                f" {e['source_url']}"
            )
        прочие = ", ".join(
            f"{a['model']} ({a['mark']}"
            + (f"; {a['fit_state']}" if a.get("fit_state") else "")
            + (f"; {a['price_state']}" if a.get("price_state") else "")
            + ")"
            for a in s["alternatives"]
        )
        if прочие:
            строки.append(f"      ещё кандидаты ({s['candidates_found']} всего): {прочие}")
    return "\n".join(строки)


DEFAULT_BRIEFS_PATH = Path(__file__).with_name("fixtures") / "planner_briefs.jsonl"


def briefs(path: Path = DEFAULT_BRIEFS_PATH) -> list[dict]:
    """Контрольный набор брифов. Негодная строка ПРОПУСКАЕТСЯ и ловится гейтом.

    Форма взята у `pipeline.load_controls`: рядом живёт `rows_in`, и гейт
    сравнивает два числа, чтобы молча пропавший контроль был виден.
    """
    if not path.is_file():
        return []
    набор: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        try:
            row = json.loads(line)
        except ValueError:
            continue
        if not isinstance(row, dict) or not row.get("id") or "brief" not in row:
            continue
        if row.get("expect_outcome") not in (PASS, FAIL, UNMEASURED):
            continue
        if row.get("expect_reason") not in REASONS:
            continue
        набор.append(row)
    return набор


def rows_in(path: Path = DEFAULT_BRIEFS_PATH) -> int:
    """Сколько строк данных в файле контроля, годных и негодных вместе."""
    if not path.is_file():
        return 0
    return sum(
        1
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("//")
    )
