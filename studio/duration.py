"""Длительность из прозы в секунды — и предел модели рядом с ней.

ЗАЧЕМ

Заказчик называет длительность почти всегда: из тринадцати настоящих брифов
владельца двое говорят её прямо («10 секунд», «15 секунд»), а в свободных
формулировках она звучит ещё чаще («ролик на 30 секунд для рекламы»).
Планировщик до 2026-09-03 не сравнивал её НИ С ЧЕМ: слово «max_seconds» в
`studio/planner.py` не встречалось ни разу, хотя предел длительности записан
у 47 моделей.

ИЗМЕРЕНО 2026-09-03 на живой базе, по всем кандидатам семи операций (84
места):

    ролик 10 с   влезает 18, НЕ влезает  1, предел не записан 65
    ролик 15 с   влезает 11, НЕ влезает  8, предел не записан 65
    ролик 30 с   влезает  2, НЕ влезает 17, предел не записан 65

То есть на тридцатисекундном ролике из девятнадцати кандидатов с записанным
пределом работу сделают ДВА, а планировщик предлагал любого.

ПОЧВА ТОНКАЯ, И ЭТО ЧАСТЬ ОТВЕТА

Предел записан у 47 моделей из 543. На большинстве кандидатов честный ответ —
«не записано», и он печатается рядом с остальными (Р2): «модель не подойдёт»
и «мы не знаем, подойдёт ли» — разные новости, и лечатся они по-разному.

ЗНАЧЕНИЯ — ПРОЗА, И ПЕРЕПИСЫВАТЬ ИХ НЕЛЬЗЯ

    «15»
    «4-15 seconds, integer values only»
    «5, 10 (enum)»
    «up to 60 s at 720p, 30 s at 1080p»
    «max_duration_ms: 30000»

Значение факта — то, что сказал источник (правило дома). Разбор живёт здесь,
как у цен и у разрешения, и по той же причине: пересказ числом теряет
оговорку, ради которой источник и писал.

ЧЕТЫРЕ ПОЛОЖЕНИЯ, А НЕ ТРИ

    влезает          предел разобран и он не меньше запрошенного
    НЕ влезает       предел разобран и он меньше
    предел не записан о длительности этой модели база молчит
    предел не разобран строка есть, числа из неё не вышло

Третье и четвёртое различаются намеренно: молчание базы лечится сбором, а
неразобранная строка — разборщиком, и свести их значило бы не знать, куда
идти. «Не записано» при этом НИГДЕ не равно «подойдёт».
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Sequence

__all__ = [
    "DUR_ABSENT",
    "DUR_IN",
    "DUR_NOT_ASKED",
    "DUR_ASK_UNPARSED",
    "DUR_ORDER",
    "DUR_OVER",
    "DUR_UNPARSED",
    "Запрос",
    "Предел",
    "влезает",
    "предел_из_строк",
    "просят",
]

#: Четыре положения. Порядок — порядок при отборе: невозможное последним.
DUR_IN = "длительность принимает"
DUR_ABSENT = "предел длительности не записан"
DUR_UNPARSED = "предел длительности не разобран"
DUR_OVER = "ролик ДЛИННЕЕ предела"

#: ПЯТОЕ положение, и оно не про модель, а про БРИФ: длительность не названа,
#: сравнивать не с чем. Отдельно от «предел не записан», потому что лечится
#: другим: тем нужен сбор, этому — вопрос заказчику. Свернуть их в одно
#: значило бы написать «предел не записан» о модели, у которой он записан, —
#: что я и увидел, прочитав первую выдачу глазами (П3).
DUR_NOT_ASKED = "длительность не спрашивали"

#: ШЕСТОЕ положение, и оно про БРИФ, как и пятое: заказчик длительность НАЗВАЛ,
#: а разборщик её не понял («полторы минуты»). Отдельно от «не спрашивали»,
#: потому что лечится другим — правкой РАЗБОРЩИКА, а не вопросом заказчику, — и
#: отдельно от «предел не разобран», потому что там не понята строка БАЗЫ.
#: Ранг тот же, что у «не спрашивали»: положение стоит у ВСЕХ кандидатов сразу
#: и порядка не решает, а поднимать в отборе модели без записанного предела
#: из-за нашего же непонимания было бы наказанием за чужую аккуратность.
DUR_ASK_UNPARSED = "длительность в брифе не разобрана"

#: КОНСТАНТА-РЕШЕНИЕ. `не записан` стоит ВЫШЕ `не разобран`, и это не
#: придирка: строка, которую мы не смогли прочесть, скорее всего содержит
#: предел, а молчание базы не содержит ничего. Обе хуже подтверждённого
#: согласия и обе лучше прямого отказа.
DUR_ORDER: dict[str, int] = {
    DUR_IN: 0,
    # Ранг тот же, что у «не записан»: когда длительность не спрашивали, это
    # положение стоит у ВСЕХ кандидатов сразу и порядка не решает.
    DUR_NOT_ASKED: 1,
    DUR_ASK_UNPARSED: 1,
    DUR_ABSENT: 1,
    DUR_UNPARSED: 2,
    DUR_OVER: 3,
}

#: Сколько секунд в минуте. ВЫБРАНО как определение, а не как измерение —
#: помечено, потому что рядом стоит `PER_CONVERSION` планировщика, где
#: множители тоже определения и это оговорено.
СЕКУНД_В_МИНУТЕ = 60
СЕКУНД_В_ЧАСЕ = 3600

#: Как заказчик называет длительность. Порядок важен: минуты проверяются
#: раньше секунд, иначе «2 минуты 30 секунд» прочитается как 30.
#:
#: ЧАСЫ ДОБАВЛЕНЫ 2026-09-08. НАЙДЕНО продуктовой проверкой на живых брифах:
#: «Переозвучьте наш вебинар 2 ЧАСА 15 минут» разбиралось как 900 с — ровно в
#: девять раз меньше настоящих 8100. По этому числу выбирается модель,
#: считается цена и проверяется предел длительности, то есть ошибается всё
#: сразу и в одну сторону — в занижение.
ПРОСЬБА = (
    (
        re.compile(r"(\d+(?:[.,]\d+)?)[\s-]*(?:час\w*|ч\b|hours?\b|hrs?\b|h\b)", re.I),
        СЕКУНД_В_ЧАСЕ,
    ),
    (
        re.compile(r"(\d+(?:[.,]\d+)?)[\s-]*(?:минут\w*|мин\b|minutes?\b|min\b)", re.I),
        СЕКУНД_В_МИНУТЕ,
    ),
    (
        re.compile(r"(\d+(?:[.,]\d+)?)[\s-]*(?:секунд\w*|сек\b|seconds?\b|sec\b|s\b)", re.I),
        1,
    ),
)

#: Тайм-код ЦЕЛИКОМ, три части. НАЙДЕНО той же проверкой: «Материалы приложены:
#: video.mp4 (00:01:20)» — длительность названа, и продукт отвечал «не названа».
#:
#: ТОЛЬКО ТРЁХЧАСТНАЯ ФОРМА, И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА: двухчастная
#: «9:16» — это формат кадра, а не минуты с секундами, и разобрать её как
#: 556 с значило бы выдумать длительность там, где её нет.
ТАЙМКОД = re.compile(r"\b(\d{1,2}):([0-5]\d):([0-5]\d)\b")

#: Сколько символов допускается МЕЖДУ частями составной длительности. ВЫБРАНО
#: 3: столько занимает « и » — «2 часа и 15 минут». Больше нельзя: «ролик 30
#: секунд, вебинар 2 часа» — это два РАЗНЫХ числа, и складывать их незачем.
РАЗРЫВ_СОСТАВНОЙ = 3

#: СЛОВА О ДЛИТЕЛЬНОСТИ БЕЗ ЧИСЛА ЦИФРАМИ. Нужны затем, чтобы отличить «не
#: сказал» от «сказал, а мы не разобрали»: это Р1, и разница здесь стоит
#: дорого. ИЗМЕРЕНО проверкой продукта 2026-09-06: бриф «…вертикаль, 15 секунд»
#: отбраковывал шесть моделей по длине, а тот же бриф словами «полторы минуты»
#: печатал «длительность в брифе не названа» — утверждение О ВХОДЕ, где оно
#: ложно, — и проверка длины при этом молча исчезала: заказчик получал план без
#: единого признака, что она не отработала.
СЛОВА_О_ДЛИТЕЛЬНОСТИ = re.compile(
    # ЧАСЫ И «ПОЛТОРА» — ЭТО ТРЕТИЙ ИСХОД, А НЕ МОЛЧАНИЕ (2026-09-08).
    # «Полтора часа» разбиралось как «длительность не названа», хотя названа:
    # честный ответ — «слова есть, числа не нашлось, РАЗОБРАТЬ НЕ СМОГЛИ».
    r"\b(?:полторы|полтора|полутора|полминуты|полчаса|минут\w*|секунд\w*|минуту|"
    r"час\w*|hours?|"
    r"пару\s+минут|несколько\s+минут|minutes?|seconds?)\b",
    re.I,
)

#: Единицы, в которых записан предел. `ms` ловится ОТДЕЛЬНО и первым: строка
#: `max_duration_ms=30000` без этого прочиталась бы как 30000 секунд, то есть
#: восемь часов, и любой ролик «влез» бы. Поймано на живой базе.
МИЛЛИСЕКУНДЫ = re.compile(r"(\d+(?:\.\d+)?)\s*(?:ms\b|millisecond)", re.I)
МИЛЛИСЕКУНД_В_ИМЕНИ = re.compile(r"_ms$|_millis", re.I)

#: Числа в строке предела. Берётся МАКСИМУМ: «4-15 seconds» — это диапазон, и
#: потолок у него 15; «5, 10 (enum)» — перечень, и самый длинный ролик 10.
ЧИСЛО = re.compile(r"\d+(?:\.\d+)?")

#: Слова, при которых число в строке НЕ является пределом длительности. Без
#: них «up to 60 s at 720p, 30 s at 1080p» дало бы 720 (номер строки развёртки
#: прочитался бы как секунды).
НЕ_СЕКУНДЫ = re.compile(r"\d+\s*(?:p\b|px\b|k\b|fps\b|%|\$|мп\b|mp\b)", re.I)


@dataclass(frozen=True)
class Запрос:
    """Сколько секунд просит заказчик. `секунды is None` — не сказал."""

    секунды: float | None
    нота: str
    #: False — в брифе БЫЛИ слова о длительности, но разобрать их не удалось.
    #: `секунды is None` при этом значит не «не сказал», а «не смогли», и
    #: вызывающий обязан считать это неизмеримостью, а не молчанием заказчика.
    разобрано: bool = True


@dataclass(frozen=True)
class Предел:
    """Сколько секунд принимает модель, и чем это положение обосновано."""

    секунды: float | None
    состояние: str
    нота: str


def просят(текст: str) -> Запрос:
    """Длительность из брифа. Не названа — так и говорится, а не 0."""
    низ = " ".join(str(текст or "").split())
    if not низ:
        return Запрос(None, "брифа нет — длительности в нём тоже нет")
    тк = ТАЙМКОД.search(низ)
    if тк:
        часы, минуты, секунды_тк = (int(г) for г in тк.groups())
        всего = часы * СЕКУНД_В_ЧАСЕ + минуты * СЕКУНД_В_МИНУТЕ + секунды_тк
        return Запрос(float(всего), f"в брифе названо {тк.group(0)!r} — это {всего:g} с (тайм-код)")
    # ВСЕ ЧАСТИ, А НЕ ПЕРВАЯ. «2 часа 15 минут» — одно число, записанное двумя
    # словами, и взять из него одно слово значит ошибиться в разы. Складываются
    # только СОСЕДНИЕ части в порядке убывания единицы: разрыв больше
    # `РАЗРЫВ_СОСТАВНОЙ` или единица, которая не меньше предыдущей, — это уже
    # другое число, и оно не наше.
    части = sorted(
        (
            (
                м.start(),
                м.end(),
                м.group(0),
                float(м.group(1).replace(",", ".")) * множитель,
                множитель,
            )
            for образец, множитель in ПРОСЬБА
            for м in образец.finditer(низ)
        ),
        key=lambda ч: ч[0],
    )
    if части:
        взяты = [части[0]]
        for часть in части[1:]:
            конец, единица = взяты[-1][1], взяты[-1][4]
            if часть[0] - конец <= РАЗРЫВ_СОСТАВНОЙ and часть[4] < единица:
                взяты.append(часть)
            else:
                break
        секунды = sum(ч[3] for ч in взяты)
        названо = " ".join(ч[2] for ч in взяты)
        куда = {СЕКУНД_В_ЧАСЕ: "часов", СЕКУНД_В_МИНУТЕ: "минут"}.get(взяты[0][4], "секунд")
        куда = куда if len(взяты) == 1 else "составная"
        return Запрос(секунды, f"в брифе названо {названо!r} — это {секунды:g} с ({куда})")
    слова = СЛОВА_О_ДЛИТЕЛЬНОСТИ.search(низ)
    if слова:
        # ТРЕТИЙ ИСХОД, А НЕ ПЕРВЫЙ (Р1). «Не разобрали» и «не сказали» лечатся
        # разным: первое — правкой разбора, второе — вопросом заказчику. Свернув
        # их, продукт утверждает о входе то, чего в нём нет, и заодно молча
        # выключает проверку длины.
        return Запрос(
            None,
            f"в брифе есть слова о длительности ({слова.group(0)!r}), но числа в них "
            "не нашлось — РАЗОБРАТЬ НЕ СМОГЛИ, а не «не спрашивали»: длина не проверена",
            разобрано=False,
        )
    return Запрос(None, "длительность в брифе не названа — сравнивать не с чем")


def предел_из_строк(строки: Sequence[tuple[str, str]]) -> Предел:
    """Наибольшая длительность, которую модель берёт, по записанным строкам.

    На вход — пары (имя атрибута, значение), уже отобранные семьёй атрибутов
    (Е1: список имён живёт в `studio/selfrag/attrfamily.py`, здесь его нет).
    """
    if not строки:
        return Предел(None, DUR_ABSENT, "о длительности этой модели база молчит")
    лучшее: float | None = None
    откуда = ""
    for имя, значение in строки:
        текст = str(значение or "")
        мс = МИЛЛИСЕКУНДЫ.search(текст) or (
            ЧИСЛО.search(текст) if МИЛЛИСЕКУНД_В_ИМЕНИ.search(имя) else None
        )
        if мс:
            секунды = float(мс.group(1) if мс.lastindex else мс.group(0)) / 1000.0
        else:
            очищено = НЕ_СЕКУНДЫ.sub(" ", текст)
            числа = [float(ч) for ч in ЧИСЛО.findall(очищено)]
            if not числа:
                continue
            секунды = max(числа)
        if лучшее is None or секунды > лучшее:
            лучшее, откуда = секунды, f"{имя}={текст[:70]}"
    if лучшее is None:
        return Предел(
            None,
            DUR_UNPARSED,
            f"строк о длительности {len(строки)}, числа из них не вышло: "
            f"{строки[0][0]}={str(строки[0][1])[:60]}",
        )
    return Предел(лучшее, DUR_IN, f"предел {лучшее:g} с: {откуда}")


def влезает(запрос: Запрос, предел: Предел) -> Предел:
    """Положение модели относительно запрошенной длительности. Четыре исхода.

    Запрос не назван — это НЕ «влезает»: сравнивать не с чем, и объявлять
    согласие по несравнённому числу было бы выдумкой. Возвращается положение
    `не записан`/`не разобран` как есть, с прежней нотой.
    """
    if предел.состояние in (DUR_ABSENT, DUR_UNPARSED):
        return предел
    if запрос.секунды is None:
        # «НЕ СПРАШИВАЛИ» ТОЛЬКО ТОГДА, КОГДА ПРАВДА НЕ СПРАШИВАЛИ. Приёмка
        # 2026-09-06: при неразобранной длительности вердикт кандидата говорил
        # «длительность не спрашивали», печать плана подавляла строку о пределе
        # (у модели он ЕСТЬ и записан), а «оси без ответа» посылали чинить сбор
        # фактов вместо разборщика. Шапка этого модуля прямо запрещает такое
        # смешение: молчание базы лечится сбором, неразобранная строка —
        # разборщиком. Починка была сделана этажом выше и остановилась на
        # первом из трёх мест (И7: грепнуть форму, а не место).
        состояние = DUR_NOT_ASKED if запрос.разобрано else DUR_ASK_UNPARSED
        return Предел(предел.секунды, состояние, f"{предел.нота}; {запрос.нота}")
    if предел.секунды is None:
        return Предел(None, DUR_ABSENT, f"{предел.нота}; {запрос.нота}")
    if предел.секунды + 1e-9 >= запрос.секунды:
        return Предел(
            предел.секунды,
            DUR_IN,
            f"{запрос.секунды:g} с ролика при пределе {предел.секунды:g} с ({предел.нота})",
        )
    return Предел(
        предел.секунды,
        DUR_OVER,
        f"ролик {запрос.секунды:g} с ДЛИННЕЕ предела {предел.секунды:g} с ({предел.нота})",
    )
