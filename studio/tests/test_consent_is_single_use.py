"""Одно согласие оплачивает ОДНО видео, а не сколько нажмут.

ВОСПРОИЗВЕДЕНО 2026-09-05 независимым аудитом на живом приложении: кадр →
`/api/consent` → три подряд `POST /api/video` одной сессией. Все три вернули
200, раннер вызван три раза, баланс 99 → 69, то есть заказчик заплатил трижды
за одно согласие (~$0.70 за прогон).

ХУЖЕ ТОГО, ВТОРОЕ И ТРЕТЬЕ ВИДЕО ШЛИ БЕЗ ОДОБРЕННОГО КАДРА. Кадр берётся из
`session["last_job_id"]`, а после первого видео там уже видео-джоба — в вызовах
2 и 3 `payload["frame"] is None`. То есть человек платит за генерацию, которой
не показывали то, на что он соглашался.

`consent_state` пропускала стадии `consented`, `video_running` И `done`. Стадия
`done` в этом списке и есть дыра: завершённая работа — не разрешение начать
новую, а именно она остаётся в сессии после первого видео.

Двойной клик в интерфейсе — обычное дело, и он не должен стоить денег.

Имена стадий — литералы (Т2): это протокол между сервером и страницей, и его
молчаливое переименование ломает поток у заказчика, а не в тесте.
"""

from __future__ import annotations

import unittest

from studio import app as A

СОГЛАСИЕ_ДАНО = "consented"
ВИДЕО_ИДЁТ = "video_running"
ЗАВЕРШЕНО = "done"
КАДР_ПОКАЗАН = "frame_shown"


def _сессия(стадия: str) -> dict:
    """Сессия с УЖЕ показанным кадром: сюда смотрит только вторая половина."""
    return {"stage": стадия, "last_job_id": "job-1", "frame_shown": True}


class СогласиеОдноразовое(unittest.TestCase):
    def setUp(self) -> None:
        # `frame_state` судит по джобе; подменяем его на «кадр показан», чтобы
        # мерить ИМЕННО согласие, а не готовность кадра.
        self._было = A.frame_state
        A.frame_state = lambda s: {  # type: ignore[assignment]
            "outcome": "pass",
            "checked": 1,
            "violations": 0,
            "unmeasured": 0,
            "note": "кадр показан",
        }
        self.addCleanup(lambda: setattr(A, "frame_state", self._было))

    def test_после_согласия_видео_разрешено(self) -> None:
        self.assertEqual(A.consent_state(_сессия(СОГЛАСИЕ_ДАНО))["outcome"], "pass")

    def test_пока_видео_идёт_второе_не_разрешено(self) -> None:
        """Двойной клик приходит именно сюда."""
        итог = A.consent_state(_сессия(ВИДЕО_ИДЁТ))
        self.assertNotEqual(итог["outcome"], "pass")
        self.assertIn("уже", итог["note"].lower())

    def test_завершённая_работа_не_разрешение_начать_новую(self) -> None:
        """Проверяется НОТА, а не только исход.

        Мутация, убирающая ветку `done`, промолчала на первой редакции этого
        теста: дальше стоит `стадия != STAGE_CONSENTED`, и вердикт выходил тот
        же. Но заказчику эти два отказа говорят разное — «вы не соглашались» и
        «по этому согласию видео уже сделано», — и второй объясняет, почему
        кнопка не работает. Сторожить надо то, ради чего ветка написана.
        """
        итог = A.consent_state(_сессия(ЗАВЕРШЕНО))
        self.assertNotEqual(итог["outcome"], "pass")
        self.assertIn("уже сделано", итог["note"].lower())

    def test_без_согласия_по_прежнему_отказ(self) -> None:
        """Негативный контроль (И5): починка не должна разучить прибор отказывать."""
        итог = A.consent_state(_сессия(КАДР_ПОКАЗАН))
        self.assertEqual(итог["outcome"], "fail")


if __name__ == "__main__":
    unittest.main()
