class ВопросВПлане(unittest.TestCase):
    def test_пустой_план_с_вопросом_меняет_причину(self):
        итог = planner.plan("Сделайте нам вертикальный ролик для маркетплейса: товар, музыка")
        self.assertEqual("нужен_ответ_заказчика", итог["reason"])
        self.assertEqual("не смогли", "не смогли")
        self.assertEqual([], итог["steps"])
        self.assertEqual("есть_ли_исходное_видео", итог["question"]["axis"])

    def test_пустой_план_без_вопроса_остаётся_прежней_причиной(self):
        итог = planner.plan("Посчитайте юнит-экономику подписки на год")
        self.assertEqual("шаги_не_выведены", итог["reason"])
        self.assertIsNone(итог["question"])

    def test_причина_есть_в_словаре_причин(self):
        self.assertIn("нужен_ответ_заказчика", planner.REASONS)

    def test_вопрос_не_отменяет_выведенных_шагов(self):
        """Р1: неполный план остаётся тем, что измерено, вопрос лишь назван рядом."""
        итог = planner.plan("Портрет клиента должен ожить и поприветствовать по имени")
        self.assertTrue(итог["steps"], "шаги пропали вместе с появлением вопроса")
        self.assertEqual("должен_ли_говорить", итог["question"]["axis"])
        self.assertNotEqual("нужен_ответ_заказчика", итог["reason"])

    def test_поле_вопроса_есть_всегда(self):
        """Поле, появляющееся только при удаче, читается как «раз не написано —
        значит нечего спрашивать», а это разные утверждения."""
        итог = planner.plan("Нужно озвучить текст и синхронизировать губы персонажа")
        self.assertIn("question", итог)

    def test_вопрос_печатается(self):
        текст = planner.render(
            planner.plan("Сделайте нам вертикальный ролик для маркетплейса: товар, музыка")
        )
        self.assertIn("ВОПРОС [есть_ли_исходное_видео]", текст)
        self.assertIn("видео есть", текст)


if __name__ == "__main__":
    unittest.main()
