"""Один вопрос вместо догадки: что он обязан спрашивать и где обязан молчать.

Т2: ожидаемое здесь — ЛИТЕРАЛЫ. Имена осей и куски текста вопроса написаны
руками, а не импортированы из `studio.clarify`: импортированное ожидание
поедет вместе с кодом и промолчит.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

from studio import clarify, planner

НАБОР = Path(__file__).resolve().parents[2] / "studio" / "knowledge" / "brief_wordings.jsonl"


def спросить(бриф: str):
    """Вопрос так, как его получает заказчик: после замыкания плана."""
    есть = planner.inputs_of(бриф)
    операции, _ = planner.замкнуть(planner.derive(бриф), есть)
    return planner.вопрос_по_плану(бриф, операции, есть)


class ГдеСпрашиваем(unittest.TestCase):
    def test_пустой_план_на_нашей_задаче_получает_вопрос(self):
        вопрос = спросить("Сделайте нам вертикальный ролик для маркетплейса: товар, музыка")
        self.assertIsNotNone(вопрос)
        self.assertEqual("есть_ли_исходное_видео", вопрос.ось)

    def test_неполный_план_получает_вопрос_про_речь(self):
        вопрос = спросить("Портрет клиента должен ожить и поприветствовать по имени")
        self.assertIsNotNone(вопрос)
        self.assertEqual("должен_ли_говорить", вопрос.ось)

    def test_открыты_обе_оси_вопрос_всё_равно_один(self):
        """Анкету заказчик не заполняет: неизвестного два, спрошено одно."""
        вопрос = спросить("Нужен ролик: клиента надо поприветствовать по имени")
        self.assertIsNotNone(вопрос)
        self.assertEqual("есть_ли_исходное_видео", вопрос.ось)

    def test_исходник_спрашивается_раньше_речи(self):
        """Порядок — константа-решение: ответ про исходник меняет больше плана."""
        вопрос = clarify.спросить(
            "Нужен ролик, где преподаватель говорит",
            производится=(),
            есть=(),
            артефакт_видео=planner.ARTEFACT_VIDEO,
            артефакт_аудио=planner.ARTEFACT_AUDIO,
        )
        self.assertEqual("есть_ли_исходное_видео", вопрос.ось)


class ГдеМолчим(unittest.TestCase):
    def test_негативный_контроль_ни_одного_вопроса_на_чужой_задаче(self):
        """И5: «есть ли у вас отснятое видео?» в ответ на юнит-экономику — та же
        ложь продукта, что и лишний шаг, только вежливее."""
        задано = []
        всего = 0
        for строка in НАБОР.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if not строка or строка.startswith("//"):
                continue
            случай = json.loads(строка)
            if случай["как_сказано"] != "мимо":
                continue
            всего += 1
            вопрос = спросить(случай["бриф"])
            if вопрос is not None:
                задано.append(f"{случай['бриф']} -> {вопрос.ось}")
        self.assertEqual(10, всего, "контрольных брифов стало меньше — проверять нечем")
        self.assertEqual([], задано)

    def test_видео_на_входе_снимает_вопрос_про_исходник(self):
        вопрос = clarify.спросить(
            "Нужен ролик по нашему сценарию",
            производится=(),
            есть=(planner.ARTEFACT_VIDEO,),
            артефакт_видео=planner.ARTEFACT_VIDEO,
            артефакт_аудио=planner.ARTEFACT_AUDIO,
        )
        self.assertIsNone(вопрос)

    def test_шаг_производящий_видео_снимает_вопрос(self):
        """Дописанный замыканием шаг закрывает нехватку — переспрашивать нечего."""
        вопрос = clarify.спросить(
            "Нужен ролик по нашему сценарию",
            производится=(planner.ARTEFACT_VIDEO,),
            есть=(),
            артефакт_видео=planner.ARTEFACT_VIDEO,
            артефакт_аудио=planner.ARTEFACT_AUDIO,
        )
        self.assertIsNone(вопрос)

    def test_без_речи_снимает_вопрос_про_речь(self):
        вопрос = clarify.спросить(
            "Портрет должен ожить и поприветствовать, но без речи",
            производится=(planner.ARTEFACT_VIDEO,),
            есть=(),
            артефакт_видео=planner.ARTEFACT_VIDEO,
            артефакт_аудио=planner.ARTEFACT_AUDIO,
        )
        self.assertIsNone(вопрос)

    def test_упомянутый_не_в_первой_фразе_ролик_не_вопрос(self):
        """«Начитка диктора по нашему тексту, один голос на весь ролик»: просят
        начитку, ролик лишь обстоятельство. План уже полон, вопрос был бы шумом."""
        self.assertIsNone(спросить("Начитка диктора по нашему тексту, один голос на весь ролик"))

    def test_пустой_бриф_не_спрашивает(self):
        self.assertIsNone(спросить("   "))


class ОтветЗакрываетВопрос(unittest.TestCase):
    """Механизм, который спрашивает одно и то же дважды, хуже молчащего.

    ИЗМЕРЕНО 2026-09-03 на четырёх брифах, ради которых он и заведён: после
    одного ответа три из четырёх собирают полный план, четвёртый переходит ко
    ВТОРОЙ оси (а не переспрашивает первую) и закрывается вторым ответом.
    """

    def test_ответ_про_исходник_снимает_свой_вопрос(self):
        вопрос = спросить("Нужен рекламный ролик с закадровым текстом по нашему сценарию")
        self.assertEqual("есть_ли_исходное_видео", вопрос.ось)
        после = спросить(
            "Нужен рекламный ролик с закадровым текстом по нашему сценарию. "
            "Снимать нечего, делаем с нуля."
        )
        self.assertIsNone(после)

    def test_ответ_про_речь_снимает_свой_вопрос(self):
        вопрос = спросить("Портрет клиента должен ожить и поприветствовать по имени")
        self.assertEqual("должен_ли_говорить", вопрос.ось)
        после = спросить(
            "Портрет клиента должен ожить и поприветствовать по имени. Он должен говорить вслух."
        )
        self.assertIsNone(после)

    def test_вторая_ось_не_повторяет_первую(self):
        бриф = (
            "Курс на английском: те же уроки, но чтобы преподаватель говорил по-английски "
            "Видео уже снято, уроки есть."
        )
        вопрос = спросить(бриф)
        self.assertIsNotNone(вопрос)
        self.assertEqual("должен_ли_говорить", вопрос.ось)

    def test_оба_ответа_закрывают_вопросы_совсем(self):
        бриф = (
            "Курс на английском: те же уроки, но чтобы преподаватель говорил по-английски "
            "Видео уже снято, уроки есть. Он должен говорить вслух."
        )
        self.assertIsNone(спросить(бриф))


