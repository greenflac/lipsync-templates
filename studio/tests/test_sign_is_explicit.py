"""Знак применимости берётся у ФАКТА, а не угадывается по имени атрибута.

ВОСПРОИЗВЕДЕНО 2026-09-05 на живой базе, самым дорогим способом: оплаченным
замером. Прогон sync-lipsync дал ОТРИЦАТЕЛЬНЫЙ результат — зубы квадратные,
по губе артефакты, — и я записал его под именем `holds_identity`. Этого имени
нет в `factaxis.CONTRA_ATTRIBUTES`, поэтому валидатор прочитал запись как
«применимость закрыта, не опровергнута» и объявил план ГОДНЫМ:

    исход плана: pass | выбран: sync-lipsync | за 1 | против 0
    применимость   pass   применимость закрыта 1 относящимися строк(ами), не опровергнута

То есть первое в истории проекта «годно» было ложным, и получено оно было из
плохой новости. База починена руками в тот же час, но правило «клади плохую
новость под правильное имя» держалось на аккуратности автора — а такое правило
не держится (Ц7).

ПОЧЕМУ НЕ ПРИБОР ПО ТЕКСТУ. Первая попытка искала в значении слова провала
(«артефакт», «ломается», «fail»). ИЗМЕРЕНО на живой базе: 5 срабатываний, из
них 4 ложных — «fails on rare characters» в описании бенчмарка, «failure_mode»
внутри ссылки на соседнюю строку. Прибор с четырьмя ложными из пяти выключат
на второй день, и это будет правильно.

Поэтому знак ОБЪЯВЛЯЕТСЯ ЯВНО полем факта, а по имени атрибута выводится
только там, где поле не заполнено — то есть у 2100 старых строк, которые никто
не будет переписывать.
"""

from __future__ import annotations

import unittest

import studio.factaxis as fa
from studio.selfrag.facts import Fact

#: Литералы (Т2): имена берутся не из проверяемого модуля.
ПОЛОЖИТЕЛЬНОЕ_ИМЯ = "holds_identity"
ОТРИЦАТЕЛЬНОЕ_ИМЯ = "failure_mode"


def _замер(attribute: str, *, contra: bool | None = None) -> Fact:
    return Fact(
        model="sync-lipsync",
        attribute=attribute,
        # Слова требования в значении — иначе прибор отношения (`relates`)
        # честно скажет «не относится», и тест мерил бы поиск, а не знак.
        value="губы и зубы на крупном плане: рот вставленный, лицо не плывёт, синхрон держится",
        source_url="https://queue.fal.run/fal-ai/sync-lipsync",
        tier="probe",
        stated_on="2026-09-05",
        witnessed="прогон 6.58 с, смотрено глазами шесть кадров",
        contra=contra,
    )


class ЗнакУФакта(unittest.TestCase):
    def test_плохая_новость_под_хорошим_именем_всё_равно_плохая(self) -> None:
        """Тот самый случай: имя положительное, знак объявлен отрицательным."""
        вердикт = fa.step_verdict(
            "липсинк",
            "губы держат синхрон всю реплику, лицо не плывёт",
            fa.mark_all([_замер(ПОЛОЖИТЕЛЬНОЕ_ИМЯ, contra=True)]),
        )
        self.assertEqual(вердикт["outcome"], "fail")
        self.assertEqual(вердикт["violations"], 1)

    def test_без_объявленного_знака_решает_имя(self) -> None:
        """Совместимость с 2100 старыми строками: поля нет — работает прежнее правило."""
        плохое = fa.step_verdict(
            "липсинк",
            "губы держат синхрон всю реплику, лицо не плывёт",
            fa.mark_all([_замер(ОТРИЦАТЕЛЬНОЕ_ИМЯ)]),
        )
        self.assertEqual(плохое["outcome"], "fail")
        хорошее = fa.step_verdict(
            "липсинк",
            "губы держат синхрон всю реплику, лицо не плывёт",
            fa.mark_all([_замер(ПОЛОЖИТЕЛЬНОЕ_ИМЯ)]),
        )
        self.assertEqual(хорошее["outcome"], "pass")

    def test_объявленный_плюс_перебивает_отрицательное_имя(self) -> None:
        """Обратная сторона (Т1): знак решает в ОБЕ стороны, иначе он не знак.

        Случай не выдуманный: `failure_mode` со значением «этого провала больше
        нет, проверено прогоном» — законная запись, и читать её как провал
        значило бы вечно держать модель отвергнутой за уже починенное.
        """
        вердикт = fa.step_verdict(
            "липсинк",
            "губы держат синхрон всю реплику, лицо не плывёт",
            fa.mark_all([_замер(ОТРИЦАТЕЛЬНОЕ_ИМЯ, contra=False)]),
        )
        self.assertEqual(вердикт["outcome"], "pass")
        self.assertEqual(вердикт["violations"], 0)


class ЗнакДоезжаетИзФайла(unittest.TestCase):
    """Поле обязано пережить дорогу «файл -> объект».

    ЗАЧЕМ ОТДЕЛЬНЫЙ ТЕСТ. Мутация, заменяющая чтение `contra` из строки файла на
    постоянный None, ПРОМОЛЧАЛА на всех прочих наборах: они строят факт в
    памяти и до файла не доходят. Знак, объявленный при записи и потерянный при
    чтении, — это ровно тот дефект, от которого всё это заведено, только тише.
    """

    def test_объявленный_знак_читается_обратно(self) -> None:
        import json
        import tempfile
        from pathlib import Path

        from studio.selfrag.facts import load_facts

        каталог = Path(tempfile.mkdtemp())
        файл = каталог / "facts.jsonl"
        строки = [
            {
                "model": "m",
                "attribute": ПОЛОЖИТЕЛЬНОЕ_ИМЯ,
                "value": "плохо",
                "source_url": "https://t.test/1",
                "tier": "probe",
                "stated_on": "2026-09-05",
                "contra": True,
            },
            {
                "model": "m",
                "attribute": ОТРИЦАТЕЛЬНОЕ_ИМЯ,
                "value": "хорошо",
                "source_url": "https://t.test/2",
                "tier": "probe",
                "stated_on": "2026-09-05",
                "contra": False,
            },
            {
                "model": "m",
                "attribute": ПОЛОЖИТЕЛЬНОЕ_ИМЯ,
                "value": "без знака",
                "source_url": "https://t.test/3",
                "tier": "probe",
                "stated_on": "2026-09-05",
            },
        ]
        файл.write_text(
            "\n".join(json.dumps(с, ensure_ascii=False) for с in строки), encoding="utf-8"
        )
        по_значению = {ф.value: ф for ф in load_facts(файл)}
        self.assertIs(по_значению["плохо"].contra, True)
        self.assertIs(по_значению["хорошо"].contra, False)
        self.assertIsNone(
            по_значению["без знака"].contra, "нет ключа — знак НЕ объявлен, а не «хороший»"
        )
        self.assertTrue(fa.is_contra(по_значению["плохо"]))
        self.assertFalse(fa.is_contra(по_значению["хорошо"]))


if __name__ == "__main__":
    unittest.main()
