"""Английское владение: набор `brought_inputs_english.jsonl` под разбором.

ЭТО ВОСПРОИЗВЕДЕНИЕ ДЕФЕКТА (И2), А НЕ ЕГО ПОЧИНКА, и часть набора КРАСНАЯ
НАРОЧНО. Разбор владения живёт в `studio/planner.py` (`ВЛАДЕНИЕ`,
`HAVE_VIDEO_CUES`, `HAVE_AUDIO_CUES`, `ПРОСЬБА`, `_оборот_владения`) — это
чужая территория (Ц2), и правка туда предложена отчётом, а не сделана здесь.
Красный тест — это и есть измеренная граница: он зеленеет ровно тогда, когда
предложенные строки применены, и ни минутой раньше.

ИЗМЕРЕНО 2026-09-07 на этом наборе, `planner.принесено` без правки:

    английское владение (положительные)   6 из 54
    негативные контроли (владения нет)   24 из 24
    русский `brought_inputs.jsonl`       28 из 28

То есть промах ОДНОСТОРОННИЙ: продукт не путает просьбу с владением, он
просто не узнаёт владения — и потому переспрашивает уже отвеченное и
дописывает оплачиваемый шаг генерации видео к брифу, где сказано «our
footage». На прототипе предложенной правки (тот же набор, тот же прибор):
54 из 54 и 24 из 24, русский набор без регресса 28 из 28.

Р2: числа печатаются рядом с вердиктом — «ноль нарушений» при нуле
прочитанных строк не успех.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

from studio import planner

НАБОР = Path(__file__).resolve().parents[1] / "fixtures" / "brought_inputs_english.jsonl"


def строки() -> list[dict]:
    прочитано = []
    for строка in НАБОР.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("//"):
            continue
        прочитано.append(json.loads(строка))
    return прочитано


class НаборЧитается(unittest.TestCase):
    def test_поля_на_месте_и_идентификаторы_уникальны(self):
        прочитано = строки()
        self.assertGreaterEqual(len(прочитано), 60)
        for r in прочитано:
            self.assertEqual({"id", "принёс", "бриф"}, set(r), r)
            self.assertTrue(r["бриф"].strip(), r)
            # Т2: ожидание — литерал набора, а не значение из planner.
            for а in r["принёс"]:
                self.assertIn(а, ("видео", "аудио"), r)
        self.assertEqual(len(прочитано), len({r["id"] for r in прочитано}))

    def test_есть_обе_стороны(self):
        """И5: набор без негативных контролей меряет не то."""
        прочитано = строки()
        с_владением = [r for r in прочитано if r["принёс"]]
        без = [r for r in прочитано if not r["принёс"]]
        self.assertGreaterEqual(len(с_владением), 20, f"положительных {len(с_владением)}")
        self.assertGreaterEqual(len(без), 10, f"негативных контролей {len(без)}")


class РазборНабора(unittest.TestCase):
    def test_негативный_контроль_просьба_не_читается_владением(self):
        """Зелёный СЕГОДНЯ и обязан остаться зелёным после правки: «I need my
        video made» — просьба, а не принесённое."""
        промахи = [
            (r["id"], sorted(planner.inputs_of(r["бриф"])))
            for r in строки()
            if not r["принёс"] and planner.inputs_of(r["бриф"])
        ]
        контролей = len([r for r in строки() if not r["принёс"]])
        self.assertEqual(
            [], промахи, f"негативных контролей {контролей}, ложно узнано {len(промахи)}"
        )

    def test_английское_владение_узнаётся(self):
        """КРАСНЫЙ ДО ПРАВКИ `planner` — это воспроизведение дефекта (И2).

        Зеленеет применением строк, перечисленных в отчёте: английские слова
        владения в `ВЛАДЕНИЕ`, английские притяжательные обороты в
        `HAVE_VIDEO_CUES`/`HAVE_AUDIO_CUES`, глаголы работы над материалом в
        левом контексте `_оборот_владения`, пропущенные английские слова
        заказа в `ПРОСЬБА`, `narration` и `reel` в `СЛОВА_ВХОДА`.
        """
        ожидаемо = [r for r in строки() if r["принёс"]]
        промахи = [
            (r["id"], r["бриф"], sorted(planner.inputs_of(r["бриф"])), sorted(r["принёс"]))
            for r in ожидаемо
            if sorted(planner.inputs_of(r["бриф"])) != sorted(r["принёс"])
        ]
        self.assertEqual(
            [],
            промахи,
            f"положительных строк {len(ожидаемо)}, узнано "
            f"{len(ожидаемо) - len(промахи)}, не узнано {len(промахи)}",
        )


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
