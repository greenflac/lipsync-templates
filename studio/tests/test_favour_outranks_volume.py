"""Что считается доводом ЗА модель: объём написанного или то, что говорит за неё.

ЗАЧЕМ. ИЗМЕРЕНО 2026-09-05 на живом брифе «есть готовое видео и своя дорожка —
сделай липсинк»: планировщик выбирал `latentsync` (4 строки применимости, из
них 3 о том, где ломается) вместо `sync-lipsync` (3 строки, из них 1 плохая), и
выбирал ИМЕННО количеством. Платный замер на снятом видео владельца в тот же
день сказал обратное: sync-lipsync сохраняет 54% относительной резкости рта
против 14% у latentsync — втрое лучше.

Порядок по общему числу строк выбирал модель, о которой БОЛЬШЕ ПЛОХОГО
написано. Теперь считается то, что говорит ЗА, а общее число решает ничью.

Ожидаемое — литералы (Т2), сети нет (Т4), развилка вызывается функцией (Т5).
"""

from __future__ import annotations

import unittest

from studio.planner import Candidate, by_evidence, why_not


def кандидат(model: str, применимость: int, против: int) -> Candidate:
    return Candidate(
        model=model,
        evidence=(),
        applicability=применимость,
        capability=0,
        unresolved=0,
        price="",
        against=против,
    )


class ЗаМодельВесомееОбъёма(unittest.TestCase):
    #: Живые числа того самого брифа.
    LATENTSYNC = ("latentsync", 4, 3)
    SYNC = ("sync-lipsync", 3, 1)

    def test_меньше_строк_но_больше_за_обгоняет(self):
        свой = кандидат(*self.SYNC)
        чужой = кандидат(*self.LATENTSYNC)
        self.assertLess(by_evidence(свой), by_evidence(чужой))

    def test_объяснение_называет_то_поле_которым_разошлись(self):
        """Строка «почему не сосед» считается из того же кортежа, по которому
        произошёл отбор (Е2). Печать, отставшая от ключа, уже подводила: поле
        называлось верно, а числа печатались чужие."""
        нота = why_not(кандидат(*self.SYNC), кандидат(*self.LATENTSYNC))
        self.assertIn("строк применимости ЗА модель", нота)
        self.assertIn("(2 против 1)", нота)

    def test_молчание_по_прежнему_хуже_плохой_новости(self):
        """Негативный контроль (И5): правка не смеет поднять кандидата, о
        котором не записано НИЧЕГО, выше того, о ком записано плохое. «Не
        смогли» на модели, о которой молчат, читатель не отличил бы от
        «годно»."""
        молчит = кандидат("о-нём-молчат", 0, 0)
        плохой = кандидат("о-нём-плохое", 2, 2)
        self.assertLess(by_evidence(плохой), by_evidence(молчит))

    def test_при_равном_числе_за_решает_общее_число(self):
        """Общее число не выброшено: оно говорит, насколько плотно база
        связывает модель с работой, и решает ничью."""
        # ОБА СПОРНЫЕ, И ЭТО УСЛОВИЕ, А НЕ ДЕТАЛЬ ФИКСТУРЫ: первая версия
        # сравнивала спорного с чистым, ступень знака решала раньше счёта, и
        # тест мерил не то поле, о котором говорит его имя.
        плотнее = кандидат("плотнее", 5, 3)
        реже = кандидат("реже", 3, 1)
        self.assertEqual(плотнее.in_favour, реже.in_favour)
        self.assertLess(by_evidence(плотнее), by_evidence(реже))

    def test_чистое_измерение_обгоняет_спорное_раньше_счёта(self):
        """Ступень знака стоит выше счёта и остаётся на месте: два «за» при
        трёх «против» не обгоняют одно «за» без единого «против»."""
        # ДВЕ СТРОКИ, А НЕ ОДНА: одна строка с 2026-09-07 — «чисто по
        # бедности» (`SIGN_THIN`), отдельная ступень ниже спорного. Тест про
        # то, что ступень знака решает РАНЬШЕ счёта, и это по-прежнему так.
        чистый = кандидат("чистый", 2, 0)
        спорный = кандидат("спорный", 5, 3)
        self.assertLess(by_evidence(чистый), by_evidence(спорный))
