"""Разрешение из прозы в числа: что разбирается, и что обязано НЕ разобраться.

Половина этих тестов — негативный контроль (И5). Выдуманный предел хуже
отсутствующего: по нему человек заплатит за прогон, который вендор отвергнет.
"""

from __future__ import annotations

import unittest

from studio import resolution as R


class Разбор(unittest.TestCase):
    def test_пара_чисел_сильнее_ступени(self):
        """«1920:1080 (1080p max, no 4K)» — источник назвал числа сам, и брать
        за него ступень значит терять точность, которая уже в строке."""
        п = R.разобрать("1920:1080 (1080p max, no 4K); enum 1280:720, 720:1280")
        self.assertEqual((п.длинная, п.короткая), (1920, 1080))
        self.assertEqual(п.outcome, "годно")

    def test_четыре_разделителя_равноправны(self):
        """Звёздочка нашлась не в голове, а в базе: `1280*704 or 704*1280`."""
        for текст in ("3840x2160", "3840:2160", "3840 × 2160", "3840*2160"):
            with self.subTest(текст=текст):
                self.assertEqual(R.разобрать(текст).длинная, 3840)

    def test_из_перечисления_берётся_потолок(self):
        """Вопрос «влезет ли» — про верх, а источники перечисляют enum и от
        меньшего, и от большего."""
        п = R.разобрать("1280:720, 720:1280, 3840:2160, 960:960")
        self.assertEqual((п.длинная, п.короткая), (3840, 2160))

    def test_ступень_задаёт_только_одну_сторону(self):
        """`720p` — высота 720 при ЛЮБОЙ ширине: 1280x720 и 720x1280 оба
        «720p». Подставить вторую сторону по 16:9 значит решить за вендора,
        какое соотношение он допускает."""
        п = R.разобрать("720p")
        self.assertEqual(п.короткая, 720)
        self.assertIsNone(п.длинная)

    def test_отрицание_ступени_пределом_не_становится(self):
        """«1080p max, no 4K» — 4K здесь запрещено, а не разрешено."""
        п = R.разобрать("max 1080p, no 4K")
        self.assertEqual(п.короткая, 1080)

    def test_верхняя_граница_диапазона(self):
        п = R.разобрать("width and height between 512 and 2048 px")
        self.assertEqual((п.длинная, п.короткая), (2048, 2048))


class ЧтоНеРазбирается(unittest.TestCase):
    """И5: прибор обязан сказать «нет» там, где сказать нечего."""

    def test_мегапиксели_это_другая_величина(self):
        """«up to 4MP output»: вопрос «влезет ли 1536x2752» решается по площади
        только вместе с допустимым соотношением сторон, которого в строке нет.
        Выдуманный предел хуже отсутствующего."""
        self.assertEqual(R.разобрать("up to 4MP output").outcome, "не годно")

    def test_пустое_это_третий_исход_а_не_второй(self):
        self.assertEqual(R.разобрать("").outcome, "не смогли")

    def test_число_внутри_числа_ступенью_не_считается(self):
        self.assertEqual(R.разобрать("21080px of nothing").outcome, "не годно")


class Влезает(unittest.TestCase):
    КАДР = (1536, 2752)

    def test_кадр_больше_предела_это_отказ(self):
        итог = R.влезает(self.КАДР, R.разобрать("720p"))
        self.assertEqual(итог["outcome"], "не годно")
        self.assertIn("1536", итог["note"], "названо, какая сторона и на сколько")

    def test_кадр_влезает(self):
        self.assertEqual(R.влезает(self.КАДР, R.разобрать("3840x2160"))["outcome"], "годно")

    def test_ориентация_значения_не_имеет(self):
        """Вертикальный 1536x2752 и горизонтальный 2752x1536 — один и тот же
        запрос к модели, объявляющей обе ориентации."""
        предел = R.разобрать("3840x2160")
        self.assertEqual(
            R.влезает((1536, 2752), предел)["outcome"],
            R.влезает((2752, 1536), предел)["outcome"],
        )

    def test_неразобранный_предел_это_не_влезает(self):
        """Третий исход не сворачивается в первый: «мы не знаем, подходит ли» —
        не «подходит»."""
        self.assertEqual(R.влезает(self.КАДР, R.разобрать("up to 4MP"))["outcome"], "не смогли")

    def test_ступень_сравнивает_только_названную_сторону(self):
        """`4K` задаёт ширину 3840 и молчит о высоте. Сравнить можно длинную
        сторону, и только её — а не объявить, что влезло всё."""
        итог = R.влезает((1536, 2752), R.разобрать("4K"))
        self.assertEqual(итог["outcome"], "годно")
        self.assertIn("длинная", итог["note"])
        self.assertNotIn("короткая", итог["note"])


if __name__ == "__main__":
    unittest.main()
