"""У применимости есть ЗНАК, и порядок отбора обязан его видеть.

ВОСПРОИЗВЕДЕНО 2026-09-05 сухим прогоном на живой базе (2118 строк). Бриф
«Оживи фотографию и сделай липсинк под мою дорожку»:

    шаг липсинк выбран: latentsync — «применимость измерена: 2 строк(и)»
    обе строки: failure_mode «зубы и губы мылятся на 256x256»
                degrades_when «точность липсинка покупается ценой стабильности»

То есть обе измеренные строки — ПЛОХИЕ НОВОСТИ, и ровно они делают кандидата
самым доказанным. Дальше валидатор смотрит на них же и говорит «не годно»:
план не может сойтись НИКОГДА, потому что победитель отбора выбран за то, за
что его потом отвергают.

ЧЕГО ЭТОТ НАБОР НЕ ТРЕБУЕТ. Он НЕ отменяет правило «молчание хуже плохой
новости»: кандидат с отрицательной строкой обязан по-прежнему обгонять того,
о ком не записано ничего — это решение модуля, оно объяснено в `by_evidence`
и проверяется здесь отдельным тестом, чтобы починка не снесла его заодно.

Требуется ровно одно: кандидат, о котором есть ХОРОШАЯ измеренная новость,
обгоняет кандидата, о котором есть только плохие, даже если плохих больше.
Иначе оплаченный замер не может ничего изменить — а замеры и есть то, ради
чего вторая ось заведена.

Знак берётся у `studio/factaxis.py` (`CONTRA_ATTRIBUTES`) и вторым списком
здесь НЕ переписывается (Е1); имена в ожиданиях — литералы (Т2).
"""

from __future__ import annotations

import unittest

from studio import planner as pn


def _кандидат(имя: str, *, применимость: int, против: int, способность: int = 0) -> pn.Candidate:
    return pn.Candidate(
        model=имя,
        evidence=(),
        applicability=применимость,
        capability=способность,
        unresolved=0,
        price="цена не записана",
        anchored=применимость + способность,
        against=против,
    )


class ЗнакПрименимости(unittest.TestCase):
    def test_чистое_измерение_обгоняет_спорное(self) -> None:
        """Главный случай: валидатор отвергает шаг по ЛЮБОЙ отрицательной
        относящейся строке, поэтому спорный кандидат впереди чистого — это
        план, который не сойдётся никогда."""
        спорный = _кандидат("а-спорный", применимость=9, против=1)
        чистый = _кандидат("я-чистый", применимость=1, против=0)
        порядок = sorted([спорный, чистый], key=pn.by_evidence)
        self.assertEqual([c.model for c in порядок], ["я-чистый", "а-спорный"])

    def test_ступени_знака_названы_числами(self) -> None:
        """Лестница достижима отдельно от ключа (Т5), и у неё четыре ступени."""
        self.assertEqual(pn.sign_rank(_кандидат("x", применимость=2, против=0)), 0)
        self.assertEqual(pn.sign_rank(_кандидат("x", применимость=2, против=1)), 1)
        self.assertEqual(pn.sign_rank(_кандидат("x", применимость=2, против=2)), 2)
        self.assertEqual(pn.sign_rank(_кандидат("x", применимость=0, против=0)), 3)

    def test_одна_хорошая_строка_обгоняет_две_плохие(self) -> None:
        """Тот самый случай с живой базы: 2 плохие против 1 хорошей."""
        плохой = _кандидат("а-две-плохие", применимость=2, против=2)
        хороший = _кандидат("я-одна-хорошая", применимость=1, против=0)
        порядок = sorted([плохой, хороший], key=pn.by_evidence)
        self.assertEqual([c.model for c in порядок], ["я-одна-хорошая", "а-две-плохие"])

    def test_плохая_новость_всё_ещё_обгоняет_молчание(self) -> None:
        """Негативный контроль (И5): починка не должна снести прежнее решение.

        Молчание не лучше плохой новости — оно хуже: про модель с записанным
        провалом валидатор скажет «не годно» и назовёт класс, а про модель, о
        которой не записано ничего, он скажет «не смогли», и читатель не
        отличит это от «годно».
        """
        плохой = _кандидат("я-плохая-новость", применимость=1, против=1)
        немой = _кандидат("а-молчание", применимость=0, против=0, способность=99)
        порядок = sorted([немой, плохой], key=pn.by_evidence)
        self.assertEqual([c.model for c in порядок], ["я-плохая-новость", "а-молчание"])

    def test_при_равном_знаке_решает_число_строк(self) -> None:
        много = _кандидат("а-две-хорошие", применимость=2, против=0)
        мало = _кандидат("я-одна-хорошая", применимость=1, против=0)
        порядок = sorted([мало, много], key=pn.by_evidence)
        self.assertEqual([c.model for c in порядок], ["а-две-хорошие", "я-одна-хорошая"])

    def test_поле_знака_названо_в_печатном_списке_полей(self) -> None:
        """`why_not` объясняет выбор ПЕРВЫМ разошедшимся полем ключа, беря имя
        из `KEY_FIELDS`. Поле, добавленное в ключ и не добавленное в список,
        сдвинуло бы все объяснения на одну позицию — молча."""
        образец = _кандидат("x", применимость=1, против=0)
        self.assertEqual(len(pn.by_evidence(образец)), len(pn.KEY_FIELDS))


if __name__ == "__main__":
    unittest.main()
