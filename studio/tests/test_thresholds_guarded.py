"""Пороги, которые никто не сторожил: длина реплики и полы поиска.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА СОСЕДНИХ. Правило дома Ц2: чужие файлы не
редактируются даже ради однострочной правки. Тесты `test_civitai.py` и
`test_knowledge.py` писали другие авторы; их фикстуры здесь ПЕРЕИСПОЛЬЗУЮТСЯ
(Е1), а не копируются.

ЧТО ЭТИ ТЕСТЫ ЗАКРЫВАЮТ. Мутационный прогон 2026-09-04 показал пять молчащих
подмен: границы длины реплики в `studio/civitai.py` и два пола отбора в
`studio/knowledge.py` не сторожил никто. У пола `DENSE_FLOOR` в исходнике при
этом СТОИТ КОММЕНТАРИЙ, что мутации проверены («A floor of 0.0 fills the answer
with noise (mutation test)») — проверены они были руками и однажды. Ровно то,
ради чего правило Ц7 и написано: обязательное живёт скриптом, а не строкой.

Т2: ожидаемое — литералы, кроме мест, где сравнивается ПОВЕДЕНИЕ при двух
значениях константы. Т4: сети нет.
"""

from __future__ import annotations

import unittest

from studio import civitai, knowledge as K
from studio.tests.test_knowledge import attach_stub_dense, tiny_index


class ДлинаРепликиРешает(unittest.TestCase):
    """`предложения` отбирает по длине, и обе границы решают судьбу строки."""

    КОРОТКАЯ = "не работает"
    ГОДНАЯ = "губы уезжают от звука на длинных репликах, особенно на быстрой речи"

    def test_короткая_реплика_отброшена(self) -> None:
        self.assertEqual([], civitai.предложения(self.КОРОТКАЯ + "."))

    def test_годная_реплика_принята(self) -> None:
        (найдено,) = civitai.предложения(self.ГОДНАЯ + ".")
        self.assertIn(self.ГОДНАЯ, найдено)

    def test_простыня_отброшена_целиком(self) -> None:
        """Верхняя граница не украшение: без неё в базу уезжает вся страница
        одним «утверждением», и прочитать его потом нельзя."""
        простыня = "слово " * 200
        self.assertEqual([], civitai.предложения(простыня + "."))

    def test_границы_стоят_по_обе_стороны_годной_длины(self) -> None:
        """И5: годная строка обязана лежать МЕЖДУ порогами, а не за одним из
        них — иначе один из порогов недостижим и не проверяется ничем."""
        длина = len(self.ГОДНАЯ)
        self.assertLess(civitai.МИНИМУМ_СИМВОЛОВ, длина)
        self.assertLess(длина, civitai.МАКСИМУМ_СИМВОЛОВ)


class ПолыОтбораНеНАБЛЮДАЕМЫ_НА_ЭТОЙ_ФИКСТУРЕ(unittest.TestCase):
    """Записанная ГРАНИЦА, а не пропущенная работа (И6).

    Мутации `DENSE_FLOOR = 0.99` и `STRUCTURAL_MIN_FIELDS = 0` на доступной
    фикстуре МОЛЧАТ, и это не дыра в тестах: корпус `tiny_index` мал, и все его
    записи проходят лексическими каналами (bm25 и фразовым) независимо от
    плотного и структурного. ИЗМЕРЕНО 2026-09-04: находок 4 при полах 0.35,
    0.0 и 0.99, и 4 же при требовании 1 и 0 полей.

    Чтобы эти два порога стало ВИДНО, нужна запись, которую находит только
    плотный канал, — то есть релевантная запись, не разделяющая с запросом ни
    одного слова. Такой фикстуры в репозитории нет, а сочинять её под ответ
    значило бы подгонять прибор.

    Мутация `DENSE_FLOOR = 0.0` при этом ловится (`studio.tests.test_knowledge`)
    и оставлена в наборе: нижняя сторона порога наблюдаема, верхняя — нет.

    И ЕЩЁ ОДНО, РАДИ ЧЕГО ЭТОТ КЛАСС НАПИСАН. В `studio/knowledge.py` рядом с
    порогом стоит комментарий, что мутации проверены («A floor of 0.0 fills the
    answer with noise (mutation test)»). Проверены они были руками и однажды;
    стоящего скрипта за этим утверждением нет. Правило Ц7 ровно об этом:
    обязательное живёт прибором, а не строкой в комментарии.
    """

    def test_граница_названа_и_измерена(self) -> None:
        """Тест-заметка: держит числа замера рядом с текстом границы.

        Он обязан УПАСТЬ, если фикстура вырастет и пороги станут наблюдаемы, —
        тогда границу надо снять и завести настоящие мутанты.
        """
        индекс = tiny_index()
        attach_stub_dense(индекс)
        прежний = K.DENSE_FLOOR
        try:
            K.DENSE_FLOOR = 0.99
            зажатый = len(K.retrieve(self.ЗАПРОС, k=50, index=индекс).get("examples", ()))
            K.DENSE_FLOOR = прежний
            обычный = len(K.retrieve(self.ЗАПРОС, k=50, index=индекс).get("examples", ()))
        finally:
            K.DENSE_FLOOR = прежний
        self.assertEqual(
            обычный,
            зажатый,
            "фикстура выросла: верхняя сторона DENSE_FLOOR стала наблюдаемой — "
            "снимите границу и заведите мутанта",
        )

    ЗАПРОС = "soft window light on a face, muted palette"


if __name__ == "__main__":
    unittest.main()
