"""Шаг, который заказчик ЗАПРЕТИЛ словами, в план не попадает.

НАЙДЕНО продуктовой проверкой 2026-09-07 (третий заход):

    «Не генерируйте видео, у нас своё. Только липсинк и ничего больше»
        -> шаг генерация_видео в плане, ДОПИСАН ПЛАНОМ
    «Озвучка не нужна, звук у нас уже есть»
        -> шаг озвучка первым

Продукт делал ровно то, что ему запретили одной фразой, и брал за это деньги.

ГРАНИЦА ПРАВИЛА НАЙДЕНА ДВУМЯ СОБСТВЕННЫМИ ПРОГОНАМИ ПОДРЯД: «липсинк БЕЗ
спешки» — «без» относится к спешке; «сделай липсинк, НЕ ДОРОЖЕ 0.10» — «не»
относится к цене, и этот случай поймал голден-сет через минуту после первой
починки. После имени операции отменяет только оборот НЕОБХОДИМОСТИ.
"""

from __future__ import annotations

import unittest

from studio import planner

ЗАПРЕТЫ: tuple[tuple[str, str], ...] = (
    ("Не генерируйте видео, у нас своё. Только липсинк", "генерация_видео"),
    ("Озвучка не нужна, звук у нас уже есть", "озвучка"),
    ("Никакого TTS, голос запишем сами", "озвучка"),
    ("липсинк без дубляжа", "дубляж"),
    ("нужен ролик без озвучки", "озвучка"),
    ("дубляж не требуется", "дубляж"),
)

ЗАКАЗЫ: tuple[str, ...] = (
    "сделай липсинк под мою озвучку",
    "нужна озвучка по нашему тексту",
    "липсинк без спешки, 20 секунд",
    "сделай липсинк, не дороже 0.10 доллара за секунду, ролик 30 секунд",
    "нужен дубляж на английский",
    "снять видео с нуля",
    "оживить фото",
    "need a talking head ad",
    "voiceover for our tutorial",
    "озвучка нужна срочно",
)


class ЗапретЧитается(unittest.TestCase):
    def test_ни_один_запрещённый_шаг_не_выведен(self) -> None:
        нарушено = [
            (бриф, шаг) for бриф, шаг in ЗАПРЕТЫ if шаг in [оп.name for оп in planner.derive(бриф)]
        ]
        self.assertEqual([], нарушено)

    def test_отрицание_перед_именем_операции(self) -> None:
        self.assertTrue(planner._операция_отменена("не генерируйте видео", "видео"))

    def test_оборот_необходимости_после_имени(self) -> None:
        self.assertTrue(planner._операция_отменена("озвучка не нужна", "озвучк"))


class ЗаказНеТеряется(unittest.TestCase):
    """И5: правило, отменяющее операцию при любом «не» рядом, снимет её с
    любого брифа — там всегда есть отрицание."""

    def test_ни_один_заказ_не_потерян(self) -> None:
        потеряны = [б for б in ЗАКАЗЫ if not planner.derive(б)]
        self.assertEqual([], потеряны)

    def test_без_после_имени_относится_к_следующему_слову(self) -> None:
        self.assertFalse(planner._операция_отменена("липсинк без спешки", "липсинк"))

    def test_не_перед_ценой_операцию_не_отменяет(self) -> None:
        """Этот случай поймал голден-сет, а не набор: одинокое «не» после
        операции отменяло её на самом обычном брифе с потолком."""
        self.assertFalse(
            planner._операция_отменена("сделай липсинк, не дороже 0.10 доллара", "липсинк")
        )

    def test_окно_отмены_не_бесконечно(self) -> None:
        текст = "нужна озвучка по нашему тексту, только не забудьте про паузы"
        self.assertFalse(planner._операция_отменена(текст, "озвучк"))


if __name__ == "__main__":
    unittest.main()
