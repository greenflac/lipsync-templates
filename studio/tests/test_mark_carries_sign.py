"""Пометка кандидата обязана нести ЗНАК, а не только число строк.

ВОСПРОИЗВЕДЕНО 2026-09-05 независимым аудитом на живой базе:

    шаг липсинк: latentsync — применимость измерена: 4 строк(и)
    ПОЧЕМУ ОТВЕРГНУТ [применимость]: … отрицательная: 3 строк(и) о том, где это ломается

Четыре строки, из них три — плохие новости. Пометка — единственное, по чему
читатель судит о модели (докстрока `plan_pipeline` прямо велит: «прочтите эту
пометку, прежде чем называть модель кому-либо»), и она давала ПОЛОЖИТЕЛЬНЫЙ
знак от отрицательного замера.

Это тот же дефект, что 2026-09-05 утром сделал первое «годно» ложным, только
не в вердикте, а в витрине: там знак выводился из имени атрибута, здесь он
не выводился вовсе.

Ожидаемые формулировки — литералы (Т2): пометка это ПРОТОКОЛ с читателем, и
её молчаливое переименование ломает не тест, а понимание.
"""

from __future__ import annotations

import unittest

import studio.planner as pn


def _кандидат(*, применимость: int, против: int) -> pn.Candidate:
    return pn.Candidate(
        model="m",
        evidence=(),
        applicability=применимость,
        capability=0,
        unresolved=0,
        price="цена не записана",
        anchored=применимость,
        against=против,
    )


class ПометкаСоЗнаком(unittest.TestCase):
    def test_плохие_новости_названы_числом(self) -> None:
        self.assertEqual(
            _кандидат(применимость=4, против=3).mark,
            "применимость измерена: 4 строк(и), из них 3 о том, где ломается",
        )

    def test_чистое_измерение_говорит_что_плохого_нет(self) -> None:
        self.assertEqual(
            _кандидат(применимость=2, против=0).mark,
            "применимость измерена: 2 строк(и), плохих новостей нет",
        )

    def test_неизмеренное_остаётся_прежним(self) -> None:
        """Негативный контроль (И5): третий исход не переименован заодно.

        Строка «применимость не измерена» — договор с читателем, на неё
        смотрят и тесты, и голден-сет; менять её тут было бы починкой чужого.
        """
        self.assertEqual(_кандидат(применимость=0, против=0).mark, pn.NOT_MEASURED_MARK)


if __name__ == "__main__":
    unittest.main()
