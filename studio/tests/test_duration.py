"""Длительность ролика против предела модели. Ожидаемое — литералы (Т2)."""

from __future__ import annotations

import unittest

from studio import duration as d


class ЧтоПроситЗаказчик(unittest.TestCase):
    def test_секунды(self) -> None:
        self.assertEqual(d.просят("ролик на 30 секунд").секунды, 30.0)

    def test_минуты_переводятся(self) -> None:
        self.assertEqual(d.просят("клип 2 минуты").секунды, 120.0)

    def test_минуты_проверяются_раньше_секунд(self) -> None:
        """«2 минуты 30 секунд» — это не 30 с. Порядок образцов решает, и
        поменяв его местами, прибор ответит 30."""
        self.assertEqual(d.просят("2 минуты 30 секунд").секунды, 120.0)

    def test_не_названа_это_None_а_не_ноль(self) -> None:
        self.assertIsNone(d.просят("оживить фото клиента").секунды)
        self.assertIsNone(d.просят("").секунды)

    def test_английские_слова_тоже(self) -> None:
        self.assertEqual(d.просят("a 15 seconds clip").секунды, 15.0)


class КакойПределУМодели(unittest.TestCase):
    def test_одно_число(self) -> None:
        self.assertEqual(d.предел_из_строк([("max_seconds", "15")]).секунды, 15.0)

    def test_диапазон_берётся_по_потолку(self) -> None:
        п = d.предел_из_строк([("duration_range_seconds", "4-15 seconds, integer values only")])
        self.assertEqual(п.секунды, 15.0)

    def test_перечень_берётся_по_самому_длинному(self) -> None:
        self.assertEqual(d.предел_из_строк([("duration_enum_seconds", "5, 10")]).секунды, 10.0)

    def test_миллисекунды_не_секунды(self) -> None:
        """`max_duration_ms=30000` без этого прочиталось бы как восемь часов,
        и любой ролик «влез» бы."""
        self.assertEqual(d.предел_из_строк([("max_duration_ms", "30000")]).секунды, 30.0)

    def test_миллисекунды_узнаются_и_по_значению(self) -> None:
        """Два способа узнать миллисекунды — имя атрибута и слово в значении —
        и оба обязаны быть наблюдаемы. Пока тест был только на имя, мутация
        «выключить разбор значения» молчала: второй заслон держал первый."""
        self.assertEqual(d.предел_из_строк([("max_seconds", "30000 ms")]).секунды, 30.0)

    def test_номер_строки_развёртки_не_секунды(self) -> None:
        """«up to 60 s at 720p» — 720 здесь не секунды, а разрешение."""
        п = d.предел_из_строк([("max_seconds", "up to 60 s at 720p, 30 s at 1080p")])
        self.assertEqual(п.секунды, 60.0)

    def test_строки_нет_вовсе_это_не_записан(self) -> None:
        self.assertEqual(d.предел_из_строк([]).состояние, "предел длительности не записан")

    def test_строка_есть_числа_нет_это_не_разобран(self) -> None:
        """Р1: молчание базы лечится сбором, неразобранная строка —
        разборщиком. Свести их значило бы не знать, куда идти."""
        п = d.предел_из_строк([("max_seconds", "длительность не указана вендором")])
        self.assertEqual(п.состояние, "предел длительности не разобран")


class ВлезаетЛиРолик(unittest.TestCase):
    def _п(self, бриф: str, строки: list[tuple[str, str]]) -> d.Предел:
        return d.влезает(d.просят(бриф), d.предел_из_строк(строки))

    def test_влезает(self) -> None:
        self.assertEqual(
            self._п("10 секунд", [("max_seconds", "15")]).состояние, "длительность принимает"
        )

    def test_ровно_на_пределе_влезает(self) -> None:
        """Граница включительно: 15 с при пределе 15 — это работа, а не отказ."""
        self.assertEqual(
            self._п("15 секунд", [("max_seconds", "15")]).состояние, "длительность принимает"
        )

    def test_не_влезает(self) -> None:
        п = self._п("30 секунд", [("max_seconds", "15")])
        self.assertEqual(п.состояние, "ролик ДЛИННЕЕ предела")
        self.assertIn("30", п.нота)
        self.assertIn("15", п.нота)

    def test_не_спрашивали_это_отдельное_положение(self) -> None:
        """И это не «предел не записан»: у модели он записан, не назван РОЛИК.
        Лечится вопросом заказчику, а не сбором."""
        п = self._п("оживить фото", [("max_seconds", "15")])
        self.assertEqual(п.состояние, "длительность не спрашивали")

    def test_молчание_базы_не_равно_подойдёт(self) -> None:
        self.assertEqual(self._п("30 секунд", []).состояние, "предел длительности не записан")

    def test_порядок_положений_невозможное_последним(self) -> None:
        self.assertEqual(d.DUR_ORDER["длительность принимает"], 0)
        self.assertEqual(d.DUR_ORDER["ролик ДЛИННЕЕ предела"], 3)
        self.assertLess(
            d.DUR_ORDER["предел длительности не записан"], d.DUR_ORDER["ролик ДЛИННЕЕ предела"]
        )


if __name__ == "__main__":
    unittest.main()
