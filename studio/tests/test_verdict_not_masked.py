"""Может ли «не смогли» перебить найденное нарушение. Не может.

ЗАЧЕМ. Аудит 2026-09-05 снял с выдачи строку, которая спорит сама с собой:

    исход: не смогли [шаг_без_кандидатов]
    классы валидатора: нет_модели, лицензия
    проверено 8, нарушений 1, не смогли 2

Нарушение найдено и посчитано — и тут же объявлено неизмеренным, потому что в
том же плане был шаг без кандидата. Р1 разводит три исхода, но не разрешает
третьему перебивать второй: «не смогли» значит «нечем мерить», а найденное
нарушение уже измерено. Заказчик читает такую строку как «не хватило данных»,
хотя план отвергнут по лицензии.

Ожидаемое — литералы (Т2): строки исходов и причин написаны руками, а не взяты
из `studio.planner`. Импортированное ожидание уехало бы вместе с кодом молча.
Входы — с обоих краёв и из середины (Т3): нарушение без шагов без кандидата,
шаги без кандидата без нарушения, оба сразу, ни одного.
"""

from __future__ import annotations

import unittest

from studio.planner import свести_исход


def отчёт(исход: str, нота: str = "лицензия: research-only") -> dict:
    return {"outcome": исход, "note": нота}


class НайденноеНарушениеНеСворачиваетсяВНеСмогли(unittest.TestCase):
    def test_нарушение_и_шаг_без_кандидата_вместе_дают_отказ(self):
        """Та самая выдача аудита: раньше здесь было «не смогли»."""
        исход, причина, нота = свести_исход(2, отчёт("fail"), 8)
        self.assertEqual(исход, "fail")
        self.assertEqual(причина, "валидатор_отверг")
        self.assertIn("лицензия: research-only", нота)

    def test_шаг_без_кандидата_из_отказа_не_пропадает(self):
        """Починка вердикта не смеет увести в тень то, ради чего третий исход
        заводился: шаг без кандидата назван вслух и в отказе тоже."""
        _, _, нота = свести_исход(2, отчёт("fail"), 8)
        self.assertIn("без единого кандидата 2", нота)
        self.assertIn("шагов выведено 8", нота)

    def test_шаг_без_кандидата_без_нарушения_это_третий_исход(self):
        """Негативный контроль (И5): починка не смеет превратить третий исход
        во второй — иначе «нечем мерить» станет «плохо», и это будет ложь в
        другую сторону."""
        исход, причина, нота = свести_исход(1, отчёт("pass", "всё сошлось"), 3)
        self.assertEqual(исход, "could not measure")
        self.assertEqual(причина, "шаг_без_кандидатов")
        self.assertIn("без единого кандидата 1", нота)

    def test_из_двух_третьих_исходов_шаг_без_кандидата_называется_первым(self):
        """Независимая проверка 2026-09-05: перестановка ЭТИХ ДВУХ веток
        оставляла все тесты зелёными. Исход в обоих случаях «не смогли», и
        разницу видно только по причине и ноте — а именно там и живёт
        обещание, что шаг без кандидата не пропадёт. Обещание, которое держится
        только на порядке строк и ничем не сторожится, — не обещание.

        Почему первым именно он: «валидатор не смог» — это про то, чего нет в
        базе, а «шаг без кандидата» — про то, что заказчику НЕЧЕМ сделать шаг.
        Второе ближе к его вопросу и потому называется раньше."""
        исход, причина, нота = свести_исход(1, отчёт("could not measure", "цены не измерены"), 5)
        self.assertEqual(исход, "could not measure")
        self.assertEqual(причина, "шаг_без_кандидатов")
        self.assertIn("без единого кандидата 1", нота)

    def test_нарушение_без_шагов_без_кандидата_это_отказ(self):
        исход, причина, _ = свести_исход(0, отчёт("fail"), 4)
        self.assertEqual(исход, "fail")
        self.assertEqual(причина, "валидатор_отверг")

    def test_валидатор_не_смог_и_кандидаты_есть_это_третий_исход(self):
        исход, причина, _ = свести_исход(0, отчёт("could not measure", "цены не измерены"), 4)
        self.assertEqual(исход, "could not measure")
        self.assertEqual(причина, "план_не_подтверждён")

    def test_всё_сошлось_это_годно(self):
        исход, причина, _ = свести_исход(0, отчёт("pass", "нарушений нет"), 4)
        self.assertEqual(исход, "pass")
        self.assertEqual(причина, "план_подтверждён")

    def test_хвост_про_кандидатов_не_приписывается_когда_их_нет(self):
        """Р2 читается только тогда, когда числа не врут: «без единого
        кандидата 0» в ноте отказа означало бы, что счётчик печатается всегда,
        и глаз перестал бы его замечать."""
        _, _, нота = свести_исход(0, отчёт("fail"), 4)
        self.assertNotIn("без единого кандидата", нота)
