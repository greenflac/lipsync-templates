"""Требование названо в брифе — значит, о нём сказано в ответе. Хотя бы «не меряем».

ЗАЧЕМ. НАЙДЕНО продуктовой проверкой 2026-09-08 на живых брифах: «Ролик 4K, 60
кадров в секунду, 10 минут, ВЕРТИКАЛЬНЫЙ формат», «must run under 200ms
latency», «нужно 200 персонализированных видео», «к завтрашнему утру», «дубляж
на 3 языка» — ни одно из требований не упоминалось в ответе НИ РАЗУ. Молчание
читается заказчиком как «учтено», и обратное он узнаёт на приёмке.

ЭТО ТРЕТИЙ ИСХОД (Р1), а не отказ и не согласие: названо, но мы про это ничего
не знаем.
"""

from __future__ import annotations

import json
import unittest

from studio import planner
from studio.mcp import server

#: Пары «бриф — что в нём названо». Литералы (Т2), а не выжимка из списка
#: признаков: выжимка поедет вместе с ним и промолчит.
НАЗВАНО: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Ролик 4K, 10 минут, нужен липсинк", ("разрешение кадра",)),
    ("нужен ролик 60 кадров в секунду", ("частота кадров",)),
    ("вертикальный ролик для сторис, нужен липсинк", ("формат кадра",)),
    ("нужен липсинк, дедлайн завтра", ("срок сдачи",)),
    ("нужно 200 персонализированных видео", ("тираж",)),
    ("нужен липсинк, задержка не больше 200 мс", ("задержка ответа",)),
    ("дубляж на 3 языка", ("сколько языков",)),
)


class НазванноеНеЗамалчивается(unittest.TestCase):
    def test_каждое_требование_названо_в_ответе(self) -> None:
        молчит = [
            бриф
            for бриф, ждём in НАЗВАНО
            if not all(и in "; ".join(planner.требования_без_ответа(бриф)) for и in ждём)
        ]
        self.assertEqual([], молчит)

    def test_несколько_требований_в_одном_брифе(self) -> None:
        найдено = planner.требования_без_ответа(
            "Ролик 4K, 60 кадров в секунду, 10 минут, вертикальный формат"
        )
        self.assertEqual(
            [
                "разрешение кадра (4k)",
                "частота кадров (кадров в секунду)",
                "формат кадра (вертикал)",
            ],
            найдено,
        )

    def test_обычный_бриф_молчит(self) -> None:
        """Негативный контроль (И5): строка не приписывается ко всему подряд."""
        self.assertEqual([], planner.требования_без_ответа("нужен липсинк на 20 секунд"))
        self.assertEqual([], planner.требования_без_ответа("dub our clip into spanish"))

    def test_английский_бриф_называет_требования_по_английски(self) -> None:
        найдено = planner.требования_без_ответа(
            "200 personalised videos by tomorrow, under 200ms latency", по_английски=True
        )
        self.assertEqual(
            ["deadline (by tomorrow)", "how many clips (personalised)", "latency (latency)"],
            найдено,
        )


class СтрокаДоходитДоЗаказчика(unittest.TestCase):
    """Счёт без ручки — не счёт: поле обязано печататься, а не только считаться."""

    def test_строка_видна_в_печати(self) -> None:
        текст = planner.render(
            json.loads(server.plan_pipeline("Ролик 4K, вертикальный формат, нужен липсинк"))
        )
        self.assertIn("НАЗВАНО В БРИФЕ, НО СТУДИЯ ЭТОГО НЕ МЕРИТ", текст)
        self.assertIn("разрешение кадра", текст)

    def test_на_английском_брифе_строка_английская(self) -> None:
        текст = planner.render(
            json.loads(server.plan_pipeline("we need a talking head ad, 4K, by tomorrow"))
        )
        self.assertIn("NAMED IN YOUR BRIEF, NOT MEASURED BY US", текст)
        self.assertNotIn("НАЗВАНО В БРИФЕ", текст)

    def test_поле_есть_всегда_даже_пустым(self) -> None:
        итог = json.loads(server.plan_pipeline("нужен липсинк, 20 секунд"))
        self.assertEqual([], итог["unmeasured_requirements"])

    def test_обычный_бриф_этой_строки_не_печатает(self) -> None:
        текст = planner.render(json.loads(server.plan_pipeline("нужен липсинк, 20 секунд")))
        self.assertNotIn("НЕ МЕРИТ", текст)


class СтороныКадраНеПечатаютсяВнутренностями(unittest.TestCase):
    """НАЙДЕНО той же проверкой: «креатив: NonexNone» в лицо заказчику.

    Внутреннее `None`, склеенное форматированием, читается как поломка ровно
    там, где прибор отработал правильно и честно сказал «файла нет».
    """

    def test_несобравшийся_размер_называется_словами(self) -> None:
        текст = planner.render(
            json.loads(server.plan_pipeline("нужен липсинк на фото", creative="photo.jpg"))
        )
        self.assertNotIn("None", текст)
        self.assertIn("стороны неизвестны", текст)


if __name__ == "__main__":
    unittest.main()
