"""Считается — значит печатается: счётчик в стол и ось, промолчавшая молча.

ЗАЧЕМ. Аудит 2026-09-05 нашёл в шаге плана три счётчика, которые считались и
НИКОГДА не попадали в напечатанный план: `retired_count`, `announced_count`,
`wrong_output_count`. Это П1 наоборот — ручка есть, счётчика нет, и «никого не
отодвинули» неотличимо от «не считали».

Там же: рендер печатал ось, только когда ей было что сказать. `BAN_UNKNOWN` и
`LIFE_LIVE` не попадали в план ВООБЩЕ, хотя в самом коде записано вслух, что
`BAN_UNKNOWN` — не «разрешено», а «в базе про запрет ничего нет». План,
молчащий об этом, отдаёт умолчание за проверку.

Обе развилки вынесены из рендера отдельными функциями (Т5). Ожидаемое —
литералы (Т2), сети нет (Т4), входы с обоих краёв и из середины (Т3).
"""

from __future__ import annotations

import unittest

from studio.planner import дата_свидетельства, оси_без_ответа, отодвинутые


class СчётчикВСтолБольшеНеСчитается(unittest.TestCase):
    def test_отодвинутые_названы_числом_и_причиной(self):
        строка = отодвинутые(
            {
                "retired_count": 2,
                "announced_count": 1,
                "wrong_output_count": 3,
                "banned_count": 6,
                "candidates_found": 36,
            }
        )
        self.assertIn("модель снята: 2", строка)
        self.assertIn("снятие объявлено впереди: 1", строка)
        self.assertIn("выход не тот: 3", строка)
        self.assertIn("вход запрещён базой: 6", строка)
        self.assertIn("из 36 кандидатов", строка)

    def test_никого_не_отодвинули_строки_нет(self):
        """Негативный контроль (И5): строка, которая печатается всегда,
        перестаёт замечаться. Ноль здесь молчит сознательно — что ось
        спрашивали, читается из соседней строки про оси без ответа."""
        self.assertEqual(
            "",
            отодвинутые(
                {
                    "retired_count": 0,
                    "announced_count": 0,
                    "wrong_output_count": 0,
                    "banned_count": 0,
                    "candidates_found": 36,
                }
            ),
        )

    def test_одна_причина_из_четырёх_тоже_печатается(self):
        строка = отодвинутые({"announced_count": 1, "candidates_found": 4})
        self.assertIn("снятие объявлено впереди: 1", строка)
        self.assertNotIn("модель снята", строка)


class ОсьПромолчавшаяНазываетсяВслух(unittest.TestCase):
    def test_молчание_по_входу_и_службе_названо(self):
        строка = оси_без_ответа(
            {
                "ban_state": "о запрете на вход не сказано",
                "life_state": "о снятии не сказано",
                "out_state": "",
                "dur_state": "длительность не спрашивали",
            }
        )
        self.assertEqual("вход, срок службы, выход, длительность", строка)

    def test_ось_которой_есть_что_сказать_в_молчащие_не_попадает(self):
        """Негативный контроль (И5): иначе список молчащих станет списком всех
        осей и перестанет что-либо означать."""
        строка = оси_без_ответа(
            {
                "ban_state": "вход разрешён явно",
                "life_state": "модель снята",
                "out_state": "отдаёт нужный вид",
                "dur_state": "укладывается",
            }
        )
        self.assertEqual("", строка)

    def test_смешанный_случай_называет_только_молчащие(self):
        строка = оси_без_ответа(
            {
                "ban_state": "вход разрешён явно",
                "life_state": "о снятии не сказано",
                "out_state": "отдаёт нужный вид",
                "dur_state": "укладывается",
            }
        )
        self.assertEqual("срок службы", строка)


class ДатаСтатьиНеПодменяетсяДнёмЧтения(unittest.TestCase):
    """`stated_on` — день, когда прочитали МЫ. Для статьи это не дата
    утверждения: ИЗМЕРЕНО 2026-09-05, из 223 строк с идентификатором статьи у
    173 записанная дата позже публикации, расхождение до 2 лет 9 месяцев."""

    def test_печатаются_обе_даты_чужая_первой(self):
        строка = дата_свидетельства({"stated_on": "2026-08-27", "published_on": "2023-11"})
        self.assertEqual("2023-11 (прочитано 2026-08-27)", строка)

    def test_совпали_печатается_одна(self):
        """Негативный контроль (И5): вторая дата рядом с каждой строкой
        перестанет замечаться, а вместе с ней и та, где расхождение есть."""
        self.assertEqual(
            "2024-03-18", дата_свидетельства({"stated_on": "2024-03-18", "published_on": "2024-03"})
        )

    def test_источник_молчит_печатается_наша(self):
        self.assertEqual("2026-09-05", дата_свидетельства({"stated_on": "2026-09-05"}))

    def test_нет_ни_одной_даты_так_и_сказано(self):
        self.assertEqual("даты нет", дата_свидетельства({"stated_on": ""}))

    def test_нашей_даты_нет_а_чужая_есть(self):
        self.assertEqual(
            "2023-11 (прочитано без даты)",
            дата_свидетельства({"stated_on": "", "published_on": "2023-11"}),
        )
