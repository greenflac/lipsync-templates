class ЧужаяЗаписьНеПерваяФраза(unittest.TestCase):
    """Место цитаты решает, а не её текст.

    НАЙДЕНО продуктовой проверкой 2026-09-08: одна и та же запись про срывы
    ретрофлексов в телугу стояла ЕДИНСТВЕННЫМ содержанием «ЧТО ДАЛЬШЕ» в 27
    ответах из 28 — включая заказ на ролик для кофейни. Инструмент сам
    приписывал «ваш заказ он не описывает» и всё равно ставил её первой фразой,
    а первую фразу читают все.

    ЦИТАТА НЕ УБИРАЕТСЯ (телугу может всплыть на съёмке) — она уходит вниз, а
    наверх поднимается работа, которую можно сделать.
    """

    ЧУЖОЙ = "реклама кофейни в Казани, нужен talking head, 30 секунд"
    СВОЙ = "нужен дубляж на телугу и тамильский, ретрофлексы важны"

    def _совет(self, бриф: str) -> str:
        return str(json.loads(server.plan_pipeline(бриф)).get("что_дальше") or "")

    def test_на_чужом_заказе_первой_идёт_работа(self) -> None:
        совет = self._совет(self.ЧУЖОЙ)
        self.assertIn("можно:", совет)
        self.assertLess(совет.index("можно:"), совет.index("провал"))

    def test_на_чужом_заказе_запись_всё_равно_приведена(self) -> None:
        """Убрать её было бы решением за заказчика."""
        совет = self._совет(self.ЧУЖОЙ)
        self.assertIn("Почему мы об этом говорим", совет)
        self.assertIn("ретрофлекс", совет)

    def test_на_своём_заказе_запись_открывает_совет(self) -> None:
        совет = self._совет(self.СВОЙ)
        self.assertIn("ИЗМЕРЕННЫЙ провал", совет)
        self.assertLess(совет.index("провал"), совет.index("Что можно сделать"))

    def test_на_своём_заказе_оговорки_об_относимости_нет(self) -> None:
        """Негативный контроль (И5): оговорка приписывается не всем подряд."""
        self.assertNotIn("в вашем брифе не названы", self._совет(self.СВОЙ))


