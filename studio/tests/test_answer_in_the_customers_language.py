"""Заказчик читает то, по чему он действует, на своём языке.

НАЙДЕНО седьмой приёмкой 2026-09-07, и это регресс МОЕЙ ЖЕ починки того дня:
английские подсказки увели английский бриф из ветки, где объяснение было
по-английски, в ветку, где английского текста не было вовсе. Из 11 брифов
набора 4 получали ответ без единого английского слова.

ЧТО СТОРОЖИТСЯ И ЧТО НЕТ, названо вслух:
  * вопрос и «что дальше» — единственные строки, по которым заказчик способен
    что-то сделать. Они обязаны быть на его языке;
  * телеметрия валидатора остаётся русской НАМЕРЕННО: её читает владелец, и
    перевод удвоил бы знание (Е1);
  * цитата из базы не переводится: она написана тем, кто её записал, и
    переписать её значило бы подменить свидетельство пересказом.
"""

from __future__ import annotations

import json
import re
import unittest

from studio import clarify, planner
from studio.mcp import server

КИРИЛЛИЦА = re.compile(r"[а-яё]", re.I)
ЛАТИНИЦА = re.compile(r"[a-z]", re.I)


class ВопросГоворитНаЯзыкеБрифа(unittest.TestCase):
    def test_у_каждого_вопроса_есть_английская_половина(self) -> None:
        """Поле обязательное без значения по умолчанию: новый вопрос без
        английской половины обязан НЕ СОБРАТЬСЯ, а не тихо заговорить
        по-русски."""
        for ось, вопрос in clarify.ВОПРОСЫ.items():
            текст, почему, варианты = вопрос.english
            self.assertTrue(текст and почему and варианты, ось)
            self.assertFalse(КИРИЛЛИЦА.search(текст), ось)

    def test_английский_бриф_получает_английский_вопрос(self) -> None:
        итог = json.loads(server.plan_pipeline("We want a short clip for instagram"))
        self.assertFalse(КИРИЛЛИЦА.search(итог["question"]["text"]))

    def test_русский_бриф_получает_русский_вопрос(self) -> None:
        """И5: продукт, заговоривший по-английски со всеми, «починен» неверно."""
        итог = json.loads(server.plan_pipeline("нужен ролик для маркетплейса"))
        self.assertTrue(КИРИЛЛИЦА.search(итог["question"]["text"]))


class СоветГоворитНаЯзыкеБрифа(unittest.TestCase):
    def test_совет_один_и_тот_же_в_обоих_местах(self) -> None:
        """Е1: строка «ответьте на вопрос» была написана ДВАЖДЫ, и при переводе
        поехала только одна — английская нота с русским советом."""
        self.assertFalse(КИРИЛЛИЦА.search(planner.ответьте_на_вопрос(True)))
        self.assertTrue(КИРИЛЛИЦА.search(planner.ответьте_на_вопрос(False)))

    def test_имя_шага_переводится(self) -> None:
        """«at step «звук_фон»» — внутреннее имя в лицо заказчику."""
        self.assertEqual("background sound", planner.шаг_словами("звук_фон", True))
        self.assertEqual("звук_фон", planner.шаг_словами("звук_фон", False))

    def test_незнакомое_имя_шага_печатается_как_есть(self) -> None:
        """Молчать о шаге, которого нет в словаре, хуже, чем показать имя."""
        self.assertEqual("новый_шаг", planner.шаг_словами("новый_шаг", True))


class СоветНеОбещаетТогоЧегоНеБудет(unittest.TestCase):
    """НАЙДЕНО продуктовой проверкой: «подать своё видео — тогда шаг уходит
    вовсе» печаталось НА ЛЮБОМ шаге, в том числе на озвучке, от которой видео
    не избавляет. Совет, который не сработает, дороже отсутствия совета."""

    def test_на_шаге_озвучки_просят_дорожку_а_не_видео(self) -> None:
        self.assertEqual("свою звуковую дорожку", planner.ЧТО_ПРИНЕСТИ["озвучка"][0])
        self.assertEqual("своё видео", planner.ЧТО_ПРИНЕСТИ["генерация_видео"][0])

    def test_у_липсинка_принести_нечего_и_совет_молчит(self) -> None:
        """И5: словарь, отвечающий на любой шаг, не различает ничего."""
        self.assertNotIn("липсинк", planner.ЧТО_ПРИНЕСТИ)


class ЧислоКандидатовНеЗавышается(unittest.TestCase):
    """«взять другого кандидата (их 11)» — а тремя строками ниже сказано, что
    троими воспользоваться нельзя."""

    def test_непригодные_вычитаются(self) -> None:
        шаг = {
            "candidates_found": 12,
            "banned_count": 2,
            "wrong_output_count": 1,
            "too_long_count": 0,
            "retired_count": 0,
        }
        self.assertEqual(8, planner.живых_кандидатов(шаг))

    def test_ноль_а_не_минус(self) -> None:
        """«Минус один кандидат» читателю не значит ничего."""
        self.assertEqual(0, planner.живых_кандидатов({"candidates_found": 1, "banned_count": 5}))

    def test_все_пригодны_вычитается_только_выбранный(self) -> None:
        self.assertEqual(11, planner.живых_кандидатов({"candidates_found": 12}))


class ПродуктГоворитЭтоЗаказчику(unittest.TestCase):
    def test_английский_план_несёт_английский_совет(self) -> None:
        итог = json.loads(
            server.plan_pipeline("Add sound effects and ambience to our clip, budget $5")
        )
        свои_слова = re.sub(r"«[^»]*»", "", итог["что_дальше"])
        self.assertTrue(ЛАТИНИЦА.search(свои_слова))
        self.assertFalse(КИРИЛЛИЦА.search(свои_слова))

    def test_цитата_из_базы_в_кавычках(self) -> None:
        """Читатель обязан видеть границу: дальше не наши слова."""
        итог = json.loads(
            server.plan_pipeline("ролик 1 минута, говорящая голова, бюджет 100000 долларов")
        )
        self.assertRegex(итог["что_дальше"], r"«[^»]+»")


if __name__ == "__main__":
    unittest.main()


class ЧужаяБедаНеВыдаётсяЗаВашу(unittest.TestCase):
    """НАЙДЕНО продуктовой проверкой 2026-09-07 (второй заход): на 26 брифах из
    30 заказчику дословно зачитывали одну и ту же запись про срыв ретрофлексов
    на телугу и тамильском — в том числе заказчику ролика про кофейню в Химках.

    Запись честная, и относится она к ОПЕРАЦИИ (синтез речи), а не к ЗАКАЗУ:
    требование шага одно на все брифы. Отказ, обоснованный тамильским языком в
    русском заказе, читается как отговорка — и заказчик перестаёт верить
    остальным строкам ответа тоже.

    ЗДЕСЬ НЕ СУДЯТ, ПОВТОРИТСЯ ЛИ ПРОВАЛ. Проверяется одно: делит ли запись
    хоть одно содержательное слово с брифом.
    """

    ЗАПИСЬ = {
        "value": (
            "Язык уходит от хинди: на хинди 0 срывов ретрофлексов, на телугу срыв 40%, "
            "тамил — самая сильная деградация из трёх языков исследования"
        )
    }

    def test_чужие_условия_названы_чужими(self) -> None:
        self.assertFalse(
            planner.условия_записи_в_брифе(self.ЗАПИСЬ, "ролик про кофейню в Химках, 20 секунд")
        )

    def test_свои_условия_названы_своими(self) -> None:
        """И5: прибор, объявляющий чужим что угодно, снимает оговорку со всего —
        и тогда заказчик, который КАК РАЗ просит телугу, её не увидит."""
        self.assertTrue(
            planner.условия_записи_в_брифе(self.ЗАПИСЬ, "нужна озвучка на телугу для Индии")
        )

    def test_общие_слова_совпадением_не_считаются(self) -> None:
        """Без этого пересечение находится всегда: «видео», «ролик», «секунд»
        есть в любом брифе и в любой записи о видеомодели."""
        общая = {"value": "модель ломается на видео длиннее 10 секунд"}
        self.assertFalse(planner.условия_записи_в_брифе(общая, "нужен ролик, видео 20 секунд"))

    def test_оговорка_доезжает_до_заказчика(self) -> None:
        строка = json.loads(
            server.plan_pipeline("ролик про кофейню в Химках, говорящая голова, 20 секунд")
        )["что_дальше"]
        self.assertIn("в вашем брифе не названы", строка)
        self.assertIn("исключить провал мы не можем", строка)

    def test_на_своём_заказе_оговорки_нет(self) -> None:
        строка = json.loads(
            server.plan_pipeline("нужна озвучка на телугу для индийского рынка, 20 секунд")
        )["что_дальше"]
        self.assertNotIn("в вашем брифе не названы", строка)


class ЧислаВОтветеНеСпорят(unittest.TestCase):
    """«взять другого кандидата (их 8)», а шагом ниже «ещё кандидаты (12
    всего)». Заказчик, которому в одном абзаце дают 8 и 12, перестаёт верить
    всем числам ответа сразу."""

    def test_оба_числа_названы_рядом_и_подписаны(self) -> None:
        строка = json.loads(server.plan_pipeline("ролик про кофейню, говорящая голова, 20 секунд"))[
            "что_дальше"
        ]
        self.assertRegex(строка, r"пригодных \d+ из \d+")

    def test_совет_не_рассогласован_по_роду(self) -> None:
        """«подать свою звуковую дорожку, если ОНО есть» — в главной строке."""
        строка = json.loads(server.plan_pipeline("ролик про кофейню, говорящая голова, 20 секунд"))[
            "что_дальше"
        ]
        self.assertNotIn("если оно есть", строка)

    def test_английский_совет_не_мешает_языки(self) -> None:
        # ЦИТАТА ИЗ БАЗЫ ВЫЧИТАЕТСЯ: она на языке того, кто её записал, и
        # переводить её значило бы подменить свидетельство пересказом.
        строка = re.sub(
            r"«[^»]*»",
            "",
            json.loads(server.plan_pipeline("Add sound effects to our clip, budget $5"))[
                "что_дальше"
            ],
        )
        self.assertNotIn(" из ", строка)
        self.assertIn(" of ", строка)
