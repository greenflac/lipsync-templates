#: Порядок подстановки: сначала ДЛИННЫЕ основы. «золотой час» обязан
#: сработать раньше, чем «золот», иначе свет превратится в палитру.
_ПОРЯДОК = tuple(sorted(ПЕРЕВОД, key=len, reverse=True))


def подставить(text: str) -> tuple[str, dict[str, str]]:
    """Текст с подставленными английскими словами и то, ЧТО подставлено.

    Подстановка ДОПИСЫВАЕТСЯ, а не заменяет: русское слово остаётся в строке.
    Так тот, кто читает намерение, видит собственные слова, а разборщик —
    свои. Замена стёрла бы вход заказчика, а он ещё пригодится соседним
    разборщикам, которые про эту таблицу не знают.
    """
    низ = str(text or "").lower()
    подставлено: dict[str, str] = {}
    # Занятые куски строки. ДЛИННАЯ ОСНОВА СЪЕДАЕТ СВОЁ МЕСТО, и короткая
    # внутри неё уже не срабатывает. НАЙДЕНО МУТАЦИЕЙ 2026-09-04: без этого
    # «золотой час» давал СРАЗУ ОБА — `golden-hour` и `gold`, — то есть свет и
    # палитру из одной фразы, а константа порядка не меняла ничего и потому
    # была ненаблюдаемой.
    занято: list[tuple[int, int]] = []
    for основа in _ПОРЯДОК:
        for совпадение in re.finditer(r"(?<![а-яё])" + re.escape(основа), низ):
            начало, конец = совпадение.span()
            if any(н <= начало < к for н, к in занято):
                continue
            занято.append((начало, конец))
            подставлено.setdefault(основа, ПЕРЕВОД[основа])
    if not подставлено:
        return низ, {}
    return низ + " " + " ".join(sorted(set(подставлено.values()))), подставлено


def непереведённые(text: str) -> list[str]:
    """Русские слова текста, которых таблица НЕ знает.

    Нужны, чтобы «не понял» было отличимо от «слова нет в списках движка»:
    первое чинится таблицей, второе — решением о словаре, и это решение не
    здесь (см. `studio/style.py`: список мал нарочно).
    """
    слова = re.findall(r"[а-яё]{3,}", str(text or "").lower())
    return sorted({с for с in слова if not any(с.startswith(о) for о in ПЕРЕВОД)})
