_WORD = re.compile(r"[a-zа-яё0-9][a-zа-яё0-9._-]*", re.I)


def bridge(text: str) -> str:
    """Текст плюс английские соответствия его доменных слов.

    Исходный текст НЕ выбрасывается: если спросили по-английски или назвали
    модель по имени, это должно продолжать работать.
    """
    добавки: list[str] = []
    for m in _WORD.finditer(text or ""):
        слово = m.group(0).lower()
        если_есть = BRIDGE.get(слово)
        if если_есть:
            добавки.append(если_есть)
    return (text or "") + (" " + " ".join(добавки) if добавки else "")


def bridged_words(text: str) -> list[str]:
    """Какие слова мост узнал. Пусто — мост в этом запросе не участвовал."""
    return sorted({m.group(0).lower() for m in _WORD.finditer(text or "")} & set(BRIDGE))
