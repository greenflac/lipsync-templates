"""Журнал против таблицы: что дописано, то остаётся дописанным.

ЗАЧЕМ ЭТОТ МОДУЛЬ ЕСТЬ. В репозитории несколько файлов объявлены журналами:
строка туда только дописывается, а отзыв прежнего утверждения — это НОВАЯ
строка, а не правка старой. Держалось это объявление словами в докстрингах, и
слова не удержали: до появления этого сторожа история уже несла три случая
(см. `ИЗВЕСТНЫЕ_НАРУШЕНИЯ`). Ц7: то, что обязано выполняться всегда, — это
гейт, а не строка правил.

ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Прежняя версия файла обязана быть ПРЕФИКСОМ нынешней:
те же строки, в том же порядке, с начала. Дописывание в конец такую проверку
проходит; удаление строки, правка строки на месте и вставка в середину — нет.
Правка на месте ловится тем же условием, что и удаление, и это не совпадение:
для журнала они одно и то же — утверждение изменилось, а следа не осталось.

ТРИ ИСХОДА (Р1). `не смогли` — отдельный и настоящий: файла нет в прежней
версии (значит журнал только заведён, сравнивать не с чем) или git недоступен.
В `годно` он не сворачивается: несравнённый журнал не проверен.

Сети здесь нет (Т4); всё, что нужно, лежит в `git`.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path

PASS = "pass"
FAIL = "fail"
UNMEASURED = "could not measure"

#: Файлы-журналы. ВЫБРАНО (мной, 2026-08-31) по объявлению «append-only» в их
#: собственных докстрингах и заголовках — список получен грепом по репозиторию,
#: а не по памяти. Файл, который журналом НЕ объявлен, сюда не попадает: гейт,
#: сторожащий заодно и таблицы, краснел бы на законных правках и был бы снят.
ЖУРНАЛЫ: tuple[str, ...] = (
    "studio/knowledge/misses.jsonl",
    "studio/knowledge/model_facts.jsonl",
    "studio/knowledge/measured.jsonl",
    "studio/knowledge/measurements.jsonl",
)

#: Отметка, с которой правило держится. ВЫБРАНО: это HEAD на момент появления
#: сторожа. Раньше него правило не действовало, и делать вид, что действовало,
#: — значит покрасить гейт навсегда и снять его через день.
ПОЛ = "fcb436d8e789e9ce4165361a46a7ae2f25c79ede"

#: ИЗМЕРЕНО 2026-08-31 ЭТИМ ЖЕ прибором, пущенным по всей истории каждого
#: журнала (`сверить_историю` с полом на первом коммите файла). Записано как
#: отрицательный результат (И6): вот чего стоило отсутствие сторожа. Четвёртую
#: строку `git diff --numstat`, которым я мерил сначала, не показал вовсе —
#: прибор строже той оценки, которой его собирались проверять.
ИЗВЕСТНЫЕ_НАРУШЕНИЯ: tuple[tuple[str, str, int, str], ...] = (
    ("studio/knowledge/misses.jsonl", "a95e218", 3, "строка 3 из 14 изменена на месте"),
    ("studio/knowledge/misses.jsonl", "8720723", 7, "строка 7 из 14 изменена на месте"),
    ("studio/knowledge/model_facts.jsonl", "9e66d61", 13, "47 строк перетированы НА МЕСТЕ"),
    ("studio/knowledge/model_facts.jsonl", "1f956bd", 4, "переписана шапка файла"),
)

#: Формы нарушения, из которых собирается негативный контроль. Пары «было» и
#: «стало», и рядом номер строки, на которой прибор обязан разойтись. Это
#: ФИКСТУРЫ, а не история репозитория, и вот почему: CI клонирует с
#: `fetch-depth: 1`, истории там нет вовсе, и контроль, опирающийся на неё,
#: краснел в CI, будучи зелёным локально (ИЗМЕРЕНО 2026-08-31, job 99556022636).
#: Прибор обязан проверяться тем, что есть везде.
ФОРМЫ_НАРУШЕНИЙ: tuple[tuple[str, tuple[str, ...], tuple[str, ...], int], ...] = (
    ("правка первой строки", ("a", "b", "c"), ("X", "b", "c"), 1),
    ("правка в середине", ("a", "b", "c"), ("a", "X", "c"), 2),
    ("правка последней", ("a", "b", "c"), ("a", "b", "X"), 3),
    ("удаление последней", ("a", "b", "c"), ("a", "b"), 3),
    ("вставка в середину", ("a", "b"), ("a", "X", "b"), 2),
    ("журнал опустошён", ("a", "b"), (), 1),
)

#: Формы, на которых прибор обязан МОЛЧАТЬ. Без них прибор, кричащий на всё,
#: прошёл бы контроль из одних нарушений (И5).
ФОРМЫ_БЕЗ_НАРУШЕНИЙ: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...] = (
    ("дописано в конец", ("a", "b"), ("a", "b", "c")),
    ("ничего не менялось", ("a", "b"), ("a", "b")),
    ("журнал только заведён", (), ("a",)),
    ("дописано много", ("a",), ("a", "b", "c", "d", "e")),
)

#: Журнал, у которого за всю историю нарушений НЕТ. Второй конец негативного
#: контроля (И5): без него прибор, красящий всё подряд, прошёл бы приёмку на
#: одних только известных нарушениях. ИЗМЕРЕНО 2026-08-31: 0 шагов `не годно`
#: от первого коммита файла до HEAD.
ЧИСТЫЙ_ЖУРНАЛ = "studio/knowledge/measured.jsonl"


@dataclass
class Сверка:
    """Один журнал, сверенный с прежней своей версией."""

    path: str
    outcome: str
    было: int = 0
    стало: int = 0
    первая_разошедшаяся: int = 0
    почему: str = ""
    добавлено: int = 0
    problems: list[str] = field(default_factory=list)


def первое_расхождение(было: list[str], стало: list[str]) -> int:
    """Номер первой строки (с 1), где нынешнее перестаёт повторять прежнее.

    Ноль означает «прежнее целиком является префиксом нынешнего». Вынесено
    отдельной функцией, а не веткой внутри сверки, чтобы её можно было
    проверить литералами (Т5, Т2).
    """
    if len(стало) < len(было):
        return len(стало) + 1
    for i, строка in enumerate(было):
        if стало[i] != строка:
            return i + 1
    return 0


def строки_в_ревизии(path: str, rev: str, *, repo: Path | None = None) -> list[str] | None:
    """Содержимое файла в ревизии, или None — если его там нет либо git молчит.

    None — это третий исход, а не пустой файл: разница между «журнала тогда не
    было» и «журнал тогда был пуст» здесь решает вердикт.
    """
    try:
        готово = subprocess.run(
            ["git", "show", f"{rev}:{path}"],
            cwd=str(repo) if repo else None,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if готово.returncode != 0:
        return None
    return готово.stdout.splitlines()


def сверить(path: str, *, rev: str, repo: Path | None = None) -> Сверка:
    """Один журнал: прежняя версия обязана быть префиксом нынешней."""
    было = строки_в_ревизии(path, rev, repo=repo)
    файл = (repo or Path(".")) / path
    if было is None:
        return Сверка(
            path=path,
            outcome=UNMEASURED,
            почему=f"в {rev} файла нет или git недоступен — сравнивать не с чем",
        )
    if not файл.is_file():
        return Сверка(
            path=path,
            outcome=FAIL,
            было=len(было),
            почему="журнал был, а теперь его нет: это удаление всех строк разом",
            problems=[f"{path}: файл исчез, а в {rev} в нём было {len(было)} строк"],
        )
    стало = файл.read_text(encoding="utf-8").splitlines()
    разошлось = первое_расхождение(было, стало)
    if разошлось:
        беда = (
            f"{path}: строка {разошлось} из {len(было)} не дожила до нынешней версии "
            f"(было {len(было)} строк, стало {len(стало)})"
        )
        return Сверка(
            path=path,
            outcome=FAIL,
            было=len(было),
            стало=len(стало),
            первая_разошедшаяся=разошлось,
            почему="журнал переписан, а не дописан",
            problems=[беда],
        )
    return Сверка(
        path=path,
        outcome=PASS,
        было=len(было),
        стало=len(стало),
        добавлено=len(стало) - len(было),
        почему=f"дописано строк {len(стало) - len(было)}, прежние на месте",
    )


def сверить_все(
    журналы: tuple[str, ...] = ЖУРНАЛЫ, *, rev: str = "HEAD", repo: Path | None = None
) -> list[Сверка]:
    return [сверить(p, rev=rev, repo=repo) for p in журналы]


def вердикт(сверки: list[Сверка]) -> dict:
    """Р1 и Р2: три исхода, и рядом числа, из которых исход получился."""
    if not сверки:
        return {
            "outcome": UNMEASURED,
            "checked": 0,
            "violations": 0,
            "unmeasured": 1,
            "note": "журналов не задано — сторож не сторожил ничего",
            "problems": [],
        }
    беды = [b for с in сверки for b in с.problems]
    не_смогли = [с for с in сверки if с.outcome == UNMEASURED]
    сверено = [с for с in сверки if с.outcome != UNMEASURED]
    if беды:
        исход = FAIL
    elif not сверено:
        исход = UNMEASURED
    else:
        исход = PASS
    return {
        "outcome": исход,
        "checked": len(сверено),
        "violations": len(беды),
        "unmeasured": len(не_смогли),
        "note": (
            "; ".join(беды)
            if беды
            else (
                "ни один журнал не сверен: сравнивать не с чем"
                if not сверено
                else f"прежние строки на месте во всех {len(сверено)}; "
                f"дописано {sum(с.добавлено for с in сверено)}"
            )
        ),
        "problems": беды,
    }


def коммиты_по(path: str, *, floor: str, repo: Path | None = None) -> list[str]:
    """Коммиты, тронувшие журнал, от пола к HEAD, в порядке применения.

    Пол в выдачу не входит: он — та версия, с которой сравнивается первая
    после него. Правило не действует раньше пола, и вид, что действовало,
    покрасил бы гейт навсегда.
    """
    диапазон = f"{floor}..HEAD" if floor else "HEAD"
    try:
        готово = subprocess.run(
            # `--full-history` ОБЯЗАТЕЛЕН, и это не украшение. Обычный `git
            # log -- path` упрощает историю: слияние, чьё содержимое совпало с
            # одним из родителей, из выдачи ИСЧЕЗАЕТ. То есть слияние,
            # выбросившее строки чужой ветки, было бы для сторожа невидимо —
            # ровно тот случай, ради которого сторож и написан. Поймано
            # собственным тестом 2026-09-02: без флага «потерявшее» слияние
            # давало ноль нарушений.
            ["git", "log", "--format=%H", "--reverse", "--full-history", диапазон, "--", path],
            cwd=str(repo) if repo else None,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if готово.returncode != 0:
        return []
    return готово.stdout.split()


def родители(rev: str, *, repo: Path | None = None) -> list[str]:
    """Родители коммита. Пусто — корень или git молчит (третий исход)."""
    try:
        готово = subprocess.run(
            ["git", "rev-list", "--parents", "-n", "1", rev],
            cwd=str(repo) if repo else None,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if готово.returncode != 0:
        return []
    части = готово.stdout.split()
    return части[1:] if len(части) > 1 else []


def пропали(было: list[str], стало: list[str]) -> list[str]:
    """Строки родителя, которых в потомке НЕТ. Для слияния это и есть правило.

    У слияния два родителя, и «дописано, а не переписано» для него значит не
    «продолжает одного», а «не потерял НИ ОДНОГО». Порядок при слиянии
    законно меняется: две ветки дописывали одновременно, и чья-то запись
    оказывается ниже чужой. Пропажа же остаётся пропажей.
    """
    есть = set(стало)
    return [строка for строка in было if строка not in есть]


def сверить_историю(path: str, *, floor: str = ПОЛ, repo: Path | None = None) -> list[Сверка]:
    """Каждый шаг истории журнала после пола: прежнее — префикс нынешнего.

    Существует потому, что сверки с HEAD недостаточно: коммит, переписавший
    журнал, с этого момента САМ становится HEAD, и разница исчезает. Ровно так
    прошли незамеченными все три известных нарушения.
    """
    шаги: list[Сверка] = []
    коммиты = коммиты_по(path, floor=floor, repo=repo)
    if not коммиты:
        return []
    # Пустой пол означает «от корня»: первый коммит сравнивать не с чем, и это
    # третий исход, а не молчаливый пропуск — иначе обход без пола вернул бы
    # ноль шагов и «ноль нарушений» прочиталось бы как успех (Р2).
    for коммит in коммиты:
        # Сравнивать с ПРЕДЫДУЩИМ В СПИСКЕ нельзя: `git log --reverse`
        # вытягивает в одну линию коммиты РАЗНЫХ веток, и после слияния
        # соседями в списке оказываются версии, которые друг друга никогда не
        # видели. Поймано 2026-09-02 на первом же слитом канале: гейт объявил
        # нарушением то, что ветка канала не продолжает мою ветку — она её и не
        # должна продолжать. Сравнивается со СВОИМ родителем.
        мои_родители = родители(коммит, repo=repo)
        if len(мои_родители) > 1:
            потери = []
            for родитель in мои_родители:
                у_родителя = строки_в_ревизии(path, родитель, repo=repo)
                стало = строки_в_ревизии(path, коммит, repo=repo)
                if у_родителя is None or стало is None:
                    continue
                пропавшие = пропали(у_родителя, стало)
                if пропавшие:
                    потери.append(
                        f"{path}@{коммит[:7]}: слияние потеряло {len(пропавшие)} строк(и) "
                        f"родителя {родитель[:7]}"
                    )
            стало = строки_в_ревизии(path, коммит, repo=repo) or []
            шаги.append(
                Сверка(
                    path=path,
                    outcome=FAIL if потери else PASS,
                    стало=len(стало),
                    почему=(
                        f"{коммит[:7]}: слияние потеряло строки"
                        if потери
                        else f"{коммит[:7]}: слияние, ни одна строка родителей не потеряна"
                    ),
                    problems=потери,
                )
            )
            continue
        предыдущий = мои_родители[0] if мои_родители else (floor or f"{коммит}~1")
        было = строки_в_ревизии(path, предыдущий, repo=repo)
        стало = строки_в_ревизии(path, коммит, repo=repo)
        if было is None:
            шаги.append(
                Сверка(path=path, outcome=UNMEASURED, почему=f"{коммит[:7]}: журнал тут заведён")
            )
            continue
        if стало is None:
            шаги.append(
                Сверка(
                    path=path,
                    outcome=FAIL,
                    было=len(было),
                    почему=f"{коммит[:7]}: журнал удалён целиком",
                    problems=[f"{path}@{коммит[:7]}: файл удалён, в нём было {len(было)} строк"],
                )
            )
            continue
        разошлось = первое_расхождение(было, стало)
        if разошлось:
            шаги.append(
                Сверка(
                    path=path,
                    outcome=FAIL,
                    было=len(было),
                    стало=len(стало),
                    первая_разошедшаяся=разошлось,
                    почему=f"{коммит[:7]}: переписан, а не дописан",
                    problems=[
                        f"{path}@{коммит[:7]}: строка {разошлось} из {len(было)} "
                        f"изменилась или исчезла (было {len(было)}, стало {len(стало)})"
                    ],
                )
            )
            continue
        шаги.append(
            Сверка(
                path=path,
                outcome=PASS,
                было=len(было),
                стало=len(стало),
                добавлено=len(стало) - len(было),
                почему=f"{коммит[:7]}: дописано {len(стало) - len(было)}",
            )
        )
    return шаги
